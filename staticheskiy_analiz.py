"""Статический анализ кода C, который создаёт Дан: среда выполнения и порождённый код программ.

Программы каталога (`каталог/программы`) и примеры (`примеры`) переводятся компилятором на Дане
в самодостаточный код C (как `dan си`): в нём вся нужная программе среда выполнения из `sreda/`
и базовая среда. Каждый файл разбирает анализатор gcc (`-fanalyzer`): он прослеживает пути
выполнения и находит утечки памяти, обращения по нулевому указателю, чтение неинициализированных
значений, двойное освобождение и подобное.

Предупреждение определяется видом и функцией, в которой оно найдено (номера строк меняются от
программы к программе). Уже разобранные предупреждения записаны в
`анализ/известные_предупреждения.txt` с причиной, почему это не ошибка; проверка падает только
на новом предупреждении. Если известное предупреждение больше не встречается, сценарий
напоминает убрать его из списка.

Запуск: python staticheskiy_analiz.py [--потоков=N] [файлы.dan ...]
"""

import concurrent.futures
import glob
import os
import re
import subprocess
import sys
import tempfile

ПАПКА = os.path.dirname(os.path.abspath(__file__))
ИЗВЕСТНЫЕ = os.path.join(ПАПКА, "анализ", "известные_предупреждения.txt")

# gcc берёт кавычки по настройке языка: прямые 'f' или типографские ‘f’
_ФУНКЦИЯ = re.compile(r"In function ['‘]([^'’]+)['’]")
_ПРЕДУПРЕЖДЕНИЕ = re.compile(r"^.*?:\d+:\d+: warning: .*\[(-Wanalyzer[a-z-]*)\]\s*$")


def предупреждения(вывод_gcc):
    """Множество пар (вид, функция) из вывода gcc -fanalyzer."""
    итог = set()
    функция = "?"
    for строка in вывод_gcc.splitlines():
        м = _ФУНКЦИЯ.search(строка)
        if м:
            функция = м.group(1)
            continue
        м = _ПРЕДУПРЕЖДЕНИЕ.match(строка)
        if м:
            итог.add((м.group(1), функция))
    return итог


def прочитать_известные(текст):
    """Пары (вид, функция) из списка известных: строка «вид функция # причина»; пустые строки и
    строки, начинающиеся с #, пропускаются. Строка без причины - ошибка списка."""
    итог = set()
    for номер, строка in enumerate(текст.splitlines(), 1):
        строка = строка.strip()
        if not строка or строка.startswith("#"):
            continue
        запись, _, причина = строка.partition("#")
        части = запись.split()
        if len(части) != 2 or not причина.strip():
            raise ValueError(f"строка {номер}: нужно «вид функция # причина»: {строка}")
        итог.add((части[0], части[1]))
    return итог


def сравнить(найдено, известные):
    """Новые предупреждения и известные, которые больше не встречаются."""
    return sorted(найдено - известные), sorted(известные - найдено)


def _разобрать(путь, папка, номер):
    """Перевести программу в C компилятором на Дане и разобрать анализатором gcc."""
    код_c = os.path.join(папка, f"п{номер}.c")
    окружение = dict(os.environ, DAN_KOMPILYATOR="сам")
    with open(код_c, "w", encoding="utf-8") as ф:
        р = subprocess.run([sys.executable, os.path.join(ПАПКА, "dan.py"), "си", путь], stdout=ф,
                           stderr=subprocess.PIPE, text=True, encoding="utf-8", env=окружение)
    if р.returncode != 0:
        return путь, None, р.stderr.strip()
    р = subprocess.run(["gcc", "-std=c11", "-O1", "-fanalyzer", "-fdiagnostics-plain-output", "-c", код_c,
                        "-o", os.devnull], capture_output=True, text=True, encoding="utf-8", errors="replace",
                       timeout=1200)
    return путь, предупреждения(р.stderr), р.stderr


def main(аргументы):
    потоков = os.cpu_count() or 2
    файлы = []
    for а in аргументы:
        if а.startswith("--потоков="):
            потоков = int(а.split("=", 1)[1])
        else:
            файлы.append(а)
    if not файлы:
        файлы = sorted(glob.glob(os.path.join(ПАПКА, "каталог", "программы", "*.dan"))
                       + glob.glob(os.path.join(ПАПКА, "примеры", "*.dan")))
    with open(ИЗВЕСТНЫЕ, encoding="utf-8") as ф:
        известные = прочитать_известные(ф.read())
    найдено = {}
    with tempfile.TemporaryDirectory() as папка, concurrent.futures.ThreadPoolExecutor(потоков) as пул:
        задания = [пул.submit(_разобрать, путь, папка, н) for н, путь in enumerate(файлы)]
        for з in concurrent.futures.as_completed(задания):
            путь, пары, вывод_ = з.result()
            if пары is None:
                print(f"не переведена в C (пропущена): {os.path.relpath(путь, ПАПКА)}: {вывод_[:200]}")
                continue
            for п in пары:
                найдено.setdefault(п, (путь, вывод_))
    новые, исчезнувшие = сравнить(set(найдено), известные)
    print(f"Программ: {len(файлы)}, разных предупреждений: {len(найдено)}, известных: {len(известные)}")
    for вид, функция in исчезнувшие:
        print(f"больше не встречается, уберите из списка: {вид} {функция}")
    if not новые:
        print("Новых предупреждений нет.")
        return 0
    for вид, функция in новые:
        путь, вывод_ = найдено[(вид, функция)]
        print(f"\nНОВОЕ: {вид} в функции {функция} (программа {os.path.relpath(путь, ПАПКА)})")
        for строка in вывод_.splitlines():
            if _ФУНКЦИЯ.search(строка) and _ФУНКЦИЯ.search(строка).group(1) == функция:
                начало = вывод_.splitlines().index(строка)
                print("\n".join(вывод_.splitlines()[начало:начало + 40]))
                break
    print(f"\nНовых предупреждений: {len(новые)}. Исправьте код или, если это ложная тревога, допишите в "
          f"{os.path.relpath(ИЗВЕСТНЫЕ, ПАПКА)} строку «вид функция # причина».")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
