"""Модули языка Дан: программа из нескольких файлов.

    подключить "расчёты.dan"                 // имена доступны как расчёты.имя
    подключить "общее/даты.dan" как даты     // своё имя для модуля

Путь указывается относительно файла, в котором записано подключение; если
такого файла нет, он ищется в пакетах проекта (папка «пакеты», раздел 14.4
спецификации), а затем в стандартной библиотеке (папка «библиотека» рядом
с компилятором): подключить "json".
Из подключённого файла видны только функции и типы, помеченные словом
«общий»; остальное - внутреннее дело модуля. В подключаемом файле могут
быть только объявления (функции, типы, подключения), поэтому подключение
ничего не выполняет само по себе и порядок подключений не важен.

Устройство: каждый файл разбирается отдельно, затем объявления модуля
получают полные имена «модуль.имя» (точка не может входить в имя, которое
пишет программист, поэтому полные имена разных модулей не совпадают),
обращения «псевдоним.имя» заменяются полными именами, и все файлы
собираются в одно дерево программы. Дальше работают обычные проверка и
генерация кода. Номер строки узла из подключённого файла хранит и номер
файла (uzly.ШАГ_ФАЙЛА), поэтому сообщения об ошибках называют файл.
"""

import os
import re
from dataclasses import fields

import uzly as у
from lexer import без_ё, ОшибкаЛексера, КЛЮЧЕВЫЕ_СЛОВА
from parser import разобрать, ОшибкаРазбора
from paketi import папка_пакетов


class ОшибкаМодуля(Exception):
    """Ошибка при подключении файлов; текст уже содержит имя файла."""


# Стандартная библиотека на самом Дане: файлы, которые находятся по имени
# из любой программы (подключить "json").
БИБЛИОТЕКА = os.path.join(os.path.dirname(os.path.abspath(__file__)), "библиотека")

ОБЪЯВЛЕНИЯ = (у.Функция, у.ОбъявлениеТипа, у.ОбъявлениеВариантов, у.ОбъявлениеИнтерфейса)
ИМЯ_В_ТИПЕ = re.compile(r"[^\W\d]\w*(?:\.[^\W\d]\w*)?")
ПОЛЯ_ТИПОВ = ("тип", "тип_результата")


class Модуль:
    def __init__(self, путь, номер, канон):
        self.путь = путь            # полный путь к файлу
        self.номер = номер          # номер файла в uzly.ФАЙЛЫ (0 - основная программа)
        self.канон = канон          # приставка полных имён ("" у основной программы)
        self.имена = {}             # имя объявления -> полное имя
        self.общие = set()          # имена, видимые снаружи
        self.инструкции = []
        self.псевдонимы = {}        # имя модуля в этом файле -> Модуль
        self.написания = {}         # имя модуля -> как оно написано (с «ё»)


class Загрузчик:
    def __init__(self, основной_путь):
        self.каталог = os.path.dirname(os.path.abspath(основной_путь)) if основной_путь else os.getcwd()
        self.основной = основной_путь or "программа.dan"
        self.модули = {}            # полный путь -> Модуль
        self.порядок = []           # модули в порядке готовности (зависимости раньше)
        self.в_работе = []          # цепочка загружаемых сейчас файлов
        self.каноны = set()
        у.ФАЙЛЫ[:] = [self._показать(self.основной)]
        у.ТЕКСТЫ[:] = [None]

    def _показать(self, путь):
        """Путь для сообщений: относительно каталога основной программы."""
        if os.path.dirname(os.path.abspath(путь)) == БИБЛИОТЕКА:
            return "библиотека/" + os.path.basename(путь)
        try:
            относительный = os.path.relpath(os.path.abspath(путь), self.каталог)
        except ValueError:          # другой диск в Windows
            return путь
        return путь if относительный.startswith("..") and os.path.isabs(путь) else относительный

    def _ошибка(self, модуль, узел, текст):
        строка = узел.строка % у.ШАГ_ФАЙЛА if узел is not None else 0
        место = f"Строка {строка}, позиция {узел.столбец}: " if узел is not None and строка else ""
        raise ОшибкаМодуля(f"{у.ФАЙЛЫ[модуль.номер]}: {место}{текст}")

    # ---------- загрузка ----------

    def основная(self, исходник):
        у.ТЕКСТЫ[0] = исходник
        модуль = Модуль(os.path.abspath(self.основной), 0, "")
        программа = разобрать(исходник)
        self._подготовить(модуль, программа, основной=True)
        итог = []
        for м in self.порядок:
            итог.extend(м.инструкции)
        итог.extend(модуль.инструкции)
        программа.инструкции = итог
        программа.файлы = list(у.ФАЙЛЫ)
        return программа

    def _найти_файл(self, откуда, узел):
        база = os.path.dirname(откуда.путь)
        путь = os.path.normpath(os.path.join(база, узел.путь))
        if not os.path.isfile(путь) and not os.path.splitext(путь)[1] and os.path.isfile(путь + ".dan"):
            путь += ".dan"
        if not os.path.isfile(путь):
            # пакеты проекта (python dan.py пакеты): пакеты/имя/имя.dan или пакеты/имя/файл.dan
            пакеты = папка_пакетов(self.основной) if self.основной else None
            if пакеты:
                части = узел.путь.replace("\\", "/").split("/")
                if len(части) == 1:
                    части = [части[0], части[0]]
                кандидат = os.path.join(пакеты, *части)
                if not os.path.splitext(кандидат)[1]:
                    кандидат += ".dan"
                if os.path.isfile(кандидат):
                    путь = кандидат
        if not os.path.isfile(путь) and "/" not in узел.путь and "\\" not in узел.путь:
            в_библиотеке = os.path.join(БИБЛИОТЕКА, узел.путь)
            if not os.path.splitext(в_библиотеке)[1]:
                в_библиотеке += ".dan"
            if os.path.isfile(в_библиотеке):
                путь = в_библиотеке
        if not os.path.isfile(путь):
            self._ошибка(откуда, узел, f"не найден подключаемый файл «{узел.путь}» "
                                       f"(путь считается от каталога файла, в котором записано подключение; "
                                       f"в стандартной библиотеке такого модуля тоже нет)")
        return путь

    def _загрузить(self, откуда, узел):
        путь = self._найти_файл(откуда, узел)
        if путь in self.модули:
            return self.модули[путь]
        if путь in self.в_работе or путь == os.path.abspath(self.основной):
            цепочка = self.в_работе[self.в_работе.index(путь):] if путь in self.в_работе else self.в_работе
            имена = [self._показать(п) for п in цепочка] + [self._показать(путь)]
            if путь == os.path.abspath(self.основной) and путь not in self.в_работе:
                имена = [self._показать(self.основной)] + имена
            self._ошибка(откуда, узел, "файлы подключают друг друга по кругу: " + " -> ".join(имена) +
                         ". Вынесите общие объявления в отдельный файл и подключите его в обоих")
        try:
            with open(путь, encoding="utf-8") as ф:
                исходник = ф.read()
        except UnicodeDecodeError:
            self._ошибка(откуда, узел, f"файл «{узел.путь}» должен быть в кодировке UTF-8")
        except OSError as о:
            self._ошибка(откуда, узел, f"не удалось открыть файл «{узел.путь}»: {о.strerror}")

        номер = len(у.ФАЙЛЫ)
        у.ФАЙЛЫ.append(self._показать(путь))
        у.ТЕКСТЫ.append(исходник)
        основа = без_ё(os.path.splitext(os.path.basename(путь))[0])
        if not re.fullmatch(r"[^\W\d]\w*", основа):
            основа = "модуль"
        канон, н = основа, 2
        while канон in self.каноны:
            канон, н = f"{основа}_{н}", н + 1
        self.каноны.add(канон)
        модуль = Модуль(путь, номер, канон)
        try:
            программа = разобрать(исходник)
        except (ОшибкаЛексера, ОшибкаРазбора) as о:
            raise ОшибкаМодуля(f"{у.ФАЙЛЫ[номер]}: ошибка в записи программы\n  {о}") from None
        self.в_работе.append(путь)
        self._подготовить(модуль, программа, основной=False)
        self.в_работе.pop()
        self.модули[путь] = модуль
        self.порядок.append(модуль)
        return модуль

    def _подготовить(self, модуль, программа, основной):
        if not основной:
            self._сдвинуть_строки(программа, модуль.номер * у.ШАГ_ФАЙЛА)
        # Подключения
        for инстр in программа.инструкции:
            if isinstance(инстр, у.Подключение):
                подключённый = self._загрузить(модуль, инстр)
                имя = инстр.имя
                написание = getattr(инстр, "написание", None) or имя
                if not имя:
                    написание = os.path.splitext(os.path.basename(инстр.путь))[0]
                    имя = без_ё(написание)
                    if not re.fullmatch(r"[^\W\d]\w*", имя) or имя in КЛЮЧЕВЫЕ_СЛОВА:
                        self._ошибка(модуль, инстр, f"название файла «{инстр.путь}» не годится как имя модуля; "
                                                    f"укажите имя: подключить \"{инстр.путь}\" как имя")
                if имя in модуль.псевдонимы:
                    self._ошибка(модуль, инстр, f"имя модуля «{имя}» уже занято другим подключением; "
                                                f"укажите другое: подключить \"{инстр.путь}\" как другое_имя")
                модуль.псевдонимы[имя] = подключённый
                модуль.написания[имя] = написание
        # Объявления
        for инстр in программа.инструкции:
            if isinstance(инстр, у.Подключение):
                continue
            if isinstance(инстр, у.Функция) and инстр.метод_типа:
                continue                    # метод виден там же, где его тип
            if isinstance(инстр, у.ВнешнийБлок):
                for ф in инстр.функции:
                    модуль.имена[ф.имя] = f"{модуль.канон}.{ф.имя}" if модуль.канон else ф.имя
                    if getattr(инстр, "общий", False):
                        модуль.общие.add(ф.имя)
                continue
            if isinstance(инстр, ОБЪЯВЛЕНИЯ):
                if инстр.имя in модуль.псевдонимы:
                    self._ошибка(модуль, инстр, f"имя «{инстр.имя}» уже занято подключённым модулем")
                полное = f"{модуль.канон}.{инстр.имя}" if модуль.канон else инстр.имя
                модуль.имена[инстр.имя] = полное
                общий = getattr(инстр, "общий", False)
                if общий:
                    модуль.общие.add(инстр.имя)
                if isinstance(инстр, у.ОбъявлениеВариантов):
                    for в in инстр.варианты:
                        модуль.имена[в.имя] = f"{модуль.канон}.{в.имя}" if модуль.канон else в.имя
                        if общий:
                            модуль.общие.add(в.имя)
            elif not основной:
                self._ошибка(модуль, инстр, "в подключаемом файле могут быть только объявления функций и типов "
                                            "(и подключения других файлов); выполняемые инструкции "
                                            "переносятся в основную программу")
        # Переименование
        for инстр in программа.инструкции:
            if isinstance(инстр, у.Подключение):
                continue
            for пт in getattr(инстр, "параметры_типа", None) or []:
                if пт.имя in модуль.имена or пт.имя in модуль.псевдонимы:
                    self._ошибка(модуль, пт, f"имя параметра типа «{пт.имя}» совпадает с именем из этого файла; "
                                             f"выберите другое, например Т")
                пт.ограничения = [self._тип(модуль, пт, о) for о in пт.ограничения]
            if isinstance(инстр, у.ВнешнийБлок):
                for ф in инстр.функции:
                    ф.имя = модуль.имена[ф.имя]
                модуль.инструкции.append(инстр)
                continue
            if isinstance(инстр, у.Функция) and инстр.метод_типа:
                if "." in инстр.метод_типа or инстр.метод_типа not in модуль.имена:
                    if "." in инстр.метод_типа:
                        self._ошибка(модуль, инстр, "метод объявляется в том же файле, что и его тип")
                else:
                    инстр.метод_типа = модуль.имена[инстр.метод_типа]
                модуль.инструкции.append(self._переписать(модуль, инстр, верхний=True))
                continue
            if not основной:
                if not getattr(инстр, "написание", None) and hasattr(инстр, "написание"):
                    инстр.написание = инстр.имя
                if isinstance(инстр, у.ОбъявлениеВариантов):
                    for в in инстр.варианты:
                        в.написание = в.написание or в.имя
                        в.имя = модуль.имена[в.имя]
                инстр.имя = модуль.имена[инстр.имя]
            модуль.инструкции.append(self._переписать(модуль, инстр, верхний=True))

    # ---------- обход дерева ----------

    def _сдвинуть_строки(self, узел, сдвиг):
        if isinstance(узел, list):
            for э in узел:
                self._сдвинуть_строки(э, сдвиг)
        elif isinstance(узел, у.Узел):
            if узел.строка:
                узел.строка += сдвиг
            for п in fields(узел):
                self._сдвинуть_строки(getattr(узел, п.name), сдвиг)

    def _внешнее(self, модуль, узел, псевдоним, имя):
        """Полное имя для «псевдоним.имя»."""
        другой = модуль.псевдонимы[псевдоним]
        if имя not in другой.имена:
            self._ошибка(модуль, узел, f"в модуле «{модуль.написания[псевдоним]}» нет функции или типа «{имя}»")
        if имя not in другой.общие:
            self._ошибка(модуль, узел, f"«{имя}» в модуле «{модуль.написания[псевдоним]}» не помечено словом «общий», "
                                       f"поэтому снаружи модуля недоступно")
        return другой.имена[имя]

    def _тип(self, модуль, узел, тип):
        def замена(совпадение):
            слово = совпадение.group(0)
            if "." in слово:
                псевдоним, имя = слово.split(".", 1)
                if псевдоним not in модуль.псевдонимы:
                    self._ошибка(модуль, узел, f"неизвестный модуль «{псевдоним}» в типе «{тип}»")
                return self._внешнее(модуль, узел, псевдоним, имя)
            return модуль.имена.get(слово, слово)
        return ИМЯ_В_ТИПЕ.sub(замена, тип)

    def _проверить_имя(self, модуль, узел, имя):
        """Имя переменной или параметра не должно совпадать с объявлением или модулем."""
        if not имя:
            return
        if имя in модуль.псевдонимы:
            self._ошибка(модуль, узел, f"имя «{модуль.написания[имя]}» уже занято подключённым модулем")
        if модуль.канон and имя in модуль.имена:
            self._ошибка(модуль, узел, f"имя «{имя}» уже занято функцией или типом этого модуля")

    def _переписать(self, модуль, узел, верхний=False):
        if isinstance(узел, list):
            return [self._переписать(модуль, э) for э in узел]
        if not isinstance(узел, у.Узел):
            return узел
        if isinstance(узел, у.Подключение):
            self._ошибка(модуль, узел, "«подключить» пишется в начале файла, вне функций и блоков")
        if isinstance(узел, у.Поле) and isinstance(узел.объект, у.Имя) and узел.объект.имя in модуль.псевдонимы:
            полное = self._внешнее(модуль, узел, узел.объект.имя, узел.имя)
            return у.Имя(полное, строка=узел.строка, столбец=узел.столбец)
        if isinstance(узел, у.Имя):
            if узел.имя in модуль.псевдонимы:
                self._ошибка(модуль, узел, f"«{узел.имя}» - подключённый модуль; обращаться нужно к его "
                                           f"функциям и типам: {узел.имя}.имя")
            if узел.имя in модуль.имена:
                узел.имя = модуль.имена[узел.имя]
            return узел
        if isinstance(узел, у.ОбразецВарианта):
            if "." in узел.имя:
                псевдоним, имя = узел.имя.split(".", 1)
                if псевдоним not in модуль.псевдонимы:
                    self._ошибка(модуль, узел, f"неизвестный модуль «{псевдоним}»")
                узел.имя = self._внешнее(модуль, узел, псевдоним, имя)
            elif узел.имя in модуль.имена:
                узел.имя = модуль.имена[узел.имя]
            for п in узел.привязки:
                self._проверить_имя(модуль, узел, п if п != "_" else None)
            return узел
        if isinstance(узел, (у.Параметр, у.ОбъявлениеПеременной)):
            self._проверить_имя(модуль, узел, узел.имя)
        elif isinstance(узел, у.Для):
            self._проверить_имя(модуль, узел, узел.переменная)
        elif isinstance(узел, (у.ЕслиЕсть, у.ЕслиОшибка)):
            self._проверить_имя(модуль, узел, узел.имя)
            self._проверить_имя(модуль, узел, getattr(узел, "имя_ошибки", None))
        for п in fields(узел):
            значение = getattr(узел, п.name)
            if п.name in ПОЛЯ_ТИПОВ and isinstance(значение, str):
                setattr(узел, п.name, self._тип(модуль, узел, значение))
            elif isinstance(значение, (у.Узел, list)):
                setattr(узел, п.name, self._переписать(модуль, значение))
        return узел


def загрузить(исходник, путь=None):
    """Разбирает основную программу и все подключённые файлы в одно дерево."""
    return Загрузчик(путь).основная(исходник)
