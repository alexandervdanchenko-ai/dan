"""Версия компилятора и редакции языка.

Редакция - это зафиксированное состояние языка: его слова, правила записи,
типы и смысл всех конструкций. Программа указывает редакцию первой строкой:

    редакция 2026

и тогда любой будущий компилятор Дана выполняет её по правилам этой редакции.
Новая редакция выходит, только если язык меняется несовместимо (слово
становится ключевым, правило записи становится строже, меняется смысл
конструкции). Изменения, которые не ломают ни одной верной программы (новые
функции библиотеки, новые конструкции, более точные сообщения, ускорение),
входят в текущую редакцию.

Для каждого перехода между соседними редакциями здесь же описывается
перевод текста программы (МИГРАЦИИ): команда «dan.py редакция файл.dan
2027» переводит программу автоматически. Переводы применяются по цепочке,
так что программу можно перевести через несколько редакций сразу.
"""

ВЕРСИЯ = "1.4"

# Редакции по порядку выхода: год -> краткое описание.
РЕДАКЦИИ = {
    "2026": "первая редакция (Дан 1.0)",
}

ТЕКУЩАЯ_РЕДАКЦИЯ = list(РЕДАКЦИИ)[-1]

# (из, в) -> функция, переводящая текст программы из редакции «из» в редакцию «в».
# Пока редакция одна, переводов нет.
МИГРАЦИИ = {}

# Устаревшие функции: имя (для модулей - «модуль.имя») -> (редакция, в которой
# функция будет удалена, совет, чем её заменить). Компилятор предупреждает о
# каждом вызове, но программа собирается: удалить функцию можно только в новой
# редакции, а до неё у программ есть время перейти на замену.
УСТАРЕВШИЕ = {}

СЛОВО = "редакция"


class ОшибкаРедакции(Exception):
    pass


def проверить_редакцию(год):
    """Сообщение об ошибке для неизвестной редакции или None."""
    if год in РЕДАКЦИИ:
        return None
    известные = ", ".join(РЕДАКЦИИ)
    if год.isdigit() and int(год) > int(ТЕКУЩАЯ_РЕДАКЦИЯ):
        return (f"программа написана для редакции языка {год}, а этот компилятор (Дан {ВЕРСИЯ}) знает "
                f"только редакции: {известные}; обновите компилятор Дана")
    return f"неизвестная редакция языка «{год}»; известные редакции: {известные}"


def строка_редакции(текст):
    """(номер строки, год) указания редакции в начале текста или (None, None).
    Указание - первая строка, кроме пустых строк и комментариев."""
    for номер, строка in enumerate(текст.splitlines(), 1):
        с = строка.strip().lstrip("﻿")
        if not с or с.startswith("//"):
            continue
        части = с.split("//")[0].split()
        if len(части) == 2 and части[0] == СЛОВО:
            return номер, части[1]
        return None, None
    return None, None


def перевести(текст, в_редакцию=None):
    """Текст программы, переведённый в редакцию «в_редакцию» (по умолчанию текущую),
    с указанием этой редакции в начале. Возвращает (новый текст, список шагов)."""
    в_редакцию = в_редакцию or ТЕКУЩАЯ_РЕДАКЦИЯ
    if в_редакцию not in РЕДАКЦИИ:
        raise ОшибкаРедакции(проверить_редакцию(в_редакцию))
    номер, из_редакции = строка_редакции(текст)
    if из_редакции is None:
        # программа без указания написана для первой редакции, в которой указание необязательно
        из_редакции = list(РЕДАКЦИИ)[0]
    elif из_редакции not in РЕДАКЦИИ:
        raise ОшибкаРедакции(проверить_редакцию(из_редакции))
    порядок = list(РЕДАКЦИИ)
    i, j = порядок.index(из_редакции), порядок.index(в_редакцию)
    if j < i:
        raise ОшибкаРедакции(f"перевод в более раннюю редакцию ({в_редакцию}) невозможен: программа написана "
                             f"для редакции {из_редакции}")
    шаги = []
    for к in range(i, j):
        перевод = МИГРАЦИИ[(порядок[к], порядок[к + 1])]
        текст = перевод(текст)
        шаги.append(f"{порядок[к]} -> {порядок[к + 1]}")
    строки = текст.split("\n")
    номер, _ = строка_редакции(текст)
    if номер is not None:
        строки[номер - 1] = f"{СЛОВО} {в_редакцию}"
    else:
        строки.insert(0, f"{СЛОВО} {в_редакцию}")
    return "\n".join(строки), шаги
