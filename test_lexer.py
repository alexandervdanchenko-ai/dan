import unittest

from lexer import разобрать, Т, ОшибкаЛексера


def виды_и_значения(текст):
    return [(т.вид, т.значение) for т in разобрать(текст)]


class ТестыЛексера(unittest.TestCase):

    def test_пустой_файл(self):
        self.assertEqual(виды_и_значения(""), [(Т.КОНЕЦ_ФАЙЛА, None)])

    def test_переменная(self):
        self.assertEqual(виды_и_значения("пусть х = 5"), [
            (Т.КЛЮЧ, "пусть"), (Т.ИМЯ, "х"), (Т.ЗНАК, "="), (Т.ЦЕЛОЕ, 5),
            (Т.КОНЕЦ_СТРОКИ, None), (Т.КОНЕЦ_ФАЙЛА, None),
        ])

    def test_числа(self):
        т = разобрать("42 3.14 1_000_000 0.5")
        self.assertEqual([(x.вид, x.значение) for x in т[:4]], [
            (Т.ЦЕЛОЕ, 42), (Т.ДРОБНОЕ, 3.14), (Т.ЦЕЛОЕ, 1000000), (Т.ДРОБНОЕ, 0.5),
        ])

    def test_диапазон_не_путается_с_дробью(self):
        self.assertEqual(виды_и_значения("1..100")[:3], [
            (Т.ЦЕЛОЕ, 1), (Т.ЗНАК, ".."), (Т.ЦЕЛОЕ, 100),
        ])

    def test_двойные_знаки(self):
        значения = [т.значение for т in разобрать("== != <= >= += -= *= /= -> < > =")[:12]]
        self.assertEqual(значения, ["==", "!=", "<=", ">=", "+=", "-=", "*=", "/=", "->", "<", ">", "="])

    def test_школьные_знаки(self):
        значения = [т.значение for т in разобрать("× · ÷ − ≤ ≥ ≠")[:7]]
        self.assertEqual(значения, ["*", "*", "/", "-", "<=", ">=", "!="])

    def test_строка_и_последовательности(self):
        т = разобрать(r'"Привет\n\t\"мир\"\\"')[0]
        self.assertEqual(т.вид, Т.СТРОКА)
        self.assertEqual(т.значение, 'Привет\n\t"мир"\\')

    def test_комментарий_пропускается(self):
        self.assertEqual(виды_и_значения("// пояснение\nх // ещё"), [
            (Т.ИМЯ, "х"), (Т.КОНЕЦ_СТРОКИ, None), (Т.КОНЕЦ_ФАЙЛА, None),
        ])

    def test_пустые_строки_не_дублируют_конец(self):
        виды = [в for в, _ in виды_и_значения("а\n\n\nб\n")]
        self.assertEqual(виды, [Т.ИМЯ, Т.КОНЕЦ_СТРОКИ, Т.ИМЯ, Т.КОНЕЦ_СТРОКИ, Т.КОНЕЦ_ФАЙЛА])

    def test_перенос_внутри_круглых_скобок(self):
        виды = [в for в, _ in виды_и_значения("ф(1,\n  2)")]
        self.assertNotIn(Т.КОНЕЦ_СТРОКИ, виды[:-2])

    def test_перенос_внутри_фигурных_скобок_значим(self):
        виды = [в for в, _ in виды_и_значения("{\nх\n}")]
        self.assertEqual(виды.count(Т.КОНЕЦ_СТРОКИ), 3)

    def test_ключевые_слова_и_имена(self):
        т = разобрать("если иначе пока для в и или не истина ложь цел счётчик Сумма_2 x")
        self.assertTrue(all(x.вид == Т.КЛЮЧ for x in т[:10]))
        self.assertTrue(all(x.вид == Т.ИМЯ for x in т[10:14]))

    def test_позиции(self):
        т = разобрать("пусть х = 5\n  вывод(х)")
        вывод = [x for x in т if x.значение == "вывод"][0]
        self.assertEqual((вывод.строка, вывод.столбец), (2, 3))

    def test_ошибка_незакрытой_строки(self):
        with self.assertRaises(ОшибкаЛексера) as к:
            разобрать('пусть с = "текст')
        self.assertIn("не закрыта", str(к.exception))
        self.assertEqual(к.exception.строка, 1)

    def test_ошибка_недопустимого_символа(self):
        with self.assertRaises(ОшибкаЛексера):
            разобрать("х = 5 @ 3")

    def test_ошибка_лишней_скобки(self):
        with self.assertRaises(ОшибкаЛексера):
            разобрать("х)")

    def test_ошибка_число_слитно_с_именем(self):
        with self.assertRaises(ОшибкаЛексера):
            разобрать("5кг")


class ТестыНадёжностиИмён(unittest.TestCase):

    def test_смешение_алфавитов_в_слове_запрещено(self):
        # первая буква «c» латинская
        with self.assertRaises(ОшибкаЛексера) as к:
            разобрать("пусть cумма = 1")
        self.assertIn("«c» (1-я буква, латинская)", str(к.exception))
        with self.assertRaises(ОшибкаЛексера):
            разобрать("пусть итoг = 1")       # латинская «o»

    def test_разные_алфавиты_в_разных_частях_имени(self):
        разобрать("пусть сжать_gzip2 = 1\nпусть хеш_sha256 = 2\nпусть total = 3")

    def test_е_и_ё_равнозначны(self):
        имена = [з for в, з in виды_и_значения("счётчик счетчик Ёж") if в == Т.ИМЯ]
        self.assertEqual(имена, ["счетчик", "счетчик", "Еж"])


class ТестыНевидимыхСимволов(unittest.TestCase):
    """Защита от атаки Trojan Source (CVE-2021-42574)."""

    def test_смена_направления_в_комментарии_запрещена(self):
        with self.assertRaises(ОшибкаЛексера) as к:
            разобрать("пусть а = 1 // проверка ‮ }; ложь\nвывод(а)")
        текст = str(к.exception)
        self.assertIn("U+202E", текст)
        self.assertIn("справа налево", текст)
        self.assertEqual((к.exception.строка, к.exception.столбец), (1, 25))

    def test_смена_направления_в_строке_запрещена(self):
        with self.assertRaises(ОшибкаЛексера) as к:
            разобрать('пусть а = 1\nпусть с = "доступ⁦ разрешён"')
        self.assertIn("U+2066", str(к.exception))
        self.assertEqual(к.exception.строка, 2)

    def test_все_символы_направления_запрещены(self):
        for с in "؜‎‏‪‫‬‭‮⁦⁧⁨⁩":
            with self.subTest(код=f"U+{ord(с):04X}"):
                with self.assertRaises(ОшибкаЛексера):
                    разобрать(f'// {с}\nпусть а = 1')

    def test_невидимый_символ_назван_кодом(self):
        with self.assertRaises(ОшибкаЛексера) as к:
            разобрать("пусть а​б = 1")
        self.assertIn("U+200B (пробел нулевой ширины)", str(к.exception))

    def test_обычный_символ_назван_видимо(self):
        with self.assertRaises(ОшибкаЛексера) as к:
            разобрать("х = 5 @ 3")
        self.assertIn("«@» (U+0040)", str(к.exception))

    def test_соединитель_в_строке_допустим(self):
        # Соединитель нулевой ширины нужен в составных значках и ряде письменностей.
        значения = [з for в, з in виды_и_значения('"👨‍👩"') if в == Т.СТРОКА]
        self.assertEqual(значения, ["👨‍👩"])

    def test_метка_порядка_байтов_в_начале_файла(self):
        self.assertEqual(виды_и_значения("﻿пусть а = 1")[:2],
                         виды_и_значения("пусть а = 1")[:2])


if __name__ == "__main__":
    unittest.main()
