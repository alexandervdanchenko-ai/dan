def _описание(текст):
    """Первая часть описания функции: без примера после двоеточия и без продолжения после «;» и «.»,
    не длиннее 60 знаков."""
    текст = текст.strip()
    for знак in ("; ", ". "):
        текст = текст.split(знак, 1)[0]
    if ": " in текст:
        до, после = текст.split(": ", 1)
        # после двоеточия - пример (но «а : б» - это деление в формуле)
        if ("=" in после or "(" in после) and len(до.split()[-1]) > 1:
            текст = до
    if len(текст) > 60:
        текст = текст[:60].rsplit(" ", 1)[0] + "..."
    return текст.strip()


ЧИСЛОВЫЕ = ("цел", "рац", "дроб", "длинное", "компл", "мн")
# варианты с разными типами из этого ряда (и «стр») записываются одним: «сумма([Ч]) -> Ч (Ч: цел, рац, дроб)»


def _шаблон(параметры, результат):
    """Вариант с первым числовым (или строковым) типом параметров, заменённым на «Ч», и сам этот тип."""
    основы = [т.strip("[]") for т in параметры]
    тип = next((о for о in основы if о in ЧИСЛОВЫЕ + ("стр",)), None)
    if тип is None:
        return None, None
    замена = lambda т: "Ч" if т == тип else ("[Ч]" if т == f"[{тип}]" else т)  # noqa: E731
    return (tuple(замена(т) for т in параметры), замена(результат)), тип


def _вариант(имя, параметры, результат):
    часть = f"{имя}({', '.join(параметры)})"
    if результат != "пусто":
        часть += f" -> {результат}"
    return часть


def _варианты(имя, варианты):
    """Варианты вызова; варианты, которые отличаются только числовым типом, записываются одним:
    «модуль(Ч) -> Ч (Ч: цел, рац, дроб)»."""
    группы = []          # [(шаблон или None, [варианты], [типы])]
    for параметры, результат in варианты:
        шаблон, тип = _шаблон(параметры, результат)
        if шаблон is not None and группы and группы[-1][0] == шаблон:
            группы[-1][1].append((параметры, результат))
            группы[-1][2].append(тип)
        else:
            группы.append((шаблон, [(параметры, результат)], [тип]))
    части = []
    for шаблон, вар, типы in группы:
        if len(вар) > 1:
            части.append(_вариант(имя, шаблон[0], шаблон[1]) + f" (Ч: {', '.join(типы)})")
        else:
            части.append(_вариант(имя, *вар[0]))
    return "; ".join(части)


def встроенные():
    """Строки «сигнатуры - описание» по группам: (заголовок, [строки])."""
    служебные = ("Обычно используется через", "обычно используется через", "Обычно используются через")
    группы = {"математика": [], "данные": [], "система": []}
