"""Порядок вычисления: части выражения вычисляются слева направо (spec.md, приоритет операций).

В C порядок вычисления аргументов функции не задан (gcc часто вычисляет их справа налево),
поэтому компилятор вычисляет заранее части с действием (вызовы, деление, индекс), после которых
в выражении есть ещё что-то, кроме постоянных.
"""

import unittest

from test_kodogen import выполнить, КОМПИЛЯТОР_ЕСТЬ

ФУНКЦИЯ = "функ ф(х: цел) -> цел {\n    вывод(х)\n    вернуть х\n}\n"


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыПорядка(unittest.TestCase):

    def вывод(self, текст, ожидается, ввод_данных=""):
        код, вывод_, ошибки = выполнить(ФУНКЦИЯ + текст, ввод_данных)
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.split(), ожидается)

    def test_действия(self):
        self.вывод("вывод(ф(1) + ф(2))", ["1", "2", "3"])
        self.вывод("вывод(ф(1) < ф(2))", ["1", "2", "истина"])
        self.вывод("функ г(а: цел, б: цел) -> цел { вернуть а - б }\nвывод(г(ф(5), ф(3)))", ["5", "3", "2"])
        self.вывод("вывод(стр(ф(7)) + стр(ф(8)))", ["7", "8", "78"])

    def test_списки_словари_индексы(self):
        self.вывод("вывод([ф(1), ф(2), 3])", ["1", "2", "[1,", "2,", "3]"])
        self.вывод("вывод({ф(1): ф(2)})", ["1", "2", "{1:", "2}"])
        self.вывод("пусть с = [10, 20, 30]\nвывод(с[ф(1)] + ф(2))", ["1", "2", "22"])

    def test_ввод(self):
        self.вывод("пусть а = ввод()\nвывод(ввод() + ввод())", ["второйтретий"], "первый\nвторой\nтретий\n")

    def test_первая_ошибка(self):
        # находка сверки сборок: деление и остаток на ноль в одном выражении
        код, _, ошибки = выполнить("пусть б = 0\nвывод(частное(1, б) + (б % 0))")
        self.assertEqual(код, 1)
        self.assertIn("деление на ноль", ошибки)
        код, _, ошибки = выполнить("пусть б = 0\nвывод((б % 0) + частное(1, б))")
        self.assertEqual(код, 1)
        self.assertIn("остаток от деления на ноль", ошибки)

    def test_переполнение_раньше_вызова(self):
        # находка сверки сборок (зерно 139): умножение с проверкой переполнения слева от вызова
        код, вывод_, ошибки = выполнить(ФУНКЦИЯ + "пусть р = 4000000000\nвывод((р * р) + ф(1))")
        self.assertEqual((код, вывод_.split()), (1, []), ошибки)
        код, вывод_, ошибки = выполнить(ФУНКЦИЯ + "пусть р = 4000000000\nвывод(ф(1) + (р * р))")
        self.assertEqual((код, вывод_.split()), (1, ["1"]), ошибки)
        код, _, ошибки = выполнить("пусть р = 4000000000\nпусть б = 0\nвывод((р * р) + частное(1, б))")
        self.assertEqual(код, 1)
        self.assertNotIn("деление на ноль", ошибки)
        self.вывод("пусть р = 3\nвывод((р * р) + ф(1))", ["1", "10"])

    def test_присваивание_элементу_и_полю(self):
        self.вывод("перем с = [0, 0, 0]\nс[ф(1)] = ф(5)\nс[ф(2)] += ф(6)\nвывод(с)", ["1", "5", "2", "6", "[0,", "5,", "6]"])
        self.вывод("перем м = [[0, 0], [0, 0]]\nм[ф(1)][ф(0)] = ф(9)\nвывод(м[1][0])", ["1", "0", "9", "9"])
        self.вывод("перем д = {1: 1}\nд[ф(2)] = ф(3)\nд[ф(1)] += ф(4)\nвывод(д[1] + д[2])", ["2", "3", "1", "4", "8"])
        self.вывод("тип Т {\n    п: цел\n}\nперем с = [Т(1), Т(2)]\nс[ф(1)].п = ф(7)\nс[ф(0)].п += ф(8)\n"
                   "перем м = [[Т(0)], [Т(0)]]\nм[ф(1)][ф(0)].п = ф(9)\nвывод(с[0].п + с[1].п + м[1][0].п)",
                   ["1", "7", "0", "8", "1", "0", "9", "25"])

    def test_вызов_метода(self):
        self.вывод('функ с(т: стр) -> стр {\n    вывод(т)\n    вернуть т\n}\nвывод(с("аб").содержит(с("б")))',
                   ["аб", "б", "истина"])


if __name__ == "__main__":
    unittest.main()
