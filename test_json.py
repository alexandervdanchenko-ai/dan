    def test_ошибки_разбора(self):
        случаи = [
            ("", "строка 1, позиция 1: текст закончился, а значение не найдено"),
            ("[1, 2", "массив не закрыт скобкой «]»"),
            ("[1 2]", "строка 1, позиция 4: между элементами массива нужна запятая"),
            ('{"а" 1}', "после имени поля нужно двоеточие"),
            ("{а: 1}", "имя поля должно быть строкой в кавычках"),
            ('{"а": 1,}', "имя поля должно быть строкой в кавычках"),
            ("[1,]", "неожиданный знак «]»"),
            ("01", "после значения лишний текст"),
            ("-", "после «-» должна идти цифра"),
            ("1.", "после десятичной точки должна идти цифра"),
            ("1e", "в показателе степени должна быть цифра"),
            ("tru", "ожидалось «true»"),
            ('"abc', "строка не закрыта кавычкой"),
            ('"\\x"', "неизвестное сочетание «\\x»"),
            ('"\\u12g4"', "после \\u нужны четыре шестнадцатеричные цифры"),
            ('"а\tб"', "управляющий символ внутри строки"),
            ("{\n  \"а\": [1,\n  2 3]}", "строка 3, позиция 5: между элементами массива нужна запятая"),
            ("[" * 600 + "]" * 600, "слишком глубокая вложенность"),
            ("NaN", "неожиданный знак «N»"),
        ]
        файлы = {f"{н:02d}.json": т for н, (т, _) in enumerate(случаи)}
        with tempfile.TemporaryDirectory() as п:
            for имя, текст in файлы.items():
                with open(os.path.join(п, имя), "w", encoding="utf-8") as ф:
                    ф.write(текст)
            путь = os.path.join(п, "программа.dan")
            текст = ПРОГРАММА_ЭХО.replace("ПАПКА", п)
            р = subprocess.run([dan.собрать(путь, текст)], capture_output=True, text=True, encoding="utf-8", timeout=60)
            self.assertEqual(р.returncode, 0, р.stderr)
            for н, (исходный, часть) in enumerate(случаи):
                with self.subTest(текст=исходный[:30]):
                    файл = os.path.join(п, f"{н:02d}.json.ошибка")
                    self.assertTrue(os.path.exists(файл), "ошибка не обнаружена")
                    with open(файл, encoding="utf-8") as ф:
                        сообщение = ф.read()
                    self.assertTrue(сообщение.startswith("JSON, строка "), сообщение)
                    self.assertIn(часть, сообщение)

