    def test_случайные_значения_как_в_python(self):
        сл = random.Random(8259)
        файлы, значения = {}, {}
        for н in range(150):
            з = случайное_значение(сл)
            вид = сл.randint(0, 3)
            текст = json.dumps(з, ensure_ascii=вид % 2 == 0, indent=None if вид < 2 else сл.choice([1, 2, "\t"]))
            имя = f"{н:03d}.json"
            файлы[имя], значения[имя] = текст, з
        with tempfile.TemporaryDirectory() as п:
            for имя, текст in файлы.items():
                with open(os.path.join(п, имя), "w", encoding="utf-8") as ф:
                    ф.write(текст)
            путь = os.path.join(п, "программа.dan")
            текст = ПРОГРАММА_ЭХО.replace("ПАПКА", п)
            исп = dan.собрать(путь, текст)
            р = subprocess.run([исп], capture_output=True, text=True, encoding="utf-8", timeout=120)
            self.assertEqual(р.returncode, 0, р.stderr)
            for имя, з in значения.items():
                with self.subTest(файл=имя, текст=файлы[имя][:200]):
                    self.assertFalse(os.path.exists(os.path.join(п, имя + ".ошибка")),
                                     open(os.path.join(п, имя + ".ошибка"), encoding="utf-8").read()
                                     if os.path.exists(os.path.join(п, имя + ".ошибка")) else "")
                    for вид in (".сжато", ".красиво"):
                        with open(os.path.join(п, имя + вид), encoding="utf-8") as ф:
                            записано = ф.read()
                        self.assertEqual(self._нормально(json.loads(записано)), self._нормально(з))

    @staticmethod
    def _нормально(з):
        """-0.0 и 0.0 равны, как и в JSON; остальное сравнивается точно."""
        if isinstance(з, float) and з == 0:
            return 0.0
        if isinstance(з, list):
            return [ТестыJSON._нормально(х) for х in з]
        if isinstance(з, dict):
            return {к: ТестыJSON._нормально(х) for к, х in з.items()}
        return з

    def test_точный_вид_записи(self):
        значение = {"а": [1, 2.5, True, None, "x\ny"], "б": {}, "в": [], "г": {"д": "е"}}
        текст = json.dumps(значение, ensure_ascii=False)
        вывод = self.вывод(f'подключить "json"\nпусть з = json.разобрать({строка_дан(текст)})!\n'
                           'вывод(json.записать(з))\nвывод(json.записать_красиво(з))')
        self.assertEqual(вывод[0], json.dumps(значение, ensure_ascii=False, separators=(",", ":")))
        self.assertEqual("\n".join(вывод[1:]), json.dumps(значение, ensure_ascii=False, indent=2))

