def выполнить_с_файлами(текст, файлы=None, таймаут=120):
    with tempfile.TemporaryDirectory() as п:
        for имя, содержимое in (файлы or {}).items():
            with open(os.path.join(п, имя), "w", encoding="utf-8", newline="") as ф:
                ф.write(содержимое)
        путь = os.path.join(п, "программа.dan")
        текст = текст.replace("ПАПКА", п)
        with open(путь, "w", encoding="utf-8") as ф:
            ф.write(текст)
        исп = dan.собрать(путь, текст)
        начало = time.perf_counter()
        р = subprocess.run([исп], capture_output=True, text=True, encoding="utf-8", timeout=таймаут, cwd=п)
        return р.returncode, р.stdout, р.stderr, time.perf_counter() - начало


def случайное_значение(сл, глубина=0):
    вид = сл.randint(0, 9 if глубина < 4 else 5)
    if вид == 0:
        return None
    if вид == 1:
        return сл.random() < 0.5
    if вид == 2:
        return сл.randint(-10 ** 15, 10 ** 15)
    if вид == 3:
        return сл.choice([0.5, -2.25, 1e-7, 3.14159, 1e21, -0.0, 123456.789, сл.uniform(-1e6, 1e6)])
    if вид <= 5:
        знаки = "абвгдеёжАБВ ЯяabcXYZ019\"\\/\n\t\b\f\r\x01\x1f€😀𝄞"
        return "".join(сл.choice(знаки) for _ in range(сл.randint(0, 12)))
    if вид <= 7:
        return [случайное_значение(сл, глубина + 1) for _ in range(сл.randint(0, 5))]
    return {"".join(сл.choice("абвabc_1 \"") for _ in range(сл.randint(0, 6))): случайное_значение(сл, глубина + 1)
            for _ in range(сл.randint(0, 5))}


