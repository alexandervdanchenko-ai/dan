import unittest

from parser import разобрать, ОшибкаРазбора
import uzly as у


def одна(текст):
    """Разбирает программу из одной инструкции и возвращает её."""
    п = разобрать(текст)
    assert len(п.инструкции) == 1, п.инструкции
    return п.инструкции[0]


def выр(текст):
    return одна(текст).выражение


Ц = у.ЦелоеЧисло
И = у.Имя
Б = у.Бинарная


class ТестыВыражений(unittest.TestCase):

    def test_приоритет_умножения(self):
        self.assertEqual(выр("1 + 2 * 3"), Б("+", Ц(1), Б("*", Ц(2), Ц(3))))

    def test_левая_ассоциативность(self):
        self.assertEqual(выр("10 - 3 - 2"), Б("-", Б("-", Ц(10), Ц(3)), Ц(2)))

    def test_скобки(self):
        self.assertEqual(выр("(1 + 2) * 3"), Б("*", Б("+", Ц(1), Ц(2)), Ц(3)))

    def test_унарный_минус(self):
        self.assertEqual(выр("-х * 2"), Б("*", у.Унарная("-", И("х")), Ц(2)))

    def test_логика_и_сравнения(self):
        self.assertEqual(
            выр("а > 1 и б < 2 или не г"),
            Б("или",
              Б("и", Б(">", И("а"), Ц(1)), Б("<", И("б"), Ц(2))),
              у.Унарная("не", И("г"))))

    def test_диапазон_ниже_сложения(self):
        self.assertEqual(выр("1..н + 1"), у.Диапазон(Ц(1), Б("+", И("н"), Ц(1))))

    def test_вызов_и_поле(self):
        self.assertEqual(
            выр("ф(1, х + 2).длина"),
            у.Поле(у.Вызов(И("ф"), [Ц(1), Б("+", И("х"), Ц(2))]), "длина"))

    def test_двоеточие_как_деление(self):
        self.assertEqual(выр("10 : 2 × 3"), Б("*", Б("/", Ц(10), Ц(2)), Ц(3)))
        и = одна("пусть х: цел = 10 : 2")
        self.assertEqual((и.тип, и.значение), ("цел", Б("/", Ц(10), Ц(2))))

    def test_литералы(self):
        self.assertEqual(выр('"текст"'), у.Строка("текст"))
        self.assertEqual(выр("2.5"), у.ДробноеЧисло(2.5))
        self.assertEqual(выр("истина"), у.Логическое(True))
        self.assertEqual(выр("ложь"), у.Логическое(False))

    def test_перенос_аргументов(self):
        self.assertEqual(выр("ф(1,\n   2)"), у.Вызов(И("ф"), [Ц(1), Ц(2)]))


class ТестыИнструкций(unittest.TestCase):

    def test_пусть_и_перем(self):
        self.assertEqual(одна("пусть х = 5"), у.ОбъявлениеПеременной("х", False, None, Ц(5)))
        self.assertEqual(одна("перем у: дроб = 1.0"),
                         у.ОбъявлениеПеременной("у", True, "дроб", у.ДробноеЧисло(1.0)))

    def test_присваивания(self):
        self.assertEqual(одна("х = 1"), у.Присваивание("х", "=", Ц(1)))
        self.assertEqual(одна("х += 2"), у.Присваивание("х", "+=", Ц(2)))

    def test_если_иначе_если_иначе(self):
        и = одна("если х > 0 {\n а = 1\n} иначе если х == 0 {\n а = 2\n} иначе {\n а = 3\n}")
        self.assertIsInstance(и, у.Если)
        self.assertIsInstance(и.иначе, у.Если)
        self.assertIsInstance(и.иначе.иначе, у.Блок)

    def test_иначе_на_следующей_строке(self):
        и = одна("если х { а = 1 }\nиначе { а = 2 }")
        self.assertIsInstance(и.иначе, у.Блок)

    def test_если_без_иначе_не_съедает_следующую_строку(self):
        п = разобрать("если х { а = 1 }\nб = 2")
        self.assertEqual(len(п.инструкции), 2)

    def test_однострочный_блок(self):
        и = одна("если н <= 1 { вернуть 1 }")
        self.assertEqual(и.тогда.инструкции, [у.Вернуть(Ц(1))])

    def test_пока(self):
        и = одна("пока х < 10 {\n х *= 2\n}")
        self.assertEqual(и, у.Пока(Б("<", И("х"), Ц(10)),
                                   у.Блок([у.Присваивание("х", "*=", Ц(2))])))

    def test_для_и_управление_циклом(self):
        и = одна("для ч в 1..10 {\n если ч == 5 { продолжить }\n прервать\n}")
        self.assertEqual(и.переменная, "ч")
        self.assertEqual(и.источник, у.Диапазон(Ц(1), Ц(10)))
        self.assertIsInstance(и.тело.инструкции[0].тогда.инструкции[0], у.Продолжить)
        self.assertIsInstance(и.тело.инструкции[1], у.Прервать)

    def test_функция(self):
        ф = одна("функ площадь(ш: дроб, в_: дроб) -> дроб {\n вернуть ш * в_\n}")
        self.assertEqual(ф.имя, "площадь")
        self.assertEqual(ф.параметры, [у.Параметр("ш", "дроб"), у.Параметр("в_", "дроб")])
        self.assertEqual(ф.тип_результата, "дроб")
        self.assertEqual(ф.тело.инструкции, [у.Вернуть(Б("*", И("ш"), И("в_")))])

    def test_функция_без_результата_и_пустой_return(self):
        ф = одна("функ привет() {\n вывод(\"привет\")\n вернуть\n}")
        self.assertIsNone(ф.тип_результата)
        self.assertEqual(ф.параметры, [])
        self.assertEqual(ф.тело.инструкции[1], у.Вернуть(None))

    def test_позиции_узлов(self):
        п = разобрать("\n\n  пусть х = 5")
        self.assertEqual((п.инструкции[0].строка, п.инструкции[0].столбец), (3, 3))


class ТестыСписков(unittest.TestCase):

    def test_литерал_списка(self):
        self.assertEqual(выр("[1, 2, 3]"), у.Список([Ц(1), Ц(2), Ц(3)]))
        self.assertEqual(выр("[]"), у.Список([]))
        self.assertEqual(выр("[1,\n 2,\n]"), у.Список([Ц(1), Ц(2)]))

    def test_индекс_и_вложенность(self):
        self.assertEqual(выр("т[1][0]"), у.Индекс(у.Индекс(И("т"), Ц(1)), Ц(0)))

    def test_присваивание_элементу(self):
        self.assertEqual(одна("с[0] += 5"), у.ПрисваиваниеЭлемента(И("с"), Ц(0), "+=", Ц(5)))

    def test_метод(self):
        self.assertEqual(выр("с.добавить(1)"), у.Вызов(у.Поле(И("с"), "добавить"), [Ц(1)]))

    def test_типы_списков(self):
        self.assertEqual(одна("перем с: [[цел]] = []").тип, "[[цел]]")
        ф = одна("функ ф(а: [стр]) -> [дроб] { вернуть [] }")
        self.assertEqual((ф.параметры[0].тип, ф.тип_результата), ("[стр]", "[дроб]"))

    def test_индекс_на_новой_строке_не_приклеивается(self):
        п = разобрать("вывод(1)\n[1, 2]")
        self.assertEqual(len(п.инструкции), 2)


class ТестыОшибок(unittest.TestCase):

    def ошибка(self, текст, фрагмент):
        with self.assertRaises(ОшибкаРазбора) as к:
            разобрать(текст)
        self.assertIn(фрагмент, str(к.exception))
        return к.exception

    def test_две_инструкции_в_строке(self):
        self.ошибка("пусть х = 1 пусть у = 2", "отдельной строке")

    def test_незакрытый_блок(self):
        о = self.ошибка("если х {\n а = 1\n", "не хватает «}»")
        self.assertEqual(о.строка, 1)

    def test_лишняя_фигурная_скобка(self):
        self.ошибка("а = 1\n}", "лишняя")

    def test_нет_значения_у_переменной(self):
        self.ошибка("пусть х", "сразу задать значение")

    def test_параметр_без_типа(self):
        self.ошибка("функ ф(а) {}", "«а: цел»")

    def test_ключевое_слово_как_имя(self):
        self.ошибка("пусть если = 1", "нельзя использовать как имя")

    def test_иначе_без_если(self):
        self.ошибка("иначе { }", "без предшествующего")

    def test_цепочка_сравнений(self):
        self.ошибка("а < б < в", "цепочкой")

    def test_присваивание_не_переменной(self):
        self.ошибка("ф() = 1", "только переменной")

    def test_незакрытая_круглая_скобка(self):
        self.ошибка("вывод(1", "«)»")

    def test_список_без_запятой(self):
        self.ошибка("пусть с = [1 2]", "«,» или «]»")

    def test_незакрытый_тип_списка(self):
        self.ошибка("перем с: [цел = []", "«]»")

    def test_повтор_параметра(self):
        self.ошибка("функ ф(а: цел, а: цел) {}", "дважды")


