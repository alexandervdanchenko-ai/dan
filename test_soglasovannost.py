"""Согласованность документации: ссылки на разделы spec.md указывают на существующие разделы.

Проверяются ссылки вида «(раздел 9.4)», «разделы 11.9-11.17» внутри spec.md и
ссылки «`spec.md`, раздел 6.5» в других документах. Ссылка на раздел другого
документа («`исследование.md`, раздел 4.4») не проверяется по spec.md.
"""

import os
import re
import unittest

ПАПКА = os.path.dirname(os.path.abspath(__file__))
ССЫЛКА = re.compile(r"раздел(?:ы|ах|е|у|ам)?\s+(\d+(?:\.\d+)*(?:\s*(?:,|и|-)\s*\d+(?:\.\d+)*)*)")
ДРУГОЙ_ДОКУМЕНТ = re.compile(r"`(?!spec\.md)[^`]+\.md`,?\s*$")


def прочитать(имя):
    with open(os.path.join(ПАПКА, имя), encoding="utf-8") as ф:
        return ф.read()


def разделы_спецификации():
    return set(re.findall(r"^#{2,4} (\d+(?:\.\d+)*)\.", прочитать("spec.md"), re.M))


def ссылки(текст, только_на_spec=False):
    """(номер раздела, номер строки) для каждой ссылки на раздел spec.md."""
    итог = []
    for м in ССЫЛКА.finditer(текст):
        перед = текст[max(0, м.start() - 40):м.start()]
        if ДРУГОЙ_ДОКУМЕНТ.search(перед):
            continue
        if только_на_spec and "spec.md" not in перед:
            continue
        строка = текст.count("\n", 0, м.start()) + 1
        итог += [(н, строка) for н in re.findall(r"\d+(?:\.\d+)*", м.group(1))]
    return итог


class ТестыСогласованности(unittest.TestCase):

    def test_ссылки_спецификации_на_саму_себя(self):
        разделы = разделы_спецификации()
        битые = [(н, с) for н, с in ссылки(прочитать("spec.md")) if н not in разделы]
        self.assertEqual(битые, [], "ссылки на несуществующие разделы spec.md (раздел, строка)")

    def test_ссылки_других_документов_на_спецификацию(self):
        разделы = разделы_спецификации()
        for имя in ("принципы.md", "исследование.md", "справочник.md", "README.md"):
            with self.subTest(документ=имя):
                битые = [(н, с) for н, с in ссылки(прочитать(имя), только_на_spec=True) if н not in разделы]
                self.assertEqual(битые, [])

    def test_цикл_по_списку_описан_одинаково(self):
        # Раньше раздел 7.2 говорил, что цикл доходит до добавленных элементов, а 7.3 - что нет.
        spec = прочитать("spec.md")
        self.assertNotIn("цикл дойдёт и до них", spec)


if __name__ == "__main__":
    unittest.main()
