"""Оценка языковых моделей: насколько верно они пишут программы на Дане с первой попытки и за три.

    python оценка_моделей/оценить.py --эталон                     # эталонные решения (для CI)
    python оценка_моделей/оценить.py --команда="claude -p"         # модель - команда оболочки
    python оценка_моделей/оценить.py --api --модель=gpt-4.1        # OpenAI-совместимый HTTP API

Каждая задача (папка «задачи»: условие и проверки в файле .задача, эталон в файле .dan) превращается
в запрос к модели: описание языка (llms-full.txt) и условие с примером. Из ответа берётся программа,
её проверяет «dan проверить», затем она собирается и выполняется на всех проверках задачи. Если
что-то не так, модель получает сообщения компилятора или расхождение вывода и присылает программу
заново (до трёх попыток). Итог - таблица долей решённых задач с первой попытки и за все попытки,
по областям, и файл JSON с подробностями: ответы модели, программы, сообщения каждой попытки.

Исполнитель - функция (сообщения, задача) -> текст ответа; сообщения - список словарей
{"role": "system" | "user" | "assistant", "content": текст}, как в OpenAI-совместимых API.
Встроенные исполнители: эталон, команда оболочки (запрос - на стандартный ввод, ответ - со
стандартного вывода) и HTTP API (адрес и ключ - из переменных среды, ключей в репозитории нет).
"""

