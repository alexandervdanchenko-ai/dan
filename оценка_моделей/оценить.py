def исполнитель_эталон(сообщения, задача):
    return "```dan\n" + задача.эталон() + "```\n"


def исполнитель_команда(команда, секунд=600):
    """Команда оболочки (строка) или список аргументов: запрос - на стандартный ввод одним текстом,
    ответ - со стандартного вывода. Диалог в записи JSON (список сообщений) лежит в файле, путь к
    которому - в переменной среды DAN_OCENKA_DIALOG, а имя задачи - в DAN_OCENKA_ZADACHA."""
    def исполнить(сообщения, задача):
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", suffix=".json", delete=False) as ф:
            json.dump(сообщения, ф, ensure_ascii=False)
            путь = ф.name
        try:
            среда = dict(os.environ, DAN_OCENKA_DIALOG=путь, DAN_OCENKA_ZADACHA=задача.имя)
            р = subprocess.run(команда, shell=isinstance(команда, str), input=диалог_в_текст(сообщения).encode("utf-8"),
                               capture_output=True, timeout=секунд, env=среда)
        finally:
            os.unlink(путь)
        if р.returncode != 0:
            raise RuntimeError(f"исполнитель завершился с кодом {р.returncode}: "
                               + р.stderr.decode("utf-8", "replace").strip()[-2000:])
        return р.stdout.decode("utf-8", "replace")
    return исполнить


def исполнитель_api(адрес, ключ, модель, температура=None, наибольший_ответ=None, секунд=600, повторов=3, пауза=5):
    """OpenAI-совместимый API: POST {адрес}/chat/completions."""
    точка = адрес.rstrip("/")
    if not точка.endswith("/chat/completions"):
        точка += "/chat/completions"

    def исполнить(сообщения, задача):
        тело = {"model": модель, "messages": сообщения}
        if температура is not None:
            тело["temperature"] = температура
        if наибольший_ответ:
            тело["max_tokens"] = наибольший_ответ
        заголовки = {"Content-Type": "application/json"}
        if ключ:
            заголовки["Authorization"] = "Bearer " + ключ
        данные = json.dumps(тело, ensure_ascii=False).encode("utf-8")
        for попытка in range(повторов):
            try:
                запрос = urllib.request.Request(точка, data=данные, headers=заголовки, method="POST")
                with urllib.request.urlopen(запрос, timeout=секунд) as о:
                    ответ = json.loads(о.read().decode("utf-8"))
                return ответ["choices"][0]["message"]["content"] or ""
            except urllib.error.HTTPError as о:
                # 429 и 5xx - временные: повторить с паузой
                if (о.code == 429 or о.code >= 500) and попытка + 1 < повторов:
                    time.sleep(2 ** попытка * пауза)
                    continue
                raise RuntimeError(f"API ответил {о.code}: {о.read().decode('utf-8', 'replace')[:2000]}")
            except (urllib.error.URLError, TimeoutError) as о:
                if попытка + 1 < повторов:
                    time.sleep(2 ** попытка * пауза)
                    continue
                raise RuntimeError(f"API недоступен: {о}")
    return исполнить


