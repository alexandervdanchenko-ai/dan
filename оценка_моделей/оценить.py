class Компилятор:
    """Компилятор на Дане (команды «проверить» и «собрать»)."""

    def __init__(self, путь=None):
        self.путь = путь or найти_компилятор()
        self.среда = dict(os.environ)
        self.среда.setdefault("DAN_HOME", КОРЕНЬ)

    def _выполнить(self, *аргументы, папка):
        р = subprocess.run([self.путь, *аргументы], capture_output=True, cwd=папка, env=self.среда,
                           timeout=СЕКУНД_НА_СБОРКУ)
        return р.returncode, (р.stdout + р.stderr).decode("utf-8", "replace").replace("\r\n", "\n")

    def проверить(self, путь):
        return self._выполнить("проверить", os.path.basename(путь), папка=os.path.dirname(путь))

    def собрать(self, путь):
        """(код, сообщения, путь к исполняемому файлу или None)."""
        код, текст = self._выполнить("собрать", os.path.basename(путь), папка=os.path.dirname(путь))
        основа = путь[:-len(".dan")]
        for кандидат in (основа + ".exe", основа):
            if код == 0 and os.path.isfile(кандидат):
                return код, текст, кандидат
        return код or 1, текст, None


def найти_компилятор():
    """Компилятор на Дане: DAN_SAM_EXE, semya/dan (после sh semya/sobrat.sh), иначе собранный
    sam_kompilyator (из сам/дан.dan, хранится в кэше)."""
    if os.environ.get("DAN_SAM_EXE"):
        return os.environ["DAN_SAM_EXE"]
    for имя in ("dan.exe", "dan"):
        путь = os.path.join(КОРЕНЬ, "semya", имя)
        if os.path.isfile(путь) and os.access(путь, os.X_OK):
            return путь
    sys.path.insert(0, КОРЕНЬ)
    import sam_kompilyator
    return sam_kompilyator.исполняемый()


def _строки(текст):
    # то же сравнение, что в задачнике (zadachnik.строки): пробелы в конце строк и пустые строки в конце не важны
    return [с.rstrip() for с in текст.replace("\r\n", "\n").rstrip("\n").split("\n")]


def _обрезать(текст, строк=40):
    с = текст.rstrip("\n").split("\n")
    if len(с) > строк:
        с = с[:строк] + [f"... (ещё строк: {len(с) - строк})"]
    return "\n".join(с)


class Итог:
    """Итог одной попытки: этап («успех» или где не прошла) и сообщение для модели."""

    def __init__(self, этап, сообщение="", пройдено=0, всего=0):
        self.этап = этап
        self.сообщение = сообщение
        self.пройдено = пройдено
        self.всего = всего

    @property
    def успех(self):
        return self.этап == "успех"


def проверить_программу(задача, программа, компилятор, папка):
    """Записать программу в папку, проверить, собрать и выполнить на всех проверках задачи."""
    if not программа.strip():
        return Итог("ответ", "В ответе нет программы.")
    for слово in задача.обязательно:
        if слово not in программа:
            return Итог("запись", f"В программе нет «{слово}», а условие требует его использовать.")
    os.makedirs(папка, exist_ok=True)
    путь = os.path.join(папка, "программа.dan")
    with open(путь, "w", encoding="utf-8", newline="\n") as ф:
        ф.write(программа)
    код, текст = компилятор.проверить(путь)
    if код != 0:
        return Итог("проверка", "Программа не прошла проверку компилятора (dan проверить программа.dan):\n" + _обрезать(текст, 60))
    код, текст, исполняемый = компилятор.собрать(путь)
    if исполняемый is None:
        return Итог("сборка", "Программа прошла проверку, но не собралась (dan собрать программа.dan):\n" + _обрезать(текст, 60))
    пройдено = 0
    первое = None
    for номер, п in enumerate(задача.проверки, 1):
        итог = _выполнить_проверку(исполняемый, п, os.path.join(папка, f"проверка_{номер}"))
        if итог is None:
            пройдено += 1
        elif первое is None:
            первое = (номер, п) + итог
    всего = len(задача.проверки)
    if первое is None:
        return Итог("успех", "", пройдено, всего)
    номер, п, этап, что = первое
    сообщение = (f"Программа собралась, но не прошла проверку {номер} из {всего} (пройдено {пройдено}).\n"
                 + п.описание() + "\nОжидалось:\n" + п.ожидаемое() + "\n" + что)
    return Итог(этап, сообщение, пройдено, всего)


def _выполнить_проверку(исполняемый, п, папка):
    """None, если проверка пройдена, иначе (этап, описание полученного)."""
    os.makedirs(папка, exist_ok=True)
    for имя, текст in п.файлы.items():
        путь = os.path.join(папка, *имя.split("/"))
        if имя.endswith("/"):
            os.makedirs(путь, exist_ok=True)
            continue
        os.makedirs(os.path.dirname(путь), exist_ok=True)
        with open(путь, "w", encoding="utf-8", newline="\n") as ф:
            ф.write(текст)
    try:
        р = subprocess.run([исполняемый, *п.аргументы], input=п.ввод.encode("utf-8"), capture_output=True,
                           cwd=папка, timeout=СЕКУНД_НА_ПРОВЕРКУ)
    except subprocess.TimeoutExpired:
        return "время", f"Получено: программа работала дольше {СЕКУНД_НА_ПРОВЕРКУ} секунд (зациклилась или ждёт ввода)."
    вывод_ = р.stdout.decode("utf-8", "replace")
    ошибки = р.stderr.decode("utf-8", "replace").strip()
    расхождения = []
    if _строки(вывод_) != _строки(п.вывод):
        расхождения.append("Вывод:\n" + (_блок(_обрезать(вывод_)) if вывод_.strip() else "(ничего)"))
    if р.returncode != п.код:
        расхождения.append(f"Код завершения: {р.returncode}")
    for имя, ожидается in п.файлы_после.items():
        путь = os.path.join(папка, *имя.split("/"))
        if not os.path.isfile(путь):
            расхождения.append(f"Файл «{имя}» не создан.")
            continue
        with open(путь, encoding="utf-8", errors="replace") as ф:
            есть = ф.read()
        if _строки(есть) != _строки(ожидается):
            расхождения.append(f"Файл «{имя}»:\n{_блок(_обрезать(есть))}")
    if not расхождения:
        return None
    if ошибки:
        расхождения.append("Поток ошибок:\n" + _блок(_обрезать(ошибки, 20)))
    return "вывод", "Получено:\n" + "\n".join(расхождения)


