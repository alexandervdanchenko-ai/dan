def прочитать_подсказку(путь):
    if not путь:
        return ""
    with open(путь, encoding="utf-8") as ф:
        return ф.read()


def первый_запрос(задача, подсказка):
    """Сообщения первой попытки: описание языка (system) и условие с примером (user)."""
    текст = ИНСТРУКЦИЯ + "\n\nЗадача:\n" + задача.условие
    if задача.обязательно:
        текст += "\n\nВ программе нужно использовать: " + ", ".join(f"«{о}»" for о in задача.обязательно) + "."
    if задача.проверки:
        пример = задача.проверки[0]
        текст += "\n\nПример.\n" + пример.описание() + "\n" + пример.ожидаемое()
    сообщения = []
    if подсказка:
        сообщения.append({"role": "system", "content": подсказка})
    сообщения.append({"role": "user", "content": текст})
    return сообщения


def диалог_в_текст(сообщения):
    """Диалог одним текстом - для исполнителя-команды, которая получает запрос на стандартный ввод."""
    части = []
    for с in сообщения:
        if с["role"] == "system":
            части.append(с["content"])
        elif с["role"] == "user":
            части.append("## Запрос\n\n" + с["content"])
        else:
            части.append("## Твой прошлый ответ\n\n" + с["content"])
    return "\n\n".join(части) + "\n"


БЛОК = re.compile(r"```[ \t]*([^\n`]*)\n(.*?)```", re.S)


def извлечь_программу(ответ):
    """Программа из ответа модели: последний блок ```dan (или ```дан), иначе последний блок ```,
    иначе весь ответ (если в нём нет блоков)."""
    блоки = БЛОК.findall(ответ or "")
    for язык, тело in reversed(блоки):
        if язык.strip().lower() in ("dan", "дан"):
            return тело
    if блоки:
        return блоки[-1][1]
    return (ответ or "").strip() + "\n"


