def запрос_исправления(итог):
    return (итог.сообщение + "\n\nИсправь программу и пришли её целиком одним блоком ```dan ... ```.")


def решить(задача, исполнитель, компилятор, подсказка, попыток=ПОПЫТОК, папка=None):
    """Подробности решения одной задачи: все попытки и номер первой удачной (или None)."""
    сообщения = первый_запрос(задача, подсказка)
    попытки = []
    решена_с = None
    своя_папка = папка is None
    папка = папка or tempfile.mkdtemp(prefix="dan_ocenka_")
    try:
        for номер in range(1, попыток + 1):
            начало = time.time()
            try:
                ответ = исполнитель(сообщения, задача)
            except Exception as о:
                попытки.append({"номер": номер, "этап": "ответ", "сообщение": f"исполнитель: {о}",
                                "ответ": "", "программа": "", "секунд_ответа": round(time.time() - начало, 2)})
                break
            секунд = round(time.time() - начало, 2)
            программа = извлечь_программу(ответ)
            итог = проверить_программу(задача, программа, компилятор, os.path.join(папка, f"попытка_{номер}"))
            попытки.append({"номер": номер, "этап": итог.этап, "сообщение": итог.сообщение,
                            "пройдено": итог.пройдено, "всего": итог.всего,
                            "ответ": ответ, "программа": программа, "секунд_ответа": секунд})
            if итог.успех:
                решена_с = номер
                break
            сообщения = сообщения + [{"role": "assistant", "content": ответ},
                                     {"role": "user", "content": запрос_исправления(итог)}]
    finally:
        if своя_папка:
            shutil.rmtree(папка, ignore_errors=True)
    return {"имя": задача.имя, "область": задача.область, "трудность": задача.трудность,
            "решена_с_попытки": решена_с, "решена_с_первой": решена_с == 1, "решена": решена_с is not None,
            "попыток": len(попытки), "попытки": попытки}


def оценить(задачи, исполнитель, компилятор=None, подсказка="", попыток=ПОПЫТОК, потоков=1, показ=None,
            модель=""):
    """Итог оценки (словарь для JSON). показ(строка) - печать хода работы."""
    компилятор = компилятор or Компилятор()
    итоги = [None] * len(задачи)

    def одна(н):
        р = решить(задачи[н], исполнитель, компилятор, подсказка, попыток)
        if показ:
            if р["решена"]:
                знак = f"решена с попытки {р['решена_с_попытки']}"
            else:
                знак = "не решена: " + ", ".join(п["этап"] for п in р["попытки"])
            показ(f"{задачи[н].имя}: {знак}")
        return н, р

    if потоков <= 1:
        for н in range(len(задачи)):
            итоги[н] = одна(н)[1]
    else:
        with concurrent.futures.ThreadPoolExecutor(потоков) as пул:
            for н, р in пул.map(одна, range(len(задачи))):
                итоги[н] = р
    return сводка(итоги, попыток, модель)


def сводка(итоги, попыток=ПОПЫТОК, модель=""):
    по_областям = {}
    for р in итоги:
        о = по_областям.setdefault(р["область"], {"задач": 0, "с_первой": 0, "решено": 0})
        о["задач"] += 1
        о["с_первой"] += р["решена_с_первой"]
        о["решено"] += р["решена"]
    первые_ошибки = {}
    for р in итоги:
        if р["попытки"] and р["попытки"][0]["этап"] != "успех":
            э = р["попытки"][0]["этап"]
            первые_ошибки[э] = первые_ошибки.get(э, 0) + 1
    порядок = {о: н for н, о in enumerate(ОБЛАСТИ)}
    return {
        "модель": модель,
        "дата": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "попыток": попыток,
        "задач": len(итоги),
        "с_первой": sum(р["решена_с_первой"] for р in итоги),
        "решено": sum(р["решена"] for р in итоги),
        "первые_ошибки": первые_ошибки,
        "по_областям": dict(sorted(по_областям.items(), key=lambda п: (порядок.get(п[0], len(порядок)), п[0]))),
        "задачи": итоги,
    }


def _доля(ч, всего):
    return f"{ч}/{всего} ({100 * ч / всего:.0f}%)" if всего else "-"


def таблица(итог):
    """Таблица итога для печати."""
    п = итог["попыток"]
    шапка = ("Область", "Задач", "С 1-й попытки", f"За {п} попытки" if 2 <= п <= 4 else f"За {п} попыток")
    строки = [шапка]
    for область, о in итог["по_областям"].items():
        строки.append((область, str(о["задач"]), _доля(о["с_первой"], о["задач"]), _доля(о["решено"], о["задач"])))
    строки.append(("всего", str(итог["задач"]), _доля(итог["с_первой"], итог["задач"]), _доля(итог["решено"], итог["задач"])))
    ширины = [max(len(с[к]) for с in строки) for к in range(4)]
    вывод_ = []
    for н, с in enumerate(строки):
        вывод_.append("  ".join(с[0].ljust(ширины[0]) if к == 0 else с[к].rjust(ширины[к]) for к in range(4)).rstrip())
        if н == 0 or н == len(строки) - 2:
            вывод_.append("  ".join("-" * ш for ш in ширины))
    if итог["первые_ошибки"]:
        вывод_.append("Первые попытки не прошли на этапе: " + ", ".join(
            f"{э} - {итог['первые_ошибки'][э]}" for э in ЭТАПЫ if э in итог["первые_ошибки"]))
    нерешённые = [р["имя"] for р in итог["задачи"] if not р["решена"]]
    if нерешённые:
        вывод_.append("Не решены: " + ", ".join(нерешённые))
    return "\n".join(вывод_)


