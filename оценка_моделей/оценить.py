def _показ_пути(путь):
    try:
        return os.path.relpath(путь, КОРЕНЬ).replace(os.sep, "/")
    except ValueError:
        # другой диск в Windows
        return путь


def main(аргументы=None):
    а = разобрать_аргументы(sys.argv[1:] if аргументы is None else аргументы)
    выбор = [в.strip() for в in а.задачи.split(",") if в.strip()]
    области = [о.strip() for о in а.области.split(",") if о.strip()]
    задачи = загрузить_задачи(выбор=выбор, области=области)
    if not задачи:
        print("Нет задач по такому выбору.", file=sys.stderr)
        return 2
