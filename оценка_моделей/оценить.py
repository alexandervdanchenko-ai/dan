class Проверка:
    """Один набор: аргументы, файлы и ввод программы, ожидаемые вывод, код завершения и файлы после."""

    def __init__(self, имя=""):
        self.имя = имя
        self.аргументы = []
        self.файлы = {}
        self.ввод = ""
        self.вывод = ""
        self.код = 0
        self.файлы_после = {}

    def описание(self):
        """Текст для запроса модели и сообщения о расхождении."""
        части = []
        if self.аргументы:
            части.append("Аргументы: " + " ".join(_показ_аргумента(а) for а in self.аргументы))
        for имя, текст in self.файлы.items():
            части.append(f"Файл «{имя}»:\n{_блок(текст)}")
        части.append("Ввод:\n" + (_блок(self.ввод) if self.ввод else "(пусто)"))
        return "\n".join(части)

    def ожидаемое(self):
        части = ["Вывод:\n" + (_блок(self.вывод) if self.вывод.strip() else "(ничего)")]
        if self.код:
            части.append(f"Код завершения: {self.код}")
        for имя, текст in self.файлы_после.items():
            части.append(f"Файл «{имя}» после выполнения:\n{_блок(текст)}")
        return "\n".join(части)


class Задача:
    def __init__(self, имя, путь):
        self.имя = имя
        self.номер = int(имя.split("_", 1)[0])
        self.путь = путь
        self.область = ""
        self.трудность = 1
        self.обязательно = []
        self.условие = ""
        self.проверки = []

    @property
    def путь_эталона(self):
        return self.путь[:-len(".задача")] + ".dan"

    def эталон(self):
        with open(self.путь_эталона, encoding="utf-8") as ф:
            return ф.read()


def _показ_аргумента(а):
    return а if а and re.fullmatch(r"[^\s\"']+", а) else json.dumps(а, ensure_ascii=False)


def _блок(текст):
    return "```\n" + текст.rstrip("\n") + "\n```"


def разобрать_задачу(текст, имя="", путь=""):
    """Файл .задача: строки «ключ: значение», пустая строка, условие, затем проверки:

        === проверка [название]
        === аргументы        (по одному на строке)
        === файл имя         (файл в папке программы до запуска)
        === ввод
        === вывод
        === код 1            (ожидаемый код завершения, по умолчанию 0)
        === файл после имя   (каким должен стать файл)

    Последняя строка «\\ нет перевода строки» в разделе файла, ввода или вывода означает, что
    перевода строки в конце нет (как в записи diff).
    """
    з = Задача(имя, путь)
    строки = текст.replace("\r\n", "\n").split("\n")
    н = 0
    while н < len(строки) and строки[н].strip():
        ключ, _, значение = строки[н].partition(":")
        ключ, значение = ключ.strip(), значение.strip()
        if ключ == "область":
            з.область = значение
        elif ключ == "трудность":
            з.трудность = int(значение)
        elif ключ == "обязательно":
            з.обязательно = [ч.strip() for ч in значение.split(";") if ч.strip()]
        else:
            raise ValueError(f"{путь}: неизвестный ключ «{ключ}» в начале задачи")
        н += 1
    условие = []
    while н < len(строки) and not строки[н].startswith("=== "):
        условие.append(строки[н])
        н += 1
    з.условие = "\n".join(условие).strip()
    проверка = None
    раздел = None
    содержимое = []

    def закончить_раздел():
        if раздел is None:
            return
        вид, параметр = раздел
        т = "".join(с + "\n" for с in содержимое)
        if содержимое and содержимое[-1] == БЕЗ_ПЕРЕВОДА:
            т = "".join(с + "\n" for с in содержимое[:-1])[:-1]
        if вид == "аргументы":
            проверка.аргументы = [с for с in содержимое if с != ""]
        elif вид == "ввод":
            проверка.ввод = т
        elif вид == "вывод":
            проверка.вывод = т
        elif вид == "файл":
            проверка.файлы[параметр] = т
        elif вид == "файл после":
            проверка.файлы_после[параметр] = т

    for с in строки[н:]:
        if с.startswith("=== "):
            закончить_раздел()
            раздел = None
            содержимое = []
            заголовок = с[4:].strip()
            if заголовок.startswith("проверка"):
                проверка = Проверка(заголовок[len("проверка"):].strip())
                з.проверки.append(проверка)
                continue
            if проверка is None:
                raise ValueError(f"{путь}: раздел «{заголовок}» до первой «=== проверка»")
            if заголовок.startswith("код"):
                проверка.код = int(заголовок[3:].strip())
            elif заголовок.startswith("файл после "):
                раздел = ("файл после", заголовок[len("файл после "):].strip())
            elif заголовок.startswith("файл "):
                раздел = ("файл", заголовок[len("файл "):].strip())
            elif заголовок in ("аргументы", "ввод", "вывод"):
                раздел = (заголовок, "")
            else:
                raise ValueError(f"{путь}: неизвестный раздел «{заголовок}»")
        elif раздел is not None:
            содержимое.append(с)
        elif с.strip():
            raise ValueError(f"{путь}: текст вне раздела: {с}")
    закончить_раздел()
    # пустые строки в конце последнего раздела файла - не часть данных
    for п in з.проверки:
        for поле in ("ввод", "вывод"):
            setattr(п, поле, getattr(п, поле).rstrip("\n") + "\n" if getattr(п, поле).strip("\n") else "")
    return з


def загрузить_задачи(папка=ЗАДАЧИ, выбор=None, области=None):
    """Задачи папки по номерам. выбор - номера или части имён («3», «10-20», «json»), области - имена областей."""
    итог = []
    for имя_файла in sorted(os.listdir(папка)):
        if not имя_файла.endswith(".задача"):
            continue
        путь = os.path.join(папка, имя_файла)
        with open(путь, encoding="utf-8") as ф:
            з = разобрать_задачу(ф.read(), имя_файла[:-len(".задача")], путь)
        if области and з.область not in области:
            continue
        if выбор and not any(_подходит(з, в) for в in выбор):
            continue
        итог.append(з)
    итог.sort(key=lambda з: з.номер)
    return итог


def _подходит(задача, выбор):
    м = re.fullmatch(r"(\d+)(?:-(\d+))?", выбор)
    if м:
        от = int(м[1])
        до = int(м[2] or м[1])
        return от <= задача.номер <= до
    return выбор in задача.имя


