"""Сверка описи математики (математика/охват.md) с таблицами встроенных функций.

Проверяется:
1. Каждое имя в столбце «функции Дана» существует: функция таблиц matematika.py и
   vysshaya.py (вместе с постоянными и синонимами), векторных ядер yadra.py, побитовых
   действий bity.py, встроенный тип (proverka.ВСТРОЕННЫЕ), особая запись компилятора на
   Дане (ОСОБЫЕ ниже) или общая функция модуля библиотеки в записи `модуль.функция`.
2. Каждая функция таблиц matematika.py, vysshaya.py, yadra.py и bity.py упомянута
   в столбце «функции Дана» хотя бы одной строки (синонимы - через основное имя).
3. Строки таблиц имеют раздел М1-М8 или «прочее» и состояние «готово», «частично» или
   «нет»; у каждого раздела есть строки, а классы задач из плана направления названы.

Запуск: python математика/сверить_охват.py (код выхода 1, если есть расхождения).
"""

import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ОПИСЬ = os.path.join(КОРЕНЬ, "математика", "охват.md")
if КОРЕНЬ not in sys.path:
    sys.path.insert(0, КОРЕНЬ)

РАЗДЕЛЫ = ("М1", "М2", "М3", "М4", "М5", "М6", "М7", "М8")
СОСТОЯНИЯ = ("готово", "частично", "нет")
ЗАГОЛОВОК = ["раздел", "класс задач", "функции Дана", "полнота", "состояние"]

# Записи, которых нет в таблицах функций: имя -> файл компилятора на Дане, где оно разбирается.
ОСОБЫЕ = {"массив": "сам/проверка.dan"}

# Классы задач из плана направления: слово, которое должно быть в столбце «класс задач» раздела.
КЛАССЫ_ПЛАНА = {
    "М1": ["Линейная алгебра", "Корни", "интеграл", "дифференциальные уравнения", "Оптимизация",
           "Интерполяция", "Фурье", "статистика"],
    "М4": ["SAT", "SMT", "Пресбургера", "Тарского"],
    "М5": ["Графы", "Комбинаторика", "Теория чисел", "Теория игр"],
}

ИМЯ = re.compile(r"^[\w]+(?:\.[\w]+)?$")


def _без_ё(с):
    return с.replace("ё", "е").replace("Ё", "Е")


def таблицы():
    """(обязательные имена, известные имена): обязательные - основные имена функций таблиц."""
    import proverka  # noqa: F401  (регистрирует функции высшей математики)
    import matematika
    import yadra
    import bity
    обязательные = []
    увиденные = set()
    for имя, запись in matematika.ФУНКЦИИ.items():
        if id(запись) in увиденные:     # синоним с тем же описанием (корни = решить, объем_куба)
            continue
        увиденные.add(id(запись))
        обязательные.append(имя)
    обязательные += list(yadra.ФУНКЦИИ) + list(bity.ФУНКЦИИ)
    известные = (set(matematika.ФУНКЦИИ) | set(matematika.КОНСТАНТЫ) | set(matematika.СИНОНИМЫ)
                 | set(yadra.ФУНКЦИИ) | set(bity.ФУНКЦИИ) | set(proverka.ВСТРОЕННЫЕ))
    return обязательные, известные


def _особое_есть(имя):
    путь = os.path.join(КОРЕНЬ, ОСОБЫЕ[имя])
    with open(путь, encoding="utf-8") as ф:
        текст = _без_ё(ф.read())
    return f'"{_без_ё(имя)}"' in текст


def _функция_модуля_есть(запись):
    модуль, функция = запись.split(".", 1)
    путь = os.path.join(КОРЕНЬ, "библиотека", модуль + ".dan")
    if not os.path.isfile(путь):
        return False
    with open(путь, encoding="utf-8") as ф:
        текст = ф.read()
    return re.search(rf"^\s*общий\s+функ\s+(?:\w+\.)?{re.escape(функция)}\s*\(", текст, re.M) is not None


def строки_описи(текст):
    """[(номер строки, [5 ячеек])] из таблиц с заголовком ЗАГОЛОВОК."""
    итог = []
    в_таблице = False
    for номер, строка in enumerate(текст.split("\n"), 1):
        с = строка.strip()
        if not с.startswith("|"):
            в_таблице = False
            continue
        ячейки = [я.strip() for я in с.strip("|").split("|")]
        if ячейки == ЗАГОЛОВОК:
            в_таблице = True
            continue
        if not в_таблице or all(set(я) <= set("-: ") for я in ячейки):
            continue
        итог.append((номер, ячейки))
    return итог


def имена_в(ячейка):
    return re.findall(r"`([^`]+)`", ячейка)


def сверить(путь=ОПИСЬ):
    """Список расхождений (пустой, если опись согласна с кодом)."""
    with open(путь, encoding="utf-8") as ф:
        текст = ф.read()
    обязательные, известные = таблицы()
    известные_без_ё = {_без_ё(и) for и in известные}
    ошибки = []
    упомянутые = set()
    по_разделам = {}
    for номер, ячейки in строки_описи(текст):
        if len(ячейки) != 5:
            ошибки.append(f"строка {номер}: в таблице {len(ячейки)} столбцов вместо 5")
            continue
        раздел, класс, функции, _, состояние = ячейки
        if раздел not in РАЗДЕЛЫ and раздел != "прочее":
            ошибки.append(f"строка {номер}: неизвестный раздел «{раздел}»")
        if состояние not in СОСТОЯНИЯ:
            ошибки.append(f"строка {номер}: состояние «{состояние}», а должно быть одно из: {', '.join(СОСТОЯНИЯ)}")
        по_разделам.setdefault(раздел, []).append(класс)
        имена = имена_в(функции)
        if not имена and функции != "нет":
            ошибки.append(f"строка {номер}: в столбце «функции Дана» нет имён в `...` и не написано «нет»")
        if функции == "нет" and состояние != "нет":
            ошибки.append(f"строка {номер}: функций нет, а состояние «{состояние}»")
        for имя in имена:
            if not ИМЯ.match(имя):
                ошибки.append(f"строка {номер}: «{имя}» - не имя функции (в этом столбце только имена)")
            elif "." in имя:
                if not _функция_модуля_есть(имя):
                    ошибки.append(f"строка {номер}: нет общей функции модуля библиотеки «{имя}»")
            elif имя in ОСОБЫЕ:
                if not _особое_есть(имя):
                    ошибки.append(f"строка {номер}: «{имя}» не найдено в {ОСОБЫЕ[имя]}")
            elif _без_ё(имя) not in известные_без_ё:
                ошибки.append(f"строка {номер}: нет встроенной функции «{имя}»")
            упомянутые.add(_без_ё(имя))
    for раздел in РАЗДЕЛЫ:
        if раздел not in по_разделам:
            ошибки.append(f"нет строк раздела {раздел}")
    for раздел, слова in КЛАССЫ_ПЛАНА.items():
        классы = " ".join(по_разделам.get(раздел, [])).lower()
        for слово in слова:
            if слово.lower() not in классы:
                ошибки.append(f"в разделе {раздел} не назван класс задач «{слово}»")
    for имя in обязательные:
        if _без_ё(имя) not in упомянутые:
            ошибки.append(f"функция «{имя}» не упомянута в описи")
    return ошибки


def главная():
    ошибки = сверить()
    for о in ошибки:
        print(о)
    if ошибки:
        print(f"Расхождений: {len(ошибки)}")
        return 1
    print("Опись согласна с таблицами встроенных функций")
    return 0


if __name__ == "__main__":
    sys.exit(главная())
