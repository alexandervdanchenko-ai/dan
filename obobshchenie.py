"""Типы как деревья: разбор записи типа, подстановка и сопоставление.

Проверка типов хранит типы строками: «цел», «[стр]», «{стр: цел}», «Т?»,
«Т!», «функ(цел) -> цел», «Пара<цел, стр>». Для обобщённых функций и типов
нужно подставлять вместо параметров (Т, А, Б) конкретные типы и находить
значения параметров по типам аргументов. Здесь строка разбирается в
дерево из кортежей:

    ("имя", "Пара", [аргументы])   ("список", т)   ("словарь", к, з)
    ("необяз", т)   ("результат", т)   ("функ", [параметры], результат)
"""

import re

ИМЯ = re.compile(r"[^\W\d][\w.]*")


def _закрывающая(текст, начало):
    """Номер закрывающей скобки для открывающей в позиции «начало»."""
    глубина = 0
    for и in range(начало, len(текст)):
        с = текст[и]
        if с in "([{<":
            глубина += 1
        elif с in ")]}" or (с == ">" and текст[и - 1] != "-"):
            глубина -= 1
            if глубина == 0:
                return и
    raise ValueError(текст)


def части(текст):
    """Делит текст по запятым верхнего уровня (вне всех скобок)."""
    результат, глубина, начало = [], 0, 0
    for и, с in enumerate(текст):
        if с in "([{<":
            глубина += 1
        elif с in ")]}" or (с == ">" and текст[и - 1] != "-"):
            глубина -= 1
        elif с == "," and глубина == 0:
            результат.append(текст[начало:и].strip())
            начало = и + 1
    if текст.strip():
        результат.append(текст[начало:].strip())
    return результат


def разобрать(тип):
    тип = тип.strip()
    if тип.startswith("функ("):
        конец = _закрывающая(тип, 4)
        параметры = [разобрать(п) for п in части(тип[5:конец])]
        остаток = тип[конец + 1:].strip()
        результат = разобрать(остаток[2:]) if остаток.startswith("->") else ("имя", "пусто", [])
        return ("функ", параметры, результат)
    if тип.endswith("?") and len(тип) > 1:
        return ("необяз", разобрать(тип[:-1]))
    if тип.endswith("!") and len(тип) > 1:
        return ("результат", разобрать(тип[:-1]))
    if тип.startswith("[") and тип.endswith("]") and тип != "[]":
        return ("список", разобрать(тип[1:-1]))
    if тип.startswith("{") and тип.endswith("}") and тип != "{}":
        внутри = тип[1:-1]
        к = внутри.index(": ")
        return ("словарь", разобрать(внутри[:к]), разобрать(внутри[к + 2:]))
    if тип.endswith(">") and "<" in тип and not тип.startswith("<"):
        н = тип.index("<")
        return ("имя", тип[:н], [разобрать(а) for а in части(тип[н + 1:-1])])
    return ("имя", тип, [])


def собрать(дерево):
    вид = дерево[0]
    if вид == "имя":
        _, имя, аргументы = дерево
        return имя + ("<" + ", ".join(собрать(а) for а in аргументы) + ">" if аргументы else "")
    if вид == "список":
        return "[" + собрать(дерево[1]) + "]"
    if вид == "словарь":
        return "{" + собрать(дерево[1]) + ": " + собрать(дерево[2]) + "}"
    if вид == "необяз":
        return собрать(дерево[1]) + "?"
    if вид == "результат":
        return собрать(дерево[1]) + "!"
    _, параметры, результат = дерево
    текст = "функ(" + ", ".join(собрать(п) for п in параметры) + ")"
    результат = собрать(результат)
    return текст if результат == "пусто" else текст + " -> " + результат


def подставить(тип, связи):
    """Заменяет параметры типа их значениями: подставить("[Т]", {"Т": "цел"}) = "[цел]"."""
    if not связи:
        return тип

    def обход(д):
        вид = д[0]
        if вид == "имя":
            if д[1] in связи and not д[2]:
                return разобрать(связи[д[1]])
            return ("имя", д[1], [обход(а) for а in д[2]])
        if вид == "словарь":
            return ("словарь", обход(д[1]), обход(д[2]))
        if вид == "функ":
            return ("функ", [обход(п) for п in д[1]], обход(д[2]))
        return (вид, обход(д[1]))
    return собрать(обход(разобрать(тип)))


def имена_в_типе(тип):
    """Все имена, встречающиеся в записи типа."""
    return set(ИМЯ.findall(тип)) - {"функ"}


def содержит(тип, имена):
    return bool(имена_в_типе(тип) & set(имена))


def сопоставить(шаблон, тип, параметры, связи, объединить):
    """Находит значения параметров, при которых тип «тип» подходит к «шаблон».

    Найденное записывается в «связи». Функция «объединить(старое, новое)»
    решает, как поступить, если параметр уже имеет значение (например,
    расширить цел до дроб); она возвращает новое значение или None, если
    значения несовместимы. Возвращает False только при таком противоречии;
    прочие несовпадения типов сообщает обычная проверка аргументов."""
    return _сопоставить(разобрать(шаблон), тип, параметры, связи, объединить)


ОСОБЫЕ = ("[]", "{}", "ничего", "ошибка", "<неизвестный>", "<функция>")


def _сопоставить(ш, тип, параметры, связи, объединить):
    if тип in ОСОБЫЕ or тип.endswith("<>"):
        return True              # о параметрах ничего не известно; решит обычная проверка
    вид = ш[0]
    if вид == "имя" and ш[1] in параметры and not ш[2]:
        имя = ш[1]
        if имя in связи:
            новое = объединить(связи[имя], тип)
            if новое is None:
                return False
            связи[имя] = новое
        else:
            связи[имя] = тип
        return True
    д = разобрать(тип)
    if вид == "необяз" and д[0] != "необяз":
        return _сопоставить(ш[1], тип, параметры, связи, объединить)
    if вид == "результат" and д[0] != "результат":
        return _сопоставить(ш[1], тип, параметры, связи, объединить)
    if д[0] != вид:
        return True              # несовпадение сообщит обычная проверка аргументов
    if вид == "имя":
        if ш[1] != д[1] or len(ш[2]) != len(д[2]):
            return True
        return all(_сопоставить(а, собрать(б), параметры, связи, объединить) for а, б in zip(ш[2], д[2]))
    if вид in ("список", "необяз", "результат"):
        return _сопоставить(ш[1], собрать(д[1]), параметры, связи, объединить)
    if вид == "словарь":
        return (_сопоставить(ш[1], собрать(д[1]), параметры, связи, объединить)
                and _сопоставить(ш[2], собрать(д[2]), параметры, связи, объединить))
    if len(ш[1]) != len(д[1]):
        return True
    return (all(_сопоставить(а, собрать(б), параметры, связи, объединить) for а, б in zip(ш[1], д[1]))
            and _сопоставить(ш[2], собрать(д[2]), параметры, связи, объединить))
