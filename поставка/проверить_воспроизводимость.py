"""Проверка воспроизводимости поставки: поставка/собрать.py дважды из одного коммита даёт те же файлы.

    python поставка/проверить_воспроизводимость.py [--llama=llama-<метка>-windows-x64.zip]

Поставка собирается два раза (без установщика Inno Setup: он сам вписывает время сборки), между
сборками папка «поставка/готово» переносится в сторону. Сверяются суммы SHA256 каждого файла папки
dan и переносного архива; при расхождении печатаются различающиеся файлы и код завершения 1.
Время файлов в архиве берётся из SOURCE_DATE_EPOCH или времени последнего коммита, поэтому обе
сборки получают одно и то же время. На GitHub - задание «Воспроизводимая сборка поставки».
"""

import hashlib
import os
import shutil
import subprocess
import sys
import tempfile

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ГОТОВО = os.path.join(КОРЕНЬ, "поставка", "готово")


def суммы(папка):
    """Относительный путь (через /) -> SHA256 для всех файлов папки."""
    итог = {}
    for корень, _, файлы in os.walk(папка):
        for ф in файлы:
            путь = os.path.join(корень, ф)
            with open(путь, "rb") as фф:
                итог[os.path.relpath(путь, папка).replace(os.sep, "/")] = hashlib.sha256(фф.read()).hexdigest()
    return итог


def сравнить(первая, вторая):
    """Список различий двух словарей сумм: пустой, если сборки совпали."""
    различия = []
    for имя in sorted(set(первая) | set(вторая)):
        if имя not in первая:
            различия.append(f"только во второй сборке: {имя}")
        elif имя not in вторая:
            различия.append(f"только в первой сборке: {имя}")
        elif первая[имя] != вторая[имя]:
            различия.append(f"разное содержимое: {имя}")
    return различия


def собрать(аргументы):
    subprocess.run([sys.executable, os.path.join(КОРЕНЬ, "поставка", "собрать.py"), *аргументы,
                    "--без-установщика"], check=True, cwd=КОРЕНЬ)
    return суммы(ГОТОВО)


def main(аргументы):
    первая = собрать(аргументы)
    with tempfile.TemporaryDirectory() as сторона:
        shutil.move(ГОТОВО, os.path.join(сторона, "первая"))
        вторая = собрать(аргументы)
    различия = сравнить(первая, вторая)
    print(f"\nфайлов в поставке: {len(вторая)}, различий: {len(различия)}")
    for строка in различия:
        print("  " + строка)
    return 1 if различия else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
