class Дисплей:
    """Виртуальный дисплей Xvfb, на котором Wine показывает окна."""

    def __enter__(self):
        for номер in range(90, 99):
            if not os.path.exists(f"/tmp/.X{номер}-lock"):
                break
        self.номер = номер
        self.процесс = subprocess.Popen(["Xvfb", f":{номер}", "-screen", "0", "1024x768x24"],
                                        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        time.sleep(1)
        return f":{номер}"

    def __exit__(self, *а):
        self.процесс.terminate()
        self.процесс.wait()


@unittest.skipUnless(test_windows.ВКЛЮЧЕНО and XVFB, "нужны DAN_WINDOWS=1, MinGW, Wine и Xvfb")
class ТестыОконWindows(unittest.TestCase):
    maxDiff = None

    def test_окна_в_windows(self):
        with Дисплей() as дисплей:
            прежний = os.environ.get("DISPLAY")
            os.environ["DISPLAY"] = дисплей
            try:
                код, вывод, ош = test_windows.выполнить_в_windows(ПРОГРАММА)
            finally:
                if прежний is None:
                    del os.environ["DISPLAY"]
                else:
                    os.environ["DISPLAY"] = прежний
        self.assertEqual(код, 0, ош)
        строки = [с for с in вывод.splitlines() if с != "закрытие"]
        self.assertEqual(строки, ОЖИДАЕТСЯ)


