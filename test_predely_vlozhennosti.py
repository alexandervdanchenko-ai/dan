"""Пределы вложенности разбора (сам/разбор.dan): на глубоко вложенном тексте компилятор на Дане
отвечает сообщением об ошибке с местом, а до пределов переводит программу без остановки.

Компилятор работает в задаче со стеком 64 МБ (сам/дан.dan), поэтому пределы (400 уровней скобок
и блоков, 500 знаков действий подряд, 1000 звеньев «иначе») помещаются в стек на всех системах (раздел 2.11). Находку,
с которой это началось, дал фаззинг компилятора (fazzing.py, мишень «компилятор»).
"""

import os
import subprocess
import tempfile
import unittest

import sam_kompilyator

ПАПКА = os.path.dirname(os.path.abspath(__file__))


def выполнить(команда, текст):
    with tempfile.TemporaryDirectory() as папка:
        путь = os.path.join(папка, "п.dan")
        with open(путь, "w", encoding="utf-8") as ф:
            ф.write(текст)
        р = subprocess.run([sam_kompilyator.исполняемый(), команда, путь], capture_output=True, cwd=папка,
                           env=sam_kompilyator.среда(), timeout=600)
        return р.returncode, р.stdout.decode("utf-8", "replace"), р.stderr.decode("utf-8", "replace")


# до предела: программа переводится и выполняется (в том числе всё, что собирал компилятор 1.13)
ВЕРНЫЕ = {
    "скобки": ("пусть а = " + "(" * 399 + "1" + ")" * 399 + "\nвывод(а)\n", "1"),
    "сумма": ("пусть а = 1" + " + 1" * 499 + "\nвывод(а)\n", "500"),
    "блоки и сумма": ("функ ф() -> цел {\n" + "если истина {\n" * 150 + "вернуть 1" + " + 1" * 300 + "\n"
                      + "}\n" * 150 + "вернуть 0\n}\nвывод(ф())\n", "301"),
    # цепочка с составными условиями на одной строке: 1.13 собирал её (находка независимого разбора)
    "иначе если с условиями": ('функ ф(к: стр, б: цел) -> цел {\n    если к == "x0" и б == 0 { вернуть 0 }'
                               + "".join(f' иначе если к == "x{и}" и б == {и} {{ вернуть {и} }}' for и in range(1, 1000))
                               + '\n    вернуть -1\n}\nвывод(ф("x500", 500))\n', "500"),
    "иначе если по строкам": ("функ ф(б: цел) -> цел {\n    если б == 0 {\n        вернуть 0\n    }"
                              + "".join(f" иначе если б == {и} {{\n        вернуть {и}\n    }}" for и in range(1, 1000))
                              + "\n    вернуть -1\n}\nвывод(ф(7))\n", "7"),
    "методы": ('пусть с = " x "' + ".обрезать()" * 499 + "\nвывод(с)\n", "x"),
    "минусы": ("пусть а = " + "- " * 498 + "1\nвывод(а)\n", "1"),
}

# за пределом: сообщение об ошибке записи с местом, без ошибки выполнения компилятора
ЛИШНИЕ = {
    "скобки": ("пусть а = " + "(" * 50000 + "1" + ")" * 50000 + "\n", "Строка 1, позиция 411: скобки и блоки"),
    "блоки": ("функ ф() {\n" + "если истина {\n" * 20000 + "}\n" * 20000 + "}\n", "Строка 401, позиция 13: скобки и блоки"),
    "сумма": ("пусть а = 1" + " + 1" * 50000 + "\n", "Строка 1, позиция 2013: выражение слишком длинное"),
    "иначе если": ("если ложь {}" + " иначе если ложь {}" * 5000 + "\n", "цепочка «иначе если» слишком длинная"),
    "минусы": ("пусть а = " + "-" * 100000 + "1\n", "выражение слишком длинное"),
    "смесь": ("пусть а = " + "(1 + 1 + " * 300 + "1" + ")" * 300 + "\n", "выражение слишком длинное"),
}


class ТестыПределовВложенности(unittest.TestCase):
    def test_до_предела(self):
        for имя, (текст, вывод) in ВЕРНЫЕ.items():
            with self.subTest(имя):
                код, вых, ош = выполнить("запустить", текст)
                self.assertEqual((код, вых.strip()), (0, вывод), ош[-2000:])
                self.assertNotIn("Ошибка выполнения", ош)

    def test_за_пределом(self):
        for имя, (текст, место) in ЛИШНИЕ.items():
            with self.subTest(имя):
                код, вых, ош = выполнить("проверить", текст)
                self.assertEqual(код, 1, вых + ош)
                self.assertIn(место, вых)
                self.assertNotIn("Ошибка выполнения", вых + ош)

    def test_большие_списки_не_ограничены(self):
        # запятые и строки обнуляют цепочку: длинные списки чисел и длинные программы разрешены
        текст = "пусть а = [" + ", ".join(str(-и) for и in range(20000)) + "]\nвывод(а.длина)\n"
        код, вых, ош = выполнить("запустить", текст)
        self.assertEqual((код, вых.strip()), (0, "20000"), ош[-2000:])


if __name__ == "__main__":
    unittest.main()
