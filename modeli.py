# закреплённая версия llama.cpp (та же - в sreda/modeli.c, DAN_LLAMA_VERSION)
ВЕРСИЯ_LLAMA = "b12190"

ФУНКЦИИ = {}


def _добавить(имя, варианты, описание):
    """варианты: список (типы аргументов, тип результата, функция C, нужна ли строка)."""
    ФУНКЦИИ[имя] = {
        "варианты": [(а, р) for а, р, _, _ in варианты],
        "c": [ф for _, _, ф, _ in варианты],
        "строка": [с for _, _, _, с in варианты],
        "описание": описание,
        "модуль": "модели",
    }


_добавить("модель_загрузить", [([СТР, ЦЕЛ, ЦЕЛ, ЛОГ, ЦЕЛ], ЦЕЛ + "!", "dan_llm_load", True)],
          "загрузить модель GGUF: путь, размер контекста (0 - как в модели), число потоков (0 - как у пула "
          "Дана), отображать ли файл в память, предел памяти в МБ (0 - без предела); результат - номер модели")
_добавить("модель_освободить", [([ЦЕЛ], ПУСТО, "dan_llm_free", True)], "освободить модель по номеру")
_добавить("модель_начать", [([ЦЕЛ, СТР, ДРОБ, ЦЕЛ, ДРОБ, ЦЕЛ, ЦЕЛ, СПИСОК_СТР], ЦЕЛ + "!", "dan_llm_start", True)],
          "начать ответ модели на запрос: температура, верх_к, верх_п, зерно, наибольшее число токенов, "
          "стоп-строки; результат - сколько токенов запроса посчитано заново (остальные взяты из кэша начала)")
_добавить("модель_часть", [([ЦЕЛ], СТР + "!", "dan_llm_next", True)],
          "следующая часть ответа модели; пустая строка - ответ закончен")
_добавить("модель_чат", [([ЦЕЛ, СПИСОК_СТР, ЛОГ], СТР + "!", "dan_llm_chat", True)],
          "запрос по шаблону чата модели: роли и тексты сообщений по очереди; истина - добавить начало ответа "
          "помощника")
_добавить("модель_токенов", [([ЦЕЛ, СТР], ЦЕЛ + "!", "dan_llm_count", True)], "сколько токенов модели в тексте")
_добавить("модель_напечатать", [([СТР], ПУСТО, "dan_llm_print", False)],
          "вывести текст без перевода строки и сразу показать его (части ответа по мере появления)")

