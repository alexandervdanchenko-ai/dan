"""Лексер языка Дан (версия 0.3).

Разбивает исходный текст программы на токены - минимальные значимые
единицы: ключевые слова, имена, числа, строки, операторы и скобки.
"""

from dataclasses import dataclass
import unicodedata
from enum import Enum, auto


class Т(Enum):
    """Виды токенов."""
    ИМЯ = auto()
    КЛЮЧ = auto()
    ЦЕЛОЕ = auto()
    ДРОБНОЕ = auto()
    СТРОКА = auto()
    ЗНАК = auto()
    КОНЕЦ_СТРОКИ = auto()
    КОНЕЦ_ФАЙЛА = auto()


КЛЮЧЕВЫЕ_СЛОВА = frozenset({
    "функ", "вернуть", "пусть", "перем",
    "если", "иначе", "пока", "для", "в",
    "прервать", "продолжить",
    "и", "или", "не", "истина", "ложь",
    "тип", "ничего", "выбор", "подключить", "как", "общий",
})

# Сначала двухсимвольные знаки, чтобы "<=" не разобрался как "<" и "=".
ДВОЙНЫЕ_ЗНАКИ = ("==", "!=", "<=", ">=", "+=", "-=", "*=", "/=", "->", "..")
ОДИНОЧНЫЕ_ЗНАКИ = "+-*/%<>=:,.(){}[]^?!"

# Школьная запись действий (как в учебниках): заменяется на основную.
МАТЕМАТИЧЕСКИЕ_ЗНАКИ = {
    "×": "*", "·": "*", "÷": "/", "−": "-",
    "≤": "<=", "≥": ">=", "≠": "!=",
}

# Надстрочные цифры степени: х² означает х ^ 2.
НАДСТРОЧНЫЕ = {"²": 2, "³": 3}

ПОСЛЕДОВАТЕЛЬНОСТИ = {"n": "\n", "t": "\t", '"': '"', "\\": "\\"}

# Символы управления направлением текста. На экране они переставляют части
# строки, поэтому человек видит не тот текст, который читает компилятор
# (атака Trojan Source, CVE-2021-42574). Запрещены везде, включая строки
# и комментарии.
СИМВОЛЫ_НАПРАВЛЕНИЯ = {
    "؜": "арабский знак направления",
    "‎": "знак направления слева направо",
    "‏": "знак направления справа налево",
    "‪": "встраивание слева направо",
    "‫": "встраивание справа налево",
    "‬": "конец встраивания или смены направления",
    "‭": "смена направления на слева направо",
    "‮": "смена направления на справа налево",
    "⁦": "изоляция слева направо",
    "⁧": "изоляция справа налево",
    "⁨": "изоляция по первому сильному символу",
    "⁩": "конец изоляции",
}

# Прочие невидимые символы, которые в тексте программы легко не заметить.
НЕВИДИМЫЕ_СИМВОЛЫ = {
    " ": "неразрывный пробел",
    "­": "мягкий перенос",
    "​": "пробел нулевой ширины",
    "‌": "разделитель нулевой ширины",
    "‍": "соединитель нулевой ширины",
    "⁠": "соединитель слов",
    "﻿": "метка порядка байтов",
}


def описание_символа(с):
    """Видимое описание символа для сообщения об ошибке."""
    код = f"U+{ord(с):04X}"
    название = СИМВОЛЫ_НАПРАВЛЕНИЯ.get(с) or НЕВИДИМЫЕ_СИМВОЛЫ.get(с)
    if название:
        return f"невидимый символ {код} ({название})"
    if not с.isprintable() or unicodedata.category(с) in ("Cf", "Zs", "Zl", "Zp"):
        return f"невидимый символ {код}"
    return f"символ «{с}» ({код})"


@dataclass(frozen=True)
class Токен:
    вид: Т
    значение: object
    строка: int
    столбец: int
    написание: str = None      # имя так, как оно написано (с «ё»), для вывода

    def __repr__(self):
        return f"{self.вид.name}({self.значение!r}) {self.строка}:{self.столбец}"


class ОшибкаЛексера(Exception):
    def __init__(self, сообщение, строка, столбец):
        super().__init__(f"Строка {строка}, позиция {столбец}: {сообщение}")
        self.строка = строка
        self.столбец = столбец


def _буква(с):
    return с.isalpha() or с == "_"


ЦИФРЫ = "0123456789"


def _цифра(с):
    return с != "" and с in ЦИФРЫ


def _буква_или_цифра(с):
    return с.isalpha() or _цифра(с) or с == "_"


def без_ё(слово):
    return слово.replace("ё", "е").replace("Ё", "Е")


НАЗВАНИЯ_АЛФАВИТОВ = {"CYRILLIC": "русские", "LATIN": "латинские", "GREEK": "греческие"}
НАЗВАНИЯ_БУКВ = {"CYRILLIC": "русская", "LATIN": "латинская", "GREEK": "греческая"}


def _алфавит(с):
    """Алфавит буквы: CYRILLIC, LATIN, GREEK и т.д.; для цифр и «_» - None."""
    if not с.isalpha():
        return None
    try:
        return unicodedata.name(с).split()[0]
    except ValueError:
        return None


def смешение_алфавитов(слово):
    """Если внутри одной части имени буквы разных алфавитов, вернуть описание
    ошибки, иначе None.

    Буквы «с» и «c», «о» и «o», «р» и «p» выглядят одинаково, но для
    компьютера это разные знаки. Такая опечатка порождает две разные
    переменные с одинаковыми на вид именами, поэтому внутри слова смешение
    запрещено. Части имени, разделённые «_» или цифрами, могут быть написаны
    разными алфавитами: «сжать_gzip», «хеш_sha256».
    """
    часть = []          # (номер буквы в имени, буква) текущей части
    for номер, с in enumerate(слово + "_", 1):
        if _алфавит(с):
            часть.append((номер, с))
            continue
        ошибка = _смешение_в_части(слово, часть)
        if ошибка:
            return ошибка
        часть = []
    return None


def _смешение_в_части(слово, часть):
    счёт = {}
    for _, с in часть:
        а = _алфавит(с)
        счёт[а] = счёт.get(а, 0) + 1
    if len(счёт) < 2:
        return None
    основной = max(счёт, key=lambda а: (счёт[а], а == "CYRILLIC"))
    чужие = [f"«{с}» ({номер}-я буква, {НАЗВАНИЯ_БУКВ.get(_алфавит(с), _алфавит(с).lower())})"
             for номер, с in часть if _алфавит(с) != основной]
    вид = НАЗВАНИЯ_АЛФАВИТОВ.get(основной, основной.lower())
    return (f"в имени «{слово}» смешаны буквы разных алфавитов: " + ", ".join(чужие)
            + f"; остальные буквы {вид}. Вероятно, включена не та раскладка клавиатуры")


class Лексер:
    def __init__(self, текст):
        # Блокнот Windows может сохранить UTF-8 с меткой порядка байтов в
        # начале файла; она не относится к тексту программы.
        if текст.startswith("﻿"):
            текст = текст[1:]
        self.текст = текст
        self.поз = 0
        self.строка = 1
        self.столбец = 1
        self.глубина_скобок = 0  # внутри ( ) и [ ] перевод строки игнорируется
        self.токены = []

    # --- вспомогательные методы ---

    def _тек(self, смещение=0):
        и = self.поз + смещение
        return self.текст[и] if и < len(self.текст) else ""

    def _шаг(self):
        с = self.текст[self.поз]
        self.поз += 1
        if с == "\n":
            self.строка += 1
            self.столбец = 1
        else:
            self.столбец += 1
        return с

    def _добавить(self, вид, значение, строка, столбец):
        self.токены.append(Токен(вид, значение, строка, столбец))

    def _ошибка(self, сообщение, строка=None, столбец=None):
        raise ОшибкаЛексера(сообщение, строка or self.строка, столбец or self.столбец)

    # --- основной цикл ---

    def _проверить_направление(self):
        """Ищет символы управления направлением во всём тексте до разбора."""
        строка, столбец = 1, 1
        for с in self.текст:
            if с in СИМВОЛЫ_НАПРАВЛЕНИЯ:
                self._ошибка(f"{описание_символа(с)}: такие символы меняют порядок "
                             "показа текста на экране и позволяют скрыть настоящий "
                             "смысл программы; удалите его", строка, столбец)
            if с == "\n":
                строка, столбец = строка + 1, 1
            else:
                столбец += 1

    def разобрать(self):
        self._проверить_направление()
        while self.поз < len(self.текст):
            с = self._тек()

            if с in " \t\r":
                self._шаг()
            elif с == "\n":
                стр, стлб = self.строка, self.столбец
                self._шаг()
                self._конец_строки(стр, стлб)
            elif с == "/" and self._тек(1) == "/":
                while self.поз < len(self.текст) and self._тек() != "\n":
                    self._шаг()
            elif _цифра(с):
                self._число()
            elif _буква(с):
                self._слово()
            elif с == '"':
                self._строка()
            else:
                self._знак()

        self._конец_строки(self.строка, self.столбец)
        self._добавить(Т.КОНЕЦ_ФАЙЛА, None, self.строка, self.столбец)
        return self.токены

    def _конец_строки(self, строка, столбец):
        # Не добавляем, если внутри скобок, в начале файла или подряд.
        if self.глубина_скобок > 0:
            return
        if not self.токены or self.токены[-1].вид == Т.КОНЕЦ_СТРОКИ:
            return
        self._добавить(Т.КОНЕЦ_СТРОКИ, None, строка, столбец)

    def _число(self):
        стр, стлб = self.строка, self.столбец
        цифры = []
        дробное = False

        def читать_цифры():
            while True:
                с = self._тек()
                if _цифра(с):
                    цифры.append(self._шаг())
                elif с == "_" and _цифра(self._тек(1)) and цифры and цифры[-1].isdigit():
                    self._шаг()
                else:
                    break

        читать_цифры()
        # Точка - часть дроби, только если за ней цифра и это не "..".
        if self._тек() == "." and _цифра(self._тек(1)):
            дробное = True
            цифры.append(self._шаг())
            читать_цифры()

        if _буква(self._тек()):
            self._ошибка("число не может переходить в имя без пробела", стр, стлб)

        запись = "".join(цифры)
        if дробное:
            self._добавить(Т.ДРОБНОЕ, float(запись), стр, стлб)
        else:
            self._добавить(Т.ЦЕЛОЕ, int(запись), стр, стлб)

    def _слово(self):
        стр, стлб = self.строка, self.столбец
        буквы = []
        while self._тек() and _буква_или_цифра(self._тек()):
            буквы.append(self._шаг())
        слово = написание = "".join(буквы)
        ошибка = смешение_алфавитов(слово)
        if ошибка:
            self._ошибка(ошибка, стр, стлб)
        # «е» и «ё» в именах равнозначны, как в обычном письме:
        # «счётчик» и «счетчик» - одна и та же переменная.
        слово = без_ё(слово)
        вид = Т.КЛЮЧ if слово in КЛЮЧЕВЫЕ_СЛОВА else Т.ИМЯ
        self.токены.append(Токен(вид, слово, стр, стлб, написание))

    def _строка(self):
        стр, стлб = self.строка, self.столбец
        self._шаг()  # открывающая кавычка
        символы = []
        while True:
            с = self._тек()
            if с == "" or с == "\n":
                self._ошибка("строка не закрыта кавычкой", стр, стлб)
            if с == '"':
                self._шаг()
                break
            if с == "\\":
                self._шаг()
                след = self._тек()
                if след not in ПОСЛЕДОВАТЕЛЬНОСТИ:
                    self._ошибка(f"неизвестная последовательность \\{след}")
                self._шаг()
                символы.append(ПОСЛЕДОВАТЕЛЬНОСТИ[след])
            else:
                символы.append(self._шаг())
        self._добавить(Т.СТРОКА, "".join(символы), стр, стлб)

    def _знак(self):
        стр, стлб = self.строка, self.столбец
        пара = self._тек() + self._тек(1)
        if пара in ДВОЙНЫЕ_ЗНАКИ:
            self._шаг()
            self._шаг()
            self._добавить(Т.ЗНАК, пара, стр, стлб)
            return
        с = self._тек()
        if с in НАДСТРОЧНЫЕ:
            self._шаг()
            self._добавить(Т.ЗНАК, "^", стр, стлб)
            self._добавить(Т.ЦЕЛОЕ, НАДСТРОЧНЫЕ[с], стр, стлб)
            return
        if с in МАТЕМАТИЧЕСКИЕ_ЗНАКИ:
            self._шаг()
            self._добавить(Т.ЗНАК, МАТЕМАТИЧЕСКИЕ_ЗНАКИ[с], стр, стлб)
            return
        if с in ОДИНОЧНЫЕ_ЗНАКИ:
            self._шаг()
            if с in "([":
                self.глубина_скобок += 1
            elif с in ")]":
                if self.глубина_скобок == 0:
                    self._ошибка(f"лишняя закрывающая скобка «{с}»", стр, стлб)
                self.глубина_скобок -= 1
            self._добавить(Т.ЗНАК, с, стр, стлб)
            return
        self._ошибка(f"недопустимый {описание_символа(с)}", стр, стлб)


def разобрать(текст):
    """Возвращает список токенов для текста программы."""
    return Лексер(текст).разобрать()


if __name__ == "__main__":
    import sys
    if len(sys.argv) != 2:
        print("Использование: python lexer.py программа.dan")
        sys.exit(1)
    with open(sys.argv[1], encoding="utf-8") as ф:
        исходник = ф.read()
    try:
        for т in разобрать(исходник):
            print(т)
    except ОшибкаЛексера as о:
        print(f"Ошибка: {о}")
        sys.exit(1)
