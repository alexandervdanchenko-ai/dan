"""Лексер языка Дан (версия 0.3).

Разбивает исходный текст программы на токены - минимальные значимые
единицы: ключевые слова, имена, числа, строки, операторы и скобки.
"""

from dataclasses import dataclass
from enum import Enum, auto


class Т(Enum):
    """Виды токенов."""
    ИМЯ = auto()
    КЛЮЧ = auto()
    ЦЕЛОЕ = auto()
    ДРОБНОЕ = auto()
    СТРОКА = auto()
    ЗНАК = auto()
    КОНЕЦ_СТРОКИ = auto()
    КОНЕЦ_ФАЙЛА = auto()


КЛЮЧЕВЫЕ_СЛОВА = frozenset({
    "функ", "вернуть", "пусть", "перем",
    "если", "иначе", "пока", "для", "в",
    "прервать", "продолжить",
    "и", "или", "не", "истина", "ложь",
})

# Сначала двухсимвольные знаки, чтобы "<=" не разобрался как "<" и "=".
ДВОЙНЫЕ_ЗНАКИ = ("==", "!=", "<=", ">=", "+=", "-=", "*=", "/=", "->", "..")
ОДИНОЧНЫЕ_ЗНАКИ = "+-*/%<>=:,.(){}[]"

# Школьная запись действий (как в учебниках): заменяется на основную.
МАТЕМАТИЧЕСКИЕ_ЗНАКИ = {
    "×": "*", "·": "*", "÷": "/", "−": "-",
    "≤": "<=", "≥": ">=", "≠": "!=",
}

ПОСЛЕДОВАТЕЛЬНОСТИ = {"n": "\n", "t": "\t", '"': '"', "\\": "\\"}


@dataclass(frozen=True)
class Токен:
    вид: Т
    значение: object
    строка: int
    столбец: int

    def __repr__(self):
        return f"{self.вид.name}({self.значение!r}) {self.строка}:{self.столбец}"


class ОшибкаЛексера(Exception):
    def __init__(self, сообщение, строка, столбец):
        super().__init__(f"Строка {строка}, позиция {столбец}: {сообщение}")
        self.строка = строка
        self.столбец = столбец


def _буква(с):
    return с.isalpha() or с == "_"


def _буква_или_цифра(с):
    return с.isalnum() or с == "_"


class Лексер:
    def __init__(self, текст):
        self.текст = текст
        self.поз = 0
        self.строка = 1
        self.столбец = 1
        self.глубина_скобок = 0  # внутри ( ) и [ ] перевод строки игнорируется
        self.токены = []

    # --- вспомогательные методы ---

    def _тек(self, смещение=0):
        и = self.поз + смещение
        return self.текст[и] if и < len(self.текст) else ""

    def _шаг(self):
        с = self.текст[self.поз]
        self.поз += 1
        if с == "\n":
            self.строка += 1
            self.столбец = 1
        else:
            self.столбец += 1
        return с

    def _добавить(self, вид, значение, строка, столбец):
        self.токены.append(Токен(вид, значение, строка, столбец))

    def _ошибка(self, сообщение, строка=None, столбец=None):
        raise ОшибкаЛексера(сообщение, строка or self.строка, столбец or self.столбец)

    # --- основной цикл ---

    def разобрать(self):
        while self.поз < len(self.текст):
            с = self._тек()

            if с in " \t\r":
                self._шаг()
            elif с == "\n":
                стр, стлб = self.строка, self.столбец
                self._шаг()
                self._конец_строки(стр, стлб)
            elif с == "/" and self._тек(1) == "/":
                while self.поз < len(self.текст) and self._тек() != "\n":
                    self._шаг()
            elif с.isdigit():
                self._число()
            elif _буква(с):
                self._слово()
            elif с == '"':
                self._строка()
            else:
                self._знак()

        self._конец_строки(self.строка, self.столбец)
        self._добавить(Т.КОНЕЦ_ФАЙЛА, None, self.строка, self.столбец)
        return self.токены

    def _конец_строки(self, строка, столбец):
        # Не добавляем, если внутри скобок, в начале файла или подряд.
        if self.глубина_скобок > 0:
            return
        if not self.токены or self.токены[-1].вид == Т.КОНЕЦ_СТРОКИ:
            return
        self._добавить(Т.КОНЕЦ_СТРОКИ, None, строка, столбец)

    def _число(self):
        стр, стлб = self.строка, self.столбец
        цифры = []
        дробное = False

        def читать_цифры():
            while True:
                с = self._тек()
                if с.isdigit():
                    цифры.append(self._шаг())
                elif с == "_" and self._тек(1).isdigit() and цифры and цифры[-1].isdigit():
                    self._шаг()
                else:
                    break

        читать_цифры()
        # Точка - часть дроби, только если за ней цифра и это не "..".
        if self._тек() == "." and self._тек(1).isdigit():
            дробное = True
            цифры.append(self._шаг())
            читать_цифры()

        if _буква(self._тек()):
            self._ошибка("число не может переходить в имя без пробела", стр, стлб)

        запись = "".join(цифры)
        if дробное:
            self._добавить(Т.ДРОБНОЕ, float(запись), стр, стлб)
        else:
            self._добавить(Т.ЦЕЛОЕ, int(запись), стр, стлб)

    def _слово(self):
        стр, стлб = self.строка, self.столбец
        буквы = []
        while self._тек() and _буква_или_цифра(self._тек()):
            буквы.append(self._шаг())
        слово = "".join(буквы)
        вид = Т.КЛЮЧ if слово in КЛЮЧЕВЫЕ_СЛОВА else Т.ИМЯ
        self._добавить(вид, слово, стр, стлб)

    def _строка(self):
        стр, стлб = self.строка, self.столбец
        self._шаг()  # открывающая кавычка
        символы = []
        while True:
            с = self._тек()
            if с == "" or с == "\n":
                self._ошибка("строка не закрыта кавычкой", стр, стлб)
            if с == '"':
                self._шаг()
                break
            if с == "\\":
                self._шаг()
                след = self._тек()
                if след not in ПОСЛЕДОВАТЕЛЬНОСТИ:
                    self._ошибка(f"неизвестная последовательность \\{след}")
                self._шаг()
                символы.append(ПОСЛЕДОВАТЕЛЬНОСТИ[след])
            else:
                символы.append(self._шаг())
        self._добавить(Т.СТРОКА, "".join(символы), стр, стлб)

    def _знак(self):
        стр, стлб = self.строка, self.столбец
        пара = self._тек() + self._тек(1)
        if пара in ДВОЙНЫЕ_ЗНАКИ:
            self._шаг()
            self._шаг()
            self._добавить(Т.ЗНАК, пара, стр, стлб)
            return
        с = self._тек()
        if с in МАТЕМАТИЧЕСКИЕ_ЗНАКИ:
            self._шаг()
            self._добавить(Т.ЗНАК, МАТЕМАТИЧЕСКИЕ_ЗНАКИ[с], стр, стлб)
            return
        if с in ОДИНОЧНЫЕ_ЗНАКИ:
            self._шаг()
            if с in "([":
                self.глубина_скобок += 1
            elif с in ")]":
                if self.глубина_скобок == 0:
                    self._ошибка(f"лишняя закрывающая скобка «{с}»", стр, стлб)
                self.глубина_скобок -= 1
            self._добавить(Т.ЗНАК, с, стр, стлб)
            return
        self._ошибка(f"недопустимый символ «{с}»", стр, стлб)


def разобрать(текст):
    """Возвращает список токенов для текста программы."""
    return Лексер(текст).разобрать()


if __name__ == "__main__":
    import sys
    if len(sys.argv) != 2:
        print("Использование: python lexer.py программа.dan")
        sys.exit(1)
    with open(sys.argv[1], encoding="utf-8") as ф:
        исходник = ф.read()
    try:
        for т in разобрать(исходник):
            print(т)
    except ОшибкаЛексера as о:
        print(f"Ошибка: {о}")
        sys.exit(1)
