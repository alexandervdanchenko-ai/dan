"""Форматирование программ на Дане: единый вид текста.

    python dan.py формат программа.dan             - привести файл к единому виду
    python dan.py формат программа.dan --проверить - только проверить, ничего не меняя

Правила: отступ - четыре пробела на каждый уровень вложенности фигурных,
круглых и квадратных скобок; вокруг знаков действий, сравнения и
присваивания - по одному пробелу (кроме унарного минуса: -5); после запятой
- пробел, перед ней - нет; внутри круглых и квадратных скобок, а также
фигурных скобок словаря у краёв пробелов нет, а у фигурных скобок блока -
есть: «{ вернуть х }»; пробелы в конце строк удаляются; подряд не больше
одной пустой строки; файл оканчивается одним переводом строки.

Знаки «<» и «>» бывают и сравнением (а < б), и скобками типа (Пара<цел, стр>):
скобками они считаются, если перед «<» стоит имя, а до парной «>» - только
имена типов и знаки записи типов. Сохраняются как есть: комментарии и
пробелы перед комментарием в конце строки (ими выравнивают комментарии);
написание слов, чисел и строк («ё», «×», «х²», 1_000_000); пробел перед
двоеточием (оно бывает и в записи типа «х: цел», и школьным знаком деления
«6 : 3»).

Форматирование меняет только пробелы и переводы строк, поэтому смысл
программы не меняется: это проверяется сравнением токенов до и после.
Если в программе есть ошибка записи (незакрытая строка, лишняя скобка),
файл не форматируется.
"""

from collections import namedtuple

import lexer
from lexer import Т, КЛЮЧЕВЫЕ_СЛОВА, без_ё

ОТСТУП = "    "
ОТКРЫВАЮЩИЕ = "([{"
ЗАКРЫВАЮЩИЕ = ")]}"

Часть = namedtuple("Часть", "вид текст пробел начало конец")


class ОшибкаФорматирования(Exception):
    pass


def _части(строка):
    """Строка исходного текста -> список частей: слово, число, строка, знак, комментарий."""
    итог, н, пробел = [], 0, False
    while н < len(строка):
        с = строка[н]
        if с in " \t\r":
            пробел = True
            н += 1
            continue
        начало = н
        if строка.startswith("//", н):
            итог.append(Часть("комментарий", строка[н:].rstrip(), пробел, н, len(строка)))
            break
        if с == '"':
            к = н + 1
            while к < len(строка) and строка[к] != '"':
                к += 2 if строка[к] == "\\" else 1
            н = к + 1
            вид = "строка"
        elif с in "0123456789":
            к = н
            while к < len(строка) and (строка[к] in "0123456789" or строка[к] == "_" or
                                       (строка[к] == "." and к + 1 < len(строка) and строка[к + 1].isdigit()
                                        and not строка.startswith("..", к))):
                к += 1
            # порядок числа: 1e30, 1.5е-7
            if к < len(строка) and строка[к] in "eEеЕ":
                д = к + 1
                if д < len(строка) and строка[д] in "+-":
                    д += 1
                if д < len(строка) and строка[д] in "0123456789":
                    к = д
                    while к < len(строка) and строка[к] in "0123456789":
                        к += 1
            н = к
            вид = "число"
        elif с.isalpha() or с == "_":
            к = н
            while к < len(строка) and (строка[к].isalnum() or строка[к] == "_") and строка[к] not in "²³":
                к += 1
            н = к
            вид = "слово"
        else:
            н += 2 if строка[н:н + 2] in lexer.ДВОЙНЫЕ_ЗНАКИ else 1
            вид = "знак"
        итог.append(Часть(вид, строка[начало:н], пробел, начало, н))
        пробел = False
    return итог


def _ключевое(часть):
    return часть.вид == "слово" and без_ё(часть.текст) in КЛЮЧЕВЫЕ_СЛОВА


def _начало_выражения(предыдущая):
    """Начинается ли после этой части новое выражение (тогда «-» - унарный минус)."""
    if предыдущая is None:
        return True
    if предыдущая.вид == "знак":
        return предыдущая.текст not in (")", "]", "}", "?", "!", "²", "³")
    return _ключевое(предыдущая) and без_ё(предыдущая.текст) not in ("истина", "ложь", "ничего")


def _словарная(предыдущая):
    """Открывает ли «{» после этой части словарь или тип словаря (а не блок)."""
    if предыдущая is None:
        return False
    if предыдущая.вид == "знак":
        return предыдущая.текст in (":", "=", "(", ",", "[", "{", "->", "+", "==", "!=", "+=", "<")
    return предыдущая.вид == "слово" and без_ё(предыдущая.текст) == "вернуть"


def _угловые_скобки(части):
    """Номера частей «<» и «>», которые служат скобками типа (Пара<цел, стр>), а не сравнением.

    «<» - скобка, если перед ним имя и до парной «>» в той же строке стоят только
    имена типов, запятые, двоеточия, скобки, «?», «!», «->» и «и» после двоеточия
    (ограничения: <Т: Сравнимое и Ключ>)."""
    скобки = set()
    for н, ч in enumerate(части):
        if not (ч.вид == "знак" and ч.текст == "<" and н > 0 and части[н - 1].вид == "слово"
                and not _ключевое(части[н - 1])):
            continue
        глубина, было_двоеточие, к = 1, False, н + 1
        while к < len(части):
            т = части[к]
            if т.вид == "знак" and т.текст == "<":
                глубина += 1
            elif т.вид == "знак" and т.текст == ">":
                глубина -= 1
                if глубина == 0:
                    break
            elif т.вид == "знак" and т.текст == ":":
                было_двоеточие = True
            elif т.вид == "слово" and _ключевое(т) and not (без_ё(т.текст) in ("и", "функ") and (было_двоеточие or без_ё(т.текст) == "функ")):
                break
            elif т.вид not in ("слово", "знак") or (т.вид == "знак" and т.текст not in
                                                        (",", ":", "[", "]", "{", "}", "?", "!", "(", ")", "->", ".")):
                break
            к += 1
        if к < len(части) and глубина == 0:
            скобки.update((н, к))
    return скобки


def _собрать(части, скобки):
    """Части одной строки (без комментария) -> текст с нормализованными пробелами.

    «скобки» - стек видов открытых фигурных скобок («блок» или «словарь»),
    общий для всех строк файла: словарь может занимать несколько строк."""
    вывод = []
    унарные = set()
    вид_открытой = {}
    угловые = _угловые_скобки(части)
    for н, ч in enumerate(части):
        пред = части[н - 1] if н > 0 else None
        if ч.вид == "знак" and ч.текст in ("-", "−") and _начало_выражения(пред):
            унарные.add(н)
        закрыта = None
        if ч.вид == "знак" and ч.текст == "{":
            вид_открытой[н] = "словарь" if _словарная(пред) else "блок"
            скобки.append(вид_открытой[н])
        elif ч.вид == "знак" and ч.текст == "}":
            закрыта = скобки.pop() if скобки else "блок"
        if пред is None:
            вывод.append(ч.текст)
            continue
        if ч.вид == "знак" and ч.текст in (",", ")", "]", ".", "?", "..", "²", "³", "№"):
            нужен = False
        elif пред.вид == "знак" and пред.текст == "№":
            нужен = False                                  # оценки№0: номер прилегает с обеих сторон
        elif ч.вид == "знак" and ч.текст == "!" and not ч.пробел:
            нужен = False                                  # ф()! - передать ошибку
        elif ч.вид == "знак" and ч.текст == ":":
            нужен = ч.пробел
        elif пред.вид == "знак" and пред.текст in ("(", "[", ".", ".."):
            нужен = False
        elif н - 1 in унарные:
            нужен = False
        elif закрыта == "словарь":
            нужен = False
        elif н - 1 in вид_открытой and вид_открытой[н - 1] == "словарь":
            нужен = False
        elif пред.вид == "знак" and пред.текст == "{" and ч.текст == "}":
            нужен = False                                  # {} - пустой блок или словарь
        elif ч.вид == "знак" and ч.текст in ("(", "["):
            # вызов и индекс прилегают к имени: ф(х), с[0], (а)(б); «если (а)» - через пробел
            прилегает = (пред.вид == "слово" and (not _ключевое(пред) or без_ё(пред.текст) == "функ")) \
                or пред.вид == "строка" \
                or (пред.вид == "знак" and пред.текст in (")", "]", "?", "!")) \
                or (пред.вид == "знак" and пред.текст == ">" and not ч.пробел)
            нужен = not прилегает
        elif н in угловые or н - 1 in угловые and пред.текст == "<":
            нужен = False                                  # Пара<цел, стр>: скобки типа без пробелов
        elif н - 1 in угловые and пред.текст == ">":
            нужен = ч.вид != "знак" or ч.текст not in ("(", "?", "!", ")", "]", ",", ">")
        else:
            нужен = True
        вывод.append((" " if нужен else "") + ч.текст)
    return "".join(вывод)


def отформатировать(текст):
    """Текст программы в едином виде. Ошибка записи - ОшибкаФорматирования."""
    try:
        исходные = lexer.разобрать(текст)
    except lexer.ОшибкаЛексера as о:
        raise ОшибкаФорматирования(str(о)) from None
    итог, пустых, скобки = [], 0, []
    открытые = []          # номера строк, в которых открыты ещё не закрытые скобки
    виды = []              # виды этих скобок: ( [ {
    блоки = []             # исходные отступы строк, открывших блок двоеточием в конце
    отступ_блоков = 0
    for номер, исходная in enumerate(текст.replace("\r\n", "\n").replace("\r", "\n").split("\n")):
        части = _части(исходная)
        if not части:
            пустых += 1
            continue
        if итог and пустых:
            итог.append("")
        пустых = 0
        код = [ч for ч in части if ч.вид != "комментарий"]
        комментарий = [ч for ч in части if ч.вид == "комментарий"]
        # отступ - число строк с незакрытыми скобками: «json.Объект({» на одной строке даёт один уровень
        закрывающих_в_начале = 0
        for ч in код:
            if ч.вид == "знак" and ч.текст in ЗАКРЫВАЮЩИЕ:
                закрывающих_в_начале += 1
            else:
                break
        # блоки двоеточием закрываются строкой с отступом не больше, чем у открывшей строки
        продолжение = bool(виды) and виды[-1] in "(["
        if not продолжение and код:
            исходный = len(исходная) - len(исходная.lstrip(" \t")) + 3 * исходная[:len(исходная) - len(исходная.lstrip(" \t"))].count("\t")
            while блоки and исходный <= блоки[-1][0]:
                блоки.pop()
        остаются = открытые[:max(0, len(открытые) - закрывающих_в_начале)]
        отступ = len(set(остаются)) + len(блоки)
        строка = _собрать(код, скобки)
        if комментарий:
            if код:
                # пробелы перед комментарием в конце строки сохраняются: ими выравнивают комментарии
                строка += " " * max(1, комментарий[0].начало - код[-1].конец) + комментарий[0].текст
            else:
                строка = комментарий[0].текст
        итог.append(ОТСТУП * отступ + строка)
        for ч in код:
            if ч.вид == "знак" and ч.текст in ОТКРЫВАЮЩИЕ:
                открытые.append(номер)
                виды.append(ч.текст)
            elif ч.вид == "знак" and ч.текст in ЗАКРЫВАЮЩИЕ and открытые:
                открытые.pop()
                виды.pop()
        if код and код[-1].вид == "знак" and код[-1].текст == ":" and not (виды and виды[-1] in "(["):
            исходный = len(исходная) - len(исходная.lstrip(" \t")) + 3 * исходная[:len(исходная) - len(исходная.lstrip(" \t"))].count("\t")
            if not продолжение:
                блоки.append((исходный, номер))
    while итог and итог[-1] == "":
        итог.pop()
    новый = "\n".join(итог) + "\n" if итог else ""
    # проверка: изменились только пробелы и переводы строк
    try:
        новые = lexer.разобрать(новый)
    except lexer.ОшибкаЛексера as о:
        raise ОшибкаФорматирования(f"внутренняя ошибка форматирования: {о}") from None
    if [(т.вид, т.значение) for т in новые if т.вид != Т.КОНЕЦ_СТРОКИ] != \
            [(т.вид, т.значение) for т in исходные if т.вид != Т.КОНЕЦ_СТРОКИ]:
        raise ОшибкаФорматирования("внутренняя ошибка форматирования: изменился смысл программы; "
                                   "файл оставлен без изменений")
    return новый
