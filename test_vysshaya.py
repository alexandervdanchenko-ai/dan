    def test_статистика_сверка(self):
        данные = [2, 4, 4, 4, 5, 5, 7, 9]
        вывод = self.строки(f"вывод(дисперсия({данные}))\nвывод(дисперсия_выборки({данные}))\n"
                            f"вывод(стандартное_отклонение({данные}))\n"
                            "вывод(корреляция([1, 2, 3, 4], [2, 4, 5, 9]))\n"
                            "вывод(линейная_регрессия([1, 2, 3], [2, 4, 6]))\nвывод(энтропия([0.5, 0.25, 0.25]))")
        среднее = Fraction(sum(данные), len(данные))
        дисп = sum((Fraction(х) - среднее) ** 2 for х in данные) / len(данные)
        self.assertEqual(дробь(вывод[0]), дисп)
        self.assertEqual(дробь(вывод[1]), дисп * len(данные) / (len(данные) - 1))
        self.assertEqual(вывод[2], "2.0")
        х, у = [1, 2, 3, 4], [2, 4, 5, 9]
        мх, му = sum(х) / 4, sum(у) / 4
        r = sum((a - мх) * (b - му) for a, b in zip(х, у)) / math.sqrt(
            sum((a - мх) ** 2 for a in х) * sum((b - му) ** 2 for b in у))
        self.assertAlmostEqual(float(вывод[3]), r, places=14)
        self.assertEqual(вывод[4:], ["[2.0, 0.0]", "1.5"])

