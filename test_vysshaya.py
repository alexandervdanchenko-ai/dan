def _определитель(м):
    м = [с[:] for с in м]
    н, знак, р = len(м), 1, Fraction(1)
    for к in range(н):
        опорная = next((и for и in range(к, н) if м[и][к] != 0), None)
        if опорная is None:
            return Fraction(0)
        if опорная != к:
            м[к], м[опорная] = м[опорная], м[к]
            знак = -знак
        р *= м[к][к]
        for и in range(к + 1, н):
            ф = м[и][к] / м[к][к]
            м[и] = [а - ф * б for а, б in zip(м[и], м[к])]
    return знак * р


