    def вывод(self, текст, ожидается):
        код, вывод, ошибки_ = выполнить(текст)
        self.assertEqual(код, 0, ошибки_)
        self.assertEqual(вывод.splitlines(), ожидается)

    def строки(self, текст):
        код, вывод, ошибки_ = выполнить(текст)
        self.assertEqual(код, 0, ошибки_)
        return вывод.splitlines()

    def ошибка(self, текст, фрагмент):
        код, _, ошибки_ = выполнить(текст)
        self.assertEqual(код, 1)
        self.assertIn(фрагмент, ошибки_)

