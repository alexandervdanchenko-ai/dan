    def test_обычные_углы_совпадают_с_библиотекой_c(self):
        углы = [0.1, 1.0, 2.5, -3.7, 10.0]
        вывод = self.строки("\n".join(f"вывод(синус({у}))\nвывод(косинус({у}))\nвывод(тангенс({у}))"
                                      for у in углы))
        ожидается = []
        for у in углы:
            ожидается += [math.sin(у), math.cos(у), math.tan(у)]
        # компиляторы C вправе разойтись с библиотекой Python на единицу последнего знака
        for полученное, нужное in zip(вывод, ожидается):
            self.assertLessEqual(abs(float(полученное) - нужное), math.ulp(нужное), (полученное, нужное))

