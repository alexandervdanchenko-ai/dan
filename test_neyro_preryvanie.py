def разобрать(вывод_):
    итог = {}
    for строка in вывод_.replace("\r\n", "\n").splitlines():
        if "=" in строка:
            ключ, значение = строка.split("=", 1)
            итог.setdefault(ключ, []).append(значение)
    return итог


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыПрерывания(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        Общее.подготовить()

    def проверить_вывод(self, о, повторов, максимум, случаев):
        обычный = о["обычный"][0]
        токенов_запроса = int(о["токенов_запроса"][0])
        if повторов > 30:
            self.assertGreater(токенов_запроса, 256)      # запрос подаётся несколькими пакетами
        self.assertEqual(о["шаги"][0], обычный)
        причина, вызовов, в_кэше, порождено = о["шаги_итог"][0].split()
        пакетов = (токенов_запроса + 255) // 256
        if причина == "предел":
            self.assertEqual(int(порождено), максимум)
            # шаг на пакет запроса и на каждый токен ответа, ещё один вызов узнаёт о пределе
            self.assertEqual(int(вызовов), пакетов + максимум + 1)
            # кэш ровно соответствует запросу и выданным токенам
            self.assertEqual(int(в_кэше), токенов_запроса + максимум)
        else:
            self.assertEqual(причина, "конец")
            self.assertEqual(int(в_кэше), токенов_запроса + int(порождено) - 1)
        self.assertEqual(о["после_конца"][0], причина + " " + в_кэше)
        прерван, _ = о["прерван"][0].split()
        self.assertEqual(прерван, "истина")
        self.assertEqual(о["событие"][0], о["событие_обычный"][0])
        self.assertEqual(о["срок"][0], обычный)
        self.assertEqual(len(о["случай"]), случаев)
        for текст, итог in zip(о["случай"], о["случай_итог"]):
            self.assertEqual(текст, обычный)
            вызовов_с, пустых, причина_с, в_кэше_с, порождено_с = итог.split()
            self.assertEqual((причина_с, в_кэше_с, порождено_с), (причина, в_кэше, порождено))
        # хотя бы в одном случае были прерывания, которые ничего не сделали
        self.assertTrue(any(int(и.split()[1]) > 0 for и in о["случай_итог"]))
        self.assertTrue(о["темп_случай"])
        for текст in о["темп_случай"]:
            self.assertEqual(текст, о["темп"][0])
        self.assertNotEqual(о["темп"][0], обычный)
        self.assertEqual(о["получатель"][0], "получатель ложь истина")
        self.assertIn("ошибка: запрос длиннее контекста модели", о["длинный"][0])
        self.assertIn("неверные параметры выборки", о["выборка"][0])
        self.assertIn("ответ не начат", о["не_начат"][0])
        # модель qwen2 тестов рано выбирает конечный токен
        if о["переполнение"][0] != "конец: ":
            self.assertIn("ошибка: контекст модели заполнен во время ответа", о["переполнение"][0])

    def test_продолжение_как_без_прерывания(self):
        """Ответ, прерванный по шагам, сроку, событию другой задачи и в случайные моменты (в том числе
        между пакетами длинного запроса), после продолжения тот же, что без прерывания."""
        for модель, повторов, максимум in (("spm", 1, 40), ("spm", 40, 60), ("q8", 40, 30), ("арх_qwen2", 2, 50)):
            with self.subTest(модель=модель, повторов=повторов):
                р = subprocess.run([Общее.программа, "сверка", Общее.модели[модель], str(повторов), str(максимум), "40"],
                                   capture_output=True, timeout=600, cwd=Общее.папка)
                вывод_ = р.stdout.decode("utf-8", "replace")
                self.assertEqual(р.returncode, 0, вывод_ + р.stderr.decode("utf-8", "replace"))
                self.проверить_вывод(разобрать(вывод_), повторов, максимум, 40)

    @unittest.skipUnless(санитайзер(), "нет санитайзера адресов")
    def test_под_санитайзерами(self):
        """Прерывание в случайные моменты под ASan, LSan и UBSan: ни ошибок памяти, ни утечек."""
        компилятор = санитайзер()
        путь = os.path.join(Общее.папка, "прерывание.dan")
        код_c = os.path.join(Общее.папка, "прерывание_san.c")
        р = subprocess.run([sam_kompilyator.исполняемый(), "си", путь], capture_output=True,
                           env=sam_kompilyator.среда(), timeout=900, cwd=Общее.папка)
        self.assertEqual(р.returncode, 0, р.stderr.decode("utf-8", "replace"))
        with open(код_c, "wb") as ф:
            ф.write(р.stdout)
        исп = os.path.join(Общее.папка, "прерывание_san")
        subprocess.run([компилятор, "-std=c11", "-fwrapv", "-ffp-contract=off", "-w", "-g", "-O1",
                        "-fsanitize=address,undefined", "-fno-sanitize-recover=all", код_c, "-o", исп, "-lm", "-pthread"],
                       check=True, timeout=1200)
        р = subprocess.run([исп, "сверка", Общее.модели["spm"], "40", "40", "30"], capture_output=True, timeout=1200,
                           cwd=Общее.папка, env=dict(os.environ, ASAN_OPTIONS="detect_leaks=1"))
        ошибки = р.stderr.decode("utf-8", "replace")
        self.assertEqual(р.returncode, 0, ошибки)
        self.assertNotIn("Sanitizer", ошибки)
        self.assertNotIn("runtime error", ошибки)
        self.проверить_вывод(разобрать(р.stdout.decode("utf-8", "replace")), 40, 40, 30)


