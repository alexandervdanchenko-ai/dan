def ошибки(текст):
    try:
        проверить(разобрать(текст))
    except ОшибкаПроверки as о:
        return "\n".join(с.текст for с in о.ошибки)
    return ""


class ТестыЗаписиТипов(unittest.TestCase):

    def test_разбор_и_сборка(self):
        for т in ["цел", "[стр]", "{стр: [цел]}", "цел?", "Пара<цел, стр>!", "функ(цел, [Т]) -> Т?",
                  "функ(Пара<цел, функ(цел) -> цел>)", "[Дерево<Пара<А, Б>>]"]:
            self.assertEqual(об.собрать(об.разобрать(т)), т)

    def test_подстановка(self):
        self.assertEqual(об.подставить("{К: [З]}", {"К": "стр", "З": "Пара<цел, цел>"}), "{стр: [Пара<цел, цел>]}")
        self.assertEqual(об.подставить("функ(Т) -> Т?", {"Т": "дроб"}), "функ(дроб) -> дроб?")

    def test_сопоставление(self):
        связи = {}
        об.сопоставить("функ([Т], функ(Т) -> Р) -> [Р]", "функ([цел], функ(цел) -> стр) -> [стр]",
                       {"Т", "Р"}, связи, lambda а, б: а if а == б else None)
        self.assertEqual(связи, {"Т": "цел", "Р": "стр"})
        self.assertFalse(об.сопоставить("Пара<Т, Т>", "Пара<цел, стр>", {"Т"}, {},
                                        lambda а, б: а if а == б else None))


class ТестыПроверки(unittest.TestCase):

    def test_тело_проверяется_по_ограничениям(self):
        self.assertIn("для «<» параметр типа Т должен выполнять интерфейс Упорядоченное",
                      ошибки("функ ф<Т>(а: Т, б: Т) -> лог { вернуть а < б }"))
        self.assertIn("для «==» параметр типа Т должен выполнять интерфейс Сравнимое",
                      ошибки("функ ф<Т>(а: Т, б: Т) -> лог { вернуть а == б }"))
        self.assertIn("для «+» параметр типа Т должен выполнять интерфейс Числовое",
                      ошибки("функ ф<Т: Упорядоченное>(а: Т) -> Т { вернуть а + а }"))
        self.assertIn("нет полей", ошибки("функ ф<Т>(а: Т) -> цел { вернуть а.поле }"))
        self.assertIn("нет метода «м»", ошибки("функ ф<Т>(а: Т) -> цел { вернуть а.м() }"))
        self.assertIn("Т(1)", ошибки("функ ф<Т: Числовое>(а: Т) -> Т { вернуть а * 2 }"))
        self.assertEqual(ошибки("функ ф<Т: Числовое>(а: Т) -> Т { вернуть а * Т(2) - а }"), "")

    def test_вызов_проверяет_тип(self):
        т = ошибки("функ ф<Т: Упорядоченное>(а: Т) -> Т { вернуть а }\nвывод(ф(истина))")
        self.assertIn("требует, чтобы тип Т выполнял интерфейс Упорядоченное", т)
        self.assertIn("а Т = лог", т)
        т = ошибки("функ ф<Т>(а: Т, б: Т) -> Т { вернуть а }\nвывод(ф(1, \"а\"))")
        self.assertIn("не согласуется с другими аргументами функции «ф» (по ним Т = цел)", т)
        self.assertEqual(ошибки("функ ф<Т: Числовое>(а: Т, б: Т) -> Т { вернуть а + б }\nвывод(ф(1, 2.5))"), "")

    def test_параметр_должен_определяться(self):
        self.assertIn("должен встречаться в типах параметров", ошибки("функ ф<Т>() -> [Т] { вернуть [] }"))
        self.assertIn("не удаётся определить Т",
                      ошибки("функ ф<Т>(с: [Т]) -> цел { вернуть с.длина }\nвывод(ф([]))"))
        self.assertIn("не встречается в полях", ошибки("тип П<А> { а: цел }"))

    def test_неизвестный_интерфейс_и_занятые_имена(self):
        self.assertIn("неизвестный интерфейс «Нечто»", ошибки("функ ф<Т: Нечто>(а: Т) -> Т { вернуть а }"))
        self.assertIn("совпадает с названием типа", ошибки("функ ф<цел>(а: цел) -> цел { вернуть а }"))
        self.assertIn("обобщённая функция", ошибки("функ ф<Т>(а: Т) -> Т { вернуть а }\nпусть г = ф"))

    def test_интерфейс_и_методы(self):
        основа = ("интерфейс Ф { функ площадь() -> дроб }\nтип К { р: дроб }\n"
                  "функ описать<Т: Ф>(а: Т) -> дроб { вернуть а.площадь() }\n")
        self.assertIn("у типа К нет метода «площадь»; объявите его: функ К.площадь() -> дроб",
                      ошибки(основа + "вывод(описать(К(1.0)))"))
        self.assertIn("должен быть объявлен так",
                      ошибки(основа + "функ К.площадь() -> цел { вернуть 1 }\nвывод(описать(К(1.0)))"))
        self.assertEqual(ошибки(основа + "функ К.площадь() -> дроб { вернуть сам.р }\nвывод(описать(К(1.0)))"), "")
        self.assertIn("уже есть поле «р»", ошибки("тип К { р: дроб }\nфунк К.р() -> дроб { вернуть 1.0 }"))
        self.assertIn("только для собственного типа", ошибки("функ цел.удвоить() -> цел { вернуть 2 }"))

    def test_сам_нельзя_изменить(self):
        self.assertIn("нельзя", ошибки("тип С { н: цел }\nфунк С.обнулить() { сам.н = 0 }"))

    def test_обобщённые_типы(self):
        self.assertIn("укажите тип переменной", ошибки("тип О<Т> { Есть(з: Т)  Нет }\nпусть х = Нет"))
        self.assertEqual(ошибки("тип О<Т> { Есть(з: Т)  Нет }\nпусть х: О<цел> = Нет\nвывод(х == Нет)"), "")
        self.assertIn("укажите их, например П<цел>", ошибки("тип П<А> { а: А }\nпусть х: П = П(1)"))
        self.assertIn("угловые скобки не нужны", ошибки("тип П { а: цел }\nпусть х: П<цел> = П(1)"))
        self.assertIn("Ключ", ошибки("тип М<Т> { с: {Т: лог} }"))

    def test_методы_обобщённых_типов(self):
        основа = "тип П<А, Б> { а: А, б: Б }\n"
        self.assertEqual(ошибки(основа + "функ П<А, Б>.обмен() -> П<Б, А> { вернуть П(сам.б, сам.а) }\n"
                                        "вывод(П(1, \"х\").обмен().а + \"!\")"), "")
        self.assertIn("метод объявляется с его параметрами типа: функ П<А, Б>.м(...)",
                      ошибки(основа + "функ П.м() -> цел { вернуть 1 }"))
        self.assertIn("у типа П параметров типа 2", ошибки(основа + "функ П<А>.м() -> цел { вернуть 1 }"))
        self.assertIn("уже есть поле «а»", ошибки(основа + "функ П<А, Б>.а() -> цел { вернуть 1 }"))
        self.assertIn("не обобщённый тип", ошибки("тип К { а: цел }\nфунк К<Т>.м() -> цел { вернуть 1 }"))
        from parser import ОшибкаРазбора
        with self.assertRaises(ОшибкаРазбора) as о:
            разобрать(основа + "функ П<А, Б>.м<В>(в: В) -> цел { вернуть 1 }")
        self.assertIn("метод не может иметь своих параметров типа", str(о.exception))
        # ограничение типа действует в методе: сравнение без ограничения - ошибка
        self.assertIn("Упорядоченное", ошибки("тип Я<Т> { з: Т }\nфунк Я<Т>.меньше(х: Т) -> лог { вернуть сам.з < х }"))
        self.assertEqual(ошибки("тип Я<Т: Упорядоченное> { з: Т }\nфунк Я<Т>.меньше(х: Т) -> лог { вернуть сам.з < х }\n"
                                "вывод(Я(1).меньше(2))"), "")

    def test_пояснение_о_подстановке(self):
        т = ошибки("функ ф<Т>(а: Т) -> Т { вернуть ф([а])[0] }\nвывод(ф(1))")
        self.assertIn("слишком глубокая цепочка подстановок", т)


