КОМПИЛЯТОР = shutil.which("gcc") or shutil.which("clang")


def санитайзер_есть():
    if not КОМПИЛЯТОР or sys.platform != "linux":
        return False
    with tempfile.TemporaryDirectory() as п:
        с = os.path.join(п, "п.c")
        with open(с, "w") as ф:
            ф.write("int main(void) { return 0; }\n")
        р = subprocess.run([КОМПИЛЯТОР, "-fsanitize=address,undefined", с, "-o", os.path.join(п, "п")],
                           capture_output=True)
        if р.returncode != 0:
            return False
        return subprocess.run([os.path.join(п, "п")], capture_output=True).returncode == 0


САНИТАЙЗЕР = санитайзер_есть()
ПАПКА = os.path.dirname(os.path.abspath(__file__))


def под_санитайзером(текст, ввод_данных=None):
    """(код завершения, вывод, ошибки) программы, собранной с проверкой памяти.
    Программа выполняется во временной папке: файлы, которые она создаёт, удаляются."""
    with tempfile.TemporaryDirectory() as п:
        с = os.path.join(п, "программа.c")
        with open(с, "w", encoding="utf-8") as ф:
            ф.write(dan.перевести(текст))
        исп = os.path.join(п, "программа")
        subprocess.run([КОМПИЛЯТОР, "-std=c11", "-fwrapv", "-w", "-g", "-O1", "-fsanitize=address,undefined",
                        "-fno-sanitize-recover=undefined", с, "-o", исп, "-lm"], check=True)
        окружение = dict(os.environ, ASAN_OPTIONS="detect_leaks=1")
        р = subprocess.run([исп], capture_output=True, text=True, encoding="utf-8", timeout=300, env=окружение,
                           cwd=п, input=ввод_данных)
        return р.returncode, р.stdout, р.stderr


