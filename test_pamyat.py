@unittest.skipUnless(САНИТАЙЗЕР, "компилятор без AddressSanitizer")
class ТестыПроверкиПамяти(unittest.TestCase):

    def test_нет_ошибок_и_утечек(self):
        for имя, текст in ПРОГРАММЫ.items():
            with self.subTest(имя=имя):
                код, вывод, ошибки = под_санитайзером(текст)
                self.assertEqual(код, 0, ошибки[-3000:])
                self.assertNotIn("Sanitizer", ошибки)
                self.assertNotIn("runtime error", ошибки)

    def test_примеры_и_каталог_без_утечек(self):
        """Память освобождают все значения и вспомогательные данные библиотеки: многочлены,
        матрицы, архивы, шаблоны. Задачи, модули и окна проверяются другими тестами."""
        import glob
        import test_katalog as каталог
        пути = каталог.программы("программы") + sorted(glob.glob(os.path.join(ПАПКА, "примеры", "*.dan")))
        for путь in пути:
            текст = каталог.прочитать(путь)
            if "запустить" in текст or "подключить" in текст or "внешняя" in текст or "окно_" in текст:
                continue
            основа = путь[:-4]
            ввод_данных = каталог.прочитать(основа + ".ввод") if os.path.exists(основа + ".ввод") else ""
            with self.subTest(путь=os.path.basename(путь)):
                код, вывод, ошибки = под_санитайзером(текст, ввод_данных)
                self.assertNotIn("Sanitizer", ошибки, ошибки[-3000:])
                self.assertNotIn("runtime error", ошибки)


@unittest.skipUnless(КОМПИЛЯТОР and sys.platform == "linux", "нужен Linux и компилятор C")
class ТестыРасходаПамяти(unittest.TestCase):

    def test_временные_строки_не_накапливаются(self):
        текст = ("перем итог = 0\nдля к в 1..3000000 {\n    пусть с = стр(к) + \"-\" + стр(к * 2)\n"
                 "    итог += с.длина\n}\nвывод(итог)")
        with tempfile.TemporaryDirectory() as п:
            путь = os.path.join(п, "программа.dan")
            with open(путь, "w", encoding="utf-8") as ф:
                ф.write(текст)
            исп = dan.собрать(путь, текст)
            # пиковый расход памяти измеряется у отдельного процесса, в котором запускается только эта программа
            замер = ("import resource, subprocess, sys\n"
                     "р = subprocess.run([sys.argv[1]], capture_output=True, text=True)\n"
                     "print(р.returncode, р.stdout.strip(), resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss)")
            р = subprocess.run([sys.executable, "-c", замер, исп], capture_output=True, text=True, timeout=120)
        код, вывод, память = р.stdout.split()
        self.assertEqual(код, "0")
        self.assertEqual(вывод, "43333347")
        # без освобождения программа занимала больше 350 МБ
        self.assertLess(int(память), 100 * 1024)


