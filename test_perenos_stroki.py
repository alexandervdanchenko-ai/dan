"""Перенос длинного выражения на новую строку после знака действия (spec.md, разделы 2.1 и А.2).

Строка, которая оканчивается знаком действия после значения («а +», «х и», «у <=»), продолжается
следующей. Прежде такая строка всегда была ошибкой разбора, поэтому смысл верных программ не
меняется: строка, которая начинается знаком («-х»), к предыдущей не присоединяется. Запись есть
только в компиляторе на Дане (сам/лексер.dan, сам/формат.dan): тесты переводят программы им.
"""

import glob
import json
import os
import subprocess
import tempfile
import unittest

import dan
import lexer
import sam_kompilyator
from test_kodogen import КОМПИЛЯТОР_ЕСТЬ

ПАПКА = os.path.dirname(os.path.abspath(__file__))
ЗНАКИ = {"+", "-", "*", "/", "%", "^", "==", "!=", "<", "<=", ">="}


def ошибка_перевода(текст):
    try:
        sam_kompilyator.перевести(текст)
    except Exception as о:
        return str(о)
    return ""


def выполнить(текст):
    код_c = sam_kompilyator.перевести(текст)
    with tempfile.TemporaryDirectory() as папка:
        исполняемый = dan.собрать_код(код_c, os.path.join(папка, "программа"), папка, выпуск=True)
        р = subprocess.run([исполняемый], capture_output=True, text=True, encoding="utf-8", timeout=60)
        return р.returncode, р.stdout, р.stderr


def форматировать(текст):
    with tempfile.TemporaryDirectory() as папка:
        путь = os.path.join(папка, "ф.dan")
        with open(путь, "w", encoding="utf-8") as ф:
            ф.write(текст)
        р = subprocess.run([sam_kompilyator.исполняемый(), "формат", путь], capture_output=True,
                           env=sam_kompilyator.среда(), timeout=120)
        вывод_ = р.stdout.decode("utf-8", "replace")
        if р.returncode != 0:
            return "ОШИБКА " + вывод_
        with open(путь, encoding="utf-8") as ф:
            return ф.read()


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыПереноса(unittest.TestCase):

    def test_перенос_после_знаков(self):
        код, вывод_, ошибки = выполнить(
            "пусть а = 1 +\n    2 *\n    3\nвывод(а)\n"
            "если а > 5 и\n        а < 10 {\n    вывод(\"да\")\n}\n"
            "пусть б = а ==\n    7\nвывод(б)\n"
            "пусть ж = \"а\" +    // комментарий после знака\n    // строка комментария\n\n    \"б\"\nвывод(ж)\n"
            "функ ф(х: цел) -> цел {\n    вернуть х -\n        1\n}\nвывод(ф(10) <=\n    9)\n"
            "пусть г = ф(3) − 1 ×\n    2\nвывод(г)\n"
            "пусть д = истина или\n    ложь\nвывод(д)\n")
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.split(), ["7", "да", "истина", "аб", "истина", "0", "истина"])

    def test_блок_отступом_после_переноса(self):
        код, вывод_, ошибки = выполнить(
            "для к в 1..3:\n    если к >= 2 и\n            к <= 2:\n        вывод(к)\n    вывод(\"шаг\")\nвывод(\"всё\")\n")
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.split(), ["шаг", "2", "шаг", "шаг", "всё"])

    def test_строка_со_знаком_в_начале_не_присоединяется(self):
        # «-а» на новой строке - отдельная инструкция, как прежде (и потому ошибка)
        текст = ошибка_перевода("пусть а = 5\nпусть б = а\n-а\n")
        self.assertIn("Строка 3", текст)

    def test_привычки_не_меняются(self):
        for текст, знак in [("перем х = 1\nх++\nвывод(х)\n", "«++» - не знак Дана"),
                            ("перем х = 1\nх--\nвывод(х)\n", "«--» - не знак Дана")]:
            with self.subTest(знак=знак):
                self.assertIn(знак, ошибка_перевода(текст))

    def test_больше_в_конце_строки_не_переносит(self):
        # «>» оканчивает и тип («поле: массив<цел>»), поэтому после него строка не продолжается
        текст = ошибка_перевода("пусть а = 2 >\n    1\nвывод(а)\n")
        self.assertIn("после «>» строка не переносится", текст)
        код, вывод_, ошибки = выполнить("тип Т {\n    м: массив<цел>\n    н: цел\n}\nвывод(Т(массив(цел, 2), 1).н)\n")
        self.assertEqual(код, 0, ошибки)

    def test_незаконченное_выражение_в_конце_файла(self):
        self.assertNotEqual(ошибка_перевода("пусть а = 1 +\n"), "")

    def test_форматирование(self):
        self.assertEqual(форматировать("пусть а = 1 +\n2*\n          3\nвывод(а)\n"),
                         "пусть а = 1 +\n    2 *\n    3\nвывод(а)\n")
        self.assertEqual(форматировать("для к в 1..3:\n  если к >= 2 и\n к <= 2:\n    вывод(к)\n  вывод(1)\n"),
                         "для к в 1..3:\n    если к >= 2 и\n        к <= 2:\n        вывод(к)\n    вывод(1)\n")
        self.assertEqual(форматировать("если а и\n        б {\n    вывод(1)\n}\n"),
                         "если а и\n    б {\n    вывод(1)\n}\n")


def проверить_json(текст):
    with tempfile.TemporaryDirectory() as папка:
        with open(os.path.join(папка, "п.dan"), "w", encoding="utf-8") as ф:
            ф.write(текст)
        р = subprocess.run([sam_kompilyator.исполняемый(), "проверить", "--json", "п.dan"], capture_output=True,
                           cwd=папка, env=sam_kompilyator.среда(), timeout=120)
        return р.returncode, json.loads(р.stdout.decode("utf-8"))


class ТестыЗнакаВНачалеСтроки(unittest.TestCase):
    """Строка, начатая знаком переноса: подсказка, что знак ставится в конце предыдущей строки (Д0332)."""

    def test_знаки_и_слова(self):
        for знак, показ in [("+", "+"), ("*", "*"), ("/", "/"), ("%", "%"), ("^", "^"), ("==", "=="), ("!=", "!="),
                            ("<", "<"), ("<=", "<="), (">=", ">="), ("и", "и"), ("или", "или"), ("×", "*"),
                            ("≤", "<=")]:
            with self.subTest(знак=знак):
                код, д = проверить_json(f"пусть а = 1\n    {знак} 2\nвывод(а)\n")
                self.assertEqual((код, д["ошибок"]), (1, 1))
                с = д["сообщения"][0]
                self.assertEqual((с["код"], с["строка"], с["позиция"]), ("Д0332", 2, 5))
                self.assertEqual(с["текст"], f"строка начинается с «{показ}»: при переносе выражения «{показ}» "
                                 "ставится в конце предыдущей строки, а не в начале следующей")
                # перенос - правка двух строк, а готовое исправление заменяет одно подчёркнутое место
                self.assertNotIn("исправление", с)

    def test_после_условия_и_пустых_строк(self):
        код, д = проверить_json("пусть а = истина\nесли а\n    и а {\n    вывод(1)\n}\n")
        с = д["сообщения"][0]
        self.assertEqual((код, с["код"], с["строка"], с["позиция"]), (1, "Д0332", 3, 5))
        код, д = проверить_json("пусть а = [1]\n\n// комментарий\n* 2\n")
        self.assertEqual(д["сообщения"][0]["код"], "Д0332")

    def test_минус_в_начале_строки(self):
        # «- 2» отдельной строкой - верная запись выражения, но его значение не используется: прежняя
        # ошибка Д0008 получает подсказку о переносе
        код, д = проверить_json("пусть а = 1\n    - 2\nвывод(а)\n")
        с = д["сообщения"][0]
        self.assertEqual((код, с["код"], с["строка"], с["позиция"]), (1, "Д0008", 2, 5))
        self.assertIn("; если это продолжение выражения с предыдущей строки, при переносе «-» ставится в конце "
                      "предыдущей строки, а не в начале следующей", с["текст"])
        # не в начале строки - прежняя подсказка
        код, д = проверить_json("пусть а = 1\nесли а > 0 { -а }\n")
        self.assertNotIn("при переносе", д["сообщения"][0]["текст"])
        # верные программы со знаком в начале строки собираются, как прежде
        self.assertEqual(проверить_json("функ ф() -> цел {\n    вернуть 1\n}\n-ф()\nпусть б = 2\n-ф()\n")[0], 0)


class ТестыСовместимостиПереноса(unittest.TestCase):
    """Доказательство, что перенос не меняет смысла прежних программ: ни одна строка программ папок
    «совместимость», «каталог», «примеры» и «библиотека» не оканчивается знаком действия вне скобок
    (замороженный лексер на Python, у которого переноса нет). Строка с таким концом прежде была
    ошибкой разбора, а прочие строки разбиваются на токены, как раньше."""

    def test_прежние_программы_не_оканчивают_строку_знаком(self):
        найдено = []
        for папка in ("совместимость",):
            for путь in glob.glob(os.path.join(ПАПКА, папка, "**", "*.dan"), recursive=True):
                with open(путь, encoding="utf-8") as ф:
                    try:
                        токены = lexer.разобрать(ф.read())
                    except Exception:
                        continue
                for п, т in zip(токены, токены[1:]):
                    if т.вид.name == "КОНЕЦ_СТРОКИ" and ((п.вид.name == "ЗНАК" and п.значение in ЗНАКИ)
                                                       or (п.вид.name == "КЛЮЧ" and п.значение in ("и", "или"))):
                        найдено.append(f"{путь}:{п.строка}")
        self.assertEqual(найдено, [])


if __name__ == "__main__":
    unittest.main()
