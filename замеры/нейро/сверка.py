"""Сверка движка «нейро» (библиотека/нейро.dan) с llama.cpp на настоящих моделях и замер скорости.

    python замеры/нейро/сверка.py папка_llama дан модель.gguf [модель.gguf ...] [--потоков=N] [--токенов=N]
                                  [--память=ГБ/с] [--итог=файл.md]

папка_llama - папка с libllama одной сборки llama.cpp (modeli.ВЕРСИЯ_LLAMA); дан - компилятор Дана
(semya/dan или dan). Для каждой модели:
  - токены набора строк (русские, английские, цифры, пробелы, знаки, служебные части) - сколько
    строк разбито так же, как llama_tokenize;
  - логиты после запроса: наибольшая разница, делённая на наибольший логит llama.cpp, - движок с
    кэшем дроб32 против llama.cpp с кэшем f32 (запрос по одному токену) и движок с кэшем по умолчанию
    (дроб16) против llama.cpp по умолчанию (кэш f16, запрос пакетом);
  - жадный ответ на запросы: сколько первых токенов совпало (в тех же двух парах);
  - скорость порождения (токенов в секунду, без обработки запроса) движка (кэш по умолчанию) и
    llama.cpp при одном и том же числе потоков; llama.cpp - с кэшем f16 и настройками по умолчанию;
    медиана трёх запусков;
  - скорость чтения длинного запроса (токенов в секунду): движок пакетами (как по умолчанию) и по одному
    токену (как до пакетов), llama.cpp - одним пакетом;
  - предел «скорость памяти / объём весов» (если задан --память) и доля движка от него.
Таблица печатается и дописывается в файл --итог (например $GITHUB_STEP_SUMMARY).
"""

import os
import statistics
import subprocess
import sys
import tempfile

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))

СТРОКИ = ["привет мир", "Привет, мир! Как дела?", "hello world", "Hello World!! It's 2026.", "  два  пробела  ",
          "числа 123 и 2026, 3.14159 и 1000000", "строка\nновая строка\n\nещё", "табы\tи\tпробелы",
          "it's don't we'll I'M they've", "ёлка Ёж ЁЖИК", "日本語 текст 中文", "emoji 😀 тут 👍🏽",
          "<|im_start|>user\nкак дела<|im_end|>\n<|im_start|>assistant\n", "<s>[INST] начало [/INST]</s>",
          "a", " ", "...!!??--", "мир" * 20, "  \n  ", "ÀÉÎ õüñ çà", "1234567890", "Ελληνικά", "def f(x):\n    return x**2\n",
          "Москва - столица России, а Париж - столица Франции."]

# длинный запрос - для скорости чтения запроса
ДЛИННЫЙ = ("The quick brown fox jumps over the lazy dog, and the dog does not mind at all. " * 6
           + "Москва - столица России, а Париж - столица Франции; обе стоят на реках. " * 6)

ЗАПРОСЫ = ["The capital of France is", "Столица России - город", "<|im_start|>user\nНапиши короткое стихотворение о море."
           "<|im_end|>\n<|im_start|>assistant\n"]


def разобрать(текст):
    итог = {}
    for строка in текст.splitlines():
        ключ, _, значение = строка.partition(":")
        if _:
            итог.setdefault(ключ, []).append(значение.strip())
    return итог


def запустить(команда, окружение=None, ошибка_можно=False):
    р = subprocess.run(команда, capture_output=True, env={**os.environ, **(окружение or {})}, timeout=3600)
    if р.returncode != 0 and not ошибка_можно:
        sys.stderr.write(р.stderr.decode("utf-8", "replace")[-3000:])
        raise SystemExit("не выполнилось: " + " ".join(команда))
    return разобрать(р.stdout.decode("utf-8", "replace"))


def главная():
    арг = [а for а in sys.argv[1:] if not а.startswith("--")]
    ключи = dict(а[2:].split("=", 1) for а in sys.argv[1:] if а.startswith("--") and "=" in а)
    llama, дан, модели = os.path.abspath(арг[0]), арг[1], [os.path.abspath(м) for м in арг[2:]]
    потоков = int(ключи.get("потоков", os.cpu_count() or 1))
    токенов = int(ключи.get("токенов", "32"))
    память = float(ключи["память"]) if "память" in ключи else None
    папка = tempfile.mkdtemp(prefix="dan_sverka_neyro_")
    сверка = os.path.join(папка, "sverka_llama")
    subprocess.run(["gcc", "-std=c11", "-O2", os.path.join(ЗДЕСЬ, "сверка_llama.c"), "-o", сверка, "-ldl"], check=True)
    программа = os.path.join(папка, "dvizhok.dan")
    with open(os.path.join(ЗДЕСЬ, "движок.dan"), encoding="utf-8") as ф, open(программа, "w", encoding="utf-8") as в:
        в.write(ф.read())
    subprocess.run([дан, "собрать", программа], check=True)
    движок = программа[:-4]
    файлы = []
    for н, с in enumerate(СТРОКИ + ЗАПРОСЫ + [ДЛИННЫЙ]):
        п = os.path.join(папка, "s%02d.txt" % н)
        with open(п, "wb") as ф:
            ф.write(с.encode("utf-8"))
        файлы.append(п)
    строки_ф, запросы_ф, длинный_ф = файлы[:len(СТРОКИ)], файлы[len(СТРОКИ):-1], файлы[-1]
    библ = os.path.join(llama, "libllama.so")
    окр_llama = {"LD_LIBRARY_PATH": llama}
    окр_дан = {"DAN_POTOKI": str(потоков)}
    таблица = ["| Модель | Размер, МБ | Токены строк | Логиты, наиб. разница (кэш f32 / f16) | "
               "Жадный ответ, совпало токенов (кэш f32 / f16) | Дан, слов/с | llama.cpp, слов/с | Дан / llama.cpp | "
               "Предел памяти, слов/с | Дан / предел | Запрос: Дан пакетами / по одному / llama.cpp, токенов/с |",
               "|---|---|---|---|---|---|---|---|---|---|---|"]
    подробно = []

    def совпало(о1, о2):
        общих = 0
        while общих < min(len(о1), len(о2)) and о1[общих] == о2[общих]:
            общих += 1
        return f"{общих}/{len(о1)}"

    def разница(их, наш):
        л1 = [float(х) for х in их["логиты"][0].split()]
        л2 = [float(х) for х in наш["логиты"][0].split()]
        return max(abs(а - б) for а, б in zip(л1, л2)) / max(abs(х) for х in л1)

    for модель in модели:
        имя = os.path.basename(модель)
        размер = os.path.getsize(модель)
        print("==", имя, размер // 1048576, "МБ", flush=True)
        # токены
        наши = запустить([движок, модель, "-", "0", *строки_ф])["токены"]
        совпало_строк = 0
        for строка, файл, наш in zip(СТРОКИ, строки_ф, наши):
            их = запустить([сверка, библ, модель, файл, "0"], окр_llama)["токены"][0]
            if их == наш:
                совпало_строк += 1
            else:
                подробно.append(f"{имя}: строка {строка!r}\n  llama.cpp: {их}\n  Дан:       {наш}")
        # логиты и жадные ответы: кэш f32 (запрос по одному токену) и по умолчанию (f16, запрос пакетом)
        разницы32, разницы16, совпадения32, совпадения16, дан_ск, загрузка = [], [], [], [], [], []
        for файл, запрос in zip(запросы_ф, ЗАПРОСЫ):
            их32 = запустить([сверка, библ, модель, файл, str(токенов), str(потоков)], окр_llama)
            наш32 = запустить([движок, модель, файл, str(токенов), "кэш32"], окр_дан)
            их16 = запустить([сверка, библ, модель, файл, str(токенов), str(потоков), "f16"], окр_llama)
            наш16 = запустить([движок, модель, файл, str(токенов)], окр_дан)
            if наш32["токены"][0] != их32["токены"][0]:
                подробно.append(f"{имя}: токены запроса {запрос!r} различаются")
            разницы32.append(разница(их32, наш32))
            разницы16.append(разница(их16, наш16))
            совпадения32.append(совпало(их32["ответ"][0].split(), наш32["ответ"][0].split()))
            совпадения16.append(совпало(их16["ответ"][0].split(), наш16["ответ"][0].split()))
            дан_ск.append(float(наш16["скорость"][0]))
            загрузка.append(float(наш16["загрузка"][0]))
            подробно.append(f"{имя}: запрос {запрос!r}\n  llama.cpp (f16): {их16['текст'][0]}\n"
                            f"  Дан (дроб16):    {наш16['текст'][0]}\n  llama.cpp (f32): {их32['текст'][0]}\n"
                            f"  Дан (дроб32):    {наш32['текст'][0]}")
        # скорость llama.cpp с настройками по умолчанию (кэш f16)
        их_ск = []
        for _ in range(3):
            их_ск.append(float(запустить([сверка, библ, модель, запросы_ф[0], str(токенов), str(потоков), "f16"],
                                         окр_llama)["скорость"][0]))
        # чтение длинного запроса
        зап_пакет, зап_один, зап_их = [], [], []
        for _ in range(2):
            зап_пакет.append(float(запустить([движок, модель, длинный_ф, "2"], окр_дан)["запрос"][0]))
            зап_их.append(float(запустить([сверка, библ, модель, длинный_ф, "2", str(потоков), "f16"],
                                          окр_llama)["запрос"][0]))
        вывод_один = запустить([движок, модель, длинный_ф, "2", "по_одному"], окр_дан)
        зап_один.append(float(вывод_один["запрос"][0]))
        длина_запроса = len(вывод_один["токены"][0].split())
        д, л = statistics.median(дан_ск), statistics.median(их_ск)
        предел = память / (размер / 1e9) if память else None
        таблица.append(f"| {имя} | {размер // 1048576} | {совпало_строк}/{len(СТРОКИ)} | {max(разницы32):.2g} / "
                       f"{max(разницы16):.2g} | {', '.join(совпадения32)} / {', '.join(совпадения16)} | {д:.1f} | {л:.1f} | "
                       f"{д / л:.2f} | " + (f"{предел:.1f} | {д / предел:.2f} |" if предел else "- | - |")
                       + f" {max(зап_пакет):.0f} / {max(зап_один):.0f} / {max(зап_их):.0f} |")
        подробно.append(f"{имя}: загрузка движком {statistics.median(загрузка):.1f} с; скорости Дана {дан_ск}, "
                        f"llama.cpp {их_ск}; запрос {длина_запроса} токенов: Дан пакетами {зап_пакет}, по одному "
                        f"{зап_один}, llama.cpp {зап_их}")
    итог = (f"Потоков: {потоков}, токенов ответа: {токенов}" + (f", скорость памяти {память} ГБ/с" if память else "")
            + "\n\n" + "\n".join(таблица) + "\n\n```\n" + "\n".join(подробно) + "\n```\n")
    print(итог)
    if "итог" in ключи:
        with open(ключи["итог"], "a", encoding="utf-8") as ф:
            ф.write("## Движок «нейро» против llama.cpp\n\n" + итог)


if __name__ == "__main__":
    главная()
