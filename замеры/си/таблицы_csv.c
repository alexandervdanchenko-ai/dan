/* Таблицы CSV: записать таблицу из 300 000 строк в текст CSV, разобрать обратно и сложить столбец.
   Эталон на C: запись в общий буфер с кавычками по правилам CSV, разбор в таблицу строк. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static size_t ёмкость = 1 << 20, длина = 0;
static char *т;

static void поле(const char *с) {
    int кавычки = strpbrk(с, "\",\r\n") != NULL;
    if (ёмкость - длина < 2 * strlen(с) + 8) { ёмкость *= 2; т = realloc(т, ёмкость); }
    if (кавычки) т[длина++] = '"';
    for (; *с; с++) { if (*с == '"') т[длина++] = '"'; т[длина++] = *с; }
    if (кавычки) т[длина++] = '"';
}

int main(void) {
    т = malloc(ёмкость);
    char б[64];
    поле("Номер"); т[длина++] = ','; поле("Клиент"); т[длина++] = ','; поле("Сумма"); т[длина++] = '\r'; т[длина++] = '\n';
    for (int к = 1; к <= 300000; к++) {
        sprintf(б, "%d", к); поле(б); т[длина++] = ',';
        sprintf(б, "Клиент \"%d\", Москва", к % 100); поле(б); т[длина++] = ',';
        sprintf(б, "%d", к * 37 % 1000); поле(б); т[длина++] = '\r'; т[длина++] = '\n';
    }
    т[длина] = 0;
    /* разбор: таблица строк, у каждой строки - массив полей */
    size_t строк = 0, ёмк_строк = 1024;
    char ***таблица = malloc(sizeof *таблица * ёмк_строк);
    const char *п = т;
    while (*п) {
        char **поля = malloc(sizeof *поля * 4);
        int число = 0;
        for (;;) {
            char *знач = malloc(64), *з = знач;
            if (*п == '"') {
                п++;
                for (;;) {
                    if (*п == '"') { if (п[1] == '"') { *з++ = '"'; п += 2; continue; } п++; break; }
                    *з++ = *п++;
                }
            } else {
                while (*п && *п != ',' && *п != '\r' && *п != '\n') *з++ = *п++;
            }
            *з = 0;
            поля[число++] = знач;
            if (*п == ',') { п++; continue; }
            if (*п == '\r') п++;
            if (*п == '\n') п++;
            break;
        }
        if (строк == ёмк_строк) { ёмк_строк *= 2; таблица = realloc(таблица, sizeof *таблица * ёмк_строк); }
        таблица[строк++] = поля;
    }
    long long итог = 0;
    for (size_t н = 1; н < строк; н++) итог += atoll(таблица[н][2]);
    printf("%zu\n%lld\n", строк, итог);
    return 0;
}
