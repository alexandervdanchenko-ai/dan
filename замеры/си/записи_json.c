/* Записи JSON в свои типы: записать 200 000 записей своего типа в текст JSON, разобрать его в тот же тип и сложить суммы.
   Эталон на C: запись в общий буфер, разбор прямо в массив структур по именам полей, без проверок Дана. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef struct { long long номер; char *имя; long long сумма; } Запись;

static const char *п;

static void пробелы(void) { while (*п == ' ' || *п == '\n' || *п == '\t' || *п == '\r') п++; }

static char *строка_json(void) {
    const char *начало = ++п;
    while (*п != '"') { if (*п == '\\') п++; п++; }
    size_t н = (size_t)(п - начало);
    char *с = malloc(н + 1);
    memcpy(с, начало, н);
    с[н] = 0;
    п++;
    return с;
}

static int ключ(const char *к, size_t н) {
    if (strncmp(п + 1, к, н) || п[1 + н] != '"') return 0;
    п += н + 2;
    return 1;
}

static void пропустить(void) {
    int глубина = 0;
    do {
        if (*п == '"') { while (*++п != '"') if (*п == '\\') п++; }
        else if (*п == '{' || *п == '[') глубина++;
        else if (*п == '}' || *п == ']') глубина--;
        п++;
    } while (глубина > 0 || (*п != ',' && *п != '}' && *п != ']'));
}

int main(void) {
    size_t ёмкость = 1 << 20, длина = 0;
    char *т = malloc(ёмкость);
    т[длина++] = '[';
    for (long long к = 1; к <= 200000; к++) {
        if (ёмкость - длина < 200) { ёмкость *= 2; т = realloc(т, ёмкость); }
        длина += (size_t)sprintf(т + длина, "%s{\"номер\":%lld,\"имя\":\"Клиент %lld\",\"сумма\":%lld}",
                                 к > 1 ? "," : "", к, к, к * 37 % 1000);
    }
    т[длина++] = ']';
    т[длина] = 0;
    long long букв = 0;
    for (size_t и = 0; и < длина; и++) букв += ((unsigned char)т[и] & 0xC0) != 0x80;
    size_t число = 0, места = 16;
    Запись *записи = malloc(места * sizeof *записи);
    п = т + 1;
    пробелы();
    while (*п == '{') {
        Запись з = { 0, NULL, 0 };
        п++;
        пробелы();
        while (*п == '"') {
            char *конец;
            if (ключ("номер", strlen("номер"))) { п++; з.номер = strtoll(п, &конец, 10); п = конец; }
            else if (ключ("имя", strlen("имя"))) { п++; з.имя = строка_json(); }
            else if (ключ("сумма", strlen("сумма"))) { п++; з.сумма = strtoll(п, &конец, 10); п = конец; }
            else { free(строка_json()); п++; пропустить(); }
            пробелы();
            if (*п == ',') п++;
            пробелы();
        }
        п++;
        if (число == места) { места *= 2; записи = realloc(записи, места * sizeof *записи); }
        записи[число++] = з;
        пробелы();
        if (*п == ',') п++;
        пробелы();
    }
    long long итог = 0;
    for (size_t и = 0; и < число; и++) итог += записи[и].сумма;
    printf("%lld\n%lld\n", букв, итог);
    return 0;
}
