/* Обмен данными JSON: записать 200 000 записей в текст JSON, разобрать его обратно и сложить суммы.
   Эталон на C: запись в общий буфер, разбор в дерево значений (как в cJSON), без проверок Дана. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef struct Зн Зн;
struct Зн {
    int вид;            /* 0 - целое, 1 - строка, 2 - массив, 3 - объект */
    long long целое;
    char *строка;
    Зн **элементы;
    char **ключи;
    int число, ёмкость;
};

static const char *п;

static Зн *новое(int вид) { Зн *з = calloc(1, sizeof *з); з->вид = вид; return з; }

static void добавить(Зн *з, char *ключ, Зн *э) {
    if (з->число == з->ёмкость) {
        з->ёмкость = з->ёмкость ? з->ёмкость * 2 : 4;
        з->элементы = realloc(з->элементы, sizeof *з->элементы * з->ёмкость);
        if (з->вид == 3) з->ключи = realloc(з->ключи, sizeof *з->ключи * з->ёмкость);
    }
    if (з->вид == 3) з->ключи[з->число] = ключ;
    з->элементы[з->число++] = э;
}

static char *строка_json(void) {
    const char *начало = ++п;
    while (*п != '"') { if (*п == '\\') п++; п++; }
    size_t н = (size_t)(п - начало);
    char *с = malloc(н + 1);
    memcpy(с, начало, н);
    с[н] = 0;
    п++;
    return с;
}

static Зн *значение(void) {
    if (*п == '{') {
        Зн *з = новое(3);
        п++;
        while (*п != '}') {
            char *ключ = строка_json();
            п++;                               /* ':' */
            добавить(з, ключ, значение());
            if (*п == ',') п++;
        }
        п++;
        return з;
    }
    if (*п == '[') {
        Зн *з = новое(2);
        п++;
        while (*п != ']') {
            добавить(з, NULL, значение());
            if (*п == ',') п++;
        }
        п++;
        return з;
    }
    if (*п == '"') { Зн *з = новое(1); з->строка = строка_json(); return з; }
    Зн *з = новое(0);
    char *конец;
    з->целое = strtoll(п, &конец, 10);
    п = конец;
    return з;
}

int main(void) {
    size_t ёмкость = 1 << 20, длина = 0;
    char *т = malloc(ёмкость);
    т[длина++] = '[';
    for (long long к = 1; к <= 200000; к++) {
        if (ёмкость - длина < 200) { ёмкость *= 2; т = realloc(т, ёмкость); }
        длина += (size_t)sprintf(т + длина, "%s{\"номер\":%lld,\"имя\":\"Клиент %lld\",\"сумма\":%lld}",
                                 к > 1 ? "," : "", к, к, к * 37 % 1000);
    }
    т[длина++] = ']';
    т[длина] = 0;
    long long букв = 0;
    for (size_t и = 0; и < длина; и++) букв += ((unsigned char)т[и] & 0xC0) != 0x80;
    п = т;
    Зн *данные = значение();
    long long итог = 0;
    for (int и = 0; и < данные->число; и++) {
        Зн *з = данные->элементы[и];
        for (int к = 0; к < з->число; к++)
            if (!strcmp(з->ключи[к], "сумма")) итог += з->элементы[к]->целое;
    }
    printf("%lld\n%lld\n", букв, итог);
    return 0;
}
