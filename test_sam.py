@unittest.skipUnless(dan.компилятор_есть(), "нет компилятора C")
class ТестыЛексераНаДане(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        путь = os.path.join(САМ, "токены.dan")
        with open(путь, encoding="utf-8") as ф:
            cls.программа = dan.собрать(путь, ф.read())

    def выполнить(self, файлы):
        """Вывод программы сверки по файлам: путь -> строки."""
        итог = {}
        for начало in range(0, len(файлы), 200):
            р = subprocess.run([os.path.abspath(self.программа), *файлы[начало:начало + 200]], capture_output=True,
                               timeout=600)
            self.assertEqual(р.returncode, 0, р.stderr.decode("utf-8", "replace"))
            путь = None
            for строка in р.stdout.decode("utf-8").replace("\r\n", "\n").split("\n"):
                if строка.startswith("== "):
                    путь = строка[3:]
                    итог[путь] = []
                elif путь is not None and (строка or итог[путь]):
                    итог[путь].append(строка)
            for путь in итог:
                while итог[путь] and итог[путь][-1] == "":
                    итог[путь].pop()
        return итог

    def сверить(self, файлы):
        полученные = self.выполнить(файлы)
        for путь in файлы:
            нужно = ожидается(прочитать(путь))
            есть = полученные.get(путь, [])
            with self.subTest(файл=os.path.relpath(путь, ПАПКА) if путь.startswith(ПАПКА) else путь):
                self.assertEqual(len(есть), len(нужно), "\n".join(есть[-3:] + ["---"] + нужно[-3:]))
                for д, п in zip(есть, нужно):
                    self.assertTrue(одинаковые(д, п), f"\nДан:    {д}\nPython: {п}")

    def test_программы_репозитория(self):
        файлы = файлы_репозитория()
        self.assertGreater(len(файлы), 100)
        self.сверить(файлы)

    def test_трудные_случаи(self):
        with tempfile.TemporaryDirectory() as папка:
            файлы = []
            for номер, текст in enumerate(ТРУДНЫЕ.values()):
                путь = os.path.join(папка, f"т{номер}.dan")
                with open(путь, "w", encoding="utf-8", newline="") as ф:
                    ф.write(текст)
                файлы.append(путь)
            self.сверить(файлы)



