def показать(т):
    """Токен lexer.py в записи сам/лексер.dan (функция показать)."""
    if т.значение is None:
        значение = ""
    elif т.вид == Т.ДРОБНОЕ:
        значение = repr(т.значение)
    else:
        значение = str(т.значение)
    значение = значение.replace("\\", "\\\\").replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    if т.написание and т.написание != т.значение:
        значение += " | " + т.написание
    return f"{т.вид.name} {т.строка}:{т.столбец} {значение}"


def ожидается(текст):
    try:
        return [показать(т) for т in разобрать(текст)]
    except ОшибкаЛексера as о:
        return ["ОШИБКА " + str(о).replace("\n", "\\n")]


def одинаковые(строка_дана, строка_питона):
    if строка_дана == строка_питона:
        return True
    # дробные числа: Дан хранит запись числа, lexer.py - само число
    if строка_дана.startswith("ДРОБНОЕ ") and строка_питона.startswith("ДРОБНОЕ "):
        место_д, запись = строка_дана.split(" ")[1:3]
        место_п, число = строка_питона.split(" ")[1:3]
        return место_д == место_п and float(запись) == float(число)
    return False


