    def выражение_или_присваивание(self):
        начало = self.тек
        выр = self.выражение()
        if self._знак(*ПРИСВАИВАНИЯ):
            оп = self._взять()
            значение = self.выражение()
            if isinstance(выр, у.Имя):
                return у.Присваивание(выр.имя, оп.значение, значение, написание=выр.написание,
                                      **self._поз(начало))
            if isinstance(выр, у.Индекс):
                return у.ПрисваиваниеЭлемента(выр.объект, выр.индекс, оп.значение, значение,
                                              **self._поз(начало))
            if isinstance(выр, у.Поле):
                return у.ПрисваиваниеПоля(выр.объект, выр.имя, оп.значение, значение,
                                          **self._поз(начало))
            self._ошибка("присваивать значение можно только переменной, элементу списка или полю", оп)
        return у.Выражение(выр, **self._поз(начало))

