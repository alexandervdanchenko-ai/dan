"""Парсер языка Дан (версия 0.3).

Получает список токенов от лексера и строит дерево программы.
Метод разбора - рекурсивный спуск: для каждого правила грамматики
есть своя функция, которая вызывает функции более мелких правил.

Приоритет операций (от низшего к высшему):
    или
    и
    не
    сравнения (== != < <= > >=)
    диапазон (..)
    сложение и вычитание (+ -)
    умножение, деление, остаток (* / : %; также × · ÷)
    унарный минус (-)
    вызов функции, обращение через точку, индекс ( ) . [ ]

Типы записываются строкой: "цел", "стр", список целых "[цел]",
список списков "[[цел]]".
"""

from lexer import Т, разобрать as разобрать_токены
import uzly as у


class ОшибкаРазбора(Exception):
    def __init__(self, сообщение, строка, столбец):
        super().__init__(f"Строка {строка}, позиция {столбец}: {сообщение}")
        self.строка = строка
        self.столбец = столбец


СРАВНЕНИЯ = ("==", "!=", "<", "<=", ">", ">=")
ПРИСВАИВАНИЯ = ("=", "+=", "-=", "*=", "/=")


def описать(токен):
    """Описание токена для сообщения об ошибке."""
    if токен.вид == Т.КОНЕЦ_СТРОКИ:
        return "конец строки"
    if токен.вид == Т.КОНЕЦ_ФАЙЛА:
        return "конец файла"
    if токен.вид == Т.СТРОКА:
        return f"строка \"{токен.значение}\""
    if токен.вид in (Т.ЦЕЛОЕ, Т.ДРОБНОЕ):
        return f"число {токен.значение}"
    return f"«{токен.значение}»"


class Парсер:
    def __init__(self, токены):
        self.токены = токены
        self.поз = 0

    # ---------- вспомогательные методы ----------

    @property
    def тек(self):
        return self.токены[self.поз]

    def _след(self, смещение=1):
        и = min(self.поз + смещение, len(self.токены) - 1)
        return self.токены[и]

    def _это(self, вид, значение=None, токен=None):
        т = токен or self.тек
        return т.вид == вид and (значение is None or т.значение == значение)

    def _знак(self, *значения):
        return self.тек.вид == Т.ЗНАК and self.тек.значение in значения

    def _ключ(self, *значения):
        return self.тек.вид == Т.КЛЮЧ and self.тек.значение in значения

    def _взять(self):
        т = self.тек
        if т.вид != Т.КОНЕЦ_ФАЙЛА:
            self.поз += 1
        return т

    def _ошибка(self, сообщение, токен=None):
        т = токен or self.тек
        raise ОшибкаРазбора(сообщение, т.строка, т.столбец)

    def _ожидать_знак(self, значение, что=None):
        if not self._знак(значение):
            self._ошибка(f"ожидалось «{значение}»{что or ''}, а найдено {описать(self.тек)}")
        return self._взять()

    def _ожидать_имя(self, что):
        if self.тек.вид != Т.ИМЯ:
            if self.тек.вид == Т.КЛЮЧ:
                self._ошибка(f"ожидалось {что}, а найдено ключевое слово «{self.тек.значение}», "
                             f"его нельзя использовать как имя")
            self._ошибка(f"ожидалось {что}, а найдено {описать(self.тек)}")
        return self._взять()

    def _пропустить_концы_строк(self):
        while self._это(Т.КОНЕЦ_СТРОКИ):
            self._взять()

    def _конец_инструкции(self):
        """После инструкции должен быть конец строки, «}» или конец файла."""
        if self._это(Т.КОНЕЦ_СТРОКИ):
            self._взять()
        elif self._знак("}") or self._это(Т.КОНЕЦ_ФАЙЛА):
            pass
        else:
            self._ошибка(f"ожидался конец строки, а найдено {описать(self.тек)}; "
                         f"каждая инструкция пишется на отдельной строке")

    def _тип(self, что):
        """Тип: имя (цел, стр, ...) или список «[тип]». Возвращает строку."""
        if self._знак("["):
            self._взять()
            внутренний = self._тип("тип элементов списка")
            self._ожидать_знак("]", " после типа элементов списка")
            return "[" + внутренний + "]"
        return self._ожидать_имя(что).значение

    @staticmethod
    def _поз(токен):
        return {"строка": токен.строка, "столбец": токен.столбец}

    # ---------- программа и блоки ----------

    def программа(self):
        начало = self.тек
        инструкции = []
        self._пропустить_концы_строк()
        while not self._это(Т.КОНЕЦ_ФАЙЛА):
            if self._знак("}"):
                self._ошибка("лишняя закрывающая скобка «}»")
            инструкции.append(self.инструкция())
            self._конец_инструкции()
            self._пропустить_концы_строк()
        return у.Программа(инструкции, **self._поз(начало))

    def блок(self, что):
        открытие = self._ожидать_знак("{", что)
        инструкции = []
        self._пропустить_концы_строк()
        while not self._знак("}"):
            if self._это(Т.КОНЕЦ_ФАЙЛА):
                self._ошибка("блок не закрыт: не хватает «}» для скобки, открытой "
                             f"в строке {открытие.строка}", открытие)
            инструкции.append(self.инструкция())
            self._конец_инструкции()
            self._пропустить_концы_строк()
        self._взять()  # «}»
        return у.Блок(инструкции, **self._поз(открытие))

    # ---------- инструкции ----------

    def инструкция(self):
        т = self.тек
        if т.вид == Т.КЛЮЧ:
            слово = т.значение
            if слово == "функ":
                return self.функция()
            if слово in ("пусть", "перем"):
                return self.объявление()
            if слово == "если":
                return self.если()
            if слово == "пока":
                return self.пока()
            if слово == "для":
                return self.для()
            if слово == "вернуть":
                return self.вернуть()
            if слово == "прервать":
                self._взять()
                return у.Прервать(**self._поз(т))
            if слово == "продолжить":
                self._взять()
                return у.Продолжить(**self._поз(т))
            if слово == "иначе":
                self._ошибка("«иначе» без предшествующего «если»")
        return self.выражение_или_присваивание()

    def функция(self):
        начало = self._взять()  # функ
        имя = self._ожидать_имя("имя функции после «функ»").значение
        self._ожидать_знак("(", " после имени функции")
        параметры = []
        if not self._знак(")"):
            while True:
                т = self._ожидать_имя("имя параметра")
                self._ожидать_знак(":", f" и тип после параметра «{т.значение}» (например, «{т.значение}: цел»)")
                тип = self._тип("название типа")
                if any(п.имя == т.значение for п in параметры):
                    self._ошибка(f"параметр «{т.значение}» указан дважды", т)
                параметры.append(у.Параметр(т.значение, тип, **self._поз(т)))
                if self._знак(","):
                    self._взять()
                    continue
                break
        self._ожидать_знак(")", " после списка параметров")
        тип_результата = None
        if self._знак("->"):
            self._взять()
            тип_результата = self._тип("тип результата после «->»")
        тело = self.блок(" перед телом функции")
        return у.Функция(имя, параметры, тип_результата, тело, **self._поз(начало))

    def объявление(self):
        начало = self._взять()  # пусть / перем
        изменяемая = начало.значение == "перем"
        имя = self._ожидать_имя(f"имя переменной после «{начало.значение}»").значение
        тип = None
        if self._знак(":"):
            self._взять()
            тип = self._тип("название типа")
        self._ожидать_знак("=", f": переменной «{имя}» нужно сразу задать значение")
        значение = self.выражение()
        return у.ОбъявлениеПеременной(имя, изменяемая, тип, значение, **self._поз(начало))

    def если(self):
        начало = self._взять()  # если
        условие = self.выражение()
        тогда = self.блок(" после условия «если»")
        иначе = None
        # «иначе» может стоять на той же строке после «}» или на следующей.
        сохр = self.поз
        self._пропустить_концы_строк()
        if self._ключ("иначе"):
            self._взять()
            if self._ключ("если"):
                иначе = self.если()
            else:
                иначе = self.блок(" или «если» после «иначе»")
        else:
            self.поз = сохр
        return у.Если(условие, тогда, иначе, **self._поз(начало))

    def пока(self):
        начало = self._взять()
        условие = self.выражение()
        тело = self.блок(" после условия «пока»")
        return у.Пока(условие, тело, **self._поз(начало))

    def для(self):
        начало = self._взять()
        переменная = self._ожидать_имя("имя переменной цикла после «для»").значение
        if not self._ключ("в"):
            self._ошибка(f"ожидалось «в» после «для {переменная}», а найдено {описать(self.тек)}")
        self._взять()
        источник = self.выражение()
        тело = self.блок(" перед телом цикла")
        return у.Для(переменная, источник, тело, **self._поз(начало))

    def вернуть(self):
        начало = self._взять()
        значение = None
        if not (self._это(Т.КОНЕЦ_СТРОКИ) or self._знак("}") or self._это(Т.КОНЕЦ_ФАЙЛА)):
            значение = self.выражение()
        return у.Вернуть(значение, **self._поз(начало))

    def выражение_или_присваивание(self):
        начало = self.тек
        выр = self.выражение()
        if self._знак(*ПРИСВАИВАНИЯ):
            оп = self._взять()
            значение = self.выражение()
            if isinstance(выр, у.Имя):
                return у.Присваивание(выр.имя, оп.значение, значение, **self._поз(начало))
            if isinstance(выр, у.Индекс):
                return у.ПрисваиваниеЭлемента(выр.объект, выр.индекс, оп.значение, значение,
                                              **self._поз(начало))
            self._ошибка("присваивать значение можно только переменной или элементу списка", оп)
        return у.Выражение(выр, **self._поз(начало))

    # ---------- выражения ----------

    def выражение(self):
        return self._или()

    def _или(self):
        левый = self._и()
        while self._ключ("или"):
            оп = self._взять()
            левый = у.Бинарная("или", левый, self._и(), **self._поз(оп))
        return левый

    def _и(self):
        левый = self._не()
        while self._ключ("и"):
            оп = self._взять()
            левый = у.Бинарная("и", левый, self._не(), **self._поз(оп))
        return левый

    def _не(self):
        if self._ключ("не"):
            оп = self._взять()
            return у.Унарная("не", self._не(), **self._поз(оп))
        return self._сравнение()

    def _сравнение(self):
        левый = self._диапазон()
        if self._знак(*СРАВНЕНИЯ):
            оп = self._взять()
            левый = у.Бинарная(оп.значение, левый, self._диапазон(), **self._поз(оп))
            if self._знак(*СРАВНЕНИЯ):
                self._ошибка("сравнения нельзя записывать цепочкой; "
                             "используйте «и», например: а < б и б < в")
        return левый

    def _диапазон(self):
        левый = self._сложение()
        if self._знак(".."):
            оп = self._взять()
            левый = у.Диапазон(левый, self._сложение(), **self._поз(оп))
        return левый

    def _сложение(self):
        левый = self._умножение()
        while self._знак("+", "-"):
            оп = self._взять()
            левый = у.Бинарная(оп.значение, левый, self._умножение(), **self._поз(оп))
        return левый

    def _умножение(self):
        левый = self._унарный()
        # Двоеточие внутри выражения - деление, как в школьной записи: 10 : 2
        while self._знак("*", "/", "%", ":"):
            оп = self._взять()
            знак = "/" if оп.значение == ":" else оп.значение
            левый = у.Бинарная(знак, левый, self._унарный(), **self._поз(оп))
        return левый

    def _унарный(self):
        if self._знак("-"):
            оп = self._взять()
            return у.Унарная("-", self._унарный(), **self._поз(оп))
        return self._постфикс()

    def _постфикс(self):
        выр = self._первичное()
        while True:
            if self._знак("("):
                скобка = self._взять()
                аргументы = []
                if not self._знак(")"):
                    аргументы.append(self.выражение())
                    while self._знак(","):
                        self._взять()
                        аргументы.append(self.выражение())
                self._ожидать_знак(")", " после аргументов функции")
                выр = у.Вызов(выр, аргументы, **self._поз(скобка))
            elif self._знак("["):
                скобка = self._взять()
                индекс = self.выражение()
                self._ожидать_знак("]", " после индекса")
                выр = у.Индекс(выр, индекс, **self._поз(скобка))
            elif self._знак("."):
                точка = self._взять()
                имя = self._ожидать_имя("имя после точки").значение
                выр = у.Поле(выр, имя, **self._поз(точка))
            else:
                return выр

    def _первичное(self):
        т = self.тек
        if т.вид == Т.ЦЕЛОЕ:
            self._взять()
            return у.ЦелоеЧисло(т.значение, **self._поз(т))
        if т.вид == Т.ДРОБНОЕ:
            self._взять()
            return у.ДробноеЧисло(т.значение, **self._поз(т))
        if т.вид == Т.СТРОКА:
            self._взять()
            return у.Строка(т.значение, **self._поз(т))
        if т.вид == Т.ИМЯ:
            self._взять()
            return у.Имя(т.значение, **self._поз(т))
        if self._ключ("истина", "ложь"):
            self._взять()
            return у.Логическое(т.значение == "истина", **self._поз(т))
        if self._знак("("):
            self._взять()
            выр = self.выражение()
            self._ожидать_знак(")", " для закрытия скобки")
            return выр
        if self._знак("["):
            self._взять()
            элементы = []
            while not self._знак("]"):
                элементы.append(self.выражение())
                if self._знак(","):
                    self._взять()
                elif not self._знак("]"):
                    self._ошибка(f"ожидалась «,» или «]» в списке, а найдено {описать(self.тек)}")
            self._взять()
            return у.Список(элементы, **self._поз(т))
        if т.вид == Т.КЛЮЧ:
            self._ошибка(f"ключевое слово «{т.значение}» не может стоять внутри выражения")
        self._ошибка(f"ожидалось значение, а найдено {описать(т)}")


def разобрать(текст):
    """Разбирает текст программы и возвращает дерево (узел Программа)."""
    return Парсер(разобрать_токены(текст)).программа()


