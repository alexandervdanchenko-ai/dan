"""Парсер языка Дан (версия 0.3).

Получает список токенов от лексера и строит дерево программы.
Метод разбора - рекурсивный спуск: для каждого правила грамматики
есть своя функция, которая вызывает функции более мелких правил.

Приоритет операций (от низшего к высшему):
    или
    и
    не
    сравнения (== != < <= > >=)
    диапазон (..)
    сложение и вычитание (+ -)
    умножение, деление, остаток (* / : %; также × · ÷)
    унарный минус (-)
    степень (^, ², ³)
    вызов функции, обращение через точку, индекс ( ) . [ ]

Типы записываются строкой: "цел", "стр", список целых "[цел]",
список списков "[[цел]]".
"""

from lexer import Т, разобрать as разобрать_токены
import uzly as у


class ОшибкаРазбора(Exception):
    def __init__(self, сообщение, строка, столбец):
        super().__init__(f"Строка {строка}, позиция {столбец}: {сообщение}")
        self.строка = строка
        self.столбец = столбец


СРАВНЕНИЯ = ("==", "!=", "<", "<=", ">", ">=")
ПРИСВАИВАНИЯ = ("=", "+=", "-=", "*=", "/=")


def описать(токен):
    """Описание токена для сообщения об ошибке."""
    if токен.вид == Т.КОНЕЦ_СТРОКИ:
        return "конец строки"
    if токен.вид == Т.КОНЕЦ_ФАЙЛА:
        return "конец файла"
    if токен.вид == Т.СТРОКА:
        return f"строка \"{токен.значение}\""
    if токен.вид in (Т.ЦЕЛОЕ, Т.ДРОБНОЕ):
        return f"число {токен.значение}"
    return f"«{токен.значение}»"


class Парсер:
    def __init__(self, токены):
        self.токены = токены
        self.поз = 0
        self.ключ_словаря = False   # внутри ключа словаря «:» отделяет значение, а не делит

    # ---------- вспомогательные методы ----------

    @property
    def тек(self):
        return self.токены[self.поз]

    def _след(self, смещение=1):
        и = min(self.поз + смещение, len(self.токены) - 1)
        return self.токены[и]

    def _это(self, вид, значение=None, токен=None):
        т = токен or self.тек
        return т.вид == вид and (значение is None or т.значение == значение)

    def _знак(self, *значения):
        return self.тек.вид == Т.ЗНАК and self.тек.значение in значения

    def _ключ(self, *значения):
        return self.тек.вид == Т.КЛЮЧ and self.тек.значение in значения

    def _взять(self):
        т = self.тек
        if т.вид != Т.КОНЕЦ_ФАЙЛА:
            self.поз += 1
        return т

    def _ошибка(self, сообщение, токен=None):
        т = токен or self.тек
        raise ОшибкаРазбора(сообщение, т.строка, т.столбец)

    def _ожидать_знак(self, значение, что=None):
        if not self._знак(значение):
            совет = ""
            if self.тек.значение == "=" and что and "условия" in что:
                совет = "; для сравнения используйте «==», а «=» означает присваивание"
            self._ошибка(f"ожидалось «{значение}»{что or ''}, а найдено {описать(self.тек)}{совет}")
        return self._взять()

    def _ожидать_имя(self, что):
        if self.тек.вид != Т.ИМЯ:
            if self.тек.вид == Т.КЛЮЧ:
                self._ошибка(f"ожидалось {что}, а найдено ключевое слово «{self.тек.значение}», "
                             f"его нельзя использовать как имя")
            self._ошибка(f"ожидалось {что}, а найдено {описать(self.тек)}")
        return self._взять()

    def _пропустить_концы_строк(self):
        while self._это(Т.КОНЕЦ_СТРОКИ):
            self._взять()

    def _конец_инструкции(self):
        """После инструкции должен быть конец строки, «}» или конец файла."""
        if self._это(Т.КОНЕЦ_СТРОКИ):
            self._взять()
        elif self._знак("}") or self._это(Т.КОНЕЦ_ФАЙЛА):
            pass
        else:
            self._ошибка(f"ожидался конец строки, а найдено {описать(self.тек)}; "
                         f"каждая инструкция пишется на отдельной строке")

    def _тип(self, что):
        """Тип: имя (цел, стр, Сотрудник, ...), список «[тип]» или
        необязательное значение «тип?». Возвращает строку."""
        if self._ключ("функ"):
            # тип функции: функ(цел, стр) -> лог
            self._взять()
            self._ожидать_знак("(", " после «функ» в типе функции")
            параметры = []
            while not self._знак(")"):
                параметры.append(self._тип("тип параметра функции"))
                if self._знак(","):
                    self._взять()
                elif not self._знак(")"):
                    self._ошибка(f"ожидалась «,» или «)» в типе функции, а найдено {описать(self.тек)}")
            self._взять()
            тип = "функ(" + ", ".join(параметры) + ")"
            if self._знак("->"):
                self._взять()
                if self._знак("!"):
                    self._взять()
                    тип += " -> пусто!"
                else:
                    тип += " -> " + self._тип("тип результата функции")
            return тип
        if self._знак("["):
            self._взять()
            внутренний = self._тип("тип элементов списка")
            self._ожидать_знак("]", " после типа элементов списка")
            тип = "[" + внутренний + "]"
        elif self._знак("{"):
            self._взять()
            ключ = self._тип("тип ключей словаря")
            self._ожидать_знак(":", " между типом ключей и типом значений словаря (например, {стр: цел})")
            значение = self._тип("тип значений словаря")
            self._ожидать_знак("}", " после типа значений словаря")
            тип = "{" + ключ + ": " + значение + "}"
        else:
            тип = self._ожидать_имя(что).значение
        if self._знак("?"):
            self._взять()
            тип += "?"
            if self._знак("?"):
                self._ошибка("знак «?» после типа ставится один раз")
        if self._знак("!"):
            self._взять()
            тип += "!"
            if self._знак("!", "?"):
                self._ошибка("знак «!» (результат может быть ошибкой) ставится один раз, в конце типа")
        return тип

    @staticmethod
    def _поз(токен):
        return {"строка": токен.строка, "столбец": токен.столбец}

    # ---------- программа и блоки ----------

    def программа(self):
        начало = self.тек
        инструкции = []
        self._пропустить_концы_строк()
        while not self._это(Т.КОНЕЦ_ФАЙЛА):
            if self._знак("}"):
                self._ошибка("лишняя закрывающая скобка «}»")
            инструкции.append(self.инструкция())
            self._конец_инструкции()
            self._пропустить_концы_строк()
        return у.Программа(инструкции, **self._поз(начало))

    def блок(self, что):
        открытие = self._ожидать_знак("{", что)
        инструкции = []
        self._пропустить_концы_строк()
        while not self._знак("}"):
            if self._это(Т.КОНЕЦ_ФАЙЛА):
                self._ошибка("блок не закрыт: не хватает «}» для скобки, открытой "
                             f"в строке {открытие.строка}", открытие)
            инструкции.append(self.инструкция())
            self._конец_инструкции()
            self._пропустить_концы_строк()
        self._взять()  # «}»
        return у.Блок(инструкции, **self._поз(открытие))

    # ---------- инструкции ----------

    def инструкция(self):
        т = self.тек
        if т.вид == Т.КЛЮЧ:
            слово = т.значение
            if слово == "функ":
                return self.функция()
            if слово == "тип":
                return self.объявление_типа()
            if слово == "выбор":
                return self.выбор()
            if слово in ("пусть", "перем"):
                return self.объявление()
            if слово == "если":
                return self.если()
            if слово == "пока":
                return self.пока()
            if слово == "для":
                return self.для()
            if слово == "вернуть":
                return self.вернуть()
            if слово == "прервать":
                self._взять()
                return у.Прервать(**self._поз(т))
            if слово == "продолжить":
                self._взять()
                return у.Продолжить(**self._поз(т))
            if слово == "иначе":
                self._ошибка("«иначе» без предшествующего «если»")
        return self.выражение_или_присваивание()

    def функция(self):
        начало = self._взять()  # функ
        имя = self._ожидать_имя("имя функции после «функ»").значение
        self._ожидать_знак("(", " после имени функции")
        параметры = []
        if not self._знак(")"):
            while True:
                т = self._ожидать_имя("имя параметра")
                self._ожидать_знак(":", f" и тип после параметра «{т.значение}» (например, «{т.значение}: цел»)")
                тип = self._тип("название типа")
                if any(п.имя == т.значение for п in параметры):
                    self._ошибка(f"параметр «{т.значение}» указан дважды", т)
                параметры.append(у.Параметр(т.значение, тип, **self._поз(т)))
                if self._знак(","):
                    self._взять()
                    continue
                break
        self._ожидать_знак(")", " после списка параметров")
        тип_результата = None
        if self._знак("->"):
            self._взять()
            if self._знак("!"):
                # -> ! : функция ничего не возвращает, но может завершиться ошибкой
                self._взять()
                тип_результата = "пусто!"
            else:
                тип_результата = self._тип("тип результата после «->»")
        тело = self.блок(" перед телом функции")
        return у.Функция(имя, параметры, тип_результата, тело, **self._поз(начало))

    def объявление_типа(self):
        начало = self._взять()  # тип
        т_имя = self._ожидать_имя("название типа после «тип»")
        имя = т_имя.значение
        открытие = self._ожидать_знак("{", f" после названия типа «{имя}»")
        # Перечисление: внутри не поля «имя: тип», а варианты «Имя(...)» или «Имя».
        сохр = self.поз
        self._пропустить_концы_строк()
        if self.тек.вид == Т.ИМЯ and not self._это(Т.ЗНАК, ":", self._след()):
            return self._варианты(начало, т_имя, открытие)
        self.поз = сохр
        поля = []
        while True:
            while self._это(Т.КОНЕЦ_СТРОКИ) or self._знак(","):
                self._взять()
            if self._знак("}"):
                self._взять()
                break
            if self._это(Т.КОНЕЦ_ФАЙЛА):
                self._ошибка(f"описание типа «{имя}» не закрыто: не хватает «}}» для скобки, "
                             f"открытой в строке {открытие.строка}", открытие)
            т = self._ожидать_имя(f"имя поля типа «{имя}»")
            if any(п.имя == т.значение for п in поля):
                self._ошибка(f"поле «{т.значение}» указано дважды", т)
            self._ожидать_знак(":", f" и тип после поля «{т.значение}» (например, «{т.значение}: стр»)")
            тип = self._тип("тип поля")
            по_умолчанию = None
            if self._знак("="):
                self._взять()
                по_умолчанию = self.выражение()
            поля.append(у.ПолеТипа(т.значение, тип, по_умолчанию, т.написание, **self._поз(т)))
            if not (self._это(Т.КОНЕЦ_СТРОКИ) or self._знак(",", "}")):
                self._ошибка(f"после поля «{т.значение}» ожидался перевод строки, «,» или «}}», "
                             f"а найдено {описать(self.тек)}")
        if not поля:
            self._ошибка(f"у типа «{имя}» должно быть хотя бы одно поле", начало)
        return у.ОбъявлениеТипа(имя, поля, т_имя.написание, **self._поз(начало))

    def _варианты(self, начало, т_имя, открытие):
        варианты = []
        while True:
            while self._это(Т.КОНЕЦ_СТРОКИ) or self._знак(",", "|"):
                self._взять()
            if self._знак("}"):
                self._взять()
                break
            if self._это(Т.КОНЕЦ_ФАЙЛА):
                self._ошибка(f"описание типа «{т_имя.значение}» не закрыто: не хватает «}}»", открытие)
            т = self._ожидать_имя(f"название варианта типа «{т_имя.значение}»")
            if any(в.имя == т.значение for в in варианты):
                self._ошибка(f"вариант «{т.значение}» указан дважды", т)
            поля = []
            if self._знак("("):
                self._взять()
                while not self._знак(")"):
                    п = self._ожидать_имя(f"имя поля варианта «{т.значение}»")
                    self._ожидать_знак(":", f" и тип после поля «{п.значение}»")
                    тип = self._тип("тип поля")
                    if any(х.имя == п.значение for х in поля):
                        self._ошибка(f"поле «{п.значение}» указано дважды", п)
                    поля.append(у.ПолеТипа(п.значение, тип, None, п.написание, **self._поз(п)))
                    if self._знак(","):
                        self._взять()
                    elif not self._знак(")"):
                        self._ошибка(f"ожидалась «,» или «)» в полях варианта, а найдено {описать(self.тек)}")
                self._взять()
            варианты.append(у.ВариантТипа(т.значение, поля, т.написание, **self._поз(т)))
        return у.ОбъявлениеВариантов(т_имя.значение, варианты, т_имя.написание, **self._поз(начало))

    def выбор(self):
        начало = self._взять()  # выбор
        значение = self.выражение()
        открытие = self._ожидать_знак("{", " после значения в «выбор»")
        ветви, иначе = [], None
        while True:
            self._пропустить_концы_строк()
            if self._знак("}"):
                self._взять()
                break
            if self._это(Т.КОНЕЦ_ФАЙЛА):
                self._ошибка("«выбор» не закрыт: не хватает «}»", открытие)
            if self._ключ("иначе"):
                т = self._взять()
                if иначе is not None:
                    self._ошибка("ветвь «иначе» в «выбор» может быть только одна", т)
                иначе = self.блок(" после «иначе» в «выбор»")
                continue
            if иначе is not None:
                self._ошибка("ветвь «иначе» должна быть последней в «выбор»")
            ветвь_начало = self.тек
            образцы = [self._образец()]
            while self._знак(","):
                self._взять()
                образцы.append(self._образец())
            тело = self.блок(" после образца в «выбор»")
            ветви.append(у.ВетвьВыбора(образцы, тело, **self._поз(ветвь_начало)))
        if not ветви and иначе is None:
            self._ошибка("в «выбор» нет ни одной ветви", начало)
        return у.Выбор(значение, ветви, иначе, **self._поз(начало))

    def _образец(self):
        т = self.тек
        if т.вид == Т.ИМЯ and not self._это(Т.ЗНАК, "..", self._след()):
            self._взять()
            привязки = []
            if self._знак("("):
                self._взять()
                while not self._знак(")"):
                    привязки.append(self._ожидать_имя("имя для поля варианта (или «_»)").значение)
                    if self._знак(","):
                        self._взять()
                    elif not self._знак(")"):
                        self._ошибка(f"ожидалась «,» или «)», а найдено {описать(self.тек)}")
                self._взять()
            return у.ОбразецВарианта(т.значение, привязки, **self._поз(т))
        # значение: число, строка, логическое значение или диапазон из них
        return self._диапазон()

    def объявление(self):
        начало = self._взять()  # пусть / перем
        изменяемая = начало.значение == "перем"
        имя = self._ожидать_имя(f"имя переменной после «{начало.значение}»").значение
        тип = None
        if self._знак(":"):
            self._взять()
            тип = self._тип("название типа")
        self._ожидать_знак("=", f": переменной «{имя}» нужно сразу задать значение")
        значение = self.выражение()
        return у.ОбъявлениеПеременной(имя, изменяемая, тип, значение, **self._поз(начало))

    def если(self):
        начало = self._взять()  # если
        проверка_значения = None
        if (self.тек.вид == Т.ИМЯ and self.тек.значение == "ошибка" and self._след().вид == Т.ИМЯ
                and self._это(Т.ЗНАК, "=", self._след(2))):
            # если ошибка о = значение { ... }
            self._взять()
            имя = self._взять().значение
            self._взять()  # =
            значение = self.выражение()
            тогда = self.блок(f" после «если ошибка {имя} = ...»")
            иначе = self._иначе_после_если()
            return у.ЕслиОшибка(имя, значение, тогда, иначе, **self._поз(начало))
        if self._ключ("пусть"):
            # если пусть имя = значение { ... }: значение необязательного типа есть
            self._взять()
            имя = self._ожидать_имя("имя после «если пусть»").значение
            self._ожидать_знак("=", f" после «если пусть {имя}»")
            проверка_значения = (имя, self.выражение())
            тогда = self.блок(f" после «если пусть {имя} = ...»")
        else:
            условие = self.выражение()
            тогда = self.блок(" после условия «если»")
        имя_ошибки = None
        if проверка_значения:
            # иначе ошибка о { ... }: в ветви доступен текст ошибки
            сохр = self.поз
            self._пропустить_концы_строк()
            if (self._ключ("иначе") and self._след().вид == Т.ИМЯ and self._след().значение == "ошибка"
                    and self._след(2).вид == Т.ИМЯ):
                self._взять()
                self._взять()
                имя_ошибки = self._взять().значение
                иначе = self.блок(f" после «иначе ошибка {имя_ошибки}»")
                return у.ЕслиЕсть(*проверка_значения, тогда, иначе, имя_ошибки, **self._поз(начало))
            self.поз = сохр
        иначе = self._иначе_после_если()
        if проверка_значения:
            return у.ЕслиЕсть(*проверка_значения, тогда, иначе, **self._поз(начало))
        return у.Если(условие, тогда, иначе, **self._поз(начало))

    def _иначе_после_если(self):
        # «иначе» может стоять на той же строке после «}» или на следующей.
        сохр = self.поз
        self._пропустить_концы_строк()
        if self._ключ("иначе"):
            self._взять()
            if self._ключ("если"):
                return self.если()
            return self.блок(" или «если» после «иначе»")
        self.поз = сохр
        return None

    def пока(self):
        начало = self._взять()
        условие = self.выражение()
        тело = self.блок(" после условия «пока»")
        return у.Пока(условие, тело, **self._поз(начало))

    def для(self):
        начало = self._взять()
        переменная = self._ожидать_имя("имя переменной цикла после «для»").значение
        if not self._ключ("в"):
            self._ошибка(f"ожидалось «в» после «для {переменная}», а найдено {описать(self.тек)}")
        self._взять()
        источник = self.выражение()
        тело = self.блок(" перед телом цикла")
        return у.Для(переменная, источник, тело, **self._поз(начало))

    def вернуть(self):
        начало = self._взять()
        значение = None
        if not (self._это(Т.КОНЕЦ_СТРОКИ) or self._знак("}") or self._это(Т.КОНЕЦ_ФАЙЛА)):
            значение = self.выражение()
        return у.Вернуть(значение, **self._поз(начало))

    def выражение_или_присваивание(self):
        начало = self.тек
        выр = self.выражение()
        if self._знак(*ПРИСВАИВАНИЯ):
            оп = self._взять()
            значение = self.выражение()
            if isinstance(выр, у.Имя):
                return у.Присваивание(выр.имя, оп.значение, значение, написание=выр.написание,
                                      **self._поз(начало))
            if isinstance(выр, у.Индекс):
                return у.ПрисваиваниеЭлемента(выр.объект, выр.индекс, оп.значение, значение,
                                              **self._поз(начало))
            if isinstance(выр, у.Поле):
                return у.ПрисваиваниеПоля(выр.объект, выр.имя, оп.значение, значение,
                                          **self._поз(начало))
            self._ошибка("присваивать значение можно только переменной, элементу списка или полю", оп)
        return у.Выражение(выр, **self._поз(начало))

    # ---------- выражения ----------

    def выражение(self):
        return self._иначе()

    def _иначе(self):
        """а иначе б - самая слабая операция; выполняется справа налево."""
        значение = self._или()
        if self._ключ("иначе"):
            оп = self._взять()
            return у.Иначе(значение, self._иначе(), **self._поз(оп))
        return значение

    def _или(self):
        левый = self._и()
        while self._ключ("или"):
            оп = self._взять()
            левый = у.Бинарная("или", левый, self._и(), **self._поз(оп))
        return левый

    def _и(self):
        левый = self._не()
        while self._ключ("и"):
            оп = self._взять()
            левый = у.Бинарная("и", левый, self._не(), **self._поз(оп))
        return левый

    def _не(self):
        if self._ключ("не"):
            оп = self._взять()
            return у.Унарная("не", self._не(), **self._поз(оп))
        return self._сравнение()

    def _сравнение(self):
        левый = self._диапазон()
        if self._знак(*СРАВНЕНИЯ):
            оп = self._взять()
            левый = у.Бинарная(оп.значение, левый, self._диапазон(), **self._поз(оп))
            if self._знак(*СРАВНЕНИЯ):
                self._ошибка("сравнения нельзя записывать цепочкой; "
                             "используйте «и», например: а < б и б < в")
        return левый

    def _диапазон(self):
        левый = self._сложение()
        if self._знак(".."):
            оп = self._взять()
            левый = у.Диапазон(левый, self._сложение(), **self._поз(оп))
        return левый

    def _сложение(self):
        левый = self._умножение()
        while self._знак("+", "-"):
            оп = self._взять()
            левый = у.Бинарная(оп.значение, левый, self._умножение(), **self._поз(оп))
        return левый

    def _умножение(self):
        левый = self._унарный()
        # Двоеточие внутри выражения - деление, как в школьной записи: 10 : 2
        while self._знак("*", "/", "%") or (self._знак(":") and not self.ключ_словаря):
            оп = self._взять()
            знак = "/" if оп.значение == ":" else оп.значение
            левый = у.Бинарная(знак, левый, self._унарный(), **self._поз(оп))
        return левый

    def _унарный(self):
        if self._знак("-"):
            оп = self._взять()
            return у.Унарная("-", self._унарный(), **self._поз(оп))
        return self._степень()

    def _степень(self):
        """а ^ н. Степень выполняется раньше унарного минуса (-2^2 = -4)
        и справа налево (2^3^2 = 2^9), как принято в математике."""
        основание = self._постфикс()
        if self._знак("^"):
            оп = self._взять()
            return у.Бинарная("^", основание, self._унарный(), **self._поз(оп))
        return основание

    def _постфикс(self):
        выр = self._первичное()
        while True:
            if self._знак("("):
                скобка = self._взять()
                аргументы, имена = [], []
                if not self._знак(")"):
                    while True:
                        # именованный аргумент: имя = значение
                        if self.тек.вид == Т.ИМЯ and self._это(Т.ЗНАК, "=", self._след()):
                            т = self._взять()
                            self._взять()
                            if т.значение in имена:
                                self._ошибка(f"аргумент «{т.значение}» указан дважды", т)
                            имена.append(т.значение)
                        else:
                            if any(имена):
                                self._ошибка("после именованных аргументов («имя = значение») "
                                             "позиционные указывать нельзя")
                            имена.append(None)
                        аргументы.append(self.выражение())
                        if not self._знак(","):
                            break
                        self._взять()
                self._ожидать_знак(")", " после аргументов функции")
                выр = у.Вызов(выр, аргументы, имена if any(имена) else None, **self._поз(скобка))
            elif self._знак("["):
                скобка = self._взять()
                индекс = self.выражение()
                self._ожидать_знак("]", " после индекса")
                выр = у.Индекс(выр, индекс, **self._поз(скобка))
            elif self._знак("!"):
                знак = self._взять()
                выр = у.Передать(выр, **self._поз(знак))
            elif self._знак("."):
                точка = self._взять()
                имя = self._ожидать_имя("имя после точки").значение
                выр = у.Поле(выр, имя, **self._поз(точка))
            else:
                return выр

    def _лямбда(self):
        начало = self._взять()  # функ
        self._ожидать_знак("(", " после «функ»: безымянная функция записывается как функ(х: цел) = х * 2")
        параметры = []
        while not self._знак(")"):
            т = self._ожидать_имя("имя параметра")
            тип = None
            if self._знак(":"):
                self._взять()
                тип = self._тип("тип параметра")
            if any(п.имя == т.значение for п in параметры):
                self._ошибка(f"параметр «{т.значение}» указан дважды", т)
            параметры.append(у.Параметр(т.значение, тип, **self._поз(т)))
            if self._знак(","):
                self._взять()
            elif not self._знак(")"):
                self._ошибка(f"ожидалась «,» или «)» в параметрах, а найдено {описать(self.тек)}")
        self._взять()
        тип_результата = None
        if self._знак("->"):
            self._взять()
            if self._знак("!"):
                self._взять()
                тип_результата = "пусто!"
            else:
                тип_результата = self._тип("тип результата после «->»")
        if self._знак("="):
            self._взять()
            сохр, self.ключ_словаря = self.ключ_словаря, False
            выражение = self.выражение()
            self.ключ_словаря = сохр
            return у.Лямбда(параметры, тип_результата, None, выражение, **self._поз(начало))
        тело = self.блок(" или «=» после параметров безымянной функции")
        return у.Лямбда(параметры, тип_результата, тело, None, **self._поз(начало))

    def _словарь(self):
        открытие = self._взять()  # {
        ключи, значения = [], []
        while True:
            self._пропустить_концы_строк()
            if self._знак("}"):
                self._взять()
                break
            if self._это(Т.КОНЕЦ_ФАЙЛА):
                self._ошибка("словарь не закрыт: не хватает «}»", открытие)
            сохр, self.ключ_словаря = self.ключ_словаря, True
            ключ = self.выражение()
            self.ключ_словаря = сохр
            self._ожидать_знак(":", " между ключом и значением словаря")
            сохр, self.ключ_словаря = self.ключ_словаря, False
            значение = self.выражение()
            self.ключ_словаря = сохр
            ключи.append(ключ)
            значения.append(значение)
            self._пропустить_концы_строк()
            if self._знак(","):
                self._взять()
            elif not self._знак("}"):
                self._ошибка(f"ожидалась «,» или «}}» в словаре, а найдено {описать(self.тек)}")
        return у.Словарь(ключи, значения, **self._поз(открытие))

    def _первичное(self):
        т = self.тек
        if т.вид == Т.ЦЕЛОЕ:
            self._взять()
            return у.ЦелоеЧисло(т.значение, **self._поз(т))
        if т.вид == Т.ДРОБНОЕ:
            self._взять()
            return у.ДробноеЧисло(т.значение, **self._поз(т))
        if т.вид == Т.СТРОКА:
            self._взять()
            return у.Строка(т.значение, **self._поз(т))
        if т.вид == Т.ИМЯ:
            self._взять()
            return у.Имя(т.значение, написание=т.написание, **self._поз(т))
        if self._ключ("истина", "ложь"):
            self._взять()
            return у.Логическое(т.значение == "истина", **self._поз(т))
        if self._ключ("ничего"):
            self._взять()
            return у.Ничего(**self._поз(т))
        if self._ключ("функ"):
            return self._лямбда()
        if self._знак("("):
            self._взять()
            сохр, self.ключ_словаря = self.ключ_словаря, False
            выр = self.выражение()
            self.ключ_словаря = сохр
            self._ожидать_знак(")", " для закрытия скобки")
            return выр
        if self._знак("{"):
            return self._словарь()
        if self._знак("["):
            self._взять()
            элементы = []
            while not self._знак("]"):
                элементы.append(self.выражение())
                if self._знак(","):
                    self._взять()
                elif not self._знак("]"):
                    self._ошибка(f"ожидалась «,» или «]» в списке, а найдено {описать(self.тек)}")
            self._взять()
            return у.Список(элементы, **self._поз(т))
        if т.вид == Т.КЛЮЧ:
            self._ошибка(f"ключевое слово «{т.значение}» не может стоять внутри выражения")
        self._ошибка(f"ожидалось значение, а найдено {описать(т)}")


def разобрать(текст):
    """Разбирает текст программы и возвращает дерево (узел Программа)."""
    return Парсер(разобрать_токены(текст)).программа()


