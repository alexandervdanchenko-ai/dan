    def выбор(self):
        начало = self._взять()  # выбор
        значение = self.выражение()
        открытие = self._ожидать_знак("{", " после значения в «выбор»")
        ветви, иначе = [], None
        while True:
            self._пропустить_концы_строк()
            if self._знак("}"):
                self._взять()
                break
            if self._это(Т.КОНЕЦ_ФАЙЛА):
                self._ошибка("«выбор» не закрыт: не хватает «}»", открытие)
            if self._ключ("иначе"):
                т = self._взять()
                if иначе is not None:
                    self._ошибка("ветвь «иначе» в «выбор» может быть только одна", т)
                иначе = self.блок(" после «иначе» в «выбор»")
                continue
            if иначе is not None:
                self._ошибка("ветвь «иначе» должна быть последней в «выбор»")
            ветвь_начало = self.тек
            образцы = [self._образец()]
            while self._знак(","):
                self._взять()
                образцы.append(self._образец())
            тело = self.блок(" после образца в «выбор»")
            ветви.append(у.ВетвьВыбора(образцы, тело, **self._поз(ветвь_начало)))
        if not ветви and иначе is None:
            self._ошибка("в «выбор» нет ни одной ветви", начало)
        return у.Выбор(значение, ветви, иначе, **self._поз(начало))

    def _образец(self):
        т = self.тек
        if т.вид == Т.ИМЯ and not self._это(Т.ЗНАК, "..", self._след()):
            имя = self._составное_имя("вариант")
            привязки = []
            if self._знак("("):
                self._взять()
                while not self._знак(")"):
                    привязки.append(self._ожидать_имя("имя для поля варианта (или «_»)").значение)
                    if self._знак(","):
                        self._взять()
                    elif not self._знак(")"):
                        self._ошибка(f"ожидалась «,» или «)», а найдено {описать(self.тек)}")
                self._взять()
            return у.ОбразецВарианта(имя, привязки, **self._поз(т))
        # значение: число, строка, логическое значение или диапазон из них
        return self._диапазон()

