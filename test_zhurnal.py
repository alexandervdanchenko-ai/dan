"""Тесты модуля журнал (библиотека/журнал.dan): уровни, поля, JSON, файл и запись из задач."""

import json
import os
import re
import subprocess
import tempfile
import unittest

import dan
from test_kodogen import КОМПИЛЯТОР_ЕСТЬ

ПРОГРАММА = """
подключить "журнал"

функ писать(ф: журнал.Журнал, н: цел) {
    для к в 1..100 { ф.сведения("задача " + стр(н) + " строка " + стр(к)) }
}

перем ж = журнал.в_поток_ошибок("сервер")
ж.сведения("запущен")
ж.отладка("не видно")
ж = ж.с_уровнем(журнал.ОТЛАДКА())
ж.отладка("видно")
ж.предупреждение_с("медленно", {"путь": "/дела 1", "мс": "1250", "кавычка": "а\\"б", "": "х"})
ж.с_источником("база").ошибка("строка1\\nстрока2")
ж.с_уровнем(журнал.ОШИБКА()).предупреждение("не видно")
пусть ф = журнал.в_файл("ж.txt", "ф").с_json()
ф.сведения_с("запрос", {"код": "200", "текст": "не заменит"})
параллельно {
    для н в 1..4 { запустить писать(ф, н) }
}
вывод(журнал.уровень_из_среды("ЖУРНАЛ", 1))
вывод(журнал.уровень_из_среды("НЕТ_ТАКОЙ_ПЕРЕМЕННОЙ", 2))
вывод(журнал.в_поток_ошибок("п").строка(журнал.СВЕДЕНИЯ(), "т", {"а": "1"}).длина)
"""

ВРЕМЯ = r"\d{4}-\d\d-\d\d \d\d:\d\d:\d\d"


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыЖурнала(unittest.TestCase):

    def test_журнал(self):
        with tempfile.TemporaryDirectory() as папка:
            путь = os.path.join(папка, "п.dan")
            with open(путь, "w", encoding="utf-8") as ф:
                ф.write(ПРОГРАММА)
            исполняемый = dan.собрать(путь, ПРОГРАММА)
            среда = dict(os.environ, ЖУРНАЛ="Warning")
            р = subprocess.run([исполняемый], capture_output=True, cwd=папка, env=среда, timeout=60)
            self.assertEqual(р.returncode, 0, р.stderr)
            self.assertEqual(р.stdout.decode("utf-8").split(), ["2", "2", str(len("2026-11-10 14:05:09 СВЕДЕНИЯ п: т а=1"))])
            строки = р.stderr.decode("utf-8").replace("\r\n", "\n").splitlines()
            ожидается = ["СВЕДЕНИЯ сервер: запущен", "ОТЛАДКА сервер: видно",
                         'ПРЕДУПРЕЖДЕНИЕ сервер: медленно путь="/дела 1" мс=1250 кавычка="а\\"б" =х',
                         "ОШИБКА база: строка1 строка2"]
            self.assertEqual(len(строки), len(ожидается), строки)
            for с, о in zip(строки, ожидается):
                self.assertRegex(с, "^" + ВРЕМЯ + " ")
                self.assertEqual(с[20:], о)
            with open(os.path.join(папка, "ж.txt"), encoding="utf-8") as ф:
                записи = [json.loads(с) for с in ф.read().splitlines()]
            self.assertEqual(len(записи), 401)
            self.assertEqual({к: в for к, в in записи[0].items() if к != "время"},
                             {"уровень": "СВЕДЕНИЯ", "источник": "ф", "текст": "запрос", "код": "200"})
            self.assertRegex(записи[0]["время"], "^" + ВРЕМЯ + "$")
            тексты = sorted(з["текст"] for з in записи[1:])
            self.assertEqual(тексты, sorted(f"задача {н} строка {к}" for н in range(1, 5) for к in range(1, 101)))


if __name__ == "__main__":
    unittest.main()
