"""Тесты выполнения: программа на Дан собирается в исполняемый файл,
запускается, и её вывод сверяется с ожидаемым."""

import os
import shutil
import subprocess
import tempfile
import unittest

import dan

КОМПИЛЯТОР_ЕСТЬ = dan.компилятор_есть()


def выполнить(текст, ввод_данных=""):
    """Возвращает (код завершения, вывод, вывод ошибок)."""
    with tempfile.TemporaryDirectory() as папка:
        путь = os.path.join(папка, "программа.dan")
        with open(путь, "w", encoding="utf-8") as ф:
            ф.write(текст)
        исполняемый = dan.собрать(путь, текст)
        р = subprocess.run([исполняемый], capture_output=True, text=True,
                           encoding="utf-8", timeout=30, input=ввод_данных)
        return р.returncode, р.stdout, р.stderr


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыВыполнения(unittest.TestCase):

    def вывод(self, текст, ожидается, ввод_данных=""):
        код, вывод, ошибки = выполнить(текст, ввод_данных)
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод.splitlines(), ожидается)

    def test_значения_всех_типов(self):
        self.вывод('вывод(42)\nвывод(-7)\nвывод(2.5)\nвывод("Привет, мир!")\nвывод(истина)\nвывод(ложь)',
                   ["42", "-7", "2.5", "Привет, мир!", "истина", "ложь"])

