"""Тесты выполнения: программа на Дан собирается в исполняемый файл,
запускается, и её вывод сверяется с ожидаемым."""

import os
import shutil
import subprocess
import tempfile
import unittest

import dan

КОМПИЛЯТОР_ЕСТЬ = any(shutil.which(к) for к in dan.КОМПИЛЯТОРЫ)


def выполнить(текст):
    """Возвращает (код завершения, вывод, вывод ошибок)."""
    with tempfile.TemporaryDirectory() as папка:
        путь = os.path.join(папка, "программа.dan")
        with open(путь, "w", encoding="utf-8") as ф:
            ф.write(текст)
        исполняемый = dan.собрать(путь, текст)
        р = subprocess.run([исполняемый], capture_output=True, text=True,
                           encoding="utf-8", timeout=30)
        return р.returncode, р.stdout, р.stderr


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыВыполнения(unittest.TestCase):

    def вывод(self, текст, ожидается):
        код, вывод, ошибки = выполнить(текст)
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод.splitlines(), ожидается)

    def test_значения_всех_типов(self):
        self.вывод('вывод(42)\nвывод(-7)\nвывод(2.5)\nвывод("Привет, мир!")\nвывод(истина)\nвывод(ложь)',
                   ["42", "-7", "2.5", "Привет, мир!", "истина", "ложь"])

    def test_арифметика_и_приоритет(self):
        self.вывод("вывод(1 + 2 * 3)\nвывод((1 + 2) * 3)\nвывод(10 - 3 - 2)\nвывод(-2 * -3)",
                   ["7", "9", "5", "6"])

    def test_деление(self):
        self.вывод("вывод(7 / 2)\nвывод(-7 / 2)\nвывод(7 / 2.0)\nвывод(7 % 3)\nвывод(-7 % 3)",
                   ["3", "-3", "3.5", "1", "-1"])

    def test_смешанная_арифметика(self):
        self.вывод("пусть а = 3\nпусть б = 0.5\nвывод(а * б)\nвывод(а + 1.0)", ["1.5", "4.0"])

    def test_дроби(self):
        self.вывод("вывод(10.0)\nвывод(0.1 + 0.2)\nвывод(1.0 / 3.0)\nвывод(100000000000000000000.0)",
                   ["10.0", "0.30000000000000004", "0.3333333333333333", "1e+20"])

    def test_большие_целые(self):
        self.вывод("вывод(9_223_372_036_854_775_807)\nвывод(1_000_000 * 1_000_000)",
                   ["9223372036854775807", "1000000000000"])

    def test_строки(self):
        self.вывод('пусть а = "Да"\nперем б = а + "н"\nб += "!"\nвывод(б)\n'
                   'вывод(б == "Дан!")\nвывод(б != "Дан!")\nвывод("кавычка \\" и \\\\ и\\tтаб")',
                   ["Дан!", "истина", "ложь", 'кавычка " и \\ и\tтаб'])

    def test_перевод_строки_в_тексте(self):
        self.вывод('вывод("раз\\nдва")', ["раз", "два"])

    def test_логика(self):
        self.вывод("вывод(истина и ложь)\nвывод(истина или ложь)\nвывод(не ложь)\n"
                   "вывод(1 < 2 и 2.5 >= 2)\nвывод(3 == 3.0)",
                   ["ложь", "истина", "истина", "истина", "истина"])

    def test_если_иначе(self):
        программа = ("функ знак(х: цел) -> стр {\n"
                     " если х > 0 { вернуть \"+\" } иначе если х == 0 { вернуть \"0\" } иначе { вернуть \"-\" }\n"
                     "}\nвывод(знак(5))\nвывод(знак(0))\nвывод(знак(-5))")
        self.вывод(программа, ["+", "0", "-"])

    def test_циклы(self):
        программа = ("перем с = 0\nдля ч в 1..10 {\n если ч == 3 { продолжить }\n"
                     " если ч == 8 { прервать }\n с += ч\n}\nвывод(с)\n"
                     "перем п = 1\nпока п < 1000 { п *= 2 }\nвывод(п)")
        self.вывод(программа, ["25", "1024"])

    def test_граница_цикла_вычисляется_один_раз(self):
        программа = ("перем н = 3\nперем раз = 0\nдля ч в 1..н {\n н += 1\n раз += 1\n}\nвывод(раз)")
        self.вывод(программа, ["3"])

    def test_пустой_диапазон(self):
        self.вывод("для ч в 5..1 { вывод(ч) }\nвывод(\"конец\")", ["конец"])

    def test_рекурсия_и_вызов_до_объявления(self):
        self.вывод("вывод(фиб(20))\nфунк фиб(н: цел) -> цел {\n если н < 2 { вернуть н }\n"
                   " вернуть фиб(н - 1) + фиб(н - 2)\n}", ["6765"])

    def test_функция_без_результата(self):
        self.вывод("функ привет(имя: стр) {\n если имя == \"\" { вернуть }\n вывод(\"Привет, \" + имя)\n}\n"
                   "привет(\"\")\nпривет(\"Дан\")", ["Привет, Дан"])

    def test_латинские_и_похожие_имена(self):
        # «summa» и «сумма» транслитерируются одинаково, но не должны совпасть в C.
        self.вывод("пусть summa = 1\nпусть сумма = 2\nпусть Сумма = 3\nвывод(summa + сумма * 10 + Сумма * 100)",
                   ["321"])

    def test_имена_совпадающие_со_словами_c(self):
        self.вывод("пусть int = 1\nпусть main = 2\nпусть printf = 3\nвывод(int + main + printf)", ["6"])

    def test_деление_на_ноль(self):
        код, вывод, ошибки = выполнить("вывод(1)\nпусть н = 0\nвывод(5 / н)")
        self.assertEqual(код, 1)
        self.assertEqual(вывод.splitlines(), ["1"])
        self.assertIn("строке 3", ошибки)
        self.assertIn("деление на ноль", ошибки)

    def test_примеры(self):
        ожидается = {
            "факториал.dan": ["3628800"],
            "сумма.dan": ["Сумма: ", "2520"],
        }
        папка = os.path.join(os.path.dirname(__file__), "примеры")
        for имя, строки in ожидается.items():
            with self.subTest(имя=имя), open(os.path.join(папка, имя), encoding="utf-8") as ф:
                self.вывод(ф.read(), строки)


if __name__ == "__main__":
    unittest.main()
