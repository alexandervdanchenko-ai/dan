        # делимое = частное × делитель + остаток, 0 <= остаток < |делитель|
        self.вывод("вывод(-7 / 2)\nвывод(-7 % 2)\nвывод(-7 % 3)\nвывод(7 / -2)\nвывод(7 % -2)\n"
                   "вывод(-7 / -2)\nвывод(-7 % -2)\nвывод(-6 / 3)\nвывод(-6 % 3)",
                   ["-4", "1", "2", "-3", "1", "4", "1", "-2", "0"])
        программа = ("перем ошибок = 0\nдля а в -20..20 {\n для б в -6..6 {\n  если б == 0 { продолжить }\n"
                     "  пусть ч = а / б\n  пусть о = а % б\n"
                     "  если ч * б + о != а или о < 0 или о >= модуль(б) { ошибок += 1 }\n }\n}\nвывод(ошибок)")
        self.вывод(программа, ["0"])

