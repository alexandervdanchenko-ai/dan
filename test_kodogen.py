    def test_ошибки_библиотеки(self):
        self.ошибка_выполнения("вывод(делители(0))", "только для натуральных чисел")
        self.ошибка_выполнения("вывод(простые_множители(-4))", "получено -4")
        self.ошибка_выполнения("вывод(делится(5, 0))", "деление на ноль")
