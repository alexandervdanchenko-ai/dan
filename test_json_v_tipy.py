ТИПЫ = """подключить "json"
тип Позиция {
    имя: стр
    цена: дроб
    число: цел = 1
}
тип Заказ {
    номер "id": цел
    клиент "customer": стр
    оплачен: лог = ложь
    позиции: [Позиция] = []
    скидка: дроб?
    метки: {стр: цел} = {}
    сырое: json.Значение = json.Пусто
}
"""


def выполнить(текст, ввод_данных=""):
    with tempfile.TemporaryDirectory() as папка:
        код_c = sam_kompilyator.перевести(текст)
        исполняемый = dan.собрать_код(код_c, os.path.join(папка, "программа"), папка, выпуск=True)
        р = subprocess.run([исполняемый], capture_output=True, text=True, encoding="utf-8", timeout=120,
                           input=ввод_данных, cwd=папка)
        return р.returncode, р.stdout, р.stderr


def ошибка_проверки(текст):
    """Текст ошибок проверки программы компилятором на Дане."""
    try:
        sam_kompilyator.перевести(текст)
    except Exception as е:                # ОшибкаЗаписиДана и подобные: текст сообщения
        return str(е)
    return ""


def случайная_строка(сл):
    знаки = ["а", "Ё", "z", " ", "\"", "\\", "\n", "\t", "\r", "\x01", "\x1f", "/", "😀", "€", "{", "}", ","]
    return "".join(сл.choice(знаки) for _ in range(сл.randint(0, 12)))


def случайный_заказ(сл, номер):
    з = {"id": сл.choice([номер, -номер, 0, 2 ** 63 - 1, -2 ** 63]), "customer": случайная_строка(сл)}
    if сл.random() < 0.5:
        з["оплачен"] = сл.random() < 0.5
    if сл.random() < 0.7:
        з["позиции"] = [{"имя": случайная_строка(сл), "цена": сл.choice([0.5, -3.25, 1e10, 7.0, 0.1]),
                         **({"число": сл.randint(-5, 5)} if сл.random() < 0.5 else {})}
                        for _ in range(сл.randint(0, 3))]
    if сл.random() < 0.5:
        з["скидка"] = сл.choice([None, 0.25, 3.0])
    if сл.random() < 0.5:
        з["метки"] = {случайная_строка(сл): сл.randint(-9, 9) for _ in range(сл.randint(0, 3))}
    if сл.random() < 0.4:
        з["сырое"] = сл.choice([[1, "а", None], {"x": True}, "строка", 2.5])
    if сл.random() < 0.3:
        з["лишнее"] = {"вложено": [1, {"а": None}], "ещё": "x"}
    return з


def полный(з):
    """Заказ так, как его записывает Дан: все поля в порядке объявления, без лишних."""
    return {"id": з["id"], "customer": з["customer"], "оплачен": з.get("оплачен", False),
            "позиции": [{"имя": п["имя"], "цена": п["цена"], "число": п.get("число", 1)} for п in з.get("позиции", [])],
            "скидка": з.get("скидка"), "метки": з.get("метки", {}), "сырое": з.get("сырое")}


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыРазбораВТипы(unittest.TestCase):

    def test_случайные_заказы_как_python(self):
        сл = random.Random(20261111)
        заказы = [случайный_заказ(сл, н) for н in range(1, 120)]
        тексты = [json.dumps(заказы, ensure_ascii=False),
                  json.dumps(заказы, ensure_ascii=True, indent=2),
                  json.dumps(заказы, ensure_ascii=False, separators=(",", ":"))]
        программа = ТИПЫ + """пусть текст = ввод()
пусть заказы = json.разобрать_в(текст, [Заказ])!
вывод(json.записать(заказы))
"""
        for текст in тексты:
            код, вывод_, ошибки = выполнить(программа, текст.replace("\n", " ") + "\n")
            self.assertEqual(код, 0, ошибки)
            self.assertEqual(json.loads(вывод_), [полный(з) for з in заказы])

    def test_запись_как_json_записать(self):
        # json.записать собственного типа даёт тот же текст, что запись того же значения json.Значение
        код, вывод_, ошибки = выполнить(ТИПЫ + """пусть з = Заказ(5, "Иван \\"Ш\\"\\n", истина, [Позиция("стол", 10.0, 2)], 0.5,
    {"а": 1}, json.Массив([json.Целое(1), json.Строка("б")]))
вывод(json.записать(з))
пусть з2 = json.разобрать(json.записать(з)) иначе json.Пусто
вывод(json.записать(з2))
вывод(json.записать([1, 2]))
вывод(json.записать({"а": [1.5, 0.0]}))
""")
        self.assertEqual(код, 0, ошибки)
        строки = вывод_.split("\n")
        self.assertEqual(строки[0], строки[1])
        self.assertEqual(json.loads(строки[0])["customer"], "Иван \"Ш\"\n")
        self.assertEqual(строки[2:4], ["[1,2]", '{"а":[1.5,0.0]}'])

    def test_умолчания_необязательные_и_лишние_поля(self):
        код, вывод_, ошибки = выполнить(ТИПЫ + """пусть з = json.разобрать_в("{\\"x\\": [1, {\\"y\\": null}], \\"customer\\": \\"к\\", \\"id\\": 3, \\"скидка\\": null}", Заказ)!
вывод(з)
пусть с = json.разобрать_в("{\\"а\\": [1, 2], \\"б\\": []}", {стр: [цел]})!
вывод(с)
пусть ч = json.разобрать_в("[1, 2.5, -1e3]", [дроб])!
вывод(ч)
""")
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.split("\n")[:3], [
            'Заказ(номер = 3, клиент = "к", оплачен = ложь, позиции = [], скидка = ничего, метки = {}, сырое = Пусто)',
            '{"а": [1, 2], "б": []}', "[1.0, 2.5, -1000.0]"])

    def test_ошибки_с_местом_и_полем(self):
        случаи = [
            ('{"customer": "а"}', "JSON, строка 1, позиция 17: нет поля «id» (тип Заказ)"),
            ('{"id": 1.5, "customer": "а"}', "JSON, строка 1, позиция 8: поле «id»: ожидалось целое число, а найдено дробное"),
            ('{"id": 1,\n "customer": 5}', "JSON, строка 2, позиция 14: поле «customer»: ожидалась строка в кавычках"),
            ('{"id": 1, "customer": "а", "позиции": [{"имя": "x"}]}', "нет поля «цена» (тип Позиция)"),
            ('{"id": 1, "customer": "а", "позиции": {}}', "поле «позиции»: ожидался массив «[...]»"),
            ('{"id": 99999999999999999999, "customer": "а"}', "поле «id»: целое число не помещается в цел"),
            ('{"id": 1, "customer": "а"} x', "после значения лишний текст"),
            ('[1]', "JSON, строка 1, позиция 1: ожидался объект «{...}»"),
            ('{"id": 1, "customer": "а"', "объект не закрыт скобкой «}»"),
            ('{"id": 1, "customer": "а", "лишнее": [1, }', "неожиданный знак «}»"),
            ('', "текст закончился, а значение не найдено"),
            ('{"id": 1, "customer": "а", "оплачен": 1}', "поле «оплачен»: ожидалось true или false"),
        ]
        программа = ТИПЫ + """пока истина {
    пусть т = ввод()
    если т == "конец" { прервать }
    если пусть з = json.разобрать_в(т.заменить("\\\\n", "\\n"), Заказ) { вывод(з.номер) } иначе ошибка о { вывод(о) }
}
"""
        ввод_ = "".join(т.replace("\n", "\\n") + "\n" for т, _ in случаи) + "конец\n"
        код, вывод_, ошибки = выполнить(программа, ввод_)
        self.assertEqual(код, 0, ошибки)
        строки = вывод_.split("\n")
        for н, (т, ожидается) in enumerate(случаи):
            self.assertIn(ожидается, строки[н], т)

    def test_глубокая_вложенность(self):
        код, вывод_, ошибки = выполнить("""подключить "json"
тип Узел {
    дети: [Узел] = []
}
пусть т = "{\\"дети\\": [".повторить(600) + "{}" + "]}".повторить(600)
если пусть у = json.разобрать_в(т, Узел) { вывод(у.дети.длина) } иначе ошибка о { вывод(о) }
пусть т2 = "{\\"дети\\": [".повторить(100) + "{}" + "]}".повторить(100)
пусть у2 = json.разобрать_в(т2, Узел)!
вывод(json.записать(у2).длина)
""")
        self.assertEqual(код, 0, ошибки)
        строки = вывод_.split("\n")
        self.assertIn("слишком глубокая вложенность (больше 500)", строки[0])
        self.assertEqual(строки[1], str(len('{"дети":[' * 100 + '{"дети":[]}' + "]}" * 100)))

    def test_ошибки_проверки(self):
        self.assertIn("второй аргумент json.разобрать_в - тип значения",
                      ошибка_проверки('подключить "json"\nпусть з = json.разобрать_в("1", 5)'))
        self.assertIn("словарь {цел: стр} нельзя прочитать из JSON",
                      ошибка_проверки('подключить "json"\nтип Т {\n    к: {цел: стр}\n}\nпусть з = json.разобрать_в("{}", [Т])'))
        self.assertIn("нельзя прочитать из JSON и записать в JSON",
                      ошибка_проверки('подключить "json"\nтип Т {\n    к: канал<цел>\n}\nвывод(json.записать(Т(канал())))'))
        self.assertIn("первый аргумент json.разобрать_в - текст JSON",
                      ошибка_проверки('подключить "json"\nпусть з = json.разобрать_в(5, [цел])'))

    def test_поле_с_ключом_форматируется_и_выводится_деревом(self):
        текст = 'тип Т {\n    номер "id": цел\n    имя: стр\n}\nвывод(Т(1, "а"))\n'
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.strip(), 'Т(номер = 1, имя = "а")')


