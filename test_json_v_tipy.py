"""JSON в собственные типы (раздел 11.20 spec.md): json.разобрать_в(текст, Тип) и json.записать(значение).

Разбор и запись порождает компилятор на Дане для каждого типа (компилятор на Python заморожен и этой
возможности не имеет). Случайные записи пишет модуль json языка Python в разных видах (с отступами
и без, с \\u-записью и без), программа на Дане разбирает их в свой тип и записывает обратно, результат
снова читает Python и сравнивает с исходным значением.
"""

