"""Подпись Ed25519 на чистом Python по описанию RFC 8032 (раздел 5.1) - только для тестов.

Медленная и без защиты от утечек по времени: ею подписываются выпуски-образцы в тестах
«dan обновить» и проверочные векторы. Выпуски Дана подписывает сценарий «Выпуск» (решение 0014).
"""

import hashlib

P = 2 ** 255 - 19
L = 2 ** 252 + 27742317777372353535851937790883648493
D = -121665 * pow(121666, P - 2, P) % P
I = pow(2, (P - 1) // 4, P)


def _x(y):
    xx = (y * y - 1) * pow(D * y * y + 1, P - 2, P)
    x = pow(xx, (P + 3) // 8, P)
    if (x * x - xx) % P:
        x = x * I % P
    return P - x if x % 2 else x


B = (_x(4 * pow(5, P - 2, P) % P), 4 * pow(5, P - 2, P) % P)


def _сложить(a, b):
    (x1, y1), (x2, y2) = a, b
    t = D * x1 * x2 * y1 * y2
    return ((x1 * y2 + x2 * y1) * pow(1 + t, P - 2, P) % P, (y1 * y2 + x1 * x2) * pow(1 - t, P - 2, P) % P)


def _умножить(точка, n):
    итог = (0, 1)
    while n:
        if n & 1:
            итог = _сложить(итог, точка)
        точка = _сложить(точка, точка)
        n >>= 1
    return итог


def _запись(точка):
    x, y = точка
    return (y | (x & 1) << 255).to_bytes(32, "little")


def _h(*части):
    return int.from_bytes(hashlib.sha512(b"".join(части)).digest(), "little")


def открытый_ключ(закрытый):
    h = hashlib.sha512(закрытый).digest()
    a = int.from_bytes(h[:32], "little") & ~7 & ~(1 << 255) | 1 << 254
    return _запись(_умножить(B, a))


def подписать(закрытый, данные):
    h = hashlib.sha512(закрытый).digest()
    a = int.from_bytes(h[:32], "little") & ~7 & ~(1 << 255) | 1 << 254
    А = _запись(_умножить(B, a))
    r = _h(h[32:], данные) % L
    R = _запись(_умножить(B, r))
    s = (r + _h(R, А, данные) * a) % L
    return R + s.to_bytes(32, "little")
