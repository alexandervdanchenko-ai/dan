"""«параллельно для к в а..б { }» (этап 19): шаги цикла не зависят друг от друга.

Проверка (компилятор на Дане) разрешает в теле читать общие переменные-числа, логические значения
и элементы общих списков чисел и массивов, записывать только свой элемент р[к] общего списка чисел
или массива, передавать общие массивы, которые шаги не пишут, во встроенные векторные функции и вызывать
функции без действий вне шага (вывода, ввода, файлов, задач, случайных чисел). Шаги выполняет пул
потоков среды; результат от числа потоков не зависит. Компилятор на Python заморожен и этой записи не знает: тесты переводят программы
компилятором на Дане.
"""

