def ошибки_проверки(текст):
    """Тексты ошибок проверки или пустой список, если программа верна."""
    try:
        sam_kompilyator.перевести(текст)
    except Exception as о:      # ОшибкаПроверки или ОшибкаРазбора с текстом сообщения
        return str(о)
    return ""


def выполнить(текст, потоков=None):
    """Каждая программа собирается и выполняется отдельным процессом: код завершения, вывод, ошибки."""
    код_c = sam_kompilyator.перевести(текст)
    среда = dict(os.environ)
    if потоков:
        среда["DAN_POTOKI"] = str(потоков)
    with tempfile.TemporaryDirectory() as папка:
        исполняемый = dan.собрать_код(код_c, os.path.join(папка, "программа"), папка, выпуск=True)
        р = subprocess.run([исполняемый], capture_output=True, text=True, encoding="utf-8", timeout=60, env=среда)
        return р.returncode, р.stdout, р.stderr


