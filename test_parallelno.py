"""«параллельно для к в а..б { }» (этап 19): шаги цикла не зависят друг от друга.

Проверка (компилятор на Дане) разрешает в теле читать общие переменные-числа, логические значения
и элементы общих списков чисел, записывать только свой элемент р[к] общего списка чисел и вызывать
функции без действий вне шага (вывода, ввода, файлов, задач, случайных чисел). Шаги выполняет пул
потоков среды; результат от числа потоков не зависит. Компилятор на Python заморожен и этой записи не знает: тесты переводят программы
компилятором на Дане.
"""

import os
import subprocess
import tempfile
import unittest

import dan
import sam_kompilyator
from test_kodogen import КОМПИЛЯТОР_ЕСТЬ


def ошибки_проверки(текст):
    """Тексты ошибок проверки или пустой список, если программа верна."""
    try:
        sam_kompilyator.перевести(текст)
    except Exception as о:      # ОшибкаПроверки или ОшибкаРазбора с текстом сообщения
        return str(о)
    return ""


def выполнить(текст, потоков=None):
    """Каждая программа собирается и выполняется отдельным процессом: код завершения, вывод, ошибки."""
    код_c = sam_kompilyator.перевести(текст)
    среда = dict(os.environ)
    if потоков:
        среда["DAN_POTOKI"] = str(потоков)
    with tempfile.TemporaryDirectory() as папка:
        исполняемый = dan.собрать_код(код_c, os.path.join(папка, "программа"), папка, выпуск=True)
        р = subprocess.run([исполняемый], capture_output=True, text=True, encoding="utf-8", timeout=60, env=среда)
        return р.returncode, р.stdout, р.stderr


ОБЩЕЕ = "перем сумма = 0\nпусть имя = \"а\"\nперем р: [цел] = [0, 0, 0]\nпусть а = [1, 2, 3]\n"


class ТестыПроверкиНезависимости(unittest.TestCase):

    def ошибка(self, тело, часть):
        текст = ошибки_проверки(ОБЩЕЕ + "параллельно для к в 0..2 {\n" + тело + "\n}\n")
        self.assertIn(часть, текст)
        self.assertIn("шаги «параллельно для» выполняются одновременно", текст)

    def test_верное_тело(self):
        текст = ("функ квадрат(х: цел) -> цел {\n    вернуть х * х\n}\n" + ОБЩЕЕ
                 + "параллельно для к в 0..р.длина - 1 {\n    пусть х = а[к] + сумма\n    перем с: [цел] = []\n"
                 "    с.добавить(х)\n    р[к] = квадрат(с[0]) + мин(х * х, 7) + модуль(-к)\n}\n")
        self.assertEqual(ошибки_проверки(текст), "")

    def test_вывод_и_функции_с_выводом(self):
        self.ошибка("    вывод(к)", "нельзя вызывать «вывод»")
        текст = ошибки_проверки("функ шумная(х: цел) -> цел {\n    вывод(х)\n    вернуть х\n}\n" + ОБЩЕЕ
                                + "параллельно для к в 0..2 {\n    р[к] = шумная(к)\n}\n")
        self.assertIn("нельзя вызывать «шумная»", текст)
        self.ошибка("    р[к] = случайное(1, 6)", "нельзя вызывать «случайное»")

    def test_общие_переменные(self):
        # сводки в общую переменную запрещены (порядок сложения зависел бы от числа потоков)
        self.ошибка("    сумма += к", "нельзя изменять общую переменную «сумма»")
        self.ошибка("    сумма = сумма + а[к]", "нельзя изменять общую переменную «сумма»")
        self.ошибка("    р[к + 1] = 1", "только свой элемент: «р[к]»")
        self.ошибка("    р[к] = имя.длина", "общую переменную «имя» типа стр")
        self.ошибка("    пусть б = а", "общую переменную «а» типа [цел]")
        self.ошибка("    р.добавить(к)", "общую переменную «р» типа [цел]")

    def test_запрещённые_записи(self):
        self.ошибка("    прервать", "нельзя использовать «прервать»")
        self.ошибка("    пусть ф = функ(х: цел) -> цел { вернуть х }", "безымянные функции")

    def test_только_диапазон(self):
        текст = ошибки_проверки(ОБЩЕЕ + "параллельно для х в а {\n}\n")
        self.assertIn("«параллельно для» перебирает диапазон целых чисел", текст)


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыВыполнения(unittest.TestCase):

    def test_результат(self):
        текст = ("функ квадрат(х: дроб) -> дроб {\n    вернуть х * х\n}\nпусть н = 1000\nперем а: [дроб] = []\n"
                 "перем р: [дроб] = []\nдля к в 0..н - 1 {\n    а.добавить(к * 0.5)\n    р.добавить(0.0)\n}\n"
                 "параллельно для к в 0..н - 1 {\n    р[к] = квадрат(а[к]) + 1.0\n}\nперем с = 0.0\n"
                 "для х в р {\n    с += х\n}\nвывод(с)\n")
        self.assertIn("dan_pool_run(", sam_kompilyator.перевести(текст))
        for потоков in (1, 2, 4, 8):
            код, вывод_, ошибки = выполнить(текст, потоков)
            self.assertEqual(код, 0, ошибки)
            self.assertEqual(вывод_.split(), [repr(sum((к * 0.5) ** 2 + 1.0 for к in range(1000)))])

    def test_вложенные_функции_и_свои_списки(self):
        текст = ("функ ряд(к: цел) -> цел {\n    перем с = 0\n    для н в 1..к {\n        с += н\n    }\n    вернуть с\n}\n"
                 "пусть н = 500\nперем р: [цел] = []\nдля к в 0..н - 1 {\n    р.добавить(0)\n}\nпусть сдвиг = 3\n"
                 "параллельно для к в 0..н - 1 {\n    перем свои: [стр] = []\n    свои.добавить(стр(к))\n"
                 "    р[к] = ряд(к) + свои[0].длина + сдвиг\n}\nперем итог = 0\nдля х в р {\n    итог += х\n}\nвывод(итог)\n")
        ожидается = str(sum(к * (к + 1) // 2 + len(str(к)) + 3 for к in range(500)))
        # свои строки и списки шагов живут в разных потоках (таблицы временных значений у каждого свои)
        код_c = sam_kompilyator.перевести(текст)
        with tempfile.TemporaryDirectory() as папка:
            исполняемый = dan.собрать_код(код_c, os.path.join(папка, "программа"), папка, выпуск=True)
            for потоков in (1, 2, 3, 4) * 10:
                р = subprocess.run([исполняемый], capture_output=True, text=True, encoding="utf-8", timeout=60,
                                   env=dict(os.environ, DAN_POTOKI=str(потоков)))
                self.assertEqual(р.returncode, 0, р.stderr)
                self.assertEqual(р.stdout.split(), [ожидается])

    def test_побитно_как_последовательно(self):
        # приёмка: дробные результаты каждого шага побитно совпадают с обычным циклом при любом числе потоков
        тело = ("пусть н = 3000\nперем а: [дроб] = []\nперем р: [дроб] = []\nперем ц: [цел] = []\n"
                "для к в 0..н - 1 {\n    а.добавить(1.0 / (к + 3))\n    р.добавить(0.0)\n    ц.добавить(0)\n}\n"
                "ЦИКЛ к в 0..н - 1 {\n    перем с = 0.0\n    для ј в 1..200 {\n        с += а[к] * ј / (ј + к * 0.5)\n    }\n"
                "    р[к] = с + корень(а[к])\n    ц[к] = к * к % 1009\n}\nдля х в р {\n    вывод(х)\n}\nвывод(сумма(ц))\n")
        код, эталон, ошибки = выполнить(тело.replace("ЦИКЛ", "для"))
        self.assertEqual(код, 0, ошибки)
        код_c = sam_kompilyator.перевести(тело.replace("ЦИКЛ", "параллельно для"))
        with tempfile.TemporaryDirectory() as папка:
            исполняемый = dan.собрать_код(код_c, os.path.join(папка, "программа"), папка, выпуск=True)
            for потоков in (1, 2, 3, 4, 8, 16):
                р = subprocess.run([исполняемый], capture_output=True, text=True, encoding="utf-8", timeout=60,
                                   env=dict(os.environ, DAN_POTOKI=str(потоков)))
                self.assertEqual(р.returncode, 0, р.stderr)
                self.assertEqual(р.stdout, эталон, f"потоков: {потоков}")

    def test_ошибка_шага(self):
        код, _, ошибки = выполнить("перем р = [0, 0]\nпараллельно для к в 0..2 {\n    р[к] = к\n}\n")
        self.assertEqual(код, 1)
        self.assertIn("индекс 2 за пределами (длина 2)", ошибки)


