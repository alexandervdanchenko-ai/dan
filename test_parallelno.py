def санитайзер(вид):
    import shutil
    import sys
    компилятор = shutil.which("gcc") or shutil.which("clang")
    if not компилятор or sys.platform != "linux":
        return None
    with tempfile.TemporaryDirectory() as п:
        с = os.path.join(п, "п.c")
        with open(с, "w") as ф:
            ф.write("int main(void) { return 0; }\n")
        if subprocess.run([компилятор, f"-fsanitize={вид}", с, "-o", os.path.join(п, "п")], capture_output=True).returncode:
            return None
        if subprocess.run([os.path.join(п, "п")], capture_output=True).returncode:
            return None
    return компилятор


def под_санитайзером(текст, вид, потоков):
    """(код, вывод, ошибки) программы, которую перевёл компилятор на Дане и собрал gcc с санитайзером."""
    компилятор = санитайзер(вид)
    with tempfile.TemporaryDirectory() as п:
        с = os.path.join(п, "программа.c")
        with open(с, "w", encoding="utf-8") as ф:
            ф.write(sam_kompilyator.перевести(текст, строки_дан=True))
        исп = os.path.join(п, "программа")
        subprocess.run([компилятор, "-std=c11", "-fwrapv", "-ffp-contract=off", "-w", "-g", "-O1", f"-fsanitize={вид}",
                        "-fno-sanitize-recover=all", с, "-o", исп, "-lm", "-pthread"], check=True)
        р = subprocess.run([исп], capture_output=True, text=True, encoding="utf-8", timeout=600, cwd=п,
                           env=dict(os.environ, DAN_POTOKI=str(потоков), TSAN_OPTIONS="halt_on_error=1",
                                    ASAN_OPTIONS="detect_leaks=1"))
    return р.returncode, р.stdout, р.stderr


