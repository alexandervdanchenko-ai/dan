class ТестыСписковИПреобразований(unittest.TestCase):

    def тип(self, текст, выражение):
        п = ок(текст + "\nпусть _р = " + выражение)
        return п.инструкции[-1].значение.тип_выр

    def test_типы_списков(self):
        self.assertEqual(self.тип("", "[1, 2]"), "[цел]")
        self.assertEqual(self.тип("", "[1, 2.5]"), "[дроб]")
        self.assertEqual(self.тип("", "[[1], []]"), "[[цел]]")
        self.assertEqual(self.тип("пусть с = [\"а\"]", "с[0]"), "стр")
        self.assertEqual(self.тип("пусть с = [1]", "с.длина"), "цел")
        self.assertEqual(self.тип("", "\"абв\".длина"), "цел")

    def test_пустой_список_с_типом(self):
        п = ок("перем с: [дроб] = []\nс.добавить(1)\nс = []")
        self.assertEqual(п.инструкции[0].значение.тип_выр, "[дроб]")
        self.assertEqual(п.инструкции[2].значение.тип_выр, "[дроб]")

    def test_литерал_подстраивается_под_тип(self):
        п = ок("пусть с: [дроб] = [1, 2]")
        self.assertEqual(п.инструкции[0].значение.тип_выр, "[дроб]")

    def test_пустой_список_в_аргументе_и_возврате(self):
        ок("функ ф(с: [цел]) -> [стр] { вернуть [] }\nпусть р = ф([])")

    def test_для_по_списку(self):
        п = ок("для с в [\"а\", \"б\"] { вывод(с + \"!\") }")
        self.assertEqual(п.инструкции[0].тип_элемента, "стр")

    def test_изменение_списка_только_через_перем(self):
        ок("перем с = [1, 2]\nс[0] = 5\nс[1] *= 2\nс.добавить(3)\nперем т = [[1]]\nт[0].добавить(2)\nт[0][0] = 7")
        for программа, фрагмент in (("пусть с = [1, 2]\nс[0] = 5", "через «пусть»"),
                                    ("пусть с = [1, 2]\nс.добавить(3)", "метод «добавить» изменяет список"),
                                    ("функ ф(с: [цел]) { с.добавить(0) }", "параметр «с» изменять нельзя"),
                                    ("для с в [[1]] { с.удалить(0) }", "переменную цикла «с»"),
                                    ("функ ф() -> [цел] { вернуть [1] }\nф().добавить(2)", "временное значение")):
            with self.subTest(программа=программа):
                self.assertIn(фрагмент, ошибки(программа)[0].текст)

    def test_имя_в_сообщении_как_написано(self):
        # «ё» в имени равнозначна «е», но в сообщении имя показано так, как написано
        текст = ошибки("пусть счётчик = 0\nсчётчик += 1")[0].текст
        self.assertIn("переменную «счётчик» нельзя изменить", текст)
        self.assertIn("«перем счётчик = ...»", текст)

    def test_пустой_список_подсказка_без_навязанного_типа(self):
        текст = ошибки("перем с = []")[0].текст
        self.assertIn("[стр]", текст)
        self.assertIn("[цел]", текст)

    def test_преобразования(self):
        self.assertEqual(self.тип("", "стр(5)"), "стр")
        self.assertEqual(self.тип("", "стр(2.5)"), "стр")
        self.assertEqual(self.тип("", "стр(ложь)"), "стр")
        self.assertEqual(self.тип("", "цел(\"5\")"), "цел")
        self.assertEqual(self.тип("", "цел(2.5)"), "цел")
        self.assertEqual(self.тип("", "дроб(\"2,5\")"), "дроб")

    def test_ввод(self):
        self.assertEqual(self.тип("", "ввод()"), "стр")
        self.assertEqual(self.тип("", "ввод(\"Имя: \")"), "стр")


