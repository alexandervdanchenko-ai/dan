import unittest

from parser import разобрать
from proverka import проверить, ОшибкаПроверки
import uzly as у


def ок(текст):
    return проверить(разобрать(текст))


def ошибки(текст):
    try:
        проверить(разобрать(текст))
    except ОшибкаПроверки as о:
        return о.ошибки
    raise AssertionError("ожидалась ошибка проверки")


class ТестыКорректныхПрограмм(unittest.TestCase):

    def test_примеры(self):
        import glob, os
        for путь in glob.glob(os.path.join(os.path.dirname(__file__), "примеры", "*.dan")):
            with self.subTest(путь=путь), open(путь, encoding="utf-8") as ф:
                ок(ф.read())

    def test_вывод_типов(self):
        п = ок("пусть а = 1\nпусть б = 2.0\nпусть в_ = а + б\nпусть г = \"х\" + \"у\"\nпусть д = а < б")
        типы = [и.значение.тип_выр for и in п.инструкции]
        self.assertEqual(типы, ["цел", "дроб", "дроб", "стр", "лог"])

    def test_целое_в_дробную_переменную(self):
        ок("пусть х: дроб = 5\nперем у = 1.5\nу = 2\nу += 1")

    def test_целочисленное_деление(self):
        п = ок("пусть х = 7 / 2")
        self.assertEqual(п.инструкции[0].значение.тип_выр, "цел")

    def test_вызов_до_объявления(self):
        ок("вывод(квадрат(3))\nфунк квадрат(х: цел) -> цел { вернуть х * х }")

    def test_рекурсия(self):
        ок("функ ф(н: цел) -> цел {\n если н <= 1 { вернуть 1 }\n вернуть н * ф(н - 1)\n}")

    def test_все_ветви_возвращают(self):
        ок("функ з(х: цел) -> стр {\n если х > 0 { вернуть \"+\" } иначе { вернуть \"-\" }\n}")

    def test_переменная_в_разных_блоках(self):
        ок("если истина { пусть а = 1 }\nесли истина { пусть а = 2 }")

    def test_одинаковые_имена_в_разных_функциях(self):
        ок("функ а(х: цел) { вывод(х) }\nфунк б(х: стр) { вывод(х) }")

    def test_цикл_с_выражениями_в_границах(self):
        ок("перем с = 0\nпусть н = 10\nдля и_ в 1..н * 2 {\n с += и_\n}")


class ТестыОшибок(unittest.TestCase):

    def одна(self, текст, фрагмент, строка=None):
        с = ошибки(текст)
        self.assertEqual(len(с), 1, [str(x) for x in с])
        self.assertIn(фрагмент, с[0].текст)
        if строка is not None:
            self.assertEqual(с[0].строка, строка)

    def test_необъявленная_переменная(self):
        self.одна("вывод(х)", "не объявлена")

    def test_повторное_объявление(self):
        self.одна("пусть а = 1\nпусть а = 2", "уже объявлена", 2)

    def test_затенение_во_вложенном_блоке(self):
        self.одна("пусть а = 1\nесли истина { пусть а = 2 }", "уже объявлена")

    def test_изменение_пусть(self):
        self.одна("пусть а = 1\nа = 2", "нельзя изменить")

    def test_изменение_параметра(self):
        self.одна("функ ф(а: цел) { а = 2 }", "нельзя изменить")

    def test_изменение_переменной_цикла(self):
        self.одна("для ч в 1..3 { ч = 5 }", "нельзя изменить")

    def test_число_плюс_строка(self):
        self.одна("пусть а = 1 + \"текст\"", "строку можно соединять только со строкой")

    def test_дробь_в_целую_переменную(self):
        self.одна("перем а = 1\nа = 2.5", "имеет тип цел")

    def test_остаток_от_дроби(self):
        self.одна("пусть а = 5.0 % 2", "только для целых")

    def test_условие_не_лог(self):
        self.одна("если 1 { }", "должно иметь тип лог")

    def test_сравнение_строки_с_числом(self):
        self.одна("пусть а = \"1\" == 1", "нельзя сравнивать")

    def test_строки_только_на_равенство(self):
        self.одна("пусть а = \"а\" < \"б\"", "только на равенство")

    def test_неверное_число_аргументов(self):
        self.одна("функ ф(а: цел, б: цел) {}\nф(1)", "принимает 2 значения, а передано 1")

    def test_неверный_тип_аргумента(self):
        self.одна("функ ф(а: цел) {}\nф(\"х\")", "аргумент 1")

    def test_неизвестная_функция(self):
        self.одна("печать(1)", "не объявлена")

    def test_неизвестный_тип(self):
        self.одна("функ ф(а: число) {}", "неизвестный тип")

    def test_нет_возврата_в_ветви(self):
        self.одна("функ ф(а: цел) -> цел {\n если а > 0 { вернуть 1 }\n}", "не вернув значение", 1)

    def test_возврат_значения_из_пустой_функции(self):
        self.одна("функ ф() { вернуть 1 }", "не возвращает значений")

    def test_неверный_тип_возврата(self):
        self.одна("функ ф() -> цел { вернуть \"х\" }", "должна вернуть цел")

    def test_вернуть_вне_функции(self):
        self.одна("вернуть 1", "только внутри функции")

    def test_прервать_вне_цикла(self):
        self.одна("прервать", "только внутри цикла")

    def test_результат_пустой_функции_в_переменную(self):
        self.одна("функ ф() {}\nпусть а = ф()", "не имеет значения")

    def test_функция_внутри_функции(self):
        self.одна("функ а() {\n функ б() {}\n}", "только на верхнем уровне")

    def test_функции_не_видят_глобальных_переменных(self):
        self.одна("пусть к = 1\nфунк ф() -> цел { вернуть к }", "не объявлена")

    def test_повтор_функции(self):
        self.одна("функ ф() {}\nфунк ф() {}", "уже объявлена", 2)

    def test_переменная_с_именем_функции(self):
        self.одна("функ ф() {}\nпусть ф = 1", "занято функцией")

    def test_диапазон_вне_цикла(self):
        self.одна("пусть д = 1..5", "только в цикле")

    def test_дробный_диапазон(self):
        self.одна("для ч в 1..2.5 {}", "целыми числами")

    def test_для_не_по_диапазону(self):
        self.одна("для ч в 5 {}", "ожидается диапазон")

    def test_поле_пока_не_поддерживается(self):
        self.одна("пусть а = \"х\"\nвывод(а.длина)", "следующих версиях")

    def test_нет_лавины_ошибок(self):
        # Одна необъявленная переменная не должна порождать ошибки в выражениях вокруг неё.
        self.одна("пусть а = (х + 1) * 2 - 3", "не объявлена")

    def test_собираются_все_ошибки_по_порядку(self):
        с = ошибки("вывод(а)\nпусть б: цел = \"х\"\nпрервать")
        self.assertEqual([x.строка for x in с], [1, 2, 3])


if __name__ == "__main__":
    unittest.main()
