def _случайный_шаблон(сл, глубина=0):
    """Случайный шаблон над буквами «а» и «б» (группы, выбор, повторения, классы)."""
    вид = сл.randint(0, 9 if глубина < 3 else 3)
    if вид <= 1:
        return сл.choice(["а", "б", "в"])
    if вид == 2:
        return сл.choice(["[аб]", "[^а]", ".", "\\w", "[а-в]"])
    if вид == 3:
        return сл.choice(["", "^", "$"]) if сл.random() < 0.15 else "а"
    if вид <= 5:
        return _случайный_шаблон(сл, глубина + 1) + _случайный_шаблон(сл, глубина + 1)
    if вид == 6:
        return "(" + _случайный_шаблон(сл, глубина + 1) + "|" + _случайный_шаблон(сл, глубина + 1) + ")"
    if вид == 7:
        return "(" + _случайный_шаблон(сл, глубина + 1) + ")"
    атом = _случайный_шаблон(сл, глубина + 1)
    if not атом or атом in ("^", "$"):
        атом = "а"
    if len(атом) > 1 and not (атом.startswith("(") and атом.endswith(")")) and not (
            атом.startswith("[") and атом.endswith("]")) and атом not in ("\\w",):
        атом = "(?:" + атом + ")"
    return атом + сл.choice(["*", "+", "?", "{2}", "{1,3}", "*?", "+?", "??", "{0,2}"])


