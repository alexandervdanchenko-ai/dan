def ошибки(текст):
    try:
        проверить(разобрать(текст))
    except ОшибкаПроверки as о:
        return "\n".join(с.текст for с in о.ошибки)
    return ""


def строка_дан(текст):
    """Запись строки Python в виде литерала Дана."""
    return '"' + текст.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


class ТестыПроверки(unittest.TestCase):

    def test_действия_с_датами(self):
        основа = "пусть д = дата(2026, 10, 26)\n"
        self.assertEqual(ошибки(основа + "вывод(д + 1)\nвывод(1 + д)\nвывод(д - 1)\nпусть р: цел = д - д\n"
                                        "вывод(д < д)\nвывод(д.год + д.месяц + д.день)"), "")
        self.assertIn("с датами возможны действия", ошибки(основа + "вывод(д + д)"))
        self.assertIn("с датами возможны действия", ошибки(основа + "вывод(д * 2)"))
        self.assertIn("с датами возможны действия", ошибки(основа + "вывод(1 - д)"))
        self.assertIn("нельзя сравнивать", ошибки(основа + "вывод(д == 5)"))
        self.assertIn("год, месяц и день даты - целые числа", ошибки("вывод(дата(2026, 1, 1.5))"))
        self.assertIn("принимает одно значение", ошибки("вывод(дата(2026, 1))"))

    def test_даты_в_обобщённом_коде(self):
        self.assertEqual(ошибки("функ наибольшее<Т: Упорядоченное>(а: Т, б: Т) -> Т {\n"
                                "    если а > б { вернуть а }\n    вернуть б\n}\n"
                                "вывод(наибольшее(дата(2026, 1, 1), дата(2025, 1, 1)))\n"
                                "пусть с: {дата: цел} = {}"), "")

    def test_библиотечные_функции(self):
        self.assertIn("функция «добавить_месяцы» вызывается так: добавить_месяцы(дата, цел)",
                      ошибки('вывод(добавить_месяцы("01.01.2026", 1))'))
        self.assertIn("возможно, имелось в виду «найти_все»", ошибки('вывод(найти_вс("а", "б"))'))


