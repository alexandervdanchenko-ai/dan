    def test_ошибки_шаблонов(self):
        for шаблон, часть in [("(а", "не закрыта круглая скобка"), ("а)", "лишняя закрывающая скобка"),
                              ("[аб", "не закрыта квадратная скобка"), ("*а", "нечего повторять"),
                              ("а{3,1}", "неверное число повторений"), ("\\q", "неизвестное сочетание \\q"),
                              ("[я-а]", "первый знак должен идти раньше второго")]:
            with self.subTest(шаблон=шаблон):
                код, _, ош = выполнить(f'вывод(совпадает("а", {строка_дан(шаблон)}))')
                self.assertEqual(код, 1)
                self.assertIn("ошибка в шаблоне", ош)
                self.assertIn(часть, ош)

    def test_случайные_шаблоны_как_в_python(self):
        сл = random.Random(2026)
        строки, ожидается = [], []
        for _ in range(400):
            шаблон = _случайный_шаблон(сл)
            текст = "".join(сл.choice("абв") for _ in range(сл.randint(0, 8)))
            try:
                рв = re.compile(шаблон)
            except re.error:
                continue
            м = рв.search(текст)
            группы = [м.group(0)] + [г if г is not None else "" for г in м.groups()] if м else []
            все = [н.group(0) for н in рв.finditer(текст)]
            полное = рв.fullmatch(текст) is not None
            замена = рв.sub("<$0>".replace("$0", r"\g<0>"), текст)
            части, начало = [], 0
            for н in рв.finditer(текст):
                части.append(текст[начало:н.start()])
                начало = н.end()
            части.append(текст[начало:])
            ш, т = строка_дан(шаблон), строка_дан(текст)
            строки.append(f"вывод(совпадает({т}, {ш}))")
            строки.append(f"вывод(группы({т}, {ш}))")
            строки.append(f"вывод(найти_все({т}, {ш}))")
            строки.append(f"вывод(заменить_шаблон({т}, {ш}, \"<$0>\"))")
            строки.append(f"вывод(разбить_по_шаблону({т}, {ш}))")
            ожидается.append(("истина" if полное else "ложь", шаблон, текст))
            ожидается.append((self._список(группы), шаблон, текст))
            ожидается.append((self._список(все), шаблон, текст))
            ожидается.append((замена, шаблон, текст))
            ожидается.append((self._список(части), шаблон, текст))
        вывод = self.вывод("\n".join(строки))
        self.assertEqual(len(вывод), len(ожидается))
        for получено, (нужно, шаблон, текст) in zip(вывод, ожидается):
            self.assertEqual(получено, нужно, f"шаблон {шаблон!r}, текст {текст!r}")

    @staticmethod
    def _список(элементы):
        return "[" + ", ".join('"' + э + '"' for э in элементы) + "]"


