"""Библиотека данных языка Дан: файлы, байты, контрольные суммы, сжатие,
шифрование и zip-архивы.

Код C находится в файле sreda/dannye.c и вставляется в программу, только
если она использует функции этого модуля или тип «байты».

Сжатие по умолчанию - LZMA2 в формате .xz (как в 7-Zip и xz) с окном до
64 МБ и контрольной суммой CRC-64; сжатие_gzip - DEFLATE в формате gzip
(как в zip). Оба формата открываются архиваторами 7-Zip и WinRAR. Шифрование с паролем -
ChaCha20-Poly1305, ключ из пароля получается функцией PBKDF2-HMAC-SHA256
(600 000 повторений). Архивы - стандартный zip; с паролем используется
шифрование WinZip AES-256, которое понимают 7-Zip и WinRAR.
"""

