"""Анализ диапазонов в компиляторе на Дане (этап 19): проверки, которые доказуемо не сработают.

Цикл «для к в а..б» проверяет границы обращений с[к + смещение] один раз до начала цикла, если
длина списка с в теле не меняется; целые «+», «-», «*» с известными при сборке пределами и
накопители («с += х» с известными пределами х) выполняются без проверки переполнения. Каждое
снятие проверки не меняет поведения программы: ошибка выхода за границы или переполнения
случается на том же шаге с тем же сообщением. Тесты собирают программы компилятором на Дане
(компилятор на Python заморожен и этих снятий не делает).
"""

import os
import subprocess
import tempfile
import unittest

import dan
import sam_kompilyator
from test_kodogen import КОМПИЛЯТОР_ЕСТЬ


def си(текст):
    return sam_kompilyator.перевести(текст)


def выполнить(текст, ввод_данных=""):
    """Код завершения, вывод и вывод ошибок программы, собранной компилятором на Дане; каждая программа -
    отдельный процесс (ошибка выхода за границы останавливает только её)."""
    код_c = си(текст)
    with tempfile.TemporaryDirectory() as папка:
        исполняемый = dan.собрать_код(код_c, os.path.join(папка, "программа"), папка, выпуск=True)
        р = subprocess.run([исполняемый], capture_output=True, text=True, encoding="utf-8", timeout=60,
                           input=ввод_данных)
        return р.returncode, р.stdout, р.stderr


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыГраниц(unittest.TestCase):

    def вывод(self, текст, ожидается):
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.split(), ожидается)

    def ошибка(self, текст, вывод_ожидается, сообщение):
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 1, вывод_)
        self.assertEqual(вывод_.split(), вывод_ожидается)
        self.assertIn(сообщение, ошибки)

    def test_снимается_для_списка_без_изменения_длины(self):
        текст = "перем с = [1, 2, 3, 4]\nперем сум = 0\nдля к в 0..с.длина - 1 {\n    сум += с[к]\n    с[к] = с[к] * 2\n}\nвывод(сум)\nвывод(с)"
        self.assertIn("_inb", си(текст))
        self.вывод(текст, ["10", "[2,", "4,", "6,", "8]"])

    def test_смещения(self):
        текст = "пусть с = [1, 2, 3, 4, 5]\nперем р: [цел] = []\nдля к в 1..с.длина - 2 {\n    р.добавить(с[к - 1] + с[к] + с[к + 1])\n}\nвывод(р)"
        self.assertIn("_inb", си(текст))
        self.вывод(текст, ["[6,", "9,", "12]"])

    def test_выход_за_границы_на_том_же_шаге(self):
        # граница цикла на один больше: все шаги до последнего выполняются, затем та же ошибка
        self.ошибка("пусть с = [5, 6, 7]\nдля к в 0..с.длина {\n    вывод(с[к])\n}", ["5", "6", "7"],
                    "индекс 3 за пределами (длина 3)")
        self.ошибка("пусть с = [5, 6, 7]\nдля к в -1..2 {\n    вывод(к)\n    вывод(с[к + 1])\n}",
                    ["-1", "5", "0", "6", "1", "7", "2"], "индекс 3 за пределами (длина 3)")
        self.ошибка("пусть с = [5, 6, 7]\nдля к в 0..2 {\n    вывод(с[к - 1])\n}", [],
                    "индекс -1 за пределами (длина 3)")
        self.ошибка("перем с = [5, 6, 7]\nдля к в 1..5 {\n    с[к] = к\n}\nвывод(с)", [],
                    "индекс 3 за пределами (длина 3)")

    def test_длина_меняется_проверка_остаётся(self):
        текст = "перем с = [1]\nдля к в 0..3 {\n    с.добавить(к)\n    вывод(с[к + 1])\n}"
        self.assertNotIn("_inb", си(текст))
        self.вывод(текст, ["0", "1", "2", "3"])
        текст = "перем с = [1, 2, 3]\nдля к в 0..2 {\n    вывод(с[к])\n    с = [9]\n}"
        self.assertNotIn("_inb", си(текст))
        self.ошибка(текст, ["1"], "индекс 1 за пределами (длина 1)")

    def test_список_передаётся_в_функцию(self):
        текст = ("функ длина_(с: [цел]) -> цел {\n    вернуть с.длина\n}\nпусть с = [1, 2]\n"
                 "для к в 0..1 {\n    вывод(с[к] + длина_(с))\n}")
        self.assertNotIn("_inb", си(текст))
        self.вывод(текст, ["3", "4"])

    def test_индекс_не_от_переменной_цикла(self):
        текст = "пусть с = [1, 2, 3]\nпусть н = цел(ввод())\nдля к в 0..2 {\n    вывод(с[н])\n}"
        self.assertNotIn("_inb", си(текст))
        код, вывод_, ошибки = выполнить(текст, "5\n")
        self.assertEqual((код, вывод_), (1, ""))
        self.assertIn("индекс 5 за пределами (длина 3)", ошибки)

    def test_цикл_раздваивается(self):
        текст = ("перем а: [дроб] = [1.0, 2.0, 3.0]\nперем б = [0.5, 0.25, 2.0]\nперем р = [0.0, 0.0, 0.0]\n"
                 "для проход в 1..3 {\n    для к в 0..р.длина - 1 {\n        р[к] = а[к] * б[к] + р[к]\n    }\n}\nвывод(р)")
        код_c = си(текст)
        self.assertRegex(код_c, r"if \(_inb\d+v\) \{")
        self.вывод(текст, ["[1.5,", "1.5,", "18.0]"])

    def test_строки_матрицы_и_вложенные_циклы(self):
        текст = ('пусть имена = ["а", "бв", "где"]\nперем м = [[1, 2], [3, 4], [5, 6]]\nперем итог = 0\n'
                 'для к в 0..имена.длина - 1 {\n    для ј в 0..1 {\n        м[к][ј] = м[к][ј] * имена[к].длина\n'
                 '        итог += м[к][ј]\n    }\n}\nвывод(м)\nвывод(итог)\nперем н: [стр] = ["", "", ""]\n'
                 'для к в 0..2 {\n    н[к] = имена[2 - к] + "!"\n}\nвывод(н)')
        self.вывод(текст, ["[[1,", "2],", "[6,", "8],", "[15,", "18]]", "50", '["где!",', '"бв!",', '"а!"]'])

    def test_пустой_цикл(self):
        self.вывод("пусть с: [цел] = []\nдля к в 0..с.длина - 1 {\n    вывод(с[к])\n}\nвывод(\"конец\")", ["конец"])


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыОтступления(unittest.TestCase):
    """Случаи, где анализ отступает: проверка границ остаётся, выход за границы ловится на том же шаге."""

    def проверка_остаётся(self, текст, вывод_ожидается, сообщение, флаг_есть=False):
        код_c = си(текст)
        if not флаг_есть:
            self.assertNotIn("_inb", код_c)
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 1, вывод_)
        self.assertEqual(вывод_.split(), вывод_ожидается)
        self.assertIn(сообщение, ошибки)

    def test_индекс_через_синоним(self):
        self.проверка_остаётся("пусть с = [1, 2]\nдля к в 0..2 {\n    пусть ј = к\n    вывод(с[ј])\n}",
                               ["1", "2"], "индекс 2 за пределами (длина 2)")

    def test_список_меняется_в_цикле(self):
        # удаление, замена значения через функцию, передача в функцию
        self.проверка_остаётся("перем с = [1, 2, 3]\nдля к в 0..2 {\n    вывод(с[к])\n    с.удалить(0)\n}",
                               ["1", "3"], "индекс 2 за пределами (длина 1)")
        self.проверка_остаётся("функ короче(с: [цел]) -> [цел] {\n    вернуть с[0..с.длина - 2]\n}\n"
                               "перем с = [1, 2, 3]\nдля к в 0..2 {\n    вывод(с[к])\n    с = короче(с)\n}",
                               ["1", "2"], "индекс 2 за пределами (длина 1)")
        self.проверка_остаётся("функ сумма_(с: [цел]) -> цел {\n    вернуть сумма(с)\n}\n"
                               "пусть с = [1, 2]\nдля к в 0..2 {\n    вывод(с[к] + сумма_(с))\n}",
                               ["4", "5"], "индекс 2 за пределами (длина 2)")

    def test_индекс_только_выглядит_ограниченным(self):
        # умножение, огромное смещение, длина, вычисленная до изменения списка
        self.проверка_остаётся("пусть с = [1, 2, 3]\nдля к в 0..2 {\n    вывод(с[к * 2])\n}",
                               ["1", "3"], "индекс 4 за пределами (длина 3)")
        self.проверка_остаётся("пусть с = [1, 2, 3]\nдля к в 0..1 {\n    вывод(с[к + 4611686018427387904])\n}",
                               [], "за пределами (длина 3)")
        self.проверка_остаётся("перем с = [1, 2, 3]\nпусть д = с.длина\nдля к в 0..д - 1 {\n    вывод(с[к])\n"
                               "    с.удалить(с.длина - 1)\n}", ["1", "2"], "индекс 2 за пределами (длина 1)")
        # отрицательные индексы: начало цикла ниже нуля - проверка до цикла не проходит, ошибка на первом шаге
        self.проверка_остаётся("пусть с = [1, 2, 3]\nдля к в -2..2 {\n    вывод(с[к])\n}", [],
                               "индекс -2 за пределами (длина 3)", флаг_есть=True)
        # обратный порядок (а > б) - цикл пустой, обращений нет
        код, вывод_, _ = выполнить("пусть с = [1]\nдля к в 5..0 {\n    вывод(с[к])\n}\nвывод(0)")
        self.assertEqual((код, вывод_.split()), (0, ["0"]))

    def test_вложенные_циклы_с_разными_списками(self):
        # б короче а: б[к] во внутреннем цикле выходит за границы на шаге к = 2
        self.проверка_остаётся("пусть а = [1, 2, 3]\nпусть б = [10, 20]\nдля к в 0..а.длина - 1 {\n"
                               "    для ј в 0..б.длина - 1 {\n        вывод(а[к] + б[ј] + б[к])\n    }\n}",
                               ["21", "31", "32", "42"], "индекс 2 за пределами (длина 2)", флаг_есть=True)


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыПереполнения(unittest.TestCase):

    def вывод(self, текст, ожидается):
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.split(), ожидается)

    def test_известные_пределы(self):
        текст = "перем с = 0\nдля к в 1..1000 {\n    с += к * к % 7\n}\nвывод(с)"
        код_c = си(текст)
        self.assertIn("(d_k * d_k)", код_c)
        self.assertIn("_acc", код_c)
        self.вывод(текст, [str(sum(к * к % 7 for к in range(1, 1001)))])

    def test_вложенные_циклы(self):
        текст = "перем с = 0\nдля а в 0..100 {\n    для б в 0..а {\n        с += а * б - б\n    }\n}\nвывод(с)"
        self.assertIn("(d_a * d_b)", си(текст))
        self.вывод(текст, [str(sum(а * б - б for а in range(101) for б in range(а + 1)))])

    def test_большие_пределы_проверяются(self):
        текст = "для к в 4000000000..4000000001 {\n    вывод(к * к)\n}"
        self.assertIn("dan_mul(d_k, d_k", си(текст))
        код, _, ошибки = выполнить(текст)
        self.assertEqual(код, 1)
        self.assertIn("слишком", ошибки)

    def test_накопитель_переполняется_с_проверкой(self):
        текст = "перем с = 9223372036854775800\nдля к в 1..10 {\n    с += 1\n    вывод(к)\n}"
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 1)
        self.assertEqual(вывод_.split(), ["1", "2", "3", "4", "5", "6", "7"])
        self.assertIn("слишком", ошибки)

    def test_накопитель_во_вложенном_цикле_не_снимается(self):
        текст = "перем с = 0\nдля к в 1..3 {\n    пока с < 10 {\n        с += 1\n    }\n}\nвывод(с)"
        self.assertNotIn("_acc", си(текст))
        self.вывод(текст, ["10"])

    def test_неизвестные_пределы(self):
        текст = "пусть н = цел(ввод())\nперем с = 0\nдля к в 1..3 {\n    с += н\n}\nвывод(с)"
        код_c = си(текст)
        self.assertNotIn("_acc", код_c)
        код, вывод_, _ = выполнить(текст, "5\n")
        self.assertEqual(вывод_.split(), ["15"])


if __name__ == "__main__":
    unittest.main()


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыПолногоДиапазона(unittest.TestCase):
    """Полный диапазон цел (2^64 шагов): число шагов не помещается в 64 бита и прежде обращалось в 0 -
    цикл молча не выполнялся (находка разбора DeepSeek, ошибка была и в компиляторе на Python).
    Теперь число шагов насыщается."""

    МИН = "-9223372036854775807 - 1"
    МАКС = "9223372036854775807"

    def test_обычный_для_выполняется(self):
        текст = (f"перем н = 0\nдля к в {self.МИН}..{self.МАКС} {{\n    н += 1\n    если н > 3 {{ прервать }}\n}}\n"
                 "вывод(н)")
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.split(), ["4"])

    def test_первые_шаги_с_минимума(self):
        текст = (f"перем н = 0\nдля к в {self.МИН}..{self.МАКС} {{\n    вывод(к)\n    н += 1\n"
                 "    если н == 2 { прервать }\n}")
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.split(), ["-9223372036854775808", "-9223372036854775807"])

    def test_накопитель_проверяется(self):
        # при обнулённом числе шагов проверка накопителя сочла бы цикл пустым и сняла бы проверку
        текст = (f"перем а = 9223372036854775000\nдля к в {self.МИН}..{self.МАКС} {{\n    а += 1000\n    вывод(а)\n"
                 "}")
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 1, вывод_)
        self.assertEqual(вывод_.split(), [])
        self.assertIn("слишком", ошибки)

    def test_параллельный_для_даёт_ошибку(self):
        текст = f"параллельно для к в {self.МИН}..{self.МАКС} {{\n    пусть у = к\n}}\nвывод(\"дошли\")"
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 1, вывод_)
        self.assertNotIn("дошли", вывод_)
        self.assertIn("слишком", ошибки)

    def test_у_самых_границ_как_прежде(self):
        текст = (f"перем н = 0\nдля к в 9223372036854775806..{self.МАКС} {{\n    н += 1\n}}\nвывод(н)\n"
                 f"перем м = 0\nдля к в {self.МИН}..-9223372036854775807 {{\n    м += 1\n}}\nвывод(м)")
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.split(), ["2", "2"])
