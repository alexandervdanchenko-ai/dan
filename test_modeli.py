    def test_случайная_порча(self):
        """Случайные байты в заголовке: модель загружается или даёт ошибку-значение, программа не падает.
        Странные числа, которые проходят проверку среды (например, число слоёв), ловит llama.cpp своими
        проверками GGML_ASSERT; среда перехватывает их остановку и возвращает ошибку."""
        import random
        with open(Общее.модель, "rb") as ф:
            исходный = ф.read()
        длина_заголовка = исходный.index(b"output.weight") + 64
        генератор = random.Random(2)
        путь = os.path.join(Общее.папка, "порча.gguf")
        for номер in range(60):
            д = bytearray(исходный)
            for _ in range(генератор.randint(1, 6)):
                д[генератор.randrange(длина_заголовка)] = генератор.randrange(256)
            with open(путь, "wb") as ф:
                ф.write(д)
            код, итог, весь = выполнить(["загрузка", путь])
            self.assertEqual(код, 0, "порча %d: %s" % (номер, весь))
            self.assertTrue("ошибка" in итог or "загружена" in весь, весь)


