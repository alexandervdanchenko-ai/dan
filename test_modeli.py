    def test_сверка_с_llama_simple(self):
        """Жадный ответ Дана совпадает с ответом примера llama.cpp llama-simple на той же модели."""
        simple = os.environ.get("DAN_LLAMA_SIMPLE")
        if not simple and os.environ.get("DAN_LLAMA"):
            место = os.environ["DAN_LLAMA"]
            if not os.path.isdir(место):
                место = os.path.dirname(место)
            simple = os.path.join(место, "llama-simple" + (".exe" if os.name == "nt" else ""))
        if not simple or not os.path.isfile(simple):
            self.skipTest("нет llama-simple (переменная DAN_LLAMA_SIMPLE)")
        р = subprocess.run([simple, "-m", Общее.модель, "-n", "24", ЗАПРОС], capture_output=True, timeout=300)
        self.assertEqual(р.returncode, 0, р.stderr.decode("utf-8", "replace"))
        вывод_ = р.stdout.decode("utf-8", "replace")
        начало = вывод_.index(ЗАПРОС) + len(ЗАПРОС)
        их = вывод_[начало:].rstrip("\n")
        наш = self.ответы()["ответ"]
        общее = min(len(их), len(наш))
        self.assertGreater(общее, 10)
        self.assertEqual(их[:общее], наш[:общее], "llama-simple: " + их + "\nДан: " + наш)


