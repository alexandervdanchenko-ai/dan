"""Многострочные и сырые строки (раздел 2.6 spec.md, решение 0015): лексер и форматирование
компилятора на Дане. Компилятор на Python заморожен и этой записи не знает."""

import os
import subprocess
import tempfile
import unittest

import sam_kompilyator

ПАПКА = os.path.dirname(os.path.abspath(__file__))


def выполнить(команда, текст):
    with tempfile.TemporaryDirectory() as папка:
        путь = os.path.join(папка, "п.dan")
        with open(путь, "w", encoding="utf-8", newline="") as ф:
            ф.write(текст)
        р = subprocess.run([sam_kompilyator.исполняемый(), команда, путь], capture_output=True, cwd=папка,
                           env=sam_kompilyator.среда(), timeout=600)
        with open(путь, encoding="utf-8", newline="") as ф:
            после = ф.read()
        return (р.returncode, р.stdout.decode("utf-8", "replace").replace("\r\n", "\n"),
                р.stderr.decode("utf-8", "replace"), после)


def вывод(текст):
    код, вых, ош, _ = выполнить("запустить", текст)
    if код != 0:
        raise AssertionError(вых + ош)
    return вых


def ошибка(текст):
    код, вых, ош, _ = выполнить("проверить", текст)
    if код == 0:
        raise AssertionError("ожидалась ошибка записи: " + вых)
    return вых + ош


class ТестыМногострочныхСтрок(unittest.TestCase):
    def test_отступ_закрывающих_кавычек_убирается(self):
        текст = ('функ письмо(имя: стр) -> стр {\n'
                 '    вернуть """\n'
                 '        Здравствуйте, "уважаемый" клиент!\n'
                 '          с отступом\n'
                 '\n'
                 '        конец\\\\\n'
                 '        """ + имя\n'
                 '}\n'
                 'пусть т = письмо("Иван")\n'
                 'вывод(т)\n'
                 'вывод(т.длина)\n')
        ожидается = 'Здравствуйте, "уважаемый" клиент!\n  с отступом\n\nконец\\Иван'
        self.assertEqual(вывод(текст), ожидается + "\n" + str(len(ожидается)) + "\n")

    def test_последовательности_обрабатываются(self):
        текст = 'пусть т = """\n    а\\tб\\n\\"в\\"\n    """\nвывод(т.длина)\nвывод(т)\n'
        self.assertEqual(вывод(текст), '7\nа\tб\n"в"\n')

    def test_одна_строка_и_строки_с_cr(self):
        self.assertEqual(вывод('вывод("""\n  одна\n  """.длина)\n'), "4\n")
        self.assertEqual(вывод('пусть т = """\r\n    а\r\n    б\r\n    """\r\nвывод(т.длина)\r\n'), "3\n")

    def test_в_списке_и_вызове(self):
        текст = 'пусть с = ["""\n    первая\n    """,\n    "вторая"]\nвывод(с.длина)\nвывод(с[0])\n'
        self.assertEqual(вывод(текст), "2\nпервая\n")

    def test_ошибки(self):
        self.assertIn('Строка 1, позиция 14: после «"""» текст многострочной строки пишется со следующей строки',
                      ошибка('пусть а = """текст\n    """\n'))
        self.assertIn('Строка 1, позиция 11: многострочная строка не закрыта',
                      ошибка('пусть а = """\n    текст\n'))
        self.assertIn('Строка 2, позиция 3: строка многострочной строки начинается левее закрывающих',
                      ошибка('пусть а = """\n  текст\n    """\n'))
        self.assertIn('Строка 2, позиция 6: неизвестная последовательность \\q',
                      ошибка('пусть а = """\n    \\q\n    """\n'))


class ТестыСырыхСтрок(unittest.TestCase):
    def test_без_обработки_обратной_черты(self):
        текст = ('пусть путь = #"C:\\папка\\новая"#\n'
                 'вывод(путь)\n'
                 'вывод(#"он сказал "да""#)\n'
                 'вывод(#"\\n"#.длина)\n')
        self.assertEqual(вывод(текст), 'C:\\папка\\новая\nон сказал "да"\n2\n')

    def test_многострочная_сырая(self):
        текст = 'пусть ш = #"""\n    \\d+ "ч"\n      \\s\n    """#\nвывод(ш)\n'
        self.assertEqual(вывод(текст), '\\d+ "ч"\n  \\s\n')

    def test_не_закрыта(self):
        self.assertIn("Строка 1, позиция 11: сырая строка не закрыта", ошибка('пусть а = #"текст\n'))


class ТестыФорматаСтрок(unittest.TestCase):
    ИСХОДНЫЙ = ('функ ф(имя:стр)->стр{\n'
                '  пусть т=f2("""\n'
                '      Текст   с пробелами   \n'
                '        отступ\n'
                '\n'
                '\n'
                '      """, #"""\n'
                '  \\сыро\n'
                '  """#)\n'
                '  вернуть т+имя\n'
                '}\n'
                'функ f2(а:стр,б:стр)->стр{вернуть а+б}\n'
                'вывод(ф(#"x\\y"#))\n')

    def test_одиночный_cr_в_тексте(self):
        # одиночный «\r» внутри многострочной строки - часть текста; формат его не трогает
        текст = 'пусть а = """\n  x\r  y\n  """\nвывод(а.длина)\n'
        код, вых, ош, после = выполнить("формат", текст)
        self.assertEqual(код, 0, вых + ош)
        self.assertIn("x\r  y", после)
        self.assertEqual(вывод(после), "5\n")

    def test_текст_строки_не_меняется(self):
        код, вых, ош, после = выполнить("формат", self.ИСХОДНЫЙ)
        self.assertEqual(код, 0, вых + ош)
        self.assertEqual(после, ('функ ф(имя: стр) -> стр {\n'
                                 '    пусть т = f2("""\n'
                                 '      Текст   с пробелами   \n'
                                 '        отступ\n'
                                 '\n'
                                 '\n'
                                 '      """, #"""\n'
                                 '  \\сыро\n'
                                 '  """#)\n'
                                 '    вернуть т + имя\n'
                                 '}\n'
                                 'функ f2(а: стр, б: стр) -> стр { вернуть а + б }\n'
                                 'вывод(ф(#"x\\y"#))\n'))
        self.assertEqual(вывод(после), вывод(self.ИСХОДНЫЙ))
        # повторное форматирование ничего не меняет
        код, вых, ош, ещё = выполнить("формат", после)
        self.assertEqual((код, ещё), (0, после), вых + ош)


if __name__ == "__main__":
    unittest.main()
