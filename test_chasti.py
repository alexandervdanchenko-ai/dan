class ТестыЧтенияВШаге(unittest.TestCase):
    """Поля общих записей и части элементов общих списков массивов в шаге (раздел 12.11)."""

    def проверка(self, тело):
        return ошибки_проверки(ЗАПИСЬ + "параллельно для к в 0..3 {\n" + тело + "\n}\n")

    def test_разрешено(self):
        for тело in ("    у[к] = дроб(м.слой.голов) * м.слой.масштаб + м.слой.веса[к] + м.слой.веса.длина",
                     "    если м.точный { у[к] = скаляр(м.слой.веса[к * 4..к * 4 + 3], м.слой.ключи[1][0..3]) }",
                     "    у[к] = скаляр(м.слой.ключи[к % 2], м.слой.ключи[0]) + скаляр(сл.веса, сл.веса)",
                     "    у[к] = матвек(сл.ключи[0][0..7], сл.ключи[1][к..к])[0]",
                     "    пусть т = Точка(дроб(к))\n    у[к] = т.квадрат()",
                     "    у[к] = склеить(сл.веса[0..1], сл.ключи[0][0..1])[0]",
                     "    перем свой = массив(дроб32, 2)\n    у[к] = склеить(свой, сл.веса)[к]"):
            with self.subTest(тело=тело):
                self.assertEqual(self.проверка(тело), "")

    def test_отказы(self):
        import kody
        for тело, код_, часть in [
                ("    пусть ч_ = м.слой.веса[0..3]", "Д0321", "часть общего массива «м.слой.веса»"),
                ("    пусть ч_ = сл.ключи[0][0..3]", "Д0321", "часть общего массива «сл.ключи[...]»"),
                ("    пусть ве = м.слой.веса", "Д0316", "общую переменную «м.слой.веса» типа массив<дроб32>"),
                ("    пусть и_ = сл.имя", "Д0316", "общую переменную «сл.имя» типа стр"),
                ("    пусть с_ = м.слой", "Д0316", "общую переменную «м.слой» типа Слой"),
                ("    у[к] = м.слой.веса.список()[0]", "Д0319", "общий массив «м.слой.веса»"),
                ("    пусть т = Точка(1.0)\n    у[к] = т.показать()", "Д0312", "нельзя выводить и вводить"),
                ("    пс.х = 1.0", "Д0308", "нельзя изменять общую переменную «пс»"),
                ("    пм.слой.веса[к] = 1.0", "Д0311", "только свои элементы")]:
            with self.subTest(тело=тело):
                текст = self.проверка(тело)
                self.assertIn(часть, текст)
                self.assertEqual(kody.код(текст.split(": ", 1)[1].split("\n")[0]), код_)

    @unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
    def test_выполнение_побитно(self):
        текст = (ЗАПИСЬ.replace("перем у = массив(дроб32, 4)\n", "")
                 + "перем у = массив(дроб32, 64)\nпусть б = массив(дроб32, 64 * 64, 0.001)\n"
                 "перем кл: [массив<дроб32>] = []\nдля ии в 0..3 { кл.добавить(массив(дроб32, 64 * 64, 0.5 + дроб(ии))) }\n"
                 "параллельно для к в 0..63 {\n"
                 "    пусть т = Точка(дроб(к))\n"
                 "    у[к] = скаляр(кл[к % 4][к * 64..к * 64 + 63], б[к * 64..к * 64 + 63]) * м.слой.масштаб + т.квадрат()"
                 " + м.слой.веса[к % 16]\n"
                 "}\n"
                 "перем ож = массив(дроб32, 64)\n"
                 "для к в 0..63 {\n"
                 "    ож[к] = скаляр(кл[к % 4][к * 64..к * 64 + 63], б[к * 64..к * 64 + 63]) * 0.5 + дроб(к * к) + 0.25\n"
                 "}\n"
                 "вывод(у == ож)\nвывод(у[63])\n")
        выводы = set()
        for потоков in (1, 3, 8):
            код, вывод, ошибки = выполнить(текст, потоков)
            self.assertEqual(код, 0, ошибки)
            выводы.add(вывод)
        self.assertEqual(len(выводы), 1)
        self.assertTrue(выводы.pop().startswith("истина\n"))


СВОДКА = """перем данные: [дроб] = []
для к в 0..НН - 1 { данные.добавить(синус(дроб(к)) * 1000.0 + 1.0 / дроб(к + 1)) }
перем сумма = 0.5
перем счёт = 0
параллельно для к в 0..данные.длина - 1 сводка сумма, счёт {
    сумма += данные[к] * данные[к]
    если данные[к] > 0.0 { счёт += 1 }
}
// тот же порядок сложения обычным циклом: мин(64, н) частей подряд, длиннее - первые
пусть н = данные.длина
пусть частей = мин(64, н)
перем ожидаемая = 0.5
перем начало = 0
для ч в 0..частей - 1 {
    перем длина = частное(н, частей)
    если ч < н % частей { длина += 1 }
    перем часть = 0.0
    для к в начало..начало + длина - 1 { часть += данные[к] * данные[к] }
    ожидаемая += часть
    начало += длина
}
вывод(сумма)
вывод(сумма == ожидаемая)
вывод(счёт)
"""


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыСводки(unittest.TestCase):
    """«параллельно для ... сводка с { с += ... }»: суммы частей с постоянным порядком (раздел 12.11)."""

    def test_побитно_при_любом_числе_потоков(self):
        текст = СВОДКА.replace("НН", "100003")
        выводы = set()
        for потоков in range(1, 17):
            код, вывод, ошибки = выполнить(текст, потоков)
            self.assertEqual(код, 0, ошибки)
            выводы.add(вывод)
        self.assertEqual(len(выводы), 1, выводы)
        строки = выводы.pop().split("\n")
        self.assertEqual(строки[1], "истина")

    def test_мало_шагов_как_обычный_цикл(self):
        # шагов не больше 64: у каждого шага своя часть, итог - как у обычного «для»
        текст = СВОДКА.replace("НН", "10") + ("перем п = 0.5\nдля к в 0..данные.длина - 1 { п += данные[к] * данные[к] }\n"
                                               "вывод(п == сумма)\n")
        код, вывод, ошибки = выполнить(текст, 3)
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод.split("\n")[1:], ["истина", "7", "истина", ""])

    def test_пустой_цикл_и_переполнение(self):
        код, вывод, _ = выполнить("перем с = 7\nпараллельно для к в 0..-1 сводка с {\n    с += 1\n}\nвывод(с)\n")
        self.assertEqual((код, вывод), (0, "7\n"))
        код, _, ошибки = выполнить("перем с = 9223372036854775000\nпараллельно для к в 0..999 сводка с {\n    с += 1\n}\n")
        self.assertNotEqual(код, 0)
        self.assertIn("слишком", ошибки)

    def test_слово_сводка_не_зарезервировано(self):
        код, вывод, ошибки = выполнить("перем сводка = 1\nсводка += 1\nвывод(сводка)\n")
        self.assertEqual((код, вывод), (0, "2\n"), ошибки)

    def test_отказы(self):
        import kody
        for запись, код_, часть in [
                ("пусть с = 0.0\nпараллельно для к в 0..3 сводка с {\n    с += 1.0\n}", "Д0340", "объявлена через «пусть»"),
                ("перем с = \"\"\nпараллельно для к в 0..3 сводка с {\n    с += \"а\"\n}", "Д0340", "имеет тип стр"),
                ("параллельно для к в 0..3 сводка с {\n}", "Д0340", "не объявлена"),
                ("перем с = 0\nпараллельно для к в 0..3 сводка с, с {\n    с += 1\n}", "Д0340", "имя повторяется"),
                ("перем с = 0\nпараллельно для к в 0..3 сводка с {\n    с = с + 1\n}", "Д0341", "можно только увеличивать"),
                ("перем с = 0\nперем р = [0, 0, 0, 0]\nпараллельно для к в 0..3 сводка с {\n    с += 1\n    р[к] = с\n}",
                 "Д0341", "можно только увеличивать")]:
            with self.subTest(запись=запись):
                текст = ошибки_проверки(запись + "\n")
                self.assertIn(часть, текст)
                self.assertEqual(kody.код(текст.split(": ", 1)[1].split("\n")[0]), код_)


if __name__ == "__main__":
    unittest.main()
