"""Узлы дерева программы (AST) языка Дан.

Парсер строит из токенов дерево таких узлов. Каждый узел помнит строку
и позицию в исходном тексте, чтобы сообщения об ошибках на следующих
этапах (проверка типов, компиляция) указывали точное место.
"""

from dataclasses import dataclass, field, fields
from typing import Optional


@dataclass
class Узел:
    строка: int = field(default=0, kw_only=True, repr=False, compare=False)
    столбец: int = field(default=0, kw_only=True, repr=False, compare=False)


# ---------- Выражения ----------

@dataclass
class ЦелоеЧисло(Узел):
    значение: int


@dataclass
class ДробноеЧисло(Узел):
    значение: float


@dataclass
class Строка(Узел):
    значение: str


@dataclass
class Логическое(Узел):
    значение: bool


@dataclass
class Имя(Узел):
    имя: str
    # имя так, как оно написано в программе (с «ё»), для сообщений об ошибках
    написание: Optional[str] = field(default=None, kw_only=True, repr=False, compare=False)


@dataclass
class Унарная(Узел):
    оператор: str          # "-" или "не"
    операнд: Узел


@dataclass
class Бинарная(Узел):
    оператор: str          # "+", "-", "*", "/", "%", "==", "!=", "<", "<=", ">", ">=", "и", "или"
    левый: Узел
    правый: Узел


@dataclass
class Диапазон(Узел):
    начало: Узел
    конец: Узел


