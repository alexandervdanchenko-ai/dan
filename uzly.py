# ---------- Печать дерева ----------

def показать(узел, отступ=0):
    """Возвращает дерево в виде текста с отступами, удобного для чтения."""
    пробелы = "  " * отступ
    if isinstance(узел, list):
        return "\n".join(показать(э, отступ) for э in узел)
    if not isinstance(узел, Узел):
        return f"{пробелы}{узел!r}"

    простые = []
    вложенные = []
    for п in fields(узел):
        if п.name in ("строка", "столбец") or not п.repr:
            continue
        значение = getattr(узел, п.name)
        if isinstance(значение, (Узел, list)) and значение != []:
            вложенные.append((п.name, значение))
        elif значение is not None and значение != []:
            простые.append(f"{п.name}={значение!r}")

    заголовок = f"{пробелы}{type(узел).__name__}"
    if простые:
        заголовок += " (" + ", ".join(простые) + ")"
    строки = [заголовок]
    for имя, значение in вложенные:
        строки.append(f"{пробелы}  {имя}:")
        строки.append(показать(значение, отступ + 2))
    return "\n".join(строки)
