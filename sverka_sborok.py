"""Сверка сборок: одна и та же программа, собранная по-разному, должна вести себя одинаково.

Случайные правильные программы на Дане (целые и дробные числа, обыкновенные
дроби, строки и их методы, списки и их методы, словари, записи, необязательные
значения, условия, циклы, функции, рекурсия; вызовы функций с выводом внутри
выражений, индексов и левой части присваивания - для проверки порядка
вычисления) переводятся
в C один раз и собираются несколькими компиляторами C с разной оптимизацией:
gcc и clang (и zig, если он есть) с -O0, -O2, -O3 и -Os. Вывод, сообщения об ошибках
и код завершения у всех сборок должны совпасть. Расхождение означает, что
код C, созданный Даном, зависит от неопределённого поведения (оптимизатор
вправе по-разному поступать с ним) или что в одном из компиляторов ошибка.
Ошибки выполнения (переполнение, деление на ноль, выход за границы списка)
допустимы: они тоже должны быть одинаковыми.

Найденная программа сохраняется в «фаззинг/находки_сборок» и проверяется
тестами при каждом запуске (test_sverka_sborok.py).

Запуск: python sverka_sborok.py [число_программ] [зерно]
"""

import os
import random
import shutil
import subprocess
import sys
import tempfile

import dan

ПАПКА = os.path.dirname(os.path.abspath(__file__))
НАХОДКИ = os.path.join(ПАПКА, "фаззинг", "находки_сборок")


# ---------- случайные программы ----------

ТИПЫ = ("цел", "дроб", "стр", "[цел]", "{стр: цел}", "Зап", "цел?")

# запись для проверки полей: поле-число и поле-список
ТИП_ЗАП = "тип Зап {\n    ч: цел\n    сп: [цел]\n}"


def _копия(пер):
    return {т: list(и) for т, и in пер.items()}


class Генератор:
    """Программа строится так, чтобы быть правильной по типам: у каждой переменной известный тип.
    «ч» - переменные, которые можно читать, «з» - которые можно изменять (тип -> имена)."""

    def __init__(self, сл):
        self.сл = сл
        self.строки = []
        self.отступ = 0
        self.счётчик = 0
        self.функции = []

    def пиши(self, текст):
        self.строки.append("    " * self.отступ + текст)

    def имя(self, основа):
        self.счётчик += 1
        return f"{основа}{self.счётчик}"

    # ---------- выражения ----------

    def цел(self, ч, глубина=2):
        сл = self.сл
        if глубина <= 0 or сл.random() < 0.3:
            if ч["цел"] and сл.random() < 0.6:
                return сл.choice(ч["цел"])
            return str(сл.choice([0, 1, 2, 3, 7, 10, 100, -1, -5, 12345, 2 ** 31, 2 ** 40 + 3, сл.randint(-99, 99)]))
        if сл.random() < 0.25:
            особое = self.цел_особое(ч, глубина)
            if особое:
                return особое
        вид = сл.randrange(10)
        а, б = self.цел(ч, глубина - 1), self.цел(ч, глубина - 1)
        if вид < 3:
            return f"({а} + {б})"
        if вид < 5:
            return f"({а} - {б})"
        if вид < 6:
            return f"({а} * {б})"
        # делитель чаще ненулевое число: иначе большинство программ кончалось бы делением на ноль
        делитель = б if сл.random() < 0.25 else str(сл.choice([1, 2, 3, 7, -4, 10, 1000]))
        if вид < 7:
            return f"частное({а}, {делитель})"
        if вид < 8:
            return f"({а} % {делитель})"
        if вид < 9 and ч["стр"]:
            return f"{сл.choice(ч['стр'])}.длина"
        if ч["[цел]"]:
            return f"{сл.choice(ч['[цел]'])}.длина"
        return f"модуль({а})"

    def вызов(self, ч, глубина):
        """Вызов функции программы: функции могут выводить, поэтому порядок вызовов виден в выводе."""
        сл = self.сл
        имя, вид_ф = сл.choice(self.функции)
        if вид_ф == "цел":
            return f"{имя}({self.цел(ч, глубина - 1)}, {self.цел(ч, глубина - 1)})"
        return f"{имя}(модуль({self.цел(ч, 0)}) % 9)"

    def цел_особое(self, ч, глубина):
        """Целое из вызова, поля записи, необязательного значения, словаря или метода; None - нет подходящего."""
        сл = self.сл
        вид = сл.randrange(7)
        if вид < 2 and self.функции:
            return self.вызов(ч, глубина)
        if вид == 2 and ч["Зап"]:
            return f"{сл.choice(ч['Зап'])}.ч"
        if вид == 3 and ч["цел?"]:
            return f"({сл.choice(ч['цел?'])} иначе {self.цел(ч, 0)})"
        if вид == 4 and ч["{стр: цел}"]:
            return f'({сл.choice(ч["{стр: цел}"])}.найти("{сл.choice(["а", "б", "в"])}") иначе -1)'
        if вид == 5 and ч["[цел]"]:
            return f"{сл.choice(ч['[цел]'])}.найти({self.цел(ч, 0)})"
        if вид == 6 and ч["стр"]:
            return f'{сл.choice(ч["стр"])}.найти("{сл.choice(["о", "а", "ё", ""])}")'
        return None

    def список(self, ч):
        """Выражение типа [цел]."""
        сл = self.сл
        вид = сл.randrange(4)
        if вид == 0 and ч["[цел]"]:
            return f"{сл.choice(ч['[цел]'])}.обратный()"
        if вид == 1 and ч["Зап"]:
            return f"{сл.choice(ч['Зап'])}.сп"
        if вид == 2 and ч["[цел]"]:
            return сл.choice(ч["[цел]"])
        return f"[{self.цел(ч, 1)}, {self.цел(ч, 1)}]"

    def дроб(self, ч, глубина=2):
        сл = self.сл
        if глубина <= 0 or сл.random() < 0.3:
            if ч["дроб"] and сл.random() < 0.6:
                return сл.choice(ч["дроб"])
            return сл.choice(["0.1", "0.2", "1.5", "3.0", "-2.25", "1e10", "1e-7", "0.333", "100.0"])
        а, б = self.дроб(ч, глубина - 1), self.дроб(ч, глубина - 1)
        вид = сл.randrange(7)
        if вид == 0:
            return f"({а} + {б})"
        if вид == 1:
            return f"({а} - {б})"
        if вид == 2:
            return f"({а} * {б})"
        if вид == 3:
            return f"({а} / {б})"
        if вид == 4:
            return f"({а} * {б} + {self.дроб(ч, 0)})"         # кандидат на слияние в одно действие (FMA)
        if вид == 5:
            return f"корень(модуль({а}))"
        return f"({а} + {self.цел(ч, 0)})"

    def рац(self, ч):
        сл = self.сл
        return f"(рац({сл.randint(-20, 20)}, {сл.randint(1, 12)}) + {self.цел(ч, 0)} / {сл.choice([3, 7, 9])})"

    def лог(self, ч, глубина=1):
        сл = self.сл
        вид = сл.randrange(6)
        if вид < 2:
            return f"{self.цел(ч, 1)} {сл.choice(['<', '>', '==', '!=', '<=', '>='])} {self.цел(ч, 1)}"
        if вид == 2:
            return f"{self.дроб(ч, 1)} {сл.choice(['<', '>'])} {self.дроб(ч, 1)}"
        if вид == 3 and ч["стр"]:
            return f'{сл.choice(ч["стр"])} {сл.choice(["<", "==", "!="])} "{сл.choice(["а", "б", "ёж", ""])}"'
        if вид == 4 and глубина > 0:
            return f"({self.лог(ч, глубина - 1)} {сл.choice(['и', 'или'])} {self.лог(ч, глубина - 1)})"
        if вид == 5 and сл.random() < 0.5:
            if ч["[цел]"] and сл.random() < 0.5:
                return f"{сл.choice(ч['[цел]'])}.содержит({self.цел(ч, 0)})"
            if ч["стр"]:
                return f'{сл.choice(ч["стр"])}.{сл.choice(["начинается", "оканчивается", "содержит"])}("{сл.choice(["д", "м", "", "ё"])}")'
            if ч["цел?"]:
                return f"{сл.choice(ч['цел?'])} {сл.choice(['==', '!='])} ничего"
        return f"не ({self.цел(ч, 0)} > {self.цел(ч, 0)})"

    def стр_(self, ч):
        сл = self.сл
        вид = сл.randrange(6)
        if вид == 0 and ч["стр"]:
            return сл.choice(ч["стр"])
        if вид == 1:
            return f"стр({self.цел(ч, 1)})"
        if вид == 2:
            return f"стр({self.дроб(ч, 1)})"
        if вид == 3 and ч["стр"]:
            return f'{сл.choice(ч["стр"])} + "{сл.choice(["ж", "Ё", "-", "ab"])}"'
        if вид == 4 and ч["стр"]:
            с = сл.choice(ч["стр"])
            вариант = сл.randrange(5)
            if вариант == 0:
                return f'{с}.заменить("а", "ё")'
            if вариант == 1:
                return f"{с}.{сл.choice(['прописные', 'строчные', 'обрезать'])}()"
            if вариант == 2:
                return f"{с}.повторить(модуль({self.цел(ч, 0)}) % 3)"
            if вариант == 3:
                return f"{с}[0..(модуль({self.цел(ч, 1)}) % ({с}.длина + 1)) - 1]"
            return f'{с}.разбить("о").соединить("-")'
        return '"' + сл.choice(["", "а", "привет", "Ёлка", "x y z"]) + '"'

    def выводимое(self, ч):
        сл = self.сл
        вид = сл.randrange(7)
        if вид == 0:
            return self.цел(ч)
        if вид == 1:
            return self.дроб(ч)
        if вид == 2:
            return self.стр_(ч)
        if вид == 3:
            return self.лог(ч)
        if вид == 4:
            return self.рац(ч)
        if вид == 5 and ч["[цел]"]:
            return сл.choice(ч["[цел]"])
        if ч["{стр: цел}"]:
            return сл.choice(ч["{стр: цел}"])
        return self.цел(ч)

    # ---------- инструкции ----------

    def инструкция(self, ч, з, глубина):
        сл = self.сл
        вид = сл.randrange(18)
        if вид < 3 and з["цел"]:
            self.пиши(f"{сл.choice(з['цел'])} = {self.цел(ч)}")
        elif вид == 3 and з["дроб"]:
            self.пиши(f"{сл.choice(з['дроб'])} = {self.дроб(ч)}")
        elif вид == 4 and з["стр"]:
            self.пиши(f"{сл.choice(з['стр'])} = {self.стр_(ч)}")
        elif вид == 5 and з["[цел]"]:
            self.пиши(f"{сл.choice(з['[цел]'])}.добавить({self.цел(ч, 1)})")
        elif вид == 6 and з["[цел]"]:
            с = сл.choice(з["[цел]"])
            self.пиши(f"если {с}.длина > 0 {{ {с}[модуль({self.цел(ч, 1)}) % {с}.длина] = {self.цел(ч, 1)} }}")
        elif вид == 7 and з["{стр: цел}"]:
            с = сл.choice(з["{стр: цел}"])
            к = сл.choice(['"а"', '"б"', '"в"']) if сл.random() < 0.7 or not ч["стр"] else сл.choice(ч["стр"])
            self.пиши(f"{с}[{к}] = {с}.получить({к}, 0) + {self.цел(ч, 0)}")
        elif вид == 8 and глубина > 0:
            self.пиши(f"если {self.лог(ч)} {{")
            self.блок(ч, з, глубина - 1)
            if сл.random() < 0.5:
                self.пиши("} иначе {")
                self.блок(ч, з, глубина - 1)
            self.пиши("}")
        elif вид == 9 and глубина > 0:
            к = self.имя("к")                     # переменная цикла: читать можно, изменять нельзя
            self.пиши(f"для {к} в {сл.randint(-2, 2)}..{сл.randint(0, 6)} {{")
            ч2 = _копия(ч)
            ч2["цел"].append(к)
            self.блок(ч2, з, глубина - 1)
            self.пиши("}")
        elif вид == 10 and глубина > 0 and ч["[цел]"]:
            с = сл.choice(ч["[цел]"])
            х = self.имя("х")
            self.пиши(f"для {х} в {с} {{")
            ч2 = _копия(ч)
            ч2["цел"].append(х)
            з2 = _копия(з)
            з2["[цел]"] = [и for и in з2["[цел]"] if и != с]
            self.блок(ч2, з2, глубина - 1)
            self.пиши("}")
        elif вид == 11 and глубина > 0:
            сч = self.имя("сч")
            self.пиши(f"перем {сч} = 0")
            self.пиши(f"пока {сч} < {сл.randint(1, 5)} {{")
            self.пиши(f"    {сч} += 1")
            ч2 = _копия(ч)
            ч2["цел"].append(сч)
            self.блок(ч2, з, глубина - 1)
            self.пиши("}")
        elif вид == 12 and self.функции:
            имя, вид_ф = сл.choice(self.функции)
            if вид_ф == "цел":
                self.пиши(f"вывод({имя}({self.цел(ч, 1)}, {self.цел(ч, 1)}))")
            else:
                self.пиши(f"вывод({имя}({сл.randint(0, 12)}))")
        elif вид == 13 and з["Зап"]:
            с = сл.choice(з["Зап"])
            вариант = сл.randrange(4)
            if вариант == 0:
                self.пиши(f"{с}.ч = {self.цел(ч)}")
            elif вариант == 1:
                self.пиши(f"{с}.сп.добавить({self.цел(ч, 1)})")
            elif вариант == 2:
                self.пиши(f"если {с}.сп.длина > 0 {{ {с}.сп[модуль({self.цел(ч, 1)}) % {с}.сп.длина] {сл.choice(['=', '+='])} "
                          f"{self.цел(ч, 1)} }}")
            else:
                self.пиши(f"{с} = Зап({self.цел(ч, 1)}, {self.список(ч)})")
        elif вид == 14 and з["цел?"]:
            н = сл.choice(з["цел?"])
            вариант = сл.randrange(3)
            if вариант == 0:
                self.пиши(f"{н} = {self.цел(ч, 1)}")
            elif вариант == 1:
                self.пиши(f"{н} = ничего")
            else:
                х = self.имя("х")
                self.пиши(f"если пусть {х} = {н} {{ вывод({х} + {self.цел(ч, 0)}) }}")
        elif вид == 15 and з["[цел]"]:
            с = сл.choice(з["[цел]"])
            if сл.random() < 0.5:
                self.пиши(f"{с}.вставить(модуль({self.цел(ч, 1)}) % ({с}.длина + 1), {self.цел(ч, 1)})")
            else:
                self.пиши(f"если {с}.длина > 0 {{ {с}.удалить(модуль({self.цел(ч, 1)}) % {с}.длина) }}")
        elif вид == 16 and self.функции and (з["[цел]"] or з["{стр: цел}"] or з["Зап"]):
            # вызовы с выводом и в индексе левой части, и в значении: порядок виден в выводе
            if з["[цел]"] and сл.random() < 0.5:
                с = сл.choice(з["[цел]"])
                self.пиши(f"если {с}.длина > 0 {{ {с}[модуль({self.вызов(ч, 1)}) % {с}.длина] {сл.choice(['=', '+=', '-='])} "
                          f"{self.вызов(ч, 1)} }}")
            elif з["{стр: цел}"] and сл.random() < 0.5:
                с = сл.choice(з["{стр: цел}"])
                self.пиши(f"{с}[стр(модуль({self.вызов(ч, 1)}) % 3)] = {self.вызов(ч, 1)}")
            elif з["Зап"]:
                с = сл.choice(з["Зап"])
                self.пиши(f"{с}.ч = {self.вызов(ч, 1)} - {self.вызов(ч, 1)}")
            else:
                self.пиши(f"вывод({self.вызов(ч, 1)} + {self.вызов(ч, 1)})")
        else:
            self.пиши(f"вывод({self.выводимое(ч)})")

    def блок(self, ч, з, глубина):
        self.отступ += 1
        for _ in range(self.сл.randint(1, 3)):
            self.инструкция(ч, з, глубина)
        self.отступ -= 1

    def программа(self):
        сл = self.сл
        пусто = {т: [] for т in ТИПЫ}
        self.пиши(ТИП_ЗАП)
        # функции над целыми и рекурсивная
        for _ in range(сл.randint(1, 3)):
            имя = self.имя("ф")
            self.пиши(f"функ {имя}(а: цел, б: цел) -> цел {{")
            self.отступ += 1
            self.пиши("перем р = а")
            ч = dict(_копия(пусто), цел=["а", "б", "р"])
            з = dict(_копия(пусто), цел=["р"])
            for _ in range(сл.randint(1, 4)):
                self.инструкция(ч, з, 1)
            self.пиши(f"вернуть р + {self.цел(ч, 1)}")
            self.отступ -= 1
            self.пиши("}")
            self.функции.append((имя, "цел"))
        имя = self.имя("рек")
        self.пиши(f"функ {имя}(н: цел) -> цел {{")
        self.пиши("    если н <= 0 { вернуть 1 }")
        self.пиши(f"    вернуть {имя}(н - 1) * {сл.choice([2, 3, -1, 7])} + н % {сл.choice([2, 5, 9])}")
        self.пиши("}")
        self.функции.append((имя, "рек"))
        # основная часть
        пер = _копия(пусто)
        for тип, нач in (("цел", lambda: str(сл.randint(-30, 30))), ("цел", lambda: "0"),
                         ("дроб", lambda: сл.choice(["0.5", "1.25", "-3.0"])),
                         ("стр", lambda: '"' + сл.choice(["а", "дом", ""]) + '"'),
                         ("[цел]", lambda: str([сл.randint(-9, 9) for _ in range(сл.randint(0, 4))])),
                         ("{стр: цел}", lambda: '{"а": 1}'),
                         ("Зап", lambda: f"Зап({сл.randint(-9, 9)}, [{сл.randint(-9, 9)}, {сл.randint(-9, 9)}])"),
                         ("цел?", lambda: сл.choice(["ничего", str(сл.randint(-9, 9))]))):
            имя = self.имя({"цел": "ц", "дроб": "д", "стр": "с", "[цел]": "сп", "{стр: цел}": "сл", "Зап": "з",
                            "цел?": "н"}[тип])
            запись = f": {тип}" if тип in ("[цел]", "{стр: цел}", "цел?") else ""
            self.пиши(f"перем {имя}{запись} = {нач()}")
            пер[тип].append(имя)
        for _ in range(сл.randint(5, 15)):
            self.инструкция(пер, пер, 2)
        for тип in ТИПЫ:
            for имя in пер[тип]:
                self.пиши(f"вывод({имя})")
        return "\n".join(self.строки) + "\n"


def случайная_программа(зерно):
    return Генератор(random.Random(зерно)).программа()


# ---------- сборки ----------

def _собирает(команда):
    """Собирает ли компилятор программу Дана (в Windows clang из Visual Studio не умеет компоновать её)."""
    with tempfile.TemporaryDirectory() as папка:
        try:
            итог = выполнить_сборки("вывод(1)\n", папка, [("проба", команда, ["-O0"])])
        except OSError:
            return False
        return итог.get("проба", ("сборка",))[0] == 0


def сборки():
    """Доступные способы сборки: (название, команда компилятора, флаги оптимизации)."""
    итог = []
    for имя in ("gcc", "clang"):
        путь = shutil.which(имя)
        if путь and _собирает([путь]):
            for уровень in ("-O0", "-O2", "-O3", "-Os"):
                итог.append((f"{имя} {уровень}", [путь], [уровень]))
    try:
        zig = dan.команда_компилятора() if os.environ.get("DAN_COMPILER") == "zig" else None
    except dan.ОшибкаСборки:
        zig = None
    if zig:
        итог.append(("zig -O2", zig, ["-O2"]))
    return итог


def выполнить_сборки(текст, папка, способы=None):
    """Собирает программу каждым способом и выполняет: {название: (код, вывод, ошибки)}."""
    способы = способы or сборки()
    путь = os.path.join(папка, "программа.dan")
    with open(путь, "w", encoding="utf-8") as ф:
        ф.write(текст)
    код_c = dan.перевести(текст, путь)
    путь_c = os.path.join(папка, "программа.c")
    with open(путь_c, "w", encoding="utf-8") as ф:
        ф.write(код_c)
    общие = [ф for ф in dan.ФЛАГИ_ОБЩИЕ]
    итог = {}
    for номер, (название, команда, уровень) in enumerate(способы):
        исп = os.path.join(папка, f"п{номер}" + (".exe" if os.name == "nt" else ""))
        библиотеки = dan.библиотеки_программы(код_c, папка, команда)
        р = dan._скомпилировать([*команда, *общие, *уровень], путь_c, исп, библиотеки)
        if р.returncode != 0:
            итог[название] = ("сборка", "", р.stderr.strip()[-2000:])
            continue
        try:
            в = subprocess.run([исп], capture_output=True, timeout=30, cwd=папка)
            итог[название] = (в.returncode, в.stdout.decode("utf-8", "replace"), в.stderr.decode("utf-8", "replace"))
        except subprocess.TimeoutExpired:
            итог[название] = ("зависание", "", "")
    return итог


def расхождение(итоги):
    """Описание расхождения или None, если все сборки дали одно и то же."""
    названия = list(итоги)
    if not названия:
        return None
    первый = итоги[названия[0]]
    for н in названия[1:]:
        if итоги[н] != первый:
            return (f"{названия[0]}: код {первый[0]}\n{первый[1]}{первый[2]}\n"
                    f"{н}: код {итоги[н][0]}\n{итоги[н][1]}{итоги[н][2]}")
    return None


def сверить(число=50, зерно=1, способы=None, сохранять=True):
    """Возвращает (проверено, ошибки_генератора, расхождения)."""
    способы = способы or сборки()
    ошибки_генератора, расхождения = [], []
    with tempfile.TemporaryDirectory() as папка:
        for н in range(число):
            текст = случайная_программа(зерно * 100_003 + н)
            try:
                итоги = выполнить_сборки(текст, папка, способы)
            except (dan.ОшибкаЛексера, dan.ОшибкаРазбора, dan.ОшибкаПроверки, dan.ОшибкаМодуля) as о:
                ошибки_генератора.append((текст, str(о)))
                continue
            р = расхождение(итоги)
            if р:
                расхождения.append((текст, р))
                if сохранять:
                    os.makedirs(НАХОДКИ, exist_ok=True)
                    with open(os.path.join(НАХОДКИ, f"зерно_{зерно}_{н}.dan"), "w", encoding="utf-8") as ф:
                        ф.write(текст)
    return число, ошибки_генератора, расхождения


