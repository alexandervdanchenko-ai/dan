"""Результат «Т!» без копии большого значения (компилятор на Дане, сам/порождение.dan).

Функция, которая сразу кладёт параметр в свою переменную («перем д = вход») и больше его не
читает, получает значение вызывающего без учёта второго места, если переменная вызывающего
сразу получает новое значение («д = шаг(д)»): тогда изменение «д.числа[0] = ...» внутри функции
не копирует массив. Прежде так передавалось значение только в простом вызове; вызов под «!»
(«д = шаг(д)!») копировал всё значение на каждом шаге. Ошибка «!» передаётся после вызова, когда
функция уже взяла значение и освободила его, поэтому выход по ошибке не освобождает его второй раз.
Смысл значений не меняется: исходное значение, которое читается дальше, остаётся прежним.
"""

import os
import subprocess
import sys
import tempfile
import unittest

import dan
import sam_kompilyator
from test_kodogen import КОМПИЛЯТОР_ЕСТЬ
from test_pamyat import КОМПИЛЯТОР, САНИТАЙЗЕР

ТИП = ("тип Данные {\n    числа: массив<дроб>\n    имя: стр\n}\n\n"
       "функ шаг(вход: Данные, к: цел) -> Данные! {\n    перем д = вход\n"
       "    если к == 7 { вернуть ошибка(\"сбой на шаге \" + стр(к)) }\n"
       "    д.числа[0] = д.числа[0] + дроб(к)\n    вернуть д\n}\n\n")

ПРОГРАММА = ТИП + """функ прогон(д0: Данные, до: цел) -> Данные! {
    перем д = д0
    для к в 1..до {
        д = шаг(д, к)!
    }
    вернуть д
}

функ последний(д0: Данные, к: цел) -> Данные! {
    перем д = д0
    вернуть шаг(д, к)!
}

пусть исходные = Данные(массив(дроб, 4, 1.0), "веса")
вывод(прогон(исходные, 5)!.числа[0])
если пусть р = прогон(исходные, 10) {
    вывод(р.числа[0])
} иначе ошибка о {
    вывод(о)
}
вывод(последний(исходные, 3)!.числа[0])
если ошибка о = последний(исходные, 7) {
    вывод(о)
}
вывод(исходные.числа[0])
перем д = исходные
для к в 1..3 {
    д = шаг(д, к)!
}
вывод(д.числа[0])
вывод(исходные.числа[0])
"""

ВЫВОД = ["16.0", "сбой на шаге 7", "4.0", "сбой на шаге 7", "1.0", "7.0", "1.0"]


def собрать_и_выполнить(код_c, флаги=()):
    with tempfile.TemporaryDirectory() as папка:
        с = os.path.join(папка, "программа.c")
        with open(с, "w", encoding="utf-8") as ф:
            ф.write(код_c)
        исп = os.path.join(папка, "программа")
        subprocess.run([КОМПИЛЯТОР, "-std=c11", "-fwrapv", "-ffp-contract=off", "-w", *флаги, с, "-o", исп, "-lm"],
                       check=True)
        окружение = dict(os.environ, ASAN_OPTIONS="detect_leaks=1")
        # пик памяти программы: её запускает отдельный процесс Python и читает свой RUSAGE_CHILDREN
        замер = ("import resource, subprocess, sys\nр = subprocess.run(sys.argv[1:], capture_output=True, text=True, "
                 "encoding='utf-8')\nsys.stdout.write(р.stdout)\nsys.stderr.write(р.stderr)\n"
                 "print(resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss, file=sys.stderr)\nsys.exit(р.returncode)\n")
        р = subprocess.run([sys.executable, "-c", замер, исп], capture_output=True, text=True, encoding="utf-8",
                           timeout=600, env=окружение, cwd=папка)
        строки = р.stderr.strip().split("\n")
        return р.returncode, р.stdout, "\n".join(строки[:-1]), int(строки[-1]) * 1024


class ТестыКодаПереноса(unittest.TestCase):

    def test_вызов_под_знаком_передаёт_значение(self):
        код = sam_kompilyator.перевести(ПРОГРАММА)
        # «д = шаг(д, к)!»: «д» отдаётся функции без учёта второго места (без _share)
        self.assertIn("d_shag(d_d, d_k)", код)
        self.assertNotIn("d_shag(dt_Dannye_share(d_d), d_k)", код)

    def test_ошибка_внутри_аргументов_не_переносит(self):
        # ошибка второго аргумента до вызова оставила бы отданное значение без хозяина: перенос не делается
        текст = ТИП + ("функ число(к: цел) -> цел! {\n    если к > 2 { вернуть ошибка(\"много\") }\n    вернуть к\n}\n"
                       "функ прогон(д0: Данные) -> Данные! {\n    перем д = д0\n    для к в 1..3 {\n"
                       "        д = шаг(д, число(к)!)!\n    }\n    вернуть д\n}\n"
                       "если ошибка о = прогон(Данные(массив(дроб, 2), \"а\")) { вывод(о) }\n")
        код = sam_kompilyator.перевести(текст)
        self.assertIn("d_shag(dt_Dannye_share(d_d)", код)


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ and КОМПИЛЯТОР and sys.platform == "linux", "нужен gcc или clang в Linux")
class ТестыВыполнения(unittest.TestCase):

    @unittest.skipUnless(САНИТАЙЗЕР, "нет AddressSanitizer")
    def test_без_ошибок_и_утечек_памяти(self):
        код = sam_kompilyator.перевести(ПРОГРАММА, строки_дан=True)
        код_завершения, вывод_, ошибки, _ = собрать_и_выполнить(
            код, ("-g", "-O1", "-fsanitize=address,undefined", "-fno-sanitize-recover=undefined"))
        self.assertEqual(код_завершения, 0, ошибки)
        self.assertEqual(вывод_.strip().split("\n"), ВЫВОД)

    def test_большое_значение_не_копируется(self):
        # массив 64 МБ, 50 шагов: с копией на каждом шаге пик памяти - две копии (больше 128 МБ)
        текст = ТИП + ("перем д = Данные(массив(дроб, 8_388_608, 1.0), \"веса\")\nдля к в 1..50 {\n"
                       "    если к != 7 { д = шаг(д, к)! }\n}\nвывод(д.числа[0])\n")
        код_завершения, вывод_, ошибки, пик = собрать_и_выполнить(sam_kompilyator.перевести(текст), ("-O2",))
        self.assertEqual(код_завершения, 0, ошибки)
        self.assertEqual(вывод_.strip(), str(1.0 + sum(к for к in range(1, 51) if к != 7)))
        self.assertLess(пик, 100 * 1024 * 1024, f"пик памяти {пик // (1024 * 1024)} МБ")


if __name__ == "__main__":
    unittest.main()
