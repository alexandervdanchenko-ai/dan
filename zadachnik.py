"""Задачник Дана: упражнения с автоматической проверкой.

    dan задачи          - скопировать задачи в папку «задачи» (если их там ещё нет)
                          и показать список;
    dan задача 3        - проверить решение задачи 3 из папки «задачи».

Задача - файл «NN_имя.dan» с условием в комментарии и заготовкой решения и
файл «NN_имя.проверки» с наборами входных данных и ожидаемого вывода:

    === ввод
    Анна
    === вывод
    Привет, Анна!

Решение собирается и запускается на каждом наборе; вывод сравнивается построчно
(пробелы в конце строк не учитываются).
"""

import glob
import os
import shutil
import subprocess
import sys

ПАПКА = os.path.join(os.path.dirname(os.path.abspath(__file__)), "учебник", "задачи")
РАБОЧАЯ = "задачи"


def задачи(папка=ПАПКА):
    """[(номер, имя файла без окончания)] по порядку."""
    итог = []
    for путь in sorted(glob.glob(os.path.join(папка, "*.dan"))):
        имя = os.path.basename(путь)[:-4]
        if имя[:2].isdigit():
            итог.append((int(имя[:2]), имя))
    return итог


def условие(путь):
    with open(путь, encoding="utf-8") as ф:
        первая = ф.readline().strip()
    return первая.lstrip("/ ").split(". ", 1)[-1]


def проверки(путь):
    """[(ввод, вывод)] из файла .проверки."""
    with open(путь, encoding="utf-8") as ф:
        текст = ф.read()
    итог = []
    for часть in текст.split("=== ввод\n")[1:]:
        ввод_, _, вывод_ = часть.partition("=== вывод\n")
        итог.append((ввод_, вывод_))
    return итог


def строки(текст):
    return [с.rstrip() for с in текст.replace("\r\n", "\n").rstrip("\n").split("\n")]


def проверить_решение(путь_решения, путь_проверок, собрать):
    """(пройдено, всего, описание первого расхождения или None).
    собрать(путь, текст) -> путь к исполняемому файлу (или исключение с сообщением)."""
    with open(путь_решения, encoding="utf-8") as ф:
        текст = ф.read()
    наборы = проверки(путь_проверок)
    исполняемый = os.path.abspath(собрать(путь_решения, текст))
    пройдено = 0
    первое = None
    for номер, (ввод_, ожидается) in enumerate(наборы, 1):
        try:
            р = subprocess.run([исполняемый], input=ввод_, capture_output=True, text=True, encoding="utf-8",
                               errors="replace", timeout=10, cwd=os.path.dirname(os.path.abspath(путь_решения)))
        except subprocess.TimeoutExpired:
            первое = первое or f"проверка {номер}: программа работала дольше 10 секунд (зациклилась?)"
            continue
        if р.returncode == 0 and строки(р.stdout) == строки(ожидается):
            пройдено += 1
            continue
        if первое is None:
            показ = ввод_.rstrip("\n").replace("\n", " | ") or "(без ввода)"
            if р.returncode != 0:
                первое = f"проверка {номер}, ввод: {показ}\n  программа остановилась с ошибкой:\n  {р.stderr.strip()}"
            else:
                первое = (f"проверка {номер}, ввод: {показ}\n  ожидалось:\n    " +
                          "\n    ".join(строки(ожидается)) + "\n  получено:\n    " + ("\n    ".join(строки(р.stdout)) if р.stdout.strip() else "(ничего не напечатано)"))
    return пройдено, len(наборы), первое


def команда_задачи():
    os.makedirs(РАБОЧАЯ, exist_ok=True)
    скопировано = 0
    for _, имя in задачи():
        for окончание in (".dan", ".проверки"):
            цель = os.path.join(РАБОЧАЯ, имя + окончание)
            if not os.path.exists(цель):
                shutil.copy(os.path.join(ПАПКА, имя + окончание), цель)
                скопировано += окончание == ".dan"
    if скопировано:
        print(f"Задачи скопированы в папку «{os.path.abspath(РАБОЧАЯ)}».")
    print("Задачи (откройте файл, допишите решение и проверьте командой «dan задача номер»):\n")
    for номер, имя in задачи(РАБОЧАЯ):
        print(f"{номер:3}. {условие(os.path.join(РАБОЧАЯ, имя + '.dan'))}")
    return 0


def команда_задача(номер_текст, собрать, ошибки_сборки):
    try:
        номер = int(номер_текст)
    except ValueError:
        print(f"Номер задачи - число, например: dan задача 3")
        return 2
    найдено = [имя for н, имя in задачи(РАБОЧАЯ) if н == номер]
    if not найдено:
        print(f"Задача {номер} не найдена в папке «{РАБОЧАЯ}». Сначала выполните: dan задачи")
        return 2
    имя = найдено[0]
    путь = os.path.join(РАБОЧАЯ, имя + ".dan")
    проверки_путь = os.path.join(РАБОЧАЯ, имя + ".проверки")
    if not os.path.exists(проверки_путь):
        проверки_путь = os.path.join(ПАПКА, имя + ".проверки")
    try:
        пройдено, всего, первое = проверить_решение(путь, проверки_путь, собрать)
    except ошибки_сборки as о:
        print(f"Задача {номер}: программа не собирается.\n{о}")
        return 1
    if пройдено == всего:
        print(f"Задача {номер} решена: пройдены все проверки ({всего}).")
        return 0
    print(f"Задача {номер}: пройдено проверок {пройдено} из {всего}.\n{первое}")
    return 1


if __name__ == "__main__":
    sys.exit(команда_задачи())
