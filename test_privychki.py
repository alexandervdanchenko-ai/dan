"""Подсказки о привычках других языков (privychki.py): язык не меняется, но сообщение
об ошибке говорит, что написать вместо слова или знака Python, JavaScript, Go."""

import unittest

import dan
import kody


class ТестыПривычек(unittest.TestCase):

    def замечание(self, текст):
        найдено = dan.замечания("п.dan", текст)
        self.assertTrue(найдено, "программа должна содержать ошибку")
        вид, _, строка, столбец, сообщение, фрагмент = найдено[0]
        позиция, длина = kody.место(фрагмент, столбец)
        return сообщение, (строка, позиция, длина), kody.исправление(сообщение) if длина else None

    def test_слова(self):
        for текст, начало, место, замена in [
            ("def f(x):\n    return x\n", "«def» - не слово Дана", (1, 1, 3), "функ"),
            ("функ ф(х: цел) -> цел {\n    return х\n}\n", "«return» - не слово Дана", (2, 5, 6), "вернуть"),
            ("если 1 > 0 and 2 > 1 {\n}\n", "«and» - не слово Дана", (1, 12, 3), "и"),
            ("функ ф() {\n    если not истина { }\n}\n", "«not» - не слово Дана", (2, 10, 3), "не"),
            ("for к in 0..3 {\n}\n", "«for» - не слово Дана", (1, 1, 3), "для"),
            ("для к in 0..3 {\n}\n", "«in» - не слово Дана", (1, 7, 2), "в"),
            ("если 1 > 0 {\n    вывод(1)\n} else {\n}\n", "«else» - не слово Дана", (3, 3, 4), "иначе"),
            ("try {\n}\n", "«try» - не слово Дана: в Дане нет исключений", (1, 1, 3), None),
        ]:
            with self.subTest(текст=текст):
                сообщение, м, и = self.замечание(текст)
                self.assertTrue(сообщение.startswith(начало), сообщение)
                self.assertEqual((м, и), (место, замена))

    def test_знаки(self):
        for текст, знак, место, замена in [
            ("перем х = 1\nх++\n", "++", (2, 2, 2), "+= 1"),
            ("перем х = 1\nх--\n", "--", (2, 2, 2), "-= 1"),
            ("вывод(2 ** 3)\n", "**", (1, 9, 2), "^"),
            ("если 1 > 0 && 2 > 1 {\n}\n", "&&", (1, 12, 2), "и"),
            ("если 1 > 0 || 2 > 1 {\n}\n", "||", (1, 12, 2), "или"),
            ("пусть г = истина\nесли !г {\n}\n", "!", (2, 6, 1), "не "),
        ]:
            with self.subTest(текст=текст):
                сообщение, м, и = self.замечание(текст)
                self.assertTrue(сообщение.startswith(f"«{знак}» - не знак Дана"), сообщение)
                self.assertEqual((м, и), (место, замена))

    def test_имена_и_методы(self):
        for текст, окончание, замена in [
            ("print(1)\n", "; в Дане: напишите «вывод»", "вывод"),
            ("пусть с = [1]\nвывод(len(с))\n", "; в Дане длина - свойство без скобок: с.длина", None),
            ("пусть х = None\n", "; в Дане: напишите «ничего»", "ничего"),
            ("перем с = [1]\nс.append(2)\n", "; в Дане: напишите «добавить»", "добавить"),
            ("пусть т = \"а\"\nвывод(т.length)\n", "; в Дане: напишите «длина»", "длина"),
            ("пусть т = \"а\"\nвывод(т.length())\n", "; в Дане длина - свойство без скобок: с.длина", None),
            ("вывод(max(1, 2))\n", "; в Дане: напишите «макс»", "макс"),
        ]:
            with self.subTest(текст=текст):
                сообщение, _, и = self.замечание(текст)
                self.assertTrue(сообщение.endswith(окончание), сообщение)
                self.assertEqual(и, замена)

    def test_верные_программы_не_меняются(self):
        # имена других языков, объявленные в программе, - обычные имена
        for текст in ("пусть for = 5\nвывод(for)\n", "функ print(х: цел) { вывод(х) }\nprint(1)\n",
                      "перем max = 1\nmax += 1\n"):
            with self.subTest(текст=текст):
                self.assertEqual(dan.замечания("п.dan", текст), [])

    def test_у_подсказок_есть_коды(self):
        for сообщение in ("«def» - не слово Дана: напишите «функ»", "«++» - не знак Дана: напишите «+= 1»"):
            self.assertNotEqual(kody.код(сообщение), "Д0000")


if __name__ == "__main__":
    unittest.main()
