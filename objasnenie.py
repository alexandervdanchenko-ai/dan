        место = f"Поле «{и.имя}» значения «{код(и.объект)}»"
        if и.оператор == "=":
            return f"{место} получает новое значение: {значение_словами(и.значение, функции)}."
        return f"{место} {ПРИСВАИВАНИЯ[и.оператор]} «{код(и.значение)}»."
