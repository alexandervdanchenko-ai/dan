def тип_словами(тип):
    """Тип по-русски: «цел» - «целое число», «[стр]» - «список строк (тип [стр])»."""
    if not тип:
        return ""
    if тип in СЛОВА_ТИПОВ:
        return f"{СЛОВА_ТИПОВ[тип]} (тип {тип})"
    if тип.endswith("?"):
        return f"необязательное значение: {тип_словами(тип[:-1])} или «ничего»"
    if тип.endswith("!"):
        return f"результат, который может оказаться ошибкой (тип {тип})"
    if тип.startswith("[") and тип.endswith("]"):
        return f"список (тип {тип})"
    if тип.startswith("{") and тип.endswith("}"):
        return f"словарь (тип {тип})"
    if тип.startswith("функ"):
        return f"функция (тип {тип})"
    return f"значение типа {тип}"


def _аргументы(узел):
    """«с аргументом «х»» или «с аргументами «х», «у»» или «без аргументов»."""
    if not узел.аргументы:
        return " без аргументов"
    список = ", ".join("«" + код(а) + "»" for а in узел.аргументы)
    return (" с аргументом " if len(узел.аргументы) == 1 else " с аргументами ") + список


def код(узел):
    """Запись выражения, восстановленная по дереву (для показа частей выражения)."""
    if isinstance(узел, у.ЦелоеЧисло):
        return str(узел.значение)
    if isinstance(узел, у.ДробноеЧисло):
        return repr(узел.значение)
    if isinstance(узел, у.Строка):
        return '"' + узел.значение.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    if isinstance(узел, у.Логическое):
        return "истина" if узел.значение else "ложь"
    if isinstance(узел, у.Ничего):
        return "ничего"
    if isinstance(узел, у.Имя):
        return узел.написание or узел.имя
    if isinstance(узел, у.Унарная):
        return ("не " if узел.оператор == "не" else узел.оператор) + _в_скобках(узел.операнд, _старшинство(узел))
    if isinstance(узел, у.Бинарная):
        с = _старшинство(узел)
        правая = узел.оператор == "^"           # степень вычисляется справа налево
        л = _в_скобках(узел.левый, с + 1 if правая else с)
        п = _в_скобках(узел.правый, с if правая else с + 1)
        return f"{л} {узел.оператор} {п}"
    if isinstance(узел, у.Диапазон):
        return f"{код(узел.начало)}..{код(узел.конец)}"
    if isinstance(узел, у.Вызов):
        аргументы = []
        for н, а in enumerate(узел.аргументы):
            имя = узел.имена[н] if узел.имена and н < len(узел.имена) else None
            аргументы.append(f"{имя} = {код(а)}" if имя else код(а))
        return f"{код(узел.функция)}({', '.join(аргументы)})"
    if isinstance(узел, у.Запуск):
        return "запустить " + код(узел.вызов)
    if isinstance(узел, у.Иначе):
        return f"{код(узел.значение)} иначе {код(узел.запасное)}"
    if isinstance(узел, у.Поле):
        return f"{код(узел.объект)}.{узел.имя}"
    if isinstance(узел, у.Список):
        return "[" + ", ".join(код(э) for э in узел.элементы) + "]"
    if isinstance(узел, у.Словарь):
        return "{" + ", ".join(f"{код(к)}: {код(з)}" for к, з in zip(узел.ключи, узел.значения)) + "}"
    if isinstance(узел, у.Индекс):
        return f"{код(узел.объект)}[{код(узел.индекс)}]"
    if isinstance(узел, у.Передать):
        return код(узел.значение) + "!"
    if isinstance(узел, у.Лямбда):
        параметры = ", ".join(п.имя for п in узел.параметры)
        return f"функ({параметры}) " + (f"= {код(узел.выражение)}" if узел.выражение is not None else "{ ... }")
    return "..."


СТАРШИНСТВО = {"или": 1, "и": 2, "==": 4, "!=": 4, "<": 4, "<=": 4, ">": 4, ">=": 4,
               "+": 5, "-": 5, "*": 6, "/": 6, "%": 6, "^": 8}


def _старшинство(узел):
    """Чем больше число, тем раньше выполняется действие («иначе» - позже всех)."""
    if isinstance(узел, у.Иначе):
        return 0
    if isinstance(узел, у.Бинарная):
        return СТАРШИНСТВО.get(узел.оператор, 5)
    if isinstance(узел, у.Унарная):
        return 3 if узел.оператор == "не" else 7
    return 9


def _в_скобках(узел, нужно):
    """Запись части выражения; в скобках, если её действие выполняется позже, чем нужно."""
    текст = код(узел)
    return f"({текст})" if _старшинство(узел) < нужно else текст


def _тип(узел):
    return getattr(узел, "тип_выр", None)


def _описание_функции(имя, функции):
    """Что делает функция: встроенная, библиотечная или функция программы (её описание ///)."""
    if имя in ВСТРОЕННЫЕ:
        return ВСТРОЕННЫЕ[имя]
    каноническое, описание = найти_в_библиотеке(имя)
    if описание is not None and описание.get("описание"):
        текст = описание["описание"].strip().rstrip(".")
        return текст[0].lower() + текст[1:] if текст else ""
    return функции.get(имя, "")


def значение_словами(узел, функции):
    """Что вычисляет выражение: одна фраза, части выражения показаны записью «...»."""
    тип = _тип(узел)
    if isinstance(узел, (у.ЦелоеЧисло, у.ДробноеЧисло)):
        return f"число {код(узел)}".replace(".", ",")
    if isinstance(узел, у.Строка):
        return f"строка {код(узел)}"
    if isinstance(узел, у.Логическое):
        return f"логическое значение «{код(узел)}»"
    if isinstance(узел, у.Ничего):
        return "«ничего» (значения нет)"
    if isinstance(узел, у.Имя):
        return f"значение «{код(узел)}»"
    if isinstance(узел, у.Унарная):
        if узел.оператор == "не":
            return f"отрицание условия «{код(узел.операнд)}» (истина, если оно ложно)"
        return f"число «{код(узел.операнд)}» с обратным знаком"
    if isinstance(узел, у.Бинарная):
        л, п, о = код(узел.левый), код(узел.правый), узел.оператор
        if о in СРАВНЕНИЯ:
            return f"условие: «{л}» {СРАВНЕНИЯ[о]} «{п}»"
        if о == "и":
            return f"условие: выполнено и «{л}», и «{п}»"
        if о == "или":
            return f"условие: выполнено «{л}» или «{п}» (хотя бы одно)"
        if о == "+" and тип == "стр":
            return f"строка «{л}», к которой приписана строка «{п}»"
        if о == "/" and getattr(узел, "деление_целых", False) or (о == "/" and тип == "рац"):
            return (f"частное «{л}» и «{п}»; деление целых чисел «/» точное и даёт обыкновенную дробь "
                    f"(частное без остатка - функция частное(а, б))")
        if о == "^":
            return f"«{л}» в степени «{п}»"
        if о == "%":
            return f"остаток от деления «{л}» на «{п}»"
        if о in ДЕЙСТВИЯ:
            return f"{ДЕЙСТВИЯ[о]} «{л}» и «{п}»"
    if isinstance(узел, у.Диапазон):
        return f"числа от «{код(узел.начало)}» до «{код(узел.конец)}» включительно"
    if isinstance(узел, у.Вызов):
        if isinstance(узел.функция, у.Поле):
            метод = узел.функция.имя
            return (f"результат метода «{метод}» значения «{код(узел.функция.объект)}»"
                    + (_аргументы(узел) if узел.аргументы else "")
                    + (f" (метод {МЕТОДЫ[метод]})" if метод in МЕТОДЫ else ""))
        имя = код(узел.функция)
        if имя in функции.get("", {}):
            return f"новое значение типа «{имя}»" + (", поля: " + ", ".join("«" + код(а) + "»" for а in узел.аргументы)
                                                      if узел.аргументы else "")
        что = _описание_функции(getattr(узел.функция, "имя", имя), функции)
        return f"результат вызова функции «{имя}»" + _аргументы(узел) + (f" (функция {что})" if что else "")
    if isinstance(узел, у.Запуск):
        return f"задача, в которой параллельно выполняется «{код(узел.вызов)}»"
    if isinstance(узел, у.Иначе):
        return f"значение «{код(узел.значение)}», а если его нет (или вместо него ошибка) - «{код(узел.запасное)}»"
    if isinstance(узел, у.Поле):
        if узел.имя == "длина":
            return f"длина «{код(узел.объект)}»"
        return f"поле «{узел.имя}» значения «{код(узел.объект)}»"
    if isinstance(узел, у.Список):
        return f"список из {len(узел.элементы)} элементов" if узел.элементы else "пустой список"
    if isinstance(узел, у.Словарь):
        return f"словарь из {len(узел.ключи)} пар «ключ: значение»" if узел.ключи else "пустой словарь"
    if isinstance(узел, у.Индекс):
        if тип and (_тип(узел.объект) or "").startswith("{"):
            return f"значение словаря «{код(узел.объект)}» по ключу «{код(узел.индекс)}»"
        return f"элемент «{код(узел.объект)}» с номером «{код(узел.индекс)}» (номера начинаются с 0)"
    if isinstance(узел, у.Передать):
        return (f"значение «{код(узел.значение)}»; если вместо него ошибка, функция сразу завершается "
                f"и передаёт ошибку тому, кто её вызвал")
    if isinstance(узел, у.Лямбда):
        return "безымянная функция"
    return f"значение «{код(узел)}»"


def _с_типом(узел, функции):
    тип = _тип(узел)
    текст = значение_словами(узел, функции)
    return текст + (f"; это {тип_словами(тип)}" if тип and not isinstance(узел, (у.Строка, у.Логическое)) else "")


def _ветви(узел):
    return " Иначе выполняется ветвь после «иначе»." if getattr(узел, "иначе", None) is not None else ""


def инструкция_словами(и, функции):
    """Объяснение одной инструкции (или объявления)."""
    if isinstance(и, у.ОбъявлениеПеременной):
        вид = ("Объявляется переменная" if и.изменяемая else "Объявляется постоянная")
        пояснение = (" (её значение можно менять)" if и.изменяемая
                     else " (её значение нельзя изменить; для изменяемой пишут «перем»)")
        тип = и.тип or getattr(и, "тип_итог", None) or _тип(и.значение)
        текст = f"{вид} «{и.имя}»{пояснение}"
