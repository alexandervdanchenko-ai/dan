"""Заморозка компилятора на Python.

С этапа 17а язык развивается только в компиляторе на Дане (папка «сам»). Компилятор на Python
остаётся эталоном прежнего поведения: с ним сверяется результат программ (test_sam.py), но новые
возможности в него не добавляются. Чтобы изменение языка не было сделано по привычке в Python,
отпечатки его файлов записаны в zamorozka.json, а тест test_zamorozka.py сверяет их с файлами.

    python zamorozka.py                          проверить: какие замороженные файлы изменены
    python zamorozka.py --принять "причина"      записать новые отпечатки с причиной (исключение)

Исключение допустимо, когда правка в Python нужна не языку: исправление ошибки в эталоне,
поддержка проверок (dan.py вызывает компилятор на Дане при DAN_KOMPILYATOR=сам), сборка.
Причина попадает в список «исключения» файла zamorozka.json и видна при проверке изменений.

Не заморожены данные, из которых создаются файлы компилятора на Дане: таблицы встроенных функций
(matematika.py, vysshaya.py, dannye.py, sistema.py -> сам/встроенные.dan), коды сообщений (kody.py ->
сам/коды.dan), привычки других языков (privychki.py -> сам/привычки.dan), версия и редакции
(versiya.py), код среды выполнения (sreda/*.c -> сам/среда.dan). Это общий источник обоих
компиляторов, а не код компилятора на Python: новая встроенная функция по-прежнему описывается в
таблице и в sreda/*.c, и сценарии создать_*.py переносят её в папку «сам». Перенос таблиц в файлы,
которые читает сам компилятор на Дане, отложен: он не даёт выигрыша, пока сценарии работают.
"""

import datetime
import hashlib
import json
import os
import sys

ПАПКА = os.path.dirname(os.path.abspath(__file__))
ЗАПИСЬ = os.path.join(ПАПКА, "zamorozka.json")

# Код компилятора на Python и его команд (у каждого есть двойник в папке «сам»).
ЗАМОРОЖЕННЫЕ = [
    "lexer.py", "parser.py", "uzly.py", "moduli.py", "proverka.py", "obobshchenie.py", "kodogen.py", "dan.py",
    "formatirovanie.py", "objasnenie.py", "dokumentaciya.py", "zadachnik.py", "paketi.py", "gotovaya_sreda.py",
]


def отпечаток(путь):
    # переводы строк приводятся к «\n»: в Windows git может выдать файлы с «\r\n»
    with open(путь, "rb") as ф:
        return hashlib.sha256(ф.read().replace(b"\r\n", b"\n")).hexdigest()


def прочитать_запись():
    with open(ЗАПИСЬ, encoding="utf-8") as ф:
        return json.load(ф)


def изменённые():
    запись = прочитать_запись()
    итог = []
    for имя in ЗАМОРОЖЕННЫЕ:
        путь = os.path.join(ПАПКА, имя)
        if not os.path.isfile(путь):
            итог.append(имя + " (удалён)")
        elif запись["отпечатки"].get(имя) != отпечаток(путь):
            итог.append(имя)
    return итог


def принять(причина):
    """Записывает отпечатки; первая запись - начало заморозки, следующие - исключения с причиной."""
    сегодня = datetime.date.today().isoformat()
    if os.path.isfile(ЗАПИСЬ):
        запись = прочитать_запись()
        было = изменённые()
        if было:
            запись["исключения"].append({"дата": сегодня, "файлы": было, "причина": причина})
    else:
        запись = {"начало": {"дата": сегодня, "причина": причина}, "исключения": []}
        было = []
    запись["отпечатки"] = {имя: отпечаток(os.path.join(ПАПКА, имя)) for имя in ЗАМОРОЖЕННЫЕ}
    with open(ЗАПИСЬ, "w", encoding="utf-8", newline="\n") as ф:
        json.dump(запись, ф, ensure_ascii=False, indent=2)
        ф.write("\n")
    return было


def main(аргументы):
    if len(аргументы) == 2 and аргументы[0] == "--принять" and аргументы[1].strip():
        было = принять(аргументы[1].strip())
        print("записаны отпечатки; изменены: " + (", ".join(было) if было else "ничего"))
        return 0
    if аргументы:
        print(__doc__)
        return 2
    изменено = изменённые()
    if изменено:
        print("изменены замороженные файлы компилятора на Python: " + ", ".join(изменено))
        return 1
    print("компилятор на Python не изменён")
    return 0


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main(sys.argv[1:]))
