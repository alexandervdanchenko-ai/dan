def путь_из_uri(uri):
    разбор = urllib.parse.urlparse(uri)
    путь = urllib.parse.unquote(разбор.path)
    if os.name == "nt" and re.match(r"^/[A-Za-z]:", путь):
        путь = путь[1:]
    return os.path.normpath(путь)


def uri_из_пути(путь):
    путь = os.path.abspath(путь).replace("\\", "/")
    if not путь.startswith("/"):
        путь = "/" + путь
    return "file://" + urllib.parse.quote(путь)


def диапазон(текст, строка, столбец):
    """Диапазон LSP для места ошибки (строка и столбец Дана с 1): до конца слова."""
    строки = текст.split("\n")
    н = max(0, строка - 1)
    с = max(0, столбец - 1)
    if н >= len(строки):
        н, с = max(0, len(строки) - 1), 0
    линия = строки[н] if строки else ""
    конец = с
    совпадение = ИМЯ.match(линия, с) or re.compile(r"\S+").match(линия, с)
    if совпадение:
        конец = совпадение.end()
    if конец == с:
        конец = min(len(линия), с + 1)
    # позиции в LSP считаются в единицах UTF-16
    def в_utf16(i):
        return len(линия[:i].encode("utf-16-le")) // 2
    return {"start": {"line": н, "character": в_utf16(с)}, "end": {"line": н, "character": в_utf16(конец)}}


def найти_ошибки(текст, путь):
    """Список ошибок файла: (строка, столбец, текст)."""
    try:
        программа = загрузить(текст, путь)
        проверить(программа)
    except (ОшибкаЛексера, ОшибкаРазбора) as о:
        сообщение = str(о).split(": ", 1)[1] if ": " in str(о) else str(о)
        return [(о.строка, о.столбец, сообщение)]
    except ОшибкаМодуля as о:
        текст_о = str(о)
        место = re.search(r"Строка (\d+), позиция (\d+): (.*)", текст_о, re.S)
        if место and текст_о.startswith(у.ФАЙЛЫ[0] + ":"):
            return [(int(место.group(1)), int(место.group(2)), место.group(3))]
        # ошибка в подключённом файле: показывается у строки подключения
        for н, линия in enumerate(текст.split("\n"), 1):
            if линия.strip().startswith("подключить"):
                return [(н, 1, текст_о)]
        return [(1, 1, текст_о)]
    except ОшибкаПроверки as о:
        итог = []
        for с in о.ошибки:
            if с.строка >= у.ШАГ_ФАЙЛА:
                файл, строка = у.место_в_файле(с.строка)
                итог.append((1, 1, f"в подключённом файле {файл}, строка {строка}: {с.текст}"))
            else:
                итог.append((с.строка, с.столбец, с.текст))
        return итог
    except RecursionError:
        return [(1, 1, "программа слишком глубоко вложена для проверки")]
    return []


def объявления(текст):
    """Функции, типы и переменные верхнего уровня файла: имя -> (вид, строка, столбец, описание)."""
    итог = {}
    try:
        программа = дерево(текст)
    except (ОшибкаЛексера, ОшибкаРазбора):
        return итог
    for и in программа.инструкции:
        if isinstance(и, у.Функция):
            параметры = ", ".join(f"{п.имя}: {п.тип}" for п in и.параметры)
            результат = f" -> {и.тип_результата}" if и.тип_результата else ""
            имя = f"{и.метод_типа}.{и.имя}" if и.метод_типа else и.имя
            итог[имя] = ("функция", и.строка, и.столбец, f"функ {имя}({параметры}){результат}",
                         getattr(и, "общий", False))
        elif isinstance(и, (у.ОбъявлениеТипа, у.ОбъявлениеВариантов, у.ОбъявлениеИнтерфейса)):
            вид = "интерфейс" if isinstance(и, у.ОбъявлениеИнтерфейса) else "тип"
            итог[и.имя] = (вид, и.строка, и.столбец, f"{вид} {и.написание or и.имя}", getattr(и, "общий", False))
            if isinstance(и, у.ОбъявлениеВариантов):
                for в in и.варианты:
                    поля = ", ".join(f"{п.имя}: {п.тип}" for п in в.поля) if в.поля else ""
                    итог[в.имя] = ("вариант", в.строка, в.столбец,
                                   f"{в.написание or в.имя}({поля}) - вариант типа {и.имя}" if поля
                                   else f"{в.написание or в.имя} - вариант типа {и.имя}",
                                   getattr(и, "общий", False))
        elif isinstance(и, у.ОбъявлениеПеременной):
            итог[и.имя] = ("переменная", и.строка, и.столбец, f"{'перем' if и.изменяемая else 'пусть'} {и.имя}", False)
    return итог


def подключения(текст, путь):
    """Подключённые модули файла: псевдоним -> путь к файлу."""
    итог = {}
    папка = os.path.dirname(os.path.abspath(путь))
    for совпадение in re.finditer(r'^\s*подключить\s+"([^"]+)"(?:\s+как\s+([^\W\d]\w*))?', текст, re.M):
        файл, псевдоним = совпадение.group(1), совпадение.group(2)
        кандидаты = [os.path.join(папка, файл), os.path.join(папка, файл + ".dan"),
                     os.path.join(БИБЛИОТЕКА, файл), os.path.join(БИБЛИОТЕКА, файл + ".dan")]
        найден = next((к for к in кандидаты if os.path.isfile(к)), None)
        if найден:
            имя = без_ё(псевдоним or os.path.splitext(os.path.basename(найден))[0])
            итог[имя] = найден
    return итог


def описание_библиотечной(имя):
    каноническое, описание = найти_в_библиотеке(имя)
    if описание is None:
        return None
    варианты = [f"{каноническое}({', '.join(п)}) -> {р}" for п, р in описание["варианты"]]
    return "\n".join(варианты) + "\n\n" + описание.get("описание", "")


def слово_в_позиции(линия, символ):
    """Слово (и, если есть, «модуль.» перед ним) под позицией символа."""
    for совпадение in re.finditer(r"(?:([^\W\d]\w*)\.)?([^\W\d]\w*)", линия):
        if совпадение.start() <= символ <= совпадение.end():
            return совпадение.group(1), совпадение.group(2)
    return None, None


def из_utf16(линия, символ):
    """Позиция LSP (единицы UTF-16) -> номер символа строки Python."""
    единиц = 0
    for н, с in enumerate(линия):
        if единиц >= символ:
            return н
        единиц += 2 if ord(с) > 0xFFFF else 1
    return len(линия)


class Сервер:
    def __init__(self, вход, выход):
        self.вход = вход
        self.выход = выход
        self.документы = {}
        self.работает = True

    # ---------- обмен сообщениями ----------

    def прочитать(self):
        заголовки = {}
        while True:
            линия = self.вход.readline()
            if not линия:
                return None
            линия = линия.decode("ascii", "replace").strip()
            if not линия:
                break
            имя, _, значение = линия.partition(":")
            заголовки[имя.strip().lower()] = значение.strip()
        длина = int(заголовки.get("content-length", 0))
        тело = self.вход.read(длина)
        return json.loads(тело.decode("utf-8"))

    def отправить(self, сообщение):
        данные = json.dumps(сообщение, ensure_ascii=False).encode("utf-8")
        self.выход.write(f"Content-Length: {len(данные)}\r\n\r\n".encode("ascii") + данные)
        self.выход.flush()

    def ответить(self, номер, результат):
        self.отправить({"jsonrpc": "2.0", "id": номер, "result": результат})

    def уведомить(self, метод, параметры):
        self.отправить({"jsonrpc": "2.0", "method": метод, "params": параметры})

    def работать(self):
        while self.работает:
            сообщение = self.прочитать()
            if сообщение is None:
                break
            метод = сообщение.get("method")
            номер = сообщение.get("id")
            try:
                обработчик = getattr(self, "м_" + (метод or "").replace("/", "_").replace("$", "_"), None)
                if обработчик is None:
                    if номер is not None and метод is not None:
                        self.отправить({"jsonrpc": "2.0", "id": номер,
                                        "error": {"code": -32601, "message": f"метод {метод} не поддерживается"}})
                    continue
                результат = обработчик(сообщение.get("params") or {})
                if номер is not None:
                    self.ответить(номер, результат)
            except Exception as о:       # сервер не должен падать из-за ошибки в одном запросе
                if номер is not None:
                    self.отправить({"jsonrpc": "2.0", "id": номер,
                                    "error": {"code": -32603, "message": f"{о}\n{traceback.format_exc()}"}})

    # ---------- жизненный цикл ----------

    def м_initialize(self, п):
        return {
            "capabilities": {
                "textDocumentSync": {"openClose": True, "change": 1, "save": {"includeText": False}},
                "completionProvider": {"triggerCharacters": ["."]},
                "hoverProvider": True,
                "definitionProvider": True,
                "documentSymbolProvider": True,
                "documentFormattingProvider": True,
            },
            "serverInfo": {"name": "Дан", "version": versiya.ВЕРСИЯ},
        }

    def м_initialized(self, п):
        return None

    def м_shutdown(self, п):
        return None

    def м_exit(self, п):
        self.работает = False

    # ---------- документы ----------

    def м_textDocument_didOpen(self, п):
        документ = п["textDocument"]
        self.документы[документ["uri"]] = документ["text"]
        self.проверить_документ(документ["uri"])

    def м_textDocument_didChange(self, п):
        uri = п["textDocument"]["uri"]
        for изменение in п["contentChanges"]:
            self.документы[uri] = изменение["text"]
        self.проверить_документ(uri)

    def м_textDocument_didSave(self, п):
        self.проверить_документ(п["textDocument"]["uri"])

    def м_textDocument_didClose(self, п):
        uri = п["textDocument"]["uri"]
        self.документы.pop(uri, None)
        self.уведомить("textDocument/publishDiagnostics", {"uri": uri, "diagnostics": []})

    def проверить_документ(self, uri):
        текст = self.документы.get(uri, "")
        ошибки = найти_ошибки(текст, путь_из_uri(uri))
        диагностика = [{"range": диапазон(текст, с, ст), "severity": 1, "source": "Дан", "message": т}
                       for с, ст, т in ошибки]
        self.уведомить("textDocument/publishDiagnostics", {"uri": uri, "diagnostics": диагностика})

    # ---------- подсказки ----------

    def м_textDocument_completion(self, п):
        uri = п["textDocument"]["uri"]
        текст = self.документы.get(uri, "")
        строки = текст.split("\n")
        н = п["position"]["line"]
        линия = строки[н] if н < len(строки) else ""
        до = линия[:из_utf16(линия, п["position"]["character"])]
        совпадение = re.search(r"([^\W\d]\w*)\.(\w*)$", до)
        варианты = []
        if совпадение:
            модули = подключения(текст, путь_из_uri(uri))
            псевдоним = без_ё(совпадение.group(1))
            if псевдоним in модули:
                with open(модули[псевдоним], encoding="utf-8") as ф:
                    for имя, (вид, _, _, описание, общий) in объявления(ф.read()).items():
                        if общий and "." not in имя:
                            варианты.append(self.вариант(имя, вид, описание))
                return {"isIncomplete": False, "items": варианты}
            # методы и свойства значений: тип здесь неизвестен, поэтому предлагаются все
            for имя in list(МЕТОДЫ_СТР) + list(МЕТОДЫ_СПИСКА) + list(ФУНКЦИОНАЛЬНЫЕ_МЕТОДЫ) + \
                    ["длина", "найти", "получить", "содержит", "удалить", "ключи", "значения", "копия",
                     "отправить", "получить", "закрыть", "дождаться", "готова"]:
                варианты.append(self.вариант(имя, "метод", ФУНКЦИОНАЛЬНЫЕ_МЕТОДЫ.get(имя, "")))
            for тип, свойства in СВОЙСТВА.items():
                for имя, т in свойства.items():
                    варианты.append(self.вариант(имя, "свойство", f"{тип}.{имя}: {т}"))
            for имя, (вид, _, _, описание, _) in объявления(текст).items():
                if "." in имя:
                    варианты.append(self.вариант(имя.split(".", 1)[1], "метод", описание))
            return {"isIncomplete": False, "items": self.без_повторов(варианты)}
        for слово in sorted(КЛЮЧЕВЫЕ_СЛОВА):
            варианты.append(self.вариант(слово, "ключевое", ОПИСАНИЯ_КЛЮЧЕВЫХ.get(слово, "ключевое слово")))
        for имя in sorted(ВСТРОЕННЫЕ):
            варианты.append(self.вариант(имя, "функция", ОПИСАНИЯ_ВСТРОЕННЫХ.get(имя, "")))
        for таблица in (matematika.ФУНКЦИИ, dannye.ФУНКЦИИ, sistema.ФУНКЦИИ):
            for имя, описание in таблица.items():
                варианты.append(self.вариант(имя, "функция", описание_библиотечной(имя) or ""))
        for имя, (вид, _, _, описание, _) in объявления(текст).items():
            if "." not in имя:
                варианты.append(self.вариант(имя, вид, описание))
        for псевдоним in подключения(текст, путь_из_uri(uri)):
            варианты.append(self.вариант(псевдоним, "модуль", f"подключённый модуль {псевдоним}"))
        # имена, уже встречавшиеся в тексте (переменные функций, параметры)
        известные = {в["label"] for в in варианты}
        for имя in set(re.findall(r"[^\W\d]\w*", текст)):
            if имя not in известные and len(имя) > 1:
                варианты.append(self.вариант(имя, "имя", ""))
        return {"isIncomplete": False, "items": варианты}

    @staticmethod
    def без_повторов(варианты):
        итог, были = [], set()
        for в in варианты:
            if в["label"] not in были:
                были.add(в["label"])
                итог.append(в)
        return итог

    @staticmethod
    def вариант(имя, вид, описание):
        виды = {"функция": 3, "метод": 2, "свойство": 10, "переменная": 6, "тип": 7, "интерфейс": 8,
                "вариант": 20, "ключевое": 14, "модуль": 9, "имя": 1}
        вариант = {"label": имя, "kind": виды.get(вид, 1)}
        if описание:
            вариант["detail"] = описание.split("\n")[0]
            вариант["documentation"] = описание
        return вариант

    def м_textDocument_hover(self, п):
        uri = п["textDocument"]["uri"]
        текст = self.документы.get(uri, "")
        строки = текст.split("\n")
        н = п["position"]["line"]
        линия = строки[н] if н < len(строки) else ""
        модуль, слово = слово_в_позиции(линия, из_utf16(линия, п["position"]["character"]))
        if not слово:
            return None
        описание = None
        if модуль:
            модули = подключения(текст, путь_из_uri(uri))
            if без_ё(модуль) in модули:
                with open(модули[без_ё(модуль)], encoding="utf-8") as ф:
                    найдено = объявления(ф.read()).get(без_ё(слово))
                if найдено:
                    описание = найдено[3]
        if описание is None:
            найдено = объявления(текст).get(без_ё(слово))
            if найдено:
                описание = найдено[3]
        if описание is None:
            описание = описание_библиотечной(без_ё(слово)) or ОПИСАНИЯ_ВСТРОЕННЫХ.get(без_ё(слово)) \
                or ОПИСАНИЯ_КЛЮЧЕВЫХ.get(без_ё(слово))
        if not описание:
            return None
        return {"contents": {"kind": "markdown", "value": "```dan\n" + описание + "\n```"}}

    def м_textDocument_definition(self, п):
        uri = п["textDocument"]["uri"]
        текст = self.документы.get(uri, "")
        строки = текст.split("\n")
        н = п["position"]["line"]
        линия = строки[н] if н < len(строки) else ""
        модуль, слово = слово_в_позиции(линия, из_utf16(линия, п["position"]["character"]))
        if not слово:
            return None
        if модуль:
            модули = подключения(текст, путь_из_uri(uri))
            if без_ё(модуль) in модули:
                путь = модули[без_ё(модуль)]
                with open(путь, encoding="utf-8") as ф:
                    чужой = ф.read()
                найдено = объявления(чужой).get(без_ё(слово))
                if найдено:
                    return {"uri": uri_из_пути(путь), "range": диапазон(чужой, найдено[1], найдено[2])}
        найдено = объявления(текст).get(без_ё(слово))
        if найдено:
            return {"uri": uri, "range": диапазон(текст, найдено[1], найдено[2])}
        return None

    def м_textDocument_documentSymbol(self, п):
        uri = п["textDocument"]["uri"]
        текст = self.документы.get(uri, "")
        итог = []
        виды = {"функция": 12, "тип": 5, "интерфейс": 11, "вариант": 22, "переменная": 13}
        for имя, (вид, строка, столбец, описание, _) in объявления(текст).items():
            д = диапазон(текст, строка, столбец)
            итог.append({"name": имя, "kind": виды.get(вид, 13), "detail": описание, "range": д, "selectionRange": д})
        return итог

    def м_textDocument_formatting(self, п):
        uri = п["textDocument"]["uri"]
        текст = self.документы.get(uri, "")
        try:
            новый = отформатировать(текст)
        except ОшибкаФорматирования:
            return []
        if новый == текст:
            return []
        строк = текст.count("\n") + 1
        return [{"range": {"start": {"line": 0, "character": 0}, "end": {"line": строк, "character": 0}},
                 "newText": новый}]


