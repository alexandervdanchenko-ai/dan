"""Создаёт сам/страницы.dan - тексты страниц и справок команд «собрать --веб», «песочница» и «обновить».

Тексты берутся из модулей на Python (veb.py, pesochnica.py, obnovlenie.py), чтобы компилятор на
Дане показывал ту же страницу программы для браузера, ту же песочницу и те же справки. Запуск:
python сам/создать_страницы.py или python пересоздать.py.
"""

import importlib.util
import os
import sys

ПАПКА = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ПАПКА)
ФАЙЛ = os.path.join(ПАПКА, "страницы.dan")


def _модуль(имя):
    # модули загружаются по пути: так сценарий не зависит от sys.path вызывающего
    описание = importlib.util.spec_from_file_location("страницы_" + имя, os.path.join(КОРЕНЬ, имя + ".py"))
    модуль = importlib.util.module_from_spec(описание)
    if КОРЕНЬ not in sys.path:
        sys.path.insert(0, КОРЕНЬ)
    описание.loader.exec_module(модуль)
    return модуль


def строка(с):
    return '"' + с.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") \
        .replace("\r", "\\r") + '"'


def длинная_строка(текст, отступ="    "):
    """Запись длинного текста: по строке Дана на строку текста."""
    части = текст.splitlines(keepends=True) or [""]
    if len(части) == 1:
        return строка(части[0])
    return "(" + ("\n" + отступ + "+ ").join(строка(ч) for ч in части) + ")"


def текст():
    veb = _модуль("veb")
    pesochnica = _модуль("pesochnica")
    obnovlenie = _модуль("obnovlenie")
    тексты = [
        ("веб_страница", "Страница программы для браузера: на место @@ЗАГОЛОВОК@@, @@WASM@@ и @@СЦЕНАРИЙ@@ "
                         "вставляются заголовок, модуль WebAssembly (base64) и сценарий",
         veb.СТРАНИЦА.format(заголовок="@@ЗАГОЛОВОК@@", wasm="@@WASM@@", сценарий="@@СЦЕНАРИЙ@@")),
        ("веб_сценарий", "Сценарий страницы программы для браузера: функции WASI на JavaScript", veb.СЦЕНАРИЙ),
        ("песочница_страница", "Страница песочницы: на место __КЛЮЧ__ вставляется ключ, на место __НАЧАЛО__ - "
                               "начальная программа (строка JSON)", pesochnica.СТРАНИЦА),
        ("песочница_начало", "Начальная программа песочницы", pesochnica.НАЧАЛО),
        ("песочница_справка", "Справка команды «песочница»", pesochnica.__doc__.strip()),
        ("обновление_справка", "Справка команды «обновить»", obnovlenie.__doc__.strip()),
    ]
    строки = [
        "/// Тексты страниц и справок команд «собрать --веб», «песочница» и «обновить».",
        "///",
        "/// Файл создан сценарием сам/создать_страницы.py из veb.py, pesochnica.py и obnovlenie.py;",
        "/// изменять его вручную не нужно.",
        "",
    ]
    for имя, описание, значение in тексты:
        строки += [f"/// {описание}.", f"общий функ {имя}() -> стр {{", "    вернуть " + длинная_строка(значение),
                   "}", ""]
    return "\n".join(строки)


if __name__ == "__main__":
    with open(ФАЙЛ, "w", encoding="utf-8", newline="\n") as ф:
        ф.write(текст())
    print("Создан", ФАЙЛ)
