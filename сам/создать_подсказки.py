"""Создаёт сам/подсказки.dan - таблицы подсказок сервера языка для редакторов (команда «дан сервер»).

Ключевые слова, встроенные функции, функции библиотеки с описаниями, методы и свойства значений
берутся из сервера языка на Python (server.py) и таблиц компилятора, чтобы сервер на Дане
подсказывал то же самое. Запуск: python сам/создать_подсказки.py или python пересоздать.py.
"""

import os
import sys

ПАПКА = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(ПАПКА)
ФАЙЛ = os.path.join(ПАПКА, "подсказки.dan")


def строка(с):
    return '"' + с.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") \
        .replace("\r", "\\r") + '"'


def словарь(имя, описание, пары):
    строки = [f"/// {описание}.", f"общий функ {имя}() -> {{стр: стр}} {{", "    перем с: {стр: стр} = {}"]
    for к, з in пары:
        строки.append(f"    с[{строка(к)}] = {строка(з)}")
    return строки + ["    вернуть с", "}", ""]


def список(имя, описание, значения):
    строки = [f"/// {описание}.", f"общий функ {имя}() -> [стр] {{", "    перем с: [стр] = []"]
    for з in значения:
        строки.append(f"    с.добавить({строка(з)})")
    return строки + ["    вернуть с", "}", ""]


def текст():
    if КОРЕНЬ not in sys.path:
        sys.path.insert(0, КОРЕНЬ)
    import server
    import matematika
    import dannye
    import sistema
    from lexer import КЛЮЧЕВЫЕ_СЛОВА, без_ё
    from proverka import ВСТРОЕННЫЕ, СВОЙСТВА, МЕТОДЫ_СТР, МЕТОДЫ_СПИСКА, ФУНКЦИОНАЛЬНЫЕ_МЕТОДЫ
    библиотечные = []
    описания = {}
    for таблица in (matematika.ФУНКЦИИ, dannye.ФУНКЦИИ, sistema.ФУНКЦИИ):
        for имя in таблица:
            описание = server.описание_библиотечной(имя) or ""
            библиотечные.append(имя)
            описания[имя] = описание
            if без_ё(имя) not in описания:
                описания[без_ё(имя)] = server.описание_библиотечной(без_ё(имя)) or ""
    # после «значение.»: методы и свойства значений (тип здесь неизвестен, поэтому все), как в server.py
    после_точки = []
    for имя in list(МЕТОДЫ_СТР) + list(МЕТОДЫ_СПИСКА) + list(ФУНКЦИОНАЛЬНЫЕ_МЕТОДЫ) + \
            ["длина", "найти", "получить", "содержит", "удалить", "ключи", "значения", "копия",
             "отправить", "получить", "закрыть", "дождаться", "готова"]:
        после_точки += [имя, "метод", ФУНКЦИОНАЛЬНЫЕ_МЕТОДЫ.get(имя, "")]
    for тип, свойства in СВОЙСТВА.items():
        for имя, т in свойства.items():
            после_точки += [имя, "свойство", f"{тип}.{имя}: {т}"]
    строки = [
        "/// Таблицы подсказок сервера языка для редакторов (команда «дан сервер»).",
        "///",
        "/// Файл создан сценарием сам/создать_подсказки.py из server.py и таблиц компилятора;",
        "/// изменять его вручную не нужно.",
        "",
    ]
    строки += список("ключевые_слова", "Ключевые слова по алфавиту", sorted(КЛЮЧЕВЫЕ_СЛОВА))
    строки += словарь("описания_ключевых", "Описания ключевых слов", server.ОПИСАНИЯ_КЛЮЧЕВЫХ.items())
    строки += список("встроенные", "Встроенные функции по алфавиту", sorted(ВСТРОЕННЫЕ))
    строки += словарь("описания_встроенных", "Описания встроенных функций", server.ОПИСАНИЯ_ВСТРОЕННЫХ.items())
    строки += список("библиотечные", "Функции библиотеки в порядке таблиц", библиотечные)
    строки += словарь("описания_библиотеки", "Описания функций библиотеки: варианты и описание", описания.items())
    строки += список("после_точки", "Подсказки после точки: имя, вид, описание (по три элемента)", после_точки)
    return "\n".join(строки)


if __name__ == "__main__":
    with open(ФАЙЛ, "w", encoding="utf-8", newline="\n") as ф:
        ф.write(текст())
    print("Создан", ФАЙЛ)
