"""Создаёт сам/привычки.dan - таблицы привычек других языков для компилятора на Дане.

Таблицы и тексты подсказок берутся из privychki.py (компилятор на Python), чтобы оба
компилятора давали одинаковые сообщения. Запуск: python сам/создать_привычки.py;
test_sam.py проверяет, что файл соответствует таблицам.
"""

import os
import sys

ПАПКА = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(ПАПКА))

import privychki  # noqa: E402

ФАЙЛ = os.path.join(ПАПКА, "привычки.dan")


def строка(с):
    return '"' + с.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def текст():
    строки = [
        "/// Привычки из других языков: слова и знаки, которые по привычке пишут в программе на Дане.",
        "///",
        "/// Файл создан сценарием сам/создать_привычки.py из таблиц privychki.py компилятора на Python;",
        "/// изменять его вручную не нужно.",
        "",
        "/// слово -> [замена, пояснение]",
        "общий функ слова() -> {стр: [стр]} {",
        "    перем т: {стр: [стр]} = {}",
    ]
    for слово, (замена, пояснение) in privychki.СЛОВА.items():
        строки.append(f"    т[{строка(слово)}] = [{строка(замена)}, {строка(пояснение)}]")
    строки += ["    вернуть т", "}", "", "/// знак -> замена", "общий функ знаки() -> {стр: стр} {",
               "    перем т: {стр: стр} = {}"]
    for знак, замена in privychki.ЗНАКИ.items():
        строки.append(f"    т[{строка(знак)}] = {строка(замена)}")
    строки += ["    вернуть т", "}", "", "/// имя -> [замена, пояснение]", "общий функ имена() -> {стр: [стр]} {",
               "    перем т: {стр: [стр]} = {}"]
    for имя, (замена, пояснение) in privychki.ИМЕНА.items():
        строки.append(f"    т[{строка(имя)}] = [{строка(замена)}, {строка(пояснение)}]")
    строки += ["    вернуть т", "}", "", "/// метод или свойство -> замена", "общий функ методы() -> {стр: стр} {",
               "    перем т: {стр: стр} = {}"]
    for имя, замена in privychki.МЕТОДЫ.items():
        строки.append(f"    т[{строка(имя)}] = {строка(замена)}")
    строки += ["    вернуть т", "}", ""]
    строки += [
        "общий функ сообщение_слова(слово: стр) -> стр {",
        "    пусть з = слова()[слово]",
        "    если з[0] != \"\" { вернуть \"«\" + слово + \"» - не слово Дана: напишите «\" + з[0] + \"»\" }",
        "    вернуть \"«\" + слово + \"» - не слово Дана: \" + з[1]",
        "}",
        "",
        "общий функ сообщение_знака(знак: стр) -> стр {",
        "    вернуть \"«\" + знак + \"» - не знак Дана: напишите «\" + знаки()[знак] + \"»\"",
        "}",
        "",
        "/// Окончание сообщения о необъявленном имени или \"\".",
        "общий функ подсказка_имени(имя: стр) -> стр {",
        "    пусть т = имена()",
        "    если не т.содержит(имя) { вернуть \"\" }",
        "    пусть з = т[имя]",
        "    если з[0] != \"\" { вернуть \"; в Дане: напишите «\" + з[0] + \"»\" }",
        "    вернуть \"; в Дане \" + з[1]",
        "}",
        "",
        "/// Окончание сообщения об отсутствующем методе (вызов) или свойстве.",
        "общий функ подсказка_метода(имя: стр, вызов: лог) -> стр {",
        "    пусть замена = методы().получить(имя, \"\")",
        "    если замена == \"\" { вернуть \"\" }",
        "    если замена == \"длина\" и вызов { вернуть \"; в Дане длина - свойство без скобок: с.длина\" }",
        "    вернуть \"; в Дане: напишите «\" + замена + \"»\"",
        "}",
        "",
    ]
    return "\n".join(строки)


if __name__ == "__main__":
    with open(ФАЙЛ, "w", encoding="utf-8", newline="\n") as ф:
        ф.write(текст())
    print("Создан", ФАЙЛ)
