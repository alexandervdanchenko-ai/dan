    ("шаблон_равенства_словаря", kodogen.ШАБЛОН_РАВЕНСТВА_СЛОВАРЯ),
    ("шаблон_поиска", kodogen.ШАБЛОН_ПОИСКА),
    ("код_строк_со_списками", kodogen.КОД_СТРОК_СО_СПИСКАМИ),
    ("математика", matematika.КОД_C),
    ("математика_дополнения", matematika.код_c_дополнения()),
    ("многочлены_строки", matematika._код_многочленов_строки()),
    ("многочлены", matematika.КОД_МНОГОЧЛЕНОВ),
