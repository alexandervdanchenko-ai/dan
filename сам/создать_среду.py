    ("комплексные_корни", kodogen.КОМПЛЕКСНЫЕ_КОРНИ_C),
    ("задачи", kodogen.ЗАДАЧИ_C),
    ("шаблон_списка", kodogen.ШАБЛОН_СПИСКА),
