"""Создаёт сам/буквы.dan - таблицу букв Юникода для лексера на Дане.

Буква - символ категорий Lu, Ll, Lt, Lm, Lo (то же, что str.isalpha в Python, которым пользуется
lexer.py); алфавит буквы - первое слово её названия в Юникоде (LATIN, CYRILLIC, CJK...), как
в lexer.py. Таблица - диапазоны подряд идущих букв одного алфавита.

Версия Юникода закреплена (ВЕРСИЯ): таблица берётся из пакета unicodedata2 этой версии или из
unicodedata самого Python, если его версия та же (Python 3.12 - Юникод 15.0). При другой версии
файл не меняется: так результат не зависит от версии Python на машине. Запуск: python
сам/создать_буквы.py (или python пересоздать.py); сверку с lexer.py делает test_bukvy.py.
"""

import os
import sys

ПАПКА = os.path.dirname(os.path.abspath(__file__))
ФАЙЛ = os.path.join(ПАПКА, "буквы.dan")
ВЕРСИЯ = "15.0.0"
КАТЕГОРИИ = ("Lu", "Ll", "Lt", "Lm", "Lo")


def база():
    """Модуль с базой Юникода закреплённой версии или None."""
    try:
        import unicodedata2
        if unicodedata2.unidata_version == ВЕРСИЯ:
            return unicodedata2
    except ImportError:
        pass
    import unicodedata
    return unicodedata if unicodedata.unidata_version == ВЕРСИЯ else None


def алфавит(б, к):
    try:
        return б.name(chr(к)).split()[0]
    except ValueError:
        return ""


def диапазоны(б):
    """[(начало, конец, алфавит)] букв выше ASCII."""
    итог = []
    for к in range(128, 0x110000):
        if б.category(chr(к)) not in КАТЕГОРИИ:
            continue
        а = алфавит(б, к)
        if итог and итог[-1][1] == к - 1 and итог[-1][2] == а:
            итог[-1][1] = к
        else:
            итог.append([к, к, а])
    return итог


def дерево(д, имена, л, п, отступ):
    """Код поиска диапазона: двоичный поиск, развёрнутый в условия (без списков в памяти)."""
    о = "    " * отступ
    if п - л < 3:
        строки = []
        for н, к, а in д[л:п + 1]:
            условие = f"к == {н}" if н == к else f"к >= {н} и к <= {к}"
            строки.append(f"{о}если {условие} {{ вернуть {имена.index(а) + 1} }}")
        строки.append(f"{о}вернуть 0")
        return строки
    с = (л + п) // 2
    н, к, а = д[с]
    return ([f"{о}если к < {н} {{"] + дерево(д, имена, л, с - 1, отступ + 1)
            + [f"{о}}}", f"{о}если к > {к} {{"] + дерево(д, имена, с + 1, п, отступ + 1)
            + [f"{о}}}", f"{о}вернуть {имена.index(а) + 1}"])


def текст():
    б = база()
    if б is None:
        # другой версии Юникода нет: файл остаётся прежним
        with open(ФАЙЛ, encoding="utf-8", newline="") as ф:
            return ф.read()
    д = диапазоны(б)
    имена = sorted({а for _, _, а in д})
    строки = [
        f"/// Буквы Юникода {ВЕРСИЯ} выше ASCII: {len(д)} диапазонов подряд идущих букв одного алфавита.",
        "///",
        "/// Файл создан сценарием сам/создать_буквы.py из базы Юникода (категории Lu, Ll, Lt, Lm, Lo,",
        "/// алфавит - первое слово названия буквы, как в lexer.py); изменять его вручную не нужно.",
        "",
        "общий функ версия_юникода() -> стр { вернуть \"" + ВЕРСИЯ + "\" }",
        "",
        "/// Номер алфавита буквы с кодом к (с 1) или 0, если это не буква; только для к >= 128.",
        "общий функ номер_алфавита(к: цел) -> цел {",
        *дерево(д, имена, 0, len(д) - 1, 1),
        "}",
        "",
        "/// Название алфавита по номеру (LATIN, CYRILLIC...).",
        "общий функ название(номер: цел) -> стр {",
        "    пусть имена: [стр] = [",
        *["        " + ", ".join('"' + а + '"' for а in имена[н:н + 8]) + "," for н in range(0, len(имена), 8)],
        "    ]",
        "    вернуть имена[номер - 1]",
        "}",
        "",
    ]
    return "\n".join(строки)


if __name__ == "__main__":
    if база() is None:
        print(f"Нужна база Юникода {ВЕРСИЯ}: pip install unicodedata2=={ВЕРСИЯ} (или Python 3.12); файл не изменён")
        sys.exit(1)
    with open(ФАЙЛ, "w", encoding="utf-8", newline="\n") as ф:
        ф.write(текст())
    print("Создан", ФАЙЛ)
