"""Создаёт сам/коды.dan - таблицу постоянных кодов сообщений для компилятора на Дане.

Таблица берётся из kody.КОДЫ (компилятор на Python), чтобы оба компилятора выдавали
одинаковые коды в `проверить --json`. Запуск: python сам/создать_коды.py; test_sam.py
проверяет, что файл соответствует таблице.
"""

import os
import sys

ПАПКА = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(ПАПКА))

import kody  # noqa: E402

ФАЙЛ = os.path.join(ПАПКА, "коды.dan")


def строка(с):
    return '"' + с.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def текст():
    строки = [
        "/// Постоянные коды сообщений компилятора: обобщённый текст сообщения -> код.",
        "///",
        "/// Файл создан сценарием сам/создать_коды.py из таблицы kody.КОДЫ компилятора на Python;",
        "/// изменять его вручную не нужно.",
        "",
        "общий функ коды() -> {стр: стр} {",
        "    перем к: {стр: стр} = {}",
    ]
    for код, шаблон in kody.КОДЫ:
        строки.append(f"    к[{строка(шаблон)}] = {строка(код)}")
    строки += ["    вернуть к", "}", ""]
    return "\n".join(строки)


if __name__ == "__main__":
    with open(ФАЙЛ, "w", encoding="utf-8", newline="\n") as ф:
        ф.write(текст())
    print("Создан", ФАЙЛ)
