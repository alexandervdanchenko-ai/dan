"""Создаёт сам/встроенные.dan - таблицы встроенных функций для проверки на Дане.

Таблицы берутся из компилятора на Python (matematika, vysshaya, dannye, sistema и
методы из proverka), чтобы компилятор на Дане знал те же функции с теми же
вариантами. Запуск: python сам/создать_встроенные.py; test_sam.py проверяет,
что файл соответствует таблицам.
"""

import os
import sys

ПАПКА = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(ПАПКА))

import proverka  # noqa: E402  (регистрирует функции высшей математики)
import dannye  # noqa: E402
import matematika  # noqa: E402
import sistema  # noqa: E402
import versiya  # noqa: E402
from lexer import без_ё  # noqa: E402

ФАЙЛ = os.path.join(ПАПКА, "встроенные.dan")


def строка(с):
    return '"' + с.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def список(значения):
    return "[" + ", ".join(строка(з) for з in значения) + "]"


def текст():
    реестры = (matematika.ФУНКЦИИ, dannye.ФУНКЦИИ, sistema.ФУНКЦИИ)
    имена = [и for р in реестры for и in р]
    # имя без «ё» (так имена приходят от лексера) -> каноническое имя
    запросы = []
    for и in имена + list(matematika.СИНОНИМЫ):
        if без_ё(и) not in запросы:
            запросы.append(без_ё(и))
    поиск = {}
    for з in запросы:
        каноническое, описание = proverka.найти_в_библиотеке(з)
        if описание is not None:
            поиск[з] = каноническое
    канонические = []
    for к in поиск.values():
        if к not in канонические:
            канонические.append(к)

    строки = [
        "/// Таблицы встроенных функций для проверки на Дане.",
        "///",
        "/// Файл создан сценарием сам/создать_встроенные.py из таблиц компилятора на Python;",
        "/// изменять его вручную не нужно.",
        "",
        "/// Вариант вызова: типы параметров и тип результата.",
        "общий тип Вариант {",
        "    параметры: [стр]",
        "    результат: стр",
        "}",
        "",
        "общий тип Таблицы {",
        "    /// имя без «ё» -> каноническое имя функции библиотеки",
        "    поиск: {стр: стр} = {}",
        "    /// каноническое имя -> варианты вызова",
        "    варианты: {стр: [Вариант]} = {}",
        "    /// имена функций библиотеки (для подсказок)",
        "    имена: [стр] = []",
        "    /// постоянные: имя -> тип",
        "    постоянные: {стр: стр} = {}",
        "    /// устаревшие функции: имя -> (редакция удаления, совет)",
        "    устаревшие: {стр: [стр]} = {}",
        "}",
        "",
        "общий функ таблицы() -> Таблицы {",
        "    перем т = Таблицы()",
    ]
    for з, к in поиск.items():
        строки.append(f"    т.поиск[{строка(з)}] = {строка(к)}")
    for к in канонические:
        _, описание = proverka.найти_в_библиотеке(без_ё(к))
        варианты = ", ".join(f"Вариант({список(п)}, {строка(р)})" for п, р in описание["варианты"])
        строки.append(f"    т.варианты[{строка(к)}] = [{варианты}]")
    for начало in range(0, len(имена), 8):
        строки.append(f"    для имя_ в {список(имена[начало:начало + 8])} {{ т.имена.добавить(имя_) }}")
    for имя, (тип, _) in matematika.КОНСТАНТЫ.items():
        строки.append(f"    т.постоянные[{строка(имя)}] = {строка(тип)}")
    for имя, (редакция, совет) in versiya.УСТАРЕВШИЕ.items():
        строки.append(f"    т.устаревшие[{строка(имя)}] = [{строка(редакция)}, {строка(совет or '')}]")
    строки += ["    вернуть т", "}", ""]
    return "\n".join(строки)


if __name__ == "__main__":
    with open(ФАЙЛ, "w", encoding="utf-8", newline="\n") as ф:
        ф.write(текст())
    print("Создан", ФАЙЛ)
