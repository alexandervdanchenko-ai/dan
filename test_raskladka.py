ВЫВОД = ["5", "4", "[4, 3]", "4.2", '{"Иванов": 65000, "Петров": 52000, "Сидорова": 78000}', '{"а": 1}',
         '["Анна"]', "[7]", "1 не больше одного", "2", "3", "4 больше трёх", "5 больше трёх", "0", "35",
         "3.0", "4.0", "3"]


class ТестыЗаписи(unittest.TestCase):

    def test_блоки_отступом_дают_те_же_токены_что_скобки(self):
        двоеточие = "если а больше 0:\n    вывод(1)\nиначе:\n    вывод(2)\nвывод(3)\n"
        скобки = "если а > 0 {\n    вывод(1)\n}\nиначе {\n    вывод(2)\n}\nвывод(3)\n"
        знаки = lambda т: [(х.вид, х.значение) for х in токены(т)]
        self.assertEqual([з for з in знаки(двоеточие) if з[1] not in ("больше", ">")],
                         [з for з in знаки(скобки) if з[1] not in ("больше", ">")])

    def test_нет_блока_после_двоеточия(self):
        with self.assertRaises(ОшибкаЛексера) as о:
            токены("если истина:\nвывод(1)\n")
        self.assertIn("с бо́льшим отступом", str(о.exception))
        with self.assertRaises(ОшибкаЛексера):
            токены("если истина:\n")

    def test_двоеточие_внутри_строки_по_прежнему_деление_и_тип(self):
        разобрать("пусть х = 10 : 2\nпусть с: [цел] = []\nпусть д: {стр: цел} = {\"а\": 1}\n"
                  "вывод((10 : 2))\nфунк ф(а: цел) -> цел {\n    вернуть а\n}\n")

    def test_больше_и_меньше_остаются_допустимыми_именами(self):
        разобрать("пусть больше = 1\nпусть меньше = больше + 1\nвывод(меньше больше больше)\n")

    def test_сравнения_словами_не_цепочкой(self):
        with self.assertRaises(ОшибкаРазбора):
            разобрать("вывод(1 меньше 2 меньше 3)\n")

    def test_смешение_записей(self):
        разобрать("если истина {\n    для к в 1..2:\n        вывод(к)\n}\nесли ложь:\n    если истина { вывод(1) }\n")

    def test_форматирование_сохраняет_запись(self):
        self.assertEqual(отформатировать(ПРОГРАММА), ПРОГРАММА)
        сдвинутая = "\n".join(с.replace("    ", "  ") for с in ПРОГРАММА.split("\n"))
        self.assertEqual(отформатировать(сдвинутая), ПРОГРАММА)


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыВыполнения(unittest.TestCase):

    def test_программа_в_русской_раскладке(self):
        код, вывод, ош = выполнить(ПРОГРАММА)
        self.assertEqual(код, 0, ош)
        self.assertEqual(вывод.splitlines(), ВЫВОД)

    def test_латинских_знаков_нет(self):
        запрещённые = set("{}[]<>")
        текст = "".join(с.split("//")[0] for с in ПРОГРАММА.split("\n"))
        self.assertEqual(запрещённые & set(текст), set())


