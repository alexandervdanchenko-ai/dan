"""Плотные массивы чисел: массив<дроб32>, массив<цел8> и другие (spec.md, раздел 4.9).

Массивы появились после заморозки компилятора на Python, поэтому программы этих тестов
всегда переводит компилятор на Дане (sam_kompilyator), в любом режиме тестов.
"""

import os
import subprocess
import tempfile
import unittest

import sam_kompilyator
from test_kodogen import КОМПИЛЯТОР_ЕСТЬ


def выполнить(текст, команда="запустить"):
    """(код завершения, вывод, ошибки) программы, собранной компилятором на Дане."""
    with tempfile.TemporaryDirectory(prefix="dan_massiv_") as папка:
        путь = os.path.join(папка, "программа.dan")
        with open(путь, "w", encoding="utf-8", newline="\n") as ф:
            ф.write(текст)
        р = subprocess.run([sam_kompilyator.исполняемый(), команда, путь], capture_output=True,
                           env=sam_kompilyator.среда(), timeout=600, cwd=папка)
        вывод_ = р.stdout.decode("utf-8", "replace").replace("\r\n", "\n")
        ошибки = р.stderr.decode("utf-8", "replace").replace("\r\n", "\n")
        return р.returncode, вывод_, ошибки


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыМассивов(unittest.TestCase):

    def вывод(self, текст, ожидается):
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 0, вывод_ + ошибки)
        self.assertEqual(вывод_.splitlines(), ожидается)

    def ошибка_выполнения(self, текст, часть):
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 1, вывод_ + ошибки)
        self.assertIn(часть, ошибки)

    def ошибка_проверки(self, текст, часть):
        код, вывод_, ошибки = выполнить(текст, "проверить")
        self.assertEqual(код, 1, вывод_ + ошибки)
        self.assertIn(часть, вывод_ + ошибки)

    def test_создание_и_вывод(self):
        self.вывод("вывод(массив(дроб32, 3))\n"
                   "вывод(массив(цел8, 2, -5))\n"
                   "вывод(массив(дроб, [1.5, 2.0]))\n"
                   "вывод(массив(дроб32, [1, 2]))\n"
                   "вывод(массив(байт, []))\n"
                   "пусть м = массив(цел16, [1, 2, 3])\n"
                   "вывод(м.длина)\n"
                   "вывод(стр(м) + \"!\")\n"
                   "вывод(м.список())\n"
                   "вывод(массив(дроб32, [0.1, 0.2]).список())",
                   ["[0.0, 0.0, 0.0]", "[-5, -5]", "[1.5, 2.0]", "[1.0, 2.0]", "[]", "3", "[1, 2, 3]!", "[1, 2, 3]",
                    "[0.10000000149011612, 0.20000000298023224]"])

    def test_дробные_виды(self):
        # дроб32 и дроб16 выводятся кратчайшей записью, дающей тот же элемент
        self.вывод("пусть м = массив(дроб32, [0.1, 1e30, -2.5])\nвывод(м)\nвывод(м[0])\n"
                   "пусть п = массив(дроб16, [1.0, 0.1, 65504.0, -0.0, 0.00006103515625, 0.000000059604644775390625])\n"
                   "вывод(п)\nвывод(п[1])\nвывод(п[2])",
                   ["[0.1, 1e+30, -2.5]", "0.10000000149011612",
                    "[1.0, 0.1, 65500.0, -0.0, 6.104e-05, 6e-08]", "0.0999755859375", "65504.0"])

    def test_индекс_запись_и_копия(self):
        # массив - значение: изменение одного места не видно в другом
        self.вывод("перем а = массив(цел32, [1, 2, 3])\nпусть б = а\nа[0] = 10\nа[1] += 5\nа[2] *= -1\n"
                   "вывод(а)\nвывод(б)\nвывод(а[0] + б[0])",
                   ["[10, 7, -3]", "[1, 2, 3]", "11"])

    def test_часть_без_копии(self):
        self.вывод("перем а = массив(цел, [1, 2, 3, 4, 5])\nперем ч = а[1..3]\nвывод(ч)\nвывод(ч.длина)\n"
                   "ч[0] = 100\nвывод(ч)\nвывод(а)\nпусть ч2 = а[2..4]\nа[2] = -7\nвывод(ч2)\nвывод(а)\n"
                   "вывод(а[1..0])\nвывод(а[1..3][1..2])",
                   ["[2, 3, 4]", "3", "[100, 3, 4]", "[1, 2, 3, 4, 5]", "[3, 4, 5]", "[1, 2, -7, 4, 5]", "[]",
                    "[-7, 4]"])

    def test_цикл_равенство_функции_типы(self):
        self.вывод("функ сумма(м: массив<дроб32>) -> дроб {\n    перем с = 0.0\n    для х в м { с += х }\n    вернуть с\n}\n"
                   "функ с_нулём(м: массив<цел>) -> массив<цел> {\n    перем к = м\n    к[0] = 0\n    вернуть к\n}\n"
                   "тип Слой {\n    веса: массив<дроб16>\n    имя: стр\n}\n"
                   "пусть а = массив(дроб32, [1.5, 2.5])\nвывод(сумма(а))\n"
                   "пусть ц = массив(цел, [5, 6])\nвывод(с_нулём(ц))\nвывод(ц)\n"
                   "вывод(ц == массив(цел, [5, 6]))\nвывод(ц != с_нулём(ц))\n"
                   "вывод(Слой(массив(дроб16, [0.5]), \"первый\"))\n"
                   "перем сп: [массив<байт>] = []\nдля н в 1..2 { сп.добавить(массив(байт, н, н)) }\nсп[1][0] = 9\nвывод(сп)\n"
                   "пусть сл: {стр: массив<цел8>} = {\"а\": массив(цел8, [-1])}\nвывод(сл)\n"
                   "пусть з = запустить с_нулём(ц)\nвывод(з.дождаться())",
                   ["4.0", "[0, 6]", "[5, 6]", "истина", "истина", "Слой(веса = [0.5], имя = \"первый\")",
                    "[[1], [9, 2]]", "{\"а\": [-1]}", "[0, 6]"])

    def test_ошибки_выполнения(self):
        self.ошибка_выполнения("пусть м = массив(цел, 3)\nвывод(м[3])", "индекс 3 за пределами (длина 3)")
        self.ошибка_выполнения("перем м = массив(цел8, 3)\nм[0] = 128",
                               "значение 128 не помещается в элемент массива<цел8> (от -128 до 127)")
        self.ошибка_выполнения("перем м = массив(байт, 1)\nм[0] = -1", "(от 0 до 255)")
        self.ошибка_выполнения("пусть м = массив(дроб16, [70000.0])", "значение 70000.0 не помещается в элемент массива<дроб16>")
        self.ошибка_выполнения("пусть м = массив(дроб32, [1e39])", "не помещается в элемент массива<дроб32>")
        self.ошибка_выполнения("пусть н = -1\nпусть м = массив(дроб, н)", "размер массива не может быть отрицательным: -1")
        self.ошибка_выполнения("пусть м = массив(цел, [1, 2])\nвывод(м[0..2])", "индекс 2 за пределами (длина 2)")

    def test_ошибки_проверки(self):
        self.ошибка_проверки("пусть м = массив(цел77, 3)", "виды элементов: дроб, дроб32, дроб16, цел, цел32, цел16, цел8, байт, цел4, цел2")
        self.ошибка_проверки("пусть м = массив(дроб32)", "массив создаётся так")
        self.ошибка_проверки("пусть м = массив(дроб32, \"х\")", "размер массива - целое число, а здесь стр")
        self.ошибка_проверки("пусть м: массив<строка> = массив(цел, 1)", "элементы массива могут быть видов")
        self.ошибка_проверки("пусть м = массив(цел, 3)\nм[0] = 1", "элемент массива нельзя изменить")
        self.ошибка_проверки("перем м = массив(цел, 3)\nм[0] = 1.5", "элементы массива имеют тип цел, а значение имеет тип дроб")
        self.ошибка_проверки("пусть м = массив(цел8, [1.5])", "элементы массива<цел8> имеют тип цел, а здесь список [дроб]")
        self.ошибка_проверки("пусть м = массив(цел, 3)\nвывод(м.сумма())", "у массива есть метод «список()» и свойство «длина»")
        self.ошибка_проверки("пусть м = массив(цел, 3)\nвывод(м < м)", "массивы можно сравнивать только на равенство")
        self.ошибка_проверки("вывод(массив(цел, 1) == массив(цел8, 1))", "нельзя сравнивать массив<цел> и массив<цел8>")

    def test_байты_и_файлы(self):
        self.вывод("пусть м = массив(дроб32, [1.5, -2.0, 3.25, 4.0])\n"
                   "пусть б = байты(м)\nвывод(б.длина)\nзаписать(\"веса.bin\", б)\n"
                   "пусть весь = массив_из_файла(дроб32, \"веса.bin\")!\nвывод(весь)\n"
                   "пусть часть = массив_из_файла(дроб32, \"веса.bin\", 4, 2)!\nвывод(часть)\n"
                   "перем изм = часть\nизм[0] = 9.0\nвывод(изм)\nвывод(часть)\n"
                   "вывод(массив(дроб32, б) == м)\n"
                   "вывод(массив(цел16, байты([1, 0, 255, 255])))\n"
                   "вывод(массив_из_файла(байт, \"веса.bin\", 16)!)\n"
                   "вывод(массив_из_файла(цел8, \"веса.bin\", 3, 1)!)",
                   ["16", "[1.5, -2.0, 3.25, 4.0]", "[-2.0, 3.25]", "[9.0, 3.25]", "[-2.0, 3.25]", "истина", "[1, -1]",
                    "[]", "[63]"])

    def test_ошибки_файлов(self):
        начало = "записать(\"веса.bin\", байты(массив(дроб32, 4)))\n"
        for вызов, текст in (("массив_из_файла(дроб32, \"нет.bin\")", "файл \"нет.bin\": файла нет"),
                             ("массив_из_файла(дроб32, \"веса.bin\", 3)", "после смещения 3 в файле 13 байт, а элемент "
                              "массива<дроб32> занимает 4: укажите количество элементов"),
                             ("массив_из_файла(дроб32, \"веса.bin\", 0, 5)", "нужно 5 элементов массива<дроб32> после "
                              "смещения 0, а в файле после него 16 байт"),
                             ("массив_из_файла(дроб32, \"веса.bin\", 17)", "смещение 17 за концом файла (в файле 16 байт)"),
                             ("массив_из_файла(дроб32, \"веса.bin\", -1)", "смещение не может быть отрицательным: -1"),
                             ("массив_из_файла(дроб32, \"веса.bin\", 0, -2)", "количество элементов не может быть "
                              "отрицательным: -2")):
            with self.subTest(вызов=вызов):
                self.вывод(начало + "если пусть х = " + вызов + " { вывод(х) } иначе ошибка о { вывод(о) }", [
                    текст if текст.startswith("файл") else "файл \"веса.bin\": " + текст])
        self.ошибка_выполнения("пусть м = массив(дроб32, байты([1, 2, 3]))",
                               "в байтах 3 байт, а элемент массива<дроб32> занимает 4")
        self.ошибка_проверки("пусть м = массив_из_файла(дроб32, 5)", "путь имеет тип стр, а здесь цел")
        self.ошибка_проверки("пусть м = массив_из_файла(\"а.bin\")", "массив_из_файла(вид, путь)")

    def test_функции_c(self):
        # массив и байты передаются функции C указателем на первый элемент, без копии
        self.вывод("внешняя \"\" {\n"
                   "    функ сравнить_память(а: массив<дроб32>, б: байты, н: цел) -> цел32 = \"memcmp\"\n"
                   "    функ сравнить_части(а: массив<цел16>, б: массив<цел16>, н: цел) -> цел32 = \"memcmp\"\n"
                   "    функ длина_строки(б: байты) -> цел = \"strlen\"\n"
                   "}\n"
                   "пусть м = массив(дроб32, [1.5, -2.0])\nвывод(сравнить_память(м, байты(м), 8))\n"
                   "пусть ц = массив(цел16, [1, 2, 3, 1, 2, 3])\nвывод(сравнить_части(ц[0..2], ц[3..5], 6))\n"
                   "вывод(сравнить_части(ц[0..2], ц[1..3], 6) != 0)\nвывод(длина_строки(байты(\"Дан\")))",
                   ["0", "0", "истина", "6"])
        self.ошибка_проверки("внешняя \"\" {\n    функ ф(м: массив<строка>)\n}",
                             "параметр внешней функции может иметь тип цел, цел32, дроб, дроб32, лог, стр, байты, массив<вид> или буфер<вид>")

    def test_буфер_для_функции_c(self):
        # буфер<вид>: функция C пишет в массив переменной; другие места массива не меняются
        self.вывод("внешняя \"\" {\n"
                   "    функ заполнить(м: буфер<цел8>, значение: цел32, н: цел) = \"memset\"\n"
                   "    функ скопировать(куда: буфер<дроб32>, откуда: массив<дроб32>, н: цел) = \"memcpy\"\n"
                   "}\n"
                   "перем а = массив(цел8, 4)\nпусть б = а\nзаполнить(а, 7, 3)\nвывод(а)\nвывод(б)\n"
                   "перем д = массив(дроб32, 3)\nскопировать(д, массив(дроб32, [1.5, 2.5, 3.5]), 8)\nвывод(д)\n"
                   "тип Т {\n    м: массив<цел8>\n}\nперем т = Т(массив(цел8, 2))\nзаполнить(т.м, -1, 2)\nвывод(т)\n"
                   "записать(\"ф.bin\", байты([1, 2]))\nперем ф = массив_из_файла(цел8, \"ф.bin\")!\nзаполнить(ф, 0, 1)\n"
                   "вывод(ф)\nвывод(массив_из_файла(цел8, \"ф.bin\")!)",
                   ["[7, 7, 7, 0]", "[0, 0, 0, 0]", "[1.5, 2.5, 0.0]", "Т(м = [-1, -1])", "[0, 2]", "[1, 2]"])
        начало = "внешняя \"\" {\n    функ заполнить(м: буфер<цел8>, значение: цел32, н: цел) = \"memset\"\n}\n"
        self.ошибка_проверки(начало + "пусть а = массив(цел8, 4)\nзаполнить(а, 7, 3)", "функция C записывает в массив, и его "
                             "нельзя изменить, так как переменную «а» изменять нельзя")
        self.ошибка_проверки(начало + "заполнить(массив(цел8, 2), 1, 1)", "сюда передаётся массив из переменной")
        self.ошибка_проверки(начало + "пусть ф = заполнить", "нельзя передать как значение")

