"""Предупреждение о пустом обработчике ошибки (spec.md, раздел 9.5; исследование.md, пункт 6.3.1).

Блок, в котором ошибка формально обработана, а фактически пропускается молча («если ошибка о = ф() { }»,
«иначе ошибка о { }», «иначе { }» после «если пусть» с результатом «Т!»), даёт предупреждение Д0331.
Это предупреждение, а не ошибка: программа по-прежнему собирается и выполняется. Комментарий в блоке -
явная пометка, что ошибка пропускается намеренно, и предупреждения не даёт. Предупреждение есть только в
компиляторе на Дане (сам/проверка.dan): тесты выполняют его команды.
"""

import glob
import json
import os
import subprocess
import tempfile
import unittest

import sam_kompilyator
from test_kodogen import КОМПИЛЯТОР_ЕСТЬ

ПАПКА = os.path.dirname(os.path.abspath(__file__))

ФУНКЦИИ = ('функ ф() -> цел! {\n    вернуть ошибка("плохо ф")\n}\n'
           'функ г() -> ! {\n    вернуть ошибка("плохо г")\n}\n')
ТЕКСТ = "ошибка пропускается молча"


def выполнить(*аргументы, текст=None, cwd=None):
    """Код завершения, вывод и поток ошибок команды компилятора на Дане для программы «текст» (п.dan)."""
    with tempfile.TemporaryDirectory() as папка:
        if текст is not None:
            with open(os.path.join(папка, "п.dan"), "w", encoding="utf-8") as ф:
                ф.write(текст)
        р = subprocess.run([sam_kompilyator.исполняемый(), *аргументы], capture_output=True, cwd=cwd or папка,
                           env=sam_kompilyator.среда(), timeout=300)
        return (р.returncode, р.stdout.decode("utf-8", "replace").replace("\r\n", "\n"),
                р.stderr.decode("utf-8", "replace").replace("\r\n", "\n"))


def предупреждения(текст):
    код, вывод_, _ = выполнить("проверить", "--json", "п.dan", текст=текст)
    д = json.loads(вывод_)
    return код, [с for с in д["сообщения"] if с["вид"] == "предупреждение"]


class ТестыПустогоОбработчика(unittest.TestCase):

    def test_все_формы(self):
        for инструкция, строка, позиция, где in [
            ("если ошибка о = ф() { }", 7, 21, "блок «если ошибка о» пустой"),
            ("если ошибка о = г() {}", 7, 21, "блок «если ошибка о» пустой"),
            ("если ошибка о = г() {\n}", 7, 21, "блок «если ошибка о» пустой"),
            ("если ошибка о = г() { } иначе {\n    вывод(1)\n}", 7, 21, "блок «если ошибка о» пустой"),
            ("если пусть з = ф() {\n    вывод(з)\n} иначе ошибка о { }", 9, 18, "блок «иначе ошибка о» пустой"),
            ("если пусть з = ф() {\n    вывод(з)\n} иначе { }", 9, 9, "блок «иначе» пустой"),
            ("функ ч() {\n    если ошибка е = г() { }\n}\nч()", 8, 25, "блок «если ошибка е» пустой"),
        ]:
            with self.subTest(инструкция=инструкция):
                код, найдено = предупреждения(ФУНКЦИИ + инструкция + "\n")
                self.assertEqual(код, 0)
                self.assertEqual(len(найдено), 1, найдено)
                п = найдено[0]
                self.assertEqual((п["код"], п["строка"], п["позиция"], п["длина"]), ("Д0331", строка, позиция, 1))
                self.assertTrue(п["текст"].startswith(ТЕКСТ + ": " + где + "; обработайте её"), п["текст"])
                self.assertIn("передайте её дальше знаком «!» после вызова", п["текст"])
                self.assertIn("напишите в блоке комментарий с причиной", п["текст"])
                self.assertNotIn("исправление", п)

    def test_подсказка_называет_ошибку(self):
        _, найдено = предупреждения(ФУНКЦИИ + "если ошибка причина = ф() { }\n")
        self.assertIn("(например, «вывод_ошибки(причина)»)", найдено[0]["текст"])
        _, найдено = предупреждения(ФУНКЦИИ + "если пусть з = ф() {\n    вывод(з)\n} иначе { }\n")
        self.assertIn("(«иначе ошибка о { вывод_ошибки(о) }»)", найдено[0]["текст"])

    def test_без_предупреждения(self):
        for инструкция in [
            # обработчик что-то делает
            "если ошибка о = ф() {\n    вывод_ошибки(о)\n}",
            "если пусть з = ф() {\n    вывод(з)\n} иначе ошибка о {\n    вывод(о)\n}",
            # комментарий в блоке - явная пометка, что ошибка пропускается намеренно
            "если ошибка о = г() {\n    // файла может не быть: это не ошибка\n}",
            "если ошибка о = г() { // нарочно\n}",
            "если пусть з = ф() {\n    вывод(з)\n} иначе ошибка о {\n\n    // не число - пропускаем\n}",
            "если пусть з = ф() {\n    вывод(з)\n} иначе {\n    // нет значения - ничего не выводим\n}",
            # «если пусть» без «иначе» - действие только над значением (как if let в Rust)
            "если пусть з = ф() {\n    вывод(з)\n}",
            # запасное значение - тоже обработка
            "вывод(ф() иначе 0)",
            # необязательное значение: «иначе» - ветвь «ничего», а не ошибки
            "пусть н: цел? = ничего\nесли пусть з = н {\n    вывод(з)\n} иначе { }",
            # пустой блок обычного «если» и «иначе» ветвей «выбор» - не обработчик ошибки
            "если 1 > 2 { }",
        ]:
            with self.subTest(инструкция=инструкция):
                код, найдено = предупреждения(ФУНКЦИИ + инструкция + "\n")
                self.assertEqual((код, найдено), (0, []))

    def test_проверить_и_сборка(self):
        текст = ФУНКЦИИ + "если ошибка о = ф() { }\nвывод(\"дальше\")\n"
        код, вывод_, ошибки = выполнить("проверить", "п.dan", текст=текст)
        self.assertEqual(код, 0)
        self.assertIn("п.dan: предупреждение: Строка 7, позиция 21: " + ТЕКСТ, ошибки + вывод_)
        self.assertIn("    7 | если ошибка о = ф() { }\n      |                     ^", ошибки + вывод_)
        if КОМПИЛЯТОР_ЕСТЬ:
            # сборка не останавливается: предупреждение - в потоке ошибок, программа выполняется
            код, вывод_, ошибки = выполнить("запустить", "п.dan", текст=текст)
            self.assertEqual((код, вывод_), (0, "дальше\n"))
            self.assertIn("п.dan: предупреждение: Строка 7, позиция 21: " + ТЕКСТ, ошибки)

    def test_объяснение_строки(self):
        код, вывод_, _ = выполнить("объяснить", "п.dan:7", текст=ФУНКЦИИ + "если ошибка о = ф() { }\n")
        self.assertEqual(код, 0)
        self.assertIn("Предупреждение компилятора: " + ТЕКСТ, вывод_)

    def test_в_подключённом_файле(self):
        with tempfile.TemporaryDirectory() as папка:
            with open(os.path.join(папка, "мод.dan"), "w", encoding="utf-8") as ф:
                ф.write(ФУНКЦИИ.replace("функ г()", "общий функ г()")
                        + "общий функ ч() {\n    если ошибка о = г() { }\n}\n")
            with open(os.path.join(папка, "п.dan"), "w", encoding="utf-8") as ф:
                ф.write('подключить "мод.dan"\nмод.ч()\n')
            код, вывод_, ошибки = выполнить("проверить", "п.dan", cwd=папка)
            self.assertEqual(код, 0)
            self.assertIn("Файл мод.dan, строка 8, позиция 25: " + ТЕКСТ, ошибки + вывод_)

    def test_сервер_языка(self):
        import test_server
        клиент = test_server.Клиент([sam_kompilyator.исполняемый(), "сервер"], sam_kompilyator.среда())
        try:
            клиент.запрос("initialize", {"processId": None, "rootUri": None, "capabilities": {}})
            клиент.уведомление("initialized", {})
            with tempfile.TemporaryDirectory() as папка:
                uri = test_server.uri_из_пути(os.path.join(папка, "п.dan"))
                клиент.уведомление("textDocument/didOpen", {"textDocument": {
                    "uri": uri, "languageId": "dan", "version": 1, "text": ФУНКЦИИ + "если ошибка о = ф() { }\n"}})
                найдено = клиент.ждать_ошибок(uri)
        finally:
            клиент.закрыть()
        self.assertEqual(len(найдено), 1)
        self.assertEqual(найдено[0]["severity"], 2)
        self.assertTrue(найдено[0]["message"].startswith(ТЕКСТ), найдено[0]["message"])
        self.assertEqual(найдено[0]["range"]["start"], {"line": 6, "character": 20})

    def test_программы_репозитория_без_предупреждения(self):
        # верные программы (и замороженная папка «совместимость») собираются как раньше: ни в одной
        # нет пустого обработчика, а там, где ошибка пропускается намеренно, есть комментарий
        файлы = []
        for маска in ("совместимость/**/*.dan", "каталог/программы/*.dan", "примеры/*.dan", "учебник/**/*.dan",
                      "библиотека/*.dan", "сам/дан.dan"):
            файлы += sorted(glob.glob(os.path.join(ПАПКА, маска), recursive=True))
        self.assertGreater(len(файлы), 100)
        for путь in файлы:
            р = subprocess.run([sam_kompilyator.исполняемый(), "проверить", путь], capture_output=True,
                               env=sam_kompilyator.среда(), timeout=300)
            with self.subTest(файл=os.path.relpath(путь, ПАПКА)):
                self.assertNotIn(ТЕКСТ, (р.stdout + р.stderr).decode("utf-8", "replace"))


if __name__ == "__main__":
    unittest.main()
