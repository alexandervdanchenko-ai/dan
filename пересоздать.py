"""Пересоздать все файлы, которые создаются сценариями из таблиц компилятора и документации.

    python пересоздать.py              пересоздать все
    python пересоздать.py --проверить  только проверить, что ни один не устарел (код 1 - устарел)

Созданные файлы: сам/встроенные.dan, сам/среда.dan, сам/коды.dan, сам/привычки.dan,
llms.txt, llms-full.txt. Их не правят руками и не сливают при конфликте: после
слияния веток (git rebase, git merge) достаточно выполнить этот сценарий и
добавить результат в коммит.
"""

import importlib.util
import os
import sys

ПАПКА = os.path.dirname(os.path.abspath(__file__))

# сценарий -> [(файл, функция текста)]; порядок важен: llms-full.txt берёт таблицы компилятора
СЦЕНАРИИ = [
    ("сам/создать_встроенные.py", [("сам/встроенные.dan", "текст")]),
    ("сам/создать_среду.py", [("сам/среда.dan", "текст")]),
    ("сам/создать_коды.py", [("сам/коды.dan", "текст")]),
    ("сам/создать_привычки.py", [("сам/привычки.dan", "текст")]),
    ("создать_llms.py", [("llms.txt", "краткий"), ("llms-full.txt", "полный")]),
]


def загрузить(сценарий):
    путь = os.path.join(ПАПКА, сценарий)
    if ПАПКА not in sys.path:
        sys.path.insert(0, ПАПКА)
    имя = "пересоздание_" + os.path.basename(сценарий)[:-3]
    описание = importlib.util.spec_from_file_location(имя, путь)
    модуль = importlib.util.module_from_spec(описание)
    описание.loader.exec_module(модуль)
    return модуль


def главная(аргументы):
    проверить = "--проверить" in аргументы
    устаревшие = []
    for сценарий, файлы in СЦЕНАРИИ:
        модуль = загрузить(сценарий)
        for файл, функция in файлы:
            текст = getattr(модуль, функция)()
            путь = os.path.join(ПАПКА, файл)
            try:
                with open(путь, encoding="utf-8", newline="") as ф:
                    было = ф.read()
            except OSError:
                было = None
            if было == текст:
                continue
            if проверить:
                устаревшие.append(файл)
            else:
                with open(путь, "w", encoding="utf-8", newline="\n") as ф:
                    ф.write(текст)
                print(f"Обновлён {файл}")
    if проверить:
        if устаревшие:
            print("Устарели: " + ", ".join(устаревшие) + ". Выполните: python пересоздать.py")
            return 1
        print("Все созданные файлы в порядке.")
    return 0


if __name__ == "__main__":
    sys.exit(главная(sys.argv[1:]))
