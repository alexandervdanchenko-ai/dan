def хи2_двух_выборок(а, б):
    """Хи-квадрат двух выборок одного размера (частоты по категориям): статистика, степени свободы и
    вероятность получить не меньше при одном распределении (по Уилсону - Хилферти). Категории с суммой
    меньше 10 объединяются."""
    import math
    редкие_а = редкие_б = 0
    статистика = 0.0
    категорий = 0
    for к in set(а) | set(б):
        х, у = а.get(к, 0), б.get(к, 0)
        if х + у < 10:
            редкие_а += х
            редкие_б += у
            continue
        статистика += (х - у) ** 2 / (х + у)
        категорий += 1
    if редкие_а + редкие_б > 0:
        статистика += (редкие_а - редкие_б) ** 2 / (редкие_а + редкие_б)
        категорий += 1
    свободы = max(1, категорий - 1)
    з = ((статистика / свободы) ** (1 / 3) - (1 - 2 / (9 * свободы))) / math.sqrt(2 / (9 * свободы))
    return статистика, свободы, 0.5 * math.erfc(з / math.sqrt(2))


