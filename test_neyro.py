def выполнить(аргументы, окружение=None):
    р = subprocess.run([Общее.программа, *аргументы], capture_output=True, timeout=600,
                       env={**os.environ, **(окружение or {})}, cwd=Общее.папка)
    вывод_ = р.stdout.decode("utf-8", "replace").replace("\r\n", "\n")
    итог = {}
    for строка in вывод_.splitlines():
        if "=" in строка:
            ключ, значение = строка.split("=", 1)
            итог.setdefault(ключ, значение)
    return р.returncode, итог, вывод_ + р.stderr.decode("utf-8", "replace")


def списки(аргументы, ключ):
    код, _, весь = выполнить(аргументы)
    return код, [с[len(ключ) + 1:] for с in весь.splitlines() if с.startswith(ключ + "=")], весь


