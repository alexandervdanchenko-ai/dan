def найти_llama():
    место = os.environ.get("DAN_LLAMA")
    if not место:
        return None
    if os.path.isdir(место):
        место = os.path.join(место, ИМЯ_БИБЛИОТЕКИ)
    return место if os.path.isfile(место) else None


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
@unittest.skipUnless(sys.platform.startswith("linux"), "сверка с llama.cpp - в Linux")
class ТестыСверкиСLlama(unittest.TestCase):
    """Нужна библиотека llama.cpp (DAN_LLAMA); без неё - пропуск с пометкой."""

    @classmethod
    def setUpClass(cls):
        cls.библиотека = найти_llama()
        if not cls.библиотека:
            raise unittest.SkipTest("нет библиотеки llama.cpp (переменная DAN_LLAMA): сверка с llama.cpp не выполняется")
        Общее.подготовить()
        компилятор = shutil.which("gcc") or shutil.which("cc") or shutil.which("clang")
        cls.сверка = os.path.join(Общее.папка, "sverka_llama")
        р = subprocess.run([компилятор, "-std=c11", "-O2", os.path.join(ПАПКА, "замеры", "нейро", "сверка_llama.c"),
                            "-o", cls.сверка, "-ldl"], capture_output=True, text=True)
        if р.returncode != 0:
            raise AssertionError(р.stderr)

    def llama(self, модель, запрос, н):
        папка = os.path.dirname(self.библиотека)
        окружение = dict(os.environ)
        окружение["LD_LIBRARY_PATH"] = папка + (os.pathsep + окружение["LD_LIBRARY_PATH"]
                                                if окружение.get("LD_LIBRARY_PATH") else "")
        р = subprocess.run([self.сверка, self.библиотека, модель, запрос, str(н)], capture_output=True, timeout=600,
                           env=окружение)
        self.assertEqual(р.returncode, 0, р.stderr.decode("utf-8", "replace"))
        итог = {}
        for строка in р.stdout.decode("utf-8", "replace").splitlines():
            if ": " in строка or строка.endswith(":"):
                ключ, _, значение = строка.partition(":")
                итог[ключ] = значение.strip()
        return итог

