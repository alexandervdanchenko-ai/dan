"""Тесты модулей: программы из нескольких файлов."""

import os
import shutil
import subprocess
import tempfile
import unittest

import dan
from moduli import загрузить, ОшибкаМодуля
from proverka import проверить, ОшибкаПроверки

КОМПИЛЯТОР_ЕСТЬ = any(shutil.which(к) for к in dan.КОМПИЛЯТОРЫ)

РАСЧЁТЫ = """
подключить "общее/ставки.dan"

общий тип Требование {
    Долг(сумма: рац)
    Пени(сумма: рац, дней: цел)
}

общий тип Итог {
    сумма: рац
    пояснение: стр = ""
}

тип Скрытый { х: цел }

функ пени(сумма: рац, дней: цел) -> рац {
    вернуть сумма * ставки.ключевая() * дней / 100
}

общий функ размер(т: Требование) -> рац {
    выбор т {
        Долг(с) { вернуть с }
        Пени(с, д) { вернуть пени(с, д) }
    }
}

общий функ итог(список: [Требование]) -> Итог {
    перем всего = рац(0)
    для т в список { всего += размер(т) }
    вернуть Итог(всего, "требований: " + стр(список.длина))
}
"""

СТАВКИ = "общий функ ключевая() -> рац { вернуть рац(1, 10) }\n"


class Папка:
    """Временный каталог с файлами программы."""

    def __init__(self, файлы):
        self.файлы = файлы

    def __enter__(self):
        self.tmp = tempfile.TemporaryDirectory()
        for имя, текст in self.файлы.items():
            путь = os.path.join(self.tmp.name, имя)
            os.makedirs(os.path.dirname(путь), exist_ok=True)
            with open(путь, "w", encoding="utf-8") as ф:
                ф.write(текст)
        return self.tmp.name

    def __exit__(self, *а):
        self.tmp.cleanup()


def ошибка_загрузки(файлы, главная):
    with Папка(файлы) as п:
        путь = os.path.join(п, "главная.dan")
        try:
            проверить(загрузить(главная, путь))
        except ОшибкаМодуля as о:
            return str(о)
        except ОшибкаПроверки as о:
            return "\n".join(str(с) for с in о.ошибки)
    return None


class ТестыЗагрузки(unittest.TestCase):
    ФАЙЛЫ = {"расчёты.dan": РАСЧЁТЫ, "общее/ставки.dan": СТАВКИ}

    def test_имена_получают_название_модуля(self):
        with Папка(self.ФАЙЛЫ) as п:
            программа = загрузить('подключить "расчёты.dan" как р\nвывод(р.размер(р.Долг(5)))',
                                  os.path.join(п, "главная.dan"))
        имена = [getattr(и, "имя", None) for и in программа.инструкции]
        self.assertIn("ставки.ключевая", имена)
        self.assertIn("расчеты.размер", имена)
        self.assertIn("расчеты.Скрытый", имена)
        # зависимости раньше зависящих от них файлов
        self.assertLess(имена.index("ставки.ключевая"), имена.index("расчеты.размер"))
        проверить(программа)

    def test_закрытое_имя_недоступно(self):
        т = ошибка_загрузки(self.ФАЙЛЫ, 'подключить "расчёты.dan"\nвывод(расчёты.пени(1, 2))')
        self.assertIn("«пени» в модуле «расчёты» не помечено словом «общий»", т)
        т = ошибка_загрузки(self.ФАЙЛЫ, 'подключить "расчёты.dan"\nпусть х: расчёты.Скрытый = 1')
        self.assertIn("не помечено словом «общий»", т)

    def test_неизвестное_имя_и_файл(self):
        т = ошибка_загрузки(self.ФАЙЛЫ, 'подключить "расчёты.dan"\nвывод(расчёты.нет(1))')
        self.assertIn("в модуле «расчёты» нет функции или типа «нет»", т)
        т = ошибка_загрузки({}, 'подключить "нет.dan"')
        self.assertIn("не найден подключаемый файл «нет.dan»", т)

    def test_расширение_можно_не_писать(self):
        self.assertIsNone(ошибка_загрузки(self.ФАЙЛЫ, 'подключить "расчёты"\nвывод(расчёты.размер(расчёты.Долг(1)))'))

    def test_стандартная_библиотека(self):
        self.assertIsNone(ошибка_загрузки({}, 'подключить "json"\nвывод(json.записать(json.Целое(1)))'))
        # свой файл с тем же именем важнее библиотечного
        т = ошибка_загрузки({"json.dan": "общий функ своя() -> цел { вернуть 1 }\n"},
                            'подключить "json"\nвывод(json.записать(json.Целое(1)))')
        self.assertIn("в модуле «json» нет функции или типа «записать»", т)
        т = ошибка_загрузки({}, 'подключить "json"\nвывод(json.разобрать_значение("1"))')
        self.assertIn("не помечено словом «общий»", т)

    def test_подключение_по_кругу(self):
        т = ошибка_загрузки({"а.dan": 'подключить "б.dan"\n', "б.dan": 'подключить "а.dan"\n'},
                            'подключить "а.dan"')
        self.assertIn("по кругу: а.dan -> б.dan -> а.dan", т)

    def test_в_модуле_только_объявления(self):
        т = ошибка_загрузки({"м.dan": 'общий функ ф() -> цел { вернуть 1 }\nвывод(1)\n'}, 'подключить "м.dan"')
        self.assertIn("м.dan: Строка 2", т)
        self.assertIn("только объявления", т)

    def test_ошибка_проверки_называет_файл(self):
        т = ошибка_загрузки({"м.dan": 'общий функ ф() -> цел {\n    вернуть "а"\n}\n'},
                            'подключить "м.dan"\nвывод(м.ф())')
        self.assertIn("Файл м.dan, строка 2", т)

    def test_ошибка_записи_в_модуле(self):
        т = ошибка_загрузки({"м.dan": 'общий функ ф() -> цел {\n    вернуть (\n}\n'}, 'подключить "м.dan"')
        self.assertTrue(т.startswith("м.dan: ошибка в записи программы"), т)

    def test_имена_не_путаются(self):
        т = ошибка_загрузки({"м.dan": 'функ ф() -> цел { вернуть 1 }\nобщий функ г(ф: цел) -> цел { вернуть ф }\n'},
                            'подключить "м.dan"')
        self.assertIn("имя «ф» уже занято функцией или типом этого модуля", т)
        т = ошибка_загрузки(self.ФАЙЛЫ, 'подключить "расчёты.dan" как р\nпусть р = 5')
        self.assertIn("имя «р» уже занято подключённым модулем", т)
        т = ошибка_загрузки(self.ФАЙЛЫ, 'подключить "расчёты.dan" как р\nвывод(р)')
        self.assertIn("«р» - подключённый модуль", т)

    def test_одинаковые_функции_в_разных_модулях(self):
        файлы = {"а.dan": 'общий функ имя() -> стр { вернуть "а" }\n',
                 "б.dan": 'общий функ имя() -> стр { вернуть "б" }\n'}
        self.assertIsNone(ошибка_загрузки(файлы, 'подключить "а.dan"\nподключить "б.dan"\nвывод(а.имя() + б.имя())'))

    def test_название_файла_не_годится_как_имя(self):
        т = ошибка_загрузки({"в.dan": ""}, 'подключить "в.dan"')
        self.assertIn('укажите имя: подключить "в.dan" как имя', т)
        self.assertIsNone(ошибка_загрузки({"в.dan": ""}, 'подключить "в.dan" как вспомогательный'))


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыВыполнения(unittest.TestCase):

    def выполнить(self, файлы, главная):
        with Папка(dict(файлы, **{"главная.dan": главная})) as п:
            путь = os.path.join(п, "главная.dan")
            исполняемый = dan.собрать(путь, главная)
            р = subprocess.run([исполняемый], capture_output=True, text=True, encoding="utf-8", timeout=30)
            return р.returncode, р.stdout.splitlines(), р.stderr

    def test_программа_из_трёх_файлов(self):
        код, вывод, _ = self.выполнить(ТестыЗагрузки.ФАЙЛЫ, """
подключить "расчёты.dan" как р
пусть требования: [р.Требование] = [р.Долг(1000), р.Пени(1000, 30)]
для т в требования {
    выбор т {
        Долг(с) { вывод("долг " + стр(с)) }
        р.Пени(_, д) { вывод("пени за " + стр(д) + " дней: " + стр(р.размер(т))) }
    }
}
пусть ит = р.итог(требования)
вывод(ит)
вывод(требования[0])
""")
        self.assertEqual(код, 0)
        self.assertEqual(вывод, ["долг 1000", "пени за 30 дней: 30", 'Итог(сумма = 1030, пояснение = "требований: 2")',
                                 "Долг(сумма = 1000)"])

    def test_ошибка_выполнения_называет_файл(self):
        код, _, ошибки = self.выполнить({"деление.dan": "общий функ ф(х: цел) -> цел {\n    вернуть частное(10, х)\n}\n"},
                                       'подключить "деление.dan"\nвывод(деление.ф(0))')
        self.assertEqual(код, 1)
        self.assertIn("в файле деление.dan, строка 2: деление на ноль", ошибки)


if __name__ == "__main__":
    unittest.main()
