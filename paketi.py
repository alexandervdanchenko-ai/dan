"""Менеджер пакетов языка Дан.

    python dan.py пакеты добавить имя адрес [версия]   - добавить пакет в проект
    python dan.py пакеты установить                   - поставить пакеты по файлу пакеты.замок.json
    python dan.py пакеты установить --заморожено      - то же, но ошибка, если замок не согласован
                                                        с пакеты.json (для автоматических проверок)
    python dan.py пакеты обновить [имя]               - перейти на версию из пакеты.json заново
    python dan.py пакеты удалить имя                  - убрать пакет из проекта
    python dan.py пакеты список                       - показать пакеты проекта
    python dan.py пакеты проверить                    - сверить пакеты с контрольными суммами
                                                        и замок с пакеты.json

Пакет - это репозиторий git (на GitHub, другом сервере или в папке на
диске) с файлами .dan. Версия - метка (tag) репозитория, например v1.2.0,
или полный номер коммита; без версии берётся последний коммит основной ветки.

Проект описывают два файла в его папке:
- пакеты.json - какие пакеты нужны: {"зависимости": {"имя": {"адрес": ..., "версия": ...}}};
- пакеты.замок.json - что именно поставлено: номер коммита и контрольная
  сумма SHA-256 всех файлов каждого пакета.
Пакеты лежат в папке «пакеты» проекта: пакеты/имя/имя.dan подключается
командой подключить "имя", пакеты/имя/другой.dan - подключить "имя/другой".

Защита от атак через пакеты (подменённые и вредоносные библиотеки):
- при установке никакой код пакета не выполняется: из репозитория
  копируются только файлы .dan, LICENSE и README; ссылки (symlink) не копируются;
- установка по замку берёт ровно записанный коммит и сверяет контрольную
  сумму: если содержимое пакета изменилось (например, метку версии
  передвинули на другой коммит), установка останавливается с ошибкой;
- поставленный пакет запоминается в папке пользователя (кэш Дана, папка
  «пакеты») под своей контрольной суммой; установка по замку на том же
  компьютере берёт его оттуда без сети, сверив сумму (DAN_NO_CACHE=1 отключает);
- зависимости пакетов (их файлы пакеты.json) ставятся в ту же папку; если
  двум пакетам нужны разные версии одного пакета, это ошибка, а не
  молчаливый выбор одной из них.
"""

import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile

ФАЙЛ = "пакеты.json"
ЗАМОК = "пакеты.замок.json"
ПАПКА = "пакеты"
КОПИРУЕМЫЕ = re.compile(r"^(?:.*\.dan|LICENSE(?:\..*)?|README(?:\..*)?|пакеты\.json)$", re.I)
ИМЯ = re.compile(r"^[^\W\d]\w*$")


class ОшибкаПакетов(Exception):
    pass


def найти_проект(откуда):
    """Папка проекта: ближайшая (вверх от «откуда») папка с файлом пакеты.json."""
    папка = os.path.abspath(откуда if os.path.isdir(откуда) else os.path.dirname(откуда))
    while True:
        if os.path.isfile(os.path.join(папка, ФАЙЛ)):
            return папка
        выше = os.path.dirname(папка)
        if выше == папка:
            return None
        папка = выше


def папка_пакетов(путь_программы):
    """Папка «пакеты» проекта, к которому относится программа, или None."""
    проект = найти_проект(путь_программы)
    if проект is None:
        return None
    папка = os.path.join(проект, ПАПКА)
    return папка if os.path.isdir(папка) else None


def _читать(путь, по_умолчанию):
    if not os.path.exists(путь):
        return по_умолчанию
    try:
        with open(путь, encoding="utf-8") as ф:
            return json.load(ф)
    except (ValueError, OSError) as о:
        raise ОшибкаПакетов(f"файл {os.path.basename(путь)} повреждён: {о}") from None


def _записать(путь, данные):
    with open(путь, "w", encoding="utf-8", newline="\n") as ф:
        json.dump(данные, ф, ensure_ascii=False, indent=2, sort_keys=True)
        ф.write("\n")


def _git(*аргументы, папка=None):
    if not shutil.which("git"):
        raise ОшибкаПакетов("для работы с пакетами нужна программа git (в Windows: winget install Git.Git)")
    окружение = dict(os.environ, GIT_TERMINAL_PROMPT="0", GIT_CONFIG_NOSYSTEM="1")
    р = subprocess.run(["git", "-c", "core.hooksPath=" + os.devnull, "-c", "protocol.file.allow=always",
                        *аргументы], cwd=папка, capture_output=True, text=True, encoding="utf-8",
                       errors="replace", env=окружение)
    if р.returncode != 0:
        raise ОшибкаПакетов(р.stderr.strip() or р.stdout.strip() or "ошибка git")
    return р.stdout.strip()


def контрольная_сумма(папка):
    """SHA-256 от имён и содержимого всех файлов папки (в порядке имён)."""
    сумма = hashlib.sha256()
    for корень, папки, файлы in os.walk(папка):
        папки.sort()
        for имя in sorted(файлы):
            путь = os.path.join(корень, имя)
            относительный = os.path.relpath(путь, папка).replace(os.sep, "/")
            сумма.update(относительный.encode("utf-8") + b"\0")
            with open(путь, "rb") as ф:
                сумма.update(ф.read())
            сумма.update(b"\0")
    return сумма.hexdigest()


def _загрузить(адрес, версия, коммит=None):
    """Копия репозитория во временной папке: (папка, коммит). Ничего из репозитория не выполняется."""
    временная = tempfile.mkdtemp(prefix="dan_pkg_")
    try:
        _git("init", "-q", временная)
        _git("remote", "add", "origin", адрес, папка=временная)
        цель = коммит or версия or "HEAD"
        try:
            _git("fetch", "-q", "--depth", "1", "--no-recurse-submodules", "origin", цель, папка=временная)
        except ОшибкаПакетов:
            if версия and not коммит:
                _git("fetch", "-q", "--depth", "1", "--no-recurse-submodules", "origin", f"refs/tags/{версия}",
                     папка=временная)
            else:
                raise
        _git("checkout", "-q", "FETCH_HEAD", папка=временная)
        полученный = _git("rev-parse", "HEAD", папка=временная)
        if коммит and полученный != коммит:
            raise ОшибкаПакетов(f"вместо коммита {коммит} получен {полученный}")
        return временная, полученный
    except ОшибкаПакетов as о:
        shutil.rmtree(временная, ignore_errors=True)
        raise ОшибкаПакетов(f"не удалось получить пакет из {адрес} (версия {версия or 'последняя'}): {о}") from None


def _скопировать(откуда, куда):
    """Только файлы .dan, LICENSE, README и пакеты.json; ссылки и служебная папка .git пропускаются."""
    if os.path.exists(куда):
        shutil.rmtree(куда)
    os.makedirs(куда)
    for корень, папки, файлы in os.walk(откуда):
        папки[:] = sorted(п for п in папки if п != ".git" and not os.path.islink(os.path.join(корень, п)))
        for имя in sorted(файлы):
            путь = os.path.join(корень, имя)
            if os.path.islink(путь) or not os.path.isfile(путь) or not КОПИРУЕМЫЕ.match(имя):
                continue
            цель = os.path.join(куда, os.path.relpath(путь, откуда))
            os.makedirs(os.path.dirname(цель), exist_ok=True)
            shutil.copyfile(путь, цель)


def хранилище():
    """Папка запомненных пакетов в кэше Дана или None, если кэш отключён."""
    if os.environ.get("DAN_NO_CACHE") == "1":
        return None
    # та же папка, что у кэша собранных программ в dan.py (папка_кэша)
    if os.environ.get("DAN_CACHE"):
        кэш = os.environ["DAN_CACHE"]
    elif os.name == "nt":
        кэш = os.path.join(os.environ.get("LOCALAPPDATA") or os.path.expanduser("~"), "Dan", "cache")
    else:
        кэш = os.path.join(os.environ.get("XDG_CACHE_HOME") or os.path.expanduser("~/.cache"), "dan")
    return os.path.join(кэш, ПАПКА)


def _взять_из_хранилища(сумма, куда):
    папка = хранилище()
    if not папка or not re.fullmatch(r"[0-9a-f]{64}", сумма or ""):
        return False
    откуда = os.path.join(папка, сумма)
    try:
        if not os.path.isdir(откуда) or контрольная_сумма(откуда) != сумма:
            return False
        if os.path.exists(куда):
            shutil.rmtree(куда)
        shutil.copytree(откуда, куда)
        return контрольная_сумма(куда) == сумма
    except OSError:
        return False


def _запомнить(сумма, откуда):
    папка = хранилище()
    if not папка:
        return
    цель = os.path.join(папка, сумма)
    if os.path.isdir(цель):
        return
    временная = цель + f".{os.getpid()}.tmp"
    try:
        os.makedirs(папка, exist_ok=True)
        shutil.copytree(откуда, временная)
        os.replace(временная, цель)
    except OSError:
        shutil.rmtree(временная, ignore_errors=True)     # хранилище - только ускорение


class Проект:
    def __init__(self, папка):
        self.папка = os.path.abspath(папка)
        self.описание = _читать(os.path.join(self.папка, ФАЙЛ), {"зависимости": {}})
        self.описание.setdefault("зависимости", {})
        self.замок = _читать(os.path.join(self.папка, ЗАМОК), {})
        self.сообщения = []

    def сохранить(self):
        _записать(os.path.join(self.папка, ФАЙЛ), self.описание)
        _записать(os.path.join(self.папка, ЗАМОК), self.замок)

    def папка_пакета(self, имя):
        return os.path.join(self.папка, ПАПКА, имя)

    def _поставить(self, имя, адрес, версия, коммит=None, сумма=None, нужен_для=None):
        """Получает пакет, кладёт его в папку «пакеты» и записывает в замок; затем его зависимости."""
        if not ИМЯ.match(имя):
            raise ОшибкаПакетов(f"«{имя}» не годится как имя пакета: оно должно быть именем Дана (буквы, цифры, «_»)")
        прежний = self.замок.get(имя)
        if нужен_для and прежний and (прежний["адрес"] != адрес or (версия or "") != (прежний.get("версия") or "")):
            raise ОшибкаПакетов(f"пакету «{нужен_для}» нужен «{имя}» версии {версия or 'последней'} из {адрес}, "
                                f"а в проекте уже есть «{имя}» версии {прежний.get('версия') or 'последней'} "
                                f"из {прежний['адрес']}; согласуйте версии")
        if коммит and сумма and _взять_из_хранилища(сумма, self.папка_пакета(имя)):
            полученный = коммит                  # тот же коммит уже ставился на этом компьютере
            откуда = " (из кэша)"
        else:
            временная, полученный = _загрузить(адрес, версия, коммит)
            try:
                _скопировать(временная, self.папка_пакета(имя))
            finally:
                shutil.rmtree(временная, ignore_errors=True)
            откуда = ""
        новая_сумма = контрольная_сумма(self.папка_пакета(имя))
        if сумма and новая_сумма != сумма:
            shutil.rmtree(self.папка_пакета(имя), ignore_errors=True)
            raise ОшибкаПакетов(f"содержимое пакета «{имя}» не совпадает с записанным в {ЗАМОК}: коммит {полученный} "
                                f"даёт другую контрольную сумму. Возможно, пакет подменили; установка остановлена")
        if not os.path.isfile(os.path.join(self.папка_пакета(имя), имя + ".dan")):
            self.сообщения.append(f"предупреждение: в пакете «{имя}» нет файла {имя}.dan; подключайте его файлы "
                                  f"так: подключить \"{имя}/файл\"")
        self.замок[имя] = {"адрес": адрес, "версия": версия or "", "коммит": полученный, "сумма": новая_сумма}
        if нужен_для:
            self.замок[имя]["нужен_для"] = нужен_для
        _запомнить(новая_сумма, self.папка_пакета(имя))
        self.сообщения.append(f"{имя}: {версия or 'последняя версия'}, коммит {полученный[:12]}{откуда}")
        # зависимости самого пакета
        свои = _читать(os.path.join(self.папка_пакета(имя), ФАЙЛ), {}).get("зависимости", {})
        for зависимость, о in sorted(свои.items()):
            уже = self.замок.get(зависимость)
            if уже and уже["адрес"] == о["адрес"] and (уже.get("версия") or "") == (о.get("версия") or ""):
                continue
            self._поставить(зависимость, о["адрес"], о.get("версия"), нужен_для=имя)

    def добавить(self, имя, адрес, версия=None):
        if os.path.isdir(адрес):
            адрес = os.path.abspath(адрес)
        self._поставить(имя, адрес, версия)
        self.описание["зависимости"][имя] = {"адрес": адрес, "версия": версия or ""}
        self.сохранить()

    def несогласованность(self):
        """Расхождения между пакеты.json и замком: пакеты, которых нет в замке, или с другой версией."""
        итог = []
        нужные = self.описание["зависимости"]
        for имя, о in sorted(нужные.items()):
            з = self.замок.get(имя)
            if з is None:
                итог.append(f"{имя}: есть в {ФАЙЛ}, но не записан в {ЗАМОК}")
            elif з["адрес"] != о["адрес"] or (з.get("версия") or "") != (о.get("версия") or ""):
                итог.append(f"{имя}: в {ФАЙЛ} версия {о.get('версия') or 'последняя'} из {о['адрес']}, "
                            f"а в {ЗАМОК} - {з.get('версия') or 'последняя'} из {з['адрес']}")
        for имя, з in sorted(self.замок.items()):
            if имя not in нужные and not з.get("нужен_для"):
                итог.append(f"{имя}: записан в {ЗАМОК}, но его нет в {ФАЙЛ}")
        return итог

    def установить(self, заморожено=False):
        """Ставит пакеты ровно по замку; пакеты без записи в замке получает заново.
        С заморожено=True замок не меняется: расхождение с пакеты.json - ошибка."""
        if заморожено:
            расхождения = self.несогласованность()
            if расхождения:
                raise ОшибкаПакетов("замок не согласован с " + ФАЙЛ + " (выполните: python dan.py пакеты "
                                    "обновить):\n  " + "\n  ".join(расхождения))
        for имя, о in sorted(self.описание["зависимости"].items()):
            if имя not in self.замок:
                self._поставить(имя, о["адрес"], о.get("версия"))
        for имя, з in sorted(self.замок.items()):
            папка = self.папка_пакета(имя)
            if os.path.isdir(папка) and контрольная_сумма(папка) == з["сумма"]:
                self.сообщения.append(f"{имя}: уже поставлен")
                continue
            self._поставить(имя, з["адрес"], з.get("версия"), коммит=з["коммит"], сумма=з["сумма"],
                            нужен_для=з.get("нужен_для"))
        self.сохранить()

    def обновить(self, только=None):
        for имя, о in sorted(self.описание["зависимости"].items()):
            if только and имя != только:
                continue
            прежний = self.замок.pop(имя, {}).get("коммит")
            self._поставить(имя, о["адрес"], о.get("версия"))
            новый = self.замок[имя]["коммит"]
            self.сообщения.append(f"{имя}: {'без изменений' if новый == прежний else 'обновлён'}")
        if только and только not in self.описание["зависимости"]:
            raise ОшибкаПакетов(f"в проекте нет пакета «{только}»")
        self.сохранить()

    def удалить(self, имя):
        if имя not in self.описание["зависимости"] and имя not in self.замок:
            raise ОшибкаПакетов(f"в проекте нет пакета «{имя}»")
        self.описание["зависимости"].pop(имя, None)
        self.замок.pop(имя, None)
        # зависимости, которые были нужны только ему
        for другое, з in list(self.замок.items()):
            if з.get("нужен_для") == имя and другое not in self.описание["зависимости"]:
                self.замок.pop(другое)
                shutil.rmtree(self.папка_пакета(другое), ignore_errors=True)
        shutil.rmtree(self.папка_пакета(имя), ignore_errors=True)
        self.сохранить()

    def проверить(self):
        """Список расхождений между папкой «пакеты» и замком."""
        расхождения = self.несогласованность()
        for имя, з in sorted(self.замок.items()):
            папка = self.папка_пакета(имя)
            if not os.path.isdir(папка):
                расхождения.append(f"{имя}: не поставлен (выполните: python dan.py пакеты установить)")
            elif контрольная_сумма(папка) != з["сумма"]:
                расхождения.append(f"{имя}: файлы пакета изменены после установки")
        return расхождения


def команда(аргументы, папка=None):
    """Выполняет команду «пакеты ...»; возвращает код завершения."""
    папка = папка or os.getcwd()
    if not аргументы:
        print(__doc__.strip())
        return 2
    действие, остальное = аргументы[0], аргументы[1:]
    проект_папка = найти_проект(папка) or папка
    проект = None
    try:
        проект = Проект(проект_папка)
        if действие == "добавить" and len(остальное) in (2, 3):
            проект.добавить(остальное[0], остальное[1], остальное[2] if len(остальное) == 3 else None)
        elif действие == "установить" and остальное in ([], ["--заморожено"]):
            проект.установить(заморожено=bool(остальное))
        elif действие == "обновить" and len(остальное) <= 1:
            проект.обновить(остальное[0] if остальное else None)
        elif действие == "удалить" and len(остальное) == 1:
            проект.удалить(остальное[0])
            проект.сообщения.append(f"{остальное[0]}: удалён")
        elif действие == "список" and not остальное:
            if not проект.замок:
                print("В проекте нет пакетов")
            for имя, з in sorted(проект.замок.items()):
                откуда = f" (нужен для {з['нужен_для']})" if з.get("нужен_для") else ""
                print(f"{имя}  {з.get('версия') or 'последняя'}  {з['коммит'][:12]}  {з['адрес']}{откуда}")
            return 0
        elif действие == "проверить" and not остальное:
            расхождения = проект.проверить()
            for р in расхождения:
                print(р)
            if not расхождения:
                print("Пакеты совпадают с контрольными суммами замка")
            return 1 if расхождения else 0
        else:
            print(__doc__.strip())
            return 2
    except ОшибкаПакетов as о:
        for с in (проект.сообщения if проект else []):
            print(с)
        print(f"Ошибка: {о}")
        return 1
    for с in проект.сообщения:
        print(с)
    return 0
