"""Перекрёстная проверка вычислений и действий со строками с независимым эталоном на Python.

Случайные выражения с целыми числами, обыкновенными дробями и дробными
числами вычисляются программой на Дане и эталоном, написанным прямо по
правилам spec.md: деление с остатком по школьному определению (остаток не
бывает отрицательным), переполнение типа цел и дроби с числителем вне
симметричного диапазона - ошибка выполнения, дробные числа - двойной
точности с кратчайшей точной записью. Ответы должны совпасть; выражения,
на которых эталон обнаруживает переполнение или деление на ноль, должны
остановить программу с сообщением, а не дать какое-либо число.

Запуск: python sverka_vychisleniy.py [число_выражений] [зерно]
"""

import math
import os
import random
import subprocess
import sys
import tempfile
from fractions import Fraction

import dan

МАКС = 2 ** 63 - 1
МИН = -2 ** 63


class Переполнение(Exception):
    pass


class НаНоль(Exception):
    pass


def _проверить(x):
    if isinstance(x, int) and not МИН <= x <= МАКС:
        raise Переполнение
    if isinstance(x, Fraction) and not (-МАКС <= x.numerator <= МАКС and x.denominator <= МАКС):
        raise Переполнение
    return x


def _дел(а, б):
    if б == 0:
        raise НаНоль
    if isinstance(а, int) and isinstance(б, int):
        ч = а // б
        if а - ч * б < 0:
            ч += -1 if б > 0 else 1
        return _проверить(ч)
    return _проверить(Fraction(а) / Fraction(б))


def вычислить(д):
    """Значение дерева выражения по правилам Дана."""
    if not isinstance(д, tuple):
        return д
    оп = д[0]
    if оп == "^":
        а, н = вычислить(д[1]), д[2]
        return _проверить(а ** н if isinstance(а, int) else Fraction(а) ** н)
    а, б = вычислить(д[1]), вычислить(д[2])
    if оп == "+":
        return _проверить(а + б)
    if оп == "-":
        return _проверить(а - б)
    if оп == "*":
        return _проверить(а * б)
    if оп == "/":
        return _дел(а, б)
    return _проверить(а - _дел(а, б) * б)       # «%»


def показать(з):
    if isinstance(з, Fraction):
        return str(з.numerator) if з.denominator == 1 else f"{з.numerator}/{з.denominator}"
    return str(з)


def случайное(сл, глубина, только_целые):
    """(текст на Дане, дерево, целое ли значение)."""
    if глубина == 0 or сл.random() < 0.3:
        if not только_целые and сл.random() < 0.3:
            ч, з = сл.randint(-20, 20), сл.randint(1, 12)
            return f"рац({ч}, {з})", Fraction(ч, з), False
        ч = сл.choice([сл.randint(-30, 30), сл.randint(-10 ** 6, 10 ** 6),
                        сл.choice([0, 1, -1, 2 ** 31, 2 ** 62, -2 ** 62])])
        return (f"({ч})" if ч < 0 else str(ч)), ч, True
    оп = сл.choice(["+", "-", "*", "/", "%", "^"])
    тл, дл, цл = случайное(сл, глубина - 1, только_целые)
    if оп == "^":
        н = сл.randint(0, 5)
        return f"({тл}) ^ {н}", ("^", дл, н), цл
    тп, дп, цп = случайное(сл, глубина - 1, только_целые or оп == "%")
    if оп == "%" and not (цл and цп):
        оп = "+"
    return f"({тл} {оп} {тп})", (оп, дл, дп), цл and цп


def случайное_дробное(сл, глубина):
    if глубина == 0 or сл.random() < 0.3:
        x = сл.choice([сл.uniform(-1000, 1000), сл.uniform(-1, 1), float(сл.randint(-50, 50)), 0.1, 0.2, 123456.789])
        return (f"({x!r})" if x < 0 else repr(x)), x
    оп = сл.choice("+-*/")
    тл, зл = случайное_дробное(сл, глубина - 1)
    тп, зп = случайное_дробное(сл, глубина - 1)
    if оп == "/" and зп == 0:
        оп = "+"
    з = {"+": зл + зп, "-": зл - зп, "*": зл * зп, "/": зл / зп if зп else 0.0}[оп]
    return f"({тл} {оп} {тп})", з


def _выполнить(текст, папка):
    путь = os.path.join(папка, "сверка.dan")
    with open(путь, "w", encoding="utf-8") as ф:
        ф.write(текст)
    р = subprocess.run([dan.собрать(путь, текст)], capture_output=True, text=True, encoding="utf-8")
    return р.returncode, р.stdout.splitlines(), р.stderr


def сверить(число=1500, зерно=1, ошибочных=20):
    """Возвращает список расхождений (выражение, ожидалось, получено)."""
    сл = random.Random(зерно)
    точные, ошибки = [], []
    while len(точные) < число or len(ошибки) < ошибочных:
        т, д, _ = случайное(сл, сл.randint(1, 4), сл.random() < 0.5)
        try:
            if len(точные) < число:
                точные.append((т, показать(вычислить(д))))
        except (Переполнение, НаНоль, ValueError):
            if len(ошибки) < ошибочных:
                ошибки.append(т)
    дробные = []
    while len(дробные) < число:
        т, з = случайное_дробное(сл, сл.randint(1, 4))
        if math.isfinite(з) and "e" not in repr(з) and "e" not in т:
            дробные.append((т, repr(з)))
    расхождения = []
    with tempfile.TemporaryDirectory() as папка:
        for пары in (точные, дробные):
            код, строки, сообщение = _выполнить("".join(f"вывод({т})\n" for т, _ in пары), папка)
            if код != 0:
                расхождения.append(("программа сверки", "код 0", f"код {код}: {сообщение.strip()}"))
            for (т, ожидалось), получено in zip(пары, строки + [""] * len(пары)):
                if ожидалось != получено:
                    расхождения.append((т, ожидалось, получено))
        for т in ошибки:
            код, строки, сообщение = _выполнить(f"вывод({т})\n", папка)
            if код != 1 or "Ошибка выполнения" not in сообщение:
                расхождения.append((т, "ошибка выполнения", " ".join(строки) or f"код {код}"))
    return расхождения



АЛФАВИТ = (list("абвгдеёжзийклмнопрстуфхцчшщъыьэюяАБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯabcxyzABCXYZ0123456789")
           + [" ", " ", " ", ",", ".", "-", "\t", "😀", "№", "«", "»"])


def _лит(с):
    return '"' + с.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t") + '"'


def _список_строк(л):
    return "[" + ", ".join('"' + x.replace("\\", "\\\\").replace('"', '\\"') + '"' for x in л) + "]"


def случаи_строк(сл, число):
    """Пары (выражение на Дане, ожидаемый вывод) для действий со строками."""
    def строка(н=None):
        return "".join(сл.choice(АЛФАВИТ) for _ in range(сл.randint(0, 12) if н is None else н))
    итог = []
    while len(итог) < число:
        с = строка()
        вид = сл.randrange(11)
        if вид == 0:
            итог.append((f"{_лит(с)}.длина", str(len(с))))
        elif вид == 1:
            итог.append((f"{_лит(с)}.прописные()", с.upper()))
        elif вид == 2:
            итог.append((f"{_лит(с)}.строчные()", с.lower()))
        elif вид == 3 and с:
            а = сл.randrange(len(с))
            б = сл.randrange(а - 1, len(с))
            итог.append((f"{_лит(с)}[{а}..{б}]", с[а:б + 1]))
        elif вид == 4:
            т = сл.choice([строка(1), строка(2), с[1:3]]) or "а"
            итог.append((f"{_лит(с)}.найти({_лит(т)})", str(с.find(т))))
        elif вид == 5:
            т = сл.choice([строка(1), с[:2]]) or "а"
            з = строка(сл.randint(0, 3))
            итог.append((f"{_лит(с)}.заменить({_лит(т)}, {_лит(з)})", с.replace(т, з)))
        elif вид == 6:
            итог.append((f"{_лит(с)}.разбить()", _список_строк(с.split())))
        elif вид == 7:
            р = сл.choice([",", " ", "а"])
            итог.append((f"{_лит(с)}.разбить({_лит(р)})", _список_строк(с.split(р))))
        elif вид == 8:
            итог.append((f"{_лит(с)}.обрезать()", с.strip(" \t\n\r")))
        elif вид == 9:
            т = строка(сл.randint(0, 2))
            итог.append((f"стр({_лит(с)} < {_лит(т)})", "истина" if с < т else "ложь"))
        elif вид == 10:
            итог.append((f"{_лит(с)}.символы().длина", str(len(с))))
    return итог


def сверить_строки(число=3000, зерно=1):
    """Действия со строками в Дане и в Python (по символам Юникода) должны совпасть."""
    случаи = случаи_строк(random.Random(зерно), число)
    with tempfile.TemporaryDirectory() as папка:
        путь = os.path.join(папка, "строки.dan")
        текст = "".join(f"вывод({в})\n" for в, _ in случаи)
        with open(путь, "w", encoding="utf-8") as ф:
            ф.write(текст)
        р = subprocess.run([dan.собрать(путь, текст)], capture_output=True, text=True, encoding="utf-8")
    строки = р.stdout.split("\n")
    расхождения = [] if р.returncode == 0 else [("программа сверки", "код 0", р.stderr.strip())]
    for (в, ожидалось), получено in zip(случаи, строки + [""] * len(случаи)):
        if ожидалось != получено:
            расхождения.append((в, ожидалось, получено))
    return расхождения


def программа_значений(сл):
    """Случайная программа со списками списков и словарём: присваивания, изменения, вызовы функций.

    Эталон - Python, где каждое присваивание и каждая передача делают полную копию
    (copy.deepcopy). В Дане копия отложенная, до первого изменения (spec.md, 7.3),
    но видимый результат обязан быть тем же: изменение одной переменной никогда
    не меняет другую."""
    import copy
    имена = ["а", "б", "г", "д"]
    знач, словарь_, ожидается = {}, {}, []
    строки = ["функ с_добавкой(с: [[цел]], ч: цел) -> [[цел]] {", "    перем р = с", "    р.добавить([ч])",
              "    если р[0].длина > 0 { р[0][0] = ч }", "    вернуть р", "}",
              "функ сумма_всех(с: [[цел]]) -> цел {", "    перем итог = 0",
              "    для часть в с { для х в часть { итог += х } }", "    вернуть итог", "}"]
    for имя in имена:
        знач[имя] = [[сл.randint(0, 9) for _ in range(сл.randint(0, 3))] for _ in range(сл.randint(1, 3))]
        строки.append(f"перем {имя}: [[цел]] = {знач[имя]}")
    строки.append("перем сл: {стр: [[цел]]} = {}")
    for _ in range(сл.randint(5, 25)):
        х, у_ = сл.choice(имена), сл.choice(имена)
        вид = сл.randrange(9)
        if вид == 0:
            строки.append(f"{х} = {у_}")
            знач[х] = copy.deepcopy(знач[у_])
        elif вид == 1:
            ч = сл.randint(0, 99)
            строки.append(f"{х}.добавить([{ч}])")
            знач[х].append([ч])
        elif вид == 2 and знач[х]:
            и, ч = сл.randrange(len(знач[х])), сл.randint(0, 99)
            строки.append(f"{х}[{и}].добавить({ч})")
            знач[х][и].append(ч)
        elif вид == 3 and any(знач[х]):
            и = сл.choice([к for к, ч in enumerate(знач[х]) if ч])
            к, ч = сл.randrange(len(знач[х][и])), сл.randint(0, 99)
            строки.append(f"{х}[{и}][{к}] = {ч}")
            знач[х][и][к] = ч
        elif вид == 4 and знач[у_]:
            и = сл.randrange(len(знач[у_]))
            строки.append(f"{х}.добавить({у_}[{и}])")
            знач[х].append(copy.deepcopy(знач[у_][и]))
        elif вид == 5:
            ч = сл.randint(0, 99)
            строки.append(f"{х} = с_добавкой({у_}, {ч})")
            р = copy.deepcopy(знач[у_])
            р.append([ч])
            if р[0]:
                р[0][0] = ч
            знач[х] = р
        elif вид == 6 and len(знач[х]) > 1:
            и = сл.randrange(len(знач[х]))
            строки.append(f"{х}.удалить({и})")
            del знач[х][и]
        elif вид == 7:
            к = сл.choice(["к1", "к2"])
            строки.append(f'сл["{к}"] = {у_}')
            словарь_[к] = copy.deepcopy(знач[у_])
        elif вид == 8 and словарь_:
            к = сл.choice(sorted(словарь_))
            строки.append(f'{х} = сл["{к}"]')
            знач[х] = copy.deepcopy(словарь_[к])
            if знач[х]:
                строки.append(f"{х}[0].добавить(7)")
                знач[х][0].append(7)
        if сл.random() < 0.3:
            ч = сл.choice(имена)
            строки += [f"вывод({ч})", f"вывод(сумма_всех({ч}))"]
            ожидается += [str(знач[ч]), str(sum(sum(п) for п in знач[ч]))]
    for имя in имена:
        строки.append(f"вывод({имя})")
        ожидается.append(str(знач[имя]))
    for к in sorted(словарь_):
        строки.append(f'вывод(сл["{к}"])')
        ожидается.append(str(словарь_[к]))
    return "\n".join(строки) + "\n", ожидается


def сверить_значения(число=100, зерно=1):
    """Списки и словари ведут себя как значения: результат совпадает с эталоном с полным копированием."""
    сл = random.Random(зерно)
    расхождения = []
    with tempfile.TemporaryDirectory() as папка:
        for _ in range(число):
            текст, ожидается = программа_значений(сл)
            код, строки, сообщение = _выполнить(текст, папка)
            if код != 0 or строки != ожидается:
                расхождения.append((текст, "\n".join(ожидается), "\n".join(строки) + сообщение))
    return расхождения

if __name__ == "__main__":
    число = int(sys.argv[1]) if len(sys.argv) > 1 else 1500
    зерно = int(sys.argv[2]) if len(sys.argv) > 2 else 1
    найдено = сверить(число, зерно) + сверить_строки(число, зерно) + сверить_значения(max(1, число // 15), зерно)
    for т, ож, пол in найдено[:20]:
        print(f"{т}\n  ожидалось: {ож}\n  получено:  {пол}")
    print(f"Сверено выражений: {2 * число} с числами, {число} со строками и 20 с обязательной ошибкой, "
          f"программ со значениями: {max(1, число // 15)}; расхождений: {len(найдено)}")
    sys.exit(1 if найдено else 0)
