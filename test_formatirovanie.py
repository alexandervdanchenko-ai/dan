"""Тесты форматирования (formatirovanie.py)."""

import glob
import os
import random
import unittest

from formatirovanie import отформатировать, ОшибкаФорматирования
import ustoychivost

ПАПКА = os.path.dirname(os.path.abspath(__file__))


class ТестыФорматирования(unittest.TestCase):

    def проверить(self, было, стало):
        self.assertEqual(отформатировать(было), стало)
        self.assertEqual(отформатировать(стало), стало)

    def test_пробелы_у_знаков(self):
        self.проверить("пусть а=1+2*3\nперем б=-а\nб+=а%2\nвывод(а==б и не(а<б))\n",
                       "пусть а = 1 + 2 * 3\nперем б = -а\nб += а % 2\nвывод(а == б и не (а < б))\n")
        self.проверить("вывод( ф( 1 ,2 ) [ 0 ] )\n", "вывод(ф(1, 2)[0])\n")
        self.проверить("пусть с = [ -1, - 2 ]\nвывод(5 - -3)\nвывод(х²+(а+б)³)\n",
                       "пусть с = [-1, -2]\nвывод(5 - -3)\nвывод(х² + (а + б)³)\n")

    def test_блоки_и_отступы(self):
        self.проверить("функ ф(х:цел)->цел{\nесли х>0{вернуть х}\n  иначе {\n вернуть -х\n}\n}\n",
                       "функ ф(х: цел) -> цел {\n    если х > 0 { вернуть х }\n    иначе {\n        вернуть -х\n    }\n}\n")
        self.проверить("вывод(сумма([1,\n2,\n3]))\n", "вывод(сумма([1,\n    2,\n    3]))\n")
        self.проверить("пусть о = json.Объект({\n\"а\": 1\n})\n", "пусть о = json.Объект({\n    \"а\": 1\n})\n")

    def test_словари_и_типы(self):
        self.проверить("пусть с: { стр : цел } = { \"а\": 1 }\nпусть п = {}\nпусть к: канал<{стр: цел}> = канал()\n",
                       "пусть с: {стр : цел} = {\"а\": 1}\nпусть п = {}\nпусть к: канал<{стр: цел}> = канал()\n")
        self.проверить("функ ф<Т: Упорядоченное>(а: [Т]) -> Пара<Т, цел>? { вернуть ничего }\n",
                       "функ ф<Т: Упорядоченное>(а: [Т]) -> Пара<Т, цел>? { вернуть ничего }\n")
        self.проверить("пусть г = функ(х) = х * 2\nпусть з = ф()!\nвывод(ф() иначе 0)\n",
                       "пусть г = функ(х) = х * 2\nпусть з = ф()!\nвывод(ф() иначе 0)\n")

    def test_комментарии_и_пустые_строки(self):
        self.проверить("\n\n// заголовок\nпусть а = 1      // выравнено\n\n\n\nпусть бб = 22   // тоже\n\n\n",
                       "// заголовок\nпусть а = 1      // выравнено\n\nпусть бб = 22   // тоже\n")
        self.проверить("вывод(\"http://адрес//не комментарий\")   // а это комментарий\n",
                       "вывод(\"http://адрес//не комментарий\")   // а это комментарий\n")

    def test_написание_сохраняется(self):
        self.проверить("пусть счётчик = 1_000_000 × 2 − 3\nвывод(6 : 3)\nвывод(\"а\\tб\\\"\")\n",
                       "пусть счётчик = 1_000_000 × 2 − 3\nвывод(6 : 3)\nвывод(\"а\\tб\\\"\")\n")

    def test_ошибка_записи_не_форматируется(self):
        with self.assertRaises(ОшибкаФорматирования):
            отформатировать("вывод(\"не закрыта)\n")

    def test_все_программы_проекта(self):
        """Форматирование не меняет токены и повторное форматирование ничего не меняет."""
        for путь in glob.glob(os.path.join(ПАПКА, "**", "*.dan"), recursive=True):
            try:
                with open(путь, encoding="utf-8") as ф:
                    текст = ф.read()
                один = отформатировать(текст)
            except (UnicodeDecodeError, ОшибкаФорматирования):
                continue        # в каталоге ошибок есть программы с ошибками записи
            with self.subTest(путь=путь):
                self.assertEqual(отформатировать(один), один)

    def test_точки_не_склеиваются(self):
        # находка проверки испорченных программ на каталоге отказов: «к. . очистить()» превращалось в «к..очистить()»
        for текст, нужно in (("к. . очистить()\n", "к. .очистить()\n"), ("а = 1 . 5\n", "а = 1 .5\n"),
                             ("для к в 0 .. 5 { }\n", "для к в 0..5 {}\n"), ("х = 1.5\n", "х = 1.5\n")):
            with self.subTest(текст=текст):
                self.assertEqual(отформатировать(текст), нужно)

    def test_испорченные_программы(self):
        """Случайно изменённые программы: либо ошибка записи, либо тот же смысл (проверяет сам форматировщик)."""
        сл = random.Random(5)
        исходные = ustoychivost.исходники()
        for _ in range(400):
            текст = ustoychivost.испортить(сл.choice(исходные), сл)
            try:
                один = отформатировать(текст)
            except ОшибкаФорматирования as о:
                self.assertNotIn("внутренняя ошибка", str(о), текст[:300])
                continue
            self.assertEqual(отформатировать(один), один)


if __name__ == "__main__":
    unittest.main()
