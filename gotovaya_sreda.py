"""Заранее собранная среда выполнения: большие библиотеки среды (данные, PDF, система,
сеть, база данных, математика) собираются компилятором C один раз и хранятся в кэше Дана
как объектные файлы; программа собирается только из своей части кода C и компонуется
с готовыми частями.

Код C программы (то, что печатает «dan си») не меняется: он по-прежнему самодостаточен.
Разделение делается при сборке:

- часть программы - весь код C, в котором тела функций библиотек заменены объявлениями,
  а переменные состояния среды (память, перехват ошибок) и функции среды, которые
  вызывают библиотеки, сделаны видимыми для компоновщика (без «static»);
- часть библиотеки - код C небольшой «образцовой» программы, которая пользуется только
  этой библиотекой: её начало (среда и нужные библиотеке типы) с объявлениями вместо
  функций среды и переменными состояния «extern», и тела функций библиотеки без «static».

Части библиотек не зависят от программы: типы, которыми пользуются библиотеки, создаются
по одним и тем же шаблонам, поэтому одна готовая часть подходит любой программе.
Готовые части хранятся в «<кэш>/среда/<отпечаток>.o»; отпечаток - SHA-256 текста части,
компилятора, параметров, системы и версии Дана.

Разделение не делается для сборок с отладкой, профилем, покрытием и параллельными
задачами (там среда другая), для окон и при DAN_NO_CACHE=1.
"""

import hashlib
import os
import re
import sys

import dannye
import kodogen
import matematika
import sistema
import vysshaya

# группа: имя, образцовая программа на Дане, тексты библиотеки (в порядке, в котором они
# стоят в коде C). Группы идут в том же порядке, что и в коде C (kodogen.Генератор.программа).
ГРУППЫ = [
    ("данные", 'вывод(хеш("а"))\n', lambda: [dannye.код_c()]),
    ("pdf", 'если пусть т = текст_pdf(байты("а")) { вывод(т) }\n', lambda: [dannye.код_pdf()]),
    ("система", "вывод(сегодня())\n", lambda: [sistema.код_c()]),
    ("сеть", "вывод(дата_для_письма())\n", lambda: [sistema.код_сети()]),
    ("база", 'если пусть б = база_открыть("а") { база_закрыть(б) }\n', lambda: [sistema.код_базы()]),
    ("математика", "вывод(синус(1.0))\n", lambda: ["\n".join([
        matematika.КОД_C, matematika.код_c_дополнения(), matematika._код_многочленов_строки(),
        matematika.КОД_МНОГОЧЛЕНОВ, vysshaya.КОД_C])]),
]

# признаки сборок, для которых готовая среда не годится
НЕ_ДЛЯ = ("#define DAN_DEBUG 1", "#define DAN_PROF_COUNT", "#define DAN_COV_COUNT", "#define DAN_TASKS 1",
          "#define DAN_GUI 1")

_ИМЯ = re.compile(r"[A-Za-z_]\w*")


# ---------- разбор кода C среды ----------
# Код среды написан в одном виде: объявления на уровне файла начинаются с начала строки,
# тело функции заканчивается строкой «}» в начале строки (вложенные блоки - с отступом).

def _строки_с_концами(текст):
    return текст.splitlines(keepends=True)


def _это_функция(строка):
    """Начинается ли со строки объявление или определение функции с «static»."""
    if not строка.startswith("static "):
        return False
    голова = строка.split("{")[0]
    if "(" not in голова:
        return False
    if голова.split("(", 1)[1].lstrip().startswith("*"):      # указатель на функцию - переменная
        return False
    return "=" not in голова.split("(")[0]


def _имя_функции(голова):
    до_скобки = голова.split("(")[0]
    имена = _ИМЯ.findall(до_скобки)
    return имена[-1] if имена else ""


def _без_static(строка):
    строка = строка[len("static "):]
    if строка.startswith("inline "):
        строка = строка[len("inline "):]
    return строка


def _разобрать(текст):
    """Части текста: ("текст", кусок) или ("функция", имя, встроенная, голова, тело-или-None, кусок)."""
    строки = _строки_с_концами(текст)
    итог = []
    обычные = []
    и = 0
    while и < len(строки):
        строка = строки[и]
        if not _это_функция(строка):
            обычные.append(строка)
            и += 1
            continue
        к = и
        while "{" not in строки[к] and not строки[к].rstrip().endswith(";"):
            к += 1
        голова = "".join(строки[и:к + 1])
        if "{" not in голова:              # объявление без тела
            if обычные:
                итог.append(("текст", "".join(обычные)))
                обычные = []
            итог.append(("функция", _имя_функции(голова), голова.startswith("static inline "), голова, None,
                         голова))
            и = к + 1
            continue
        # тело: строка, где «}» закрывает функцию; короткая функция - в одной строке
        if голова.rstrip().endswith("}") and голова.count("{") == голова.count("}"):
            конец = к
        else:
            конец = к + 1
            while конец < len(строки) and not строки[конец].startswith("}"):
                конец += 1
        if обычные:
            итог.append(("текст", "".join(обычные)))
            обычные = []
        кусок = "".join(строки[и:конец + 1])
        позиция = кусок.index("{")
        итог.append(("функция", _имя_функции(кусок[:позиция]), кусок.startswith("static inline "),
                     кусок[:позиция], кусок[позиция:], кусок))
        и = конец + 1
    if обычные:
        итог.append(("текст", "".join(обычные)))
    return итог


def _объявление(голова):
    """Объявление функции по её заголовку: без «static» и «inline», с «;» в конце."""
    return _без_static(голова.rstrip()) + ";\n"


def _библиотека_как_объявления(текст):
    """Текст библиотеки, в котором тела функций заменены объявлениями без «static»."""
    итог = []
    for часть in _разобрать(текст):
        if часть[0] == "текст":
            итог.append(часть[1])
        else:
            итог.append(_объявление(часть[3]))
    return "".join(итог)


def _библиотека_с_телами(текст):
    """Текст библиотеки с телами функций, все функции видимы снаружи (без «static»)."""
    итог = []
    for часть in _разобрать(текст):
        if часть[0] == "текст":
            итог.append(часть[1])
        else:
            итог.append(_без_static(часть[5]))
    return "".join(итог)


_ПЕРЕМЕННАЯ = re.compile(r"^static ((?!const )(?:[^\n(=;]|\(\s*\*)[^\n=;]*?)(\s*=[^\n;]*)?;", re.M)


def _переменные_среды(текст):
    """Переменные состояния среды (изменяемые переменные уровня файла)."""
    return list(_ПЕРЕМЕННАЯ.finditer(текст))


# Функции среды, которые зависят от программы (имена её файлов в сообщениях об ошибках):
# в части библиотеки они только объявлены, а определены в части программы.
_ЗАВИСЯТ_ОТ_ПРОГРАММЫ = ("dan_files", "DAN_FILE_COUNT")


def _среда_для_библиотеки(среда):
    """Текст среды для части библиотеки: переменные состояния - «extern», функции, зависящие
    от программы, - объявления; остальные функции остаются (компилятор C соберёт только
    вызываемые). Результат: (текст, имена объявленных функций)."""
    итог = []
    имена = []
    части = _разобрать(среда)
    определённые = {ч[1] for ч in части if ч[0] == "функция" and ч[4] is not None}
    for часть in части:
        if часть[0] == "текст":
            итог.append(_ПЕРЕМЕННАЯ.sub(_внешняя_переменная, часть[1]))
        elif часть[4] is None and часть[1] not in определённые:
            итог.append(_без_static(часть[5]))      # объявление функции из библиотеки
        elif часть[4] is not None and any(с in часть[4] for с in _ЗАВИСЯТ_ОТ_ПРОГРАММЫ):
            имена.append(часть[1])
            итог.append(_объявление(часть[3]))
        else:
            итог.append(часть[5])
    # объявления без тела тех же функций - тоже без «static»
    объявленные = set(имена)
    итог = [_без_static(к) if к.startswith("static ") and _это_функция(к) and _имя_функции(к) in объявленные
            else к for к in итог]
    return "".join(итог), имена


def _внешняя_переменная(м):
    return "extern " + м.group(1) + ";"


def _среда_для_программы(среда, видимые):
    """Текст среды в части программы: переменные состояния и функции из «видимые» - без «static»."""
    итог = []
    части = _разобрать(среда)
    определённые = {ч[1] for ч in части if ч[0] == "функция" and ч[4] is not None}
    for часть in части:
        if часть[0] == "текст":
            итог.append(_ПЕРЕМЕННАЯ.sub(lambda м: м.group(0)[len("static "):], часть[1]))
        elif часть[1] in видимые or (часть[4] is None and часть[1] not in определённые):
            итог.append(_без_static(часть[5]))
        else:
            итог.append(часть[5])
    return "".join(итог)


# ---------- разделение ----------

_образцы = {}


def _образец(группа, перевести):
    if группа not in _образцы:
        исходник = dict((г[0], г[1]) for г in ГРУППЫ)[группа]
        _образцы[группа] = перевести(исходник)
    return _образцы[группа]


def _текст_группы(группа):
    return "\n".join(dict((г[0], г[2]) for г in ГРУППЫ)[группа]())


_части = {}


def часть_библиотеки(группа, перевести):
    """Текст C готовой части группы и имена функций среды, которые она вызывает."""
    if группа not in _части:
        _части[группа] = _часть_библиотеки(группа, перевести)
    return _части[группа]


def _часть_библиотеки(группа, перевести):
    код = _образец(группа, перевести)
    среда = kodogen.СРЕДА
    начало_среды = код.index(среда)
    места = []
    for г, _, _ in ГРУППЫ:
        текст = _текст_группы(г)
        п = код.find(текст)
        if п >= 0:
            места.append((п, г, текст))
    места.sort()
    if not места or всё(г != группа for _, г, _ in места):
        raise RuntimeError(f"образцовая программа группы «{группа}» не содержит её библиотеку")
    начало = код[:места[0][0]]
    среда_б, функции_среды = _среда_для_библиотеки(среда)
    части = [начало[:начало_среды], среда_б, начало[начало_среды + len(среда):]]
    for _, г, текст in места:
        части.append("\n")
        части.append(_библиотека_с_телами(текст) if г == группа else _библиотека_как_объявления(текст))
    итог = "".join(части)
    # функции среды, которые упоминаются в части библиотеки не только своим объявлением
    объявленные = set(функции_среды)
    встречи = {}
    for имя in _ИМЯ.findall(итог):
        if имя in объявленные:
            встречи[имя] = встречи.get(имя, 0) + 1
    видимые = sorted(и for и, ч in встречи.items() if ч > 1)
    return итог, видимые


def всё(последовательность):
    return all(последовательность)


def разделить(код_c, перевести):
    """(код части программы, [группы]) или None, если готовая среда не годится.
    перевести(исходник) -> код C образцовой программы тем же компилятором."""
    if any(п in код_c for п in НЕ_ДЛЯ):
        return None
    среда = kodogen.СРЕДА
    if код_c.count(среда) != 1:
        return None
    группы = []
    программа = код_c
    for г, _, _ in ГРУППЫ:
        текст = _текст_группы(г)
        if текст and программа.count(текст) == 1:
            программа = программа.replace(текст, _библиотека_как_объявления(текст), 1)
            группы.append(г)
    if not группы:
        return None
    видимые = set()
    for г in группы:
        видимые |= set(часть_библиотеки(г, перевести)[1])
    программа = программа.replace(среда, _среда_для_программы(среда, видимые), 1)
    return программа, группы


def отпечаток(текст, команда, флаги):
    import versiya
    о = hashlib.sha256()
    for часть in (versiya.ВЕРСИЯ, sys.platform, " ".join(команда), " ".join(флаги)):
        о.update(часть.encode("utf-8", "surrogatepass") + b"\0")
    for путь in [к for к in команда if os.path.isfile(к)]:
        с = os.stat(путь)
        о.update(f"{путь}|{с.st_size}|{с.st_mtime_ns}".encode("utf-8", "surrogatepass") + b"\0")
    о.update(текст.encode("utf-8", "surrogatepass"))
    return о.hexdigest()
