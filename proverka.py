# десятичных: коэффициенты многочлена всегда точные.
В_МНОГОЧЛЕН = (ЦЕЛ, РАЦ, МН)


def общий_числовой(*типы):
    """Тип результата арифметики: самый «широкий» из числовых типов."""
    return max(типы, key=ЧИСЛА.index)


def это_список(тип):
    return тип.startswith("[") and тип.endswith("]") and тип != ПУСТОЙ_СПИСОК


def элемент(тип):
    return тип[1:-1]


def это_словарь(тип):
    return тип.startswith("{") and тип.endswith("}") and тип != ПУСТОЙ_СЛОВАРЬ


def ключ_словаря(тип):
    """Тип ключей: для «{стр: [цел]}» это «стр» (ключи - простые типы без двоеточий)."""
    return тип[1:тип.index(": ")]


def значение_словаря(тип):
    return тип[тип.index(": ") + 2:-1]


def словарь(ключ, значение):
    return "{" + ключ + ": " + значение + "}"


def это_функция(тип):
    """Тип функции: «функ(цел, стр) -> лог»."""
    return тип.startswith("функ(")


def _части_верхнего_уровня(текст):
    """Делит текст по запятым, не входящим в скобки."""
    части, глубина, начало = [], 0, 0
    for и, с in enumerate(текст):
        if с in "([{":
            глубина += 1
        elif с in ")]}":
            глубина -= 1
        elif с == "," and глубина == 0:
            части.append(текст[начало:и].strip())
            начало = и + 1
    if текст.strip():
        части.append(текст[начало:].strip())
    return части


def разобрать_тип_функции(тип):
    """(типы параметров, тип результата) для «функ(цел, стр) -> лог»; без «->» результат «пусто»."""
    глубина = 0
    for и, с in enumerate(тип):
        if с == "(":
            глубина += 1
        elif с == ")":
            глубина -= 1
            if глубина == 0:
                параметры = _части_верхнего_уровня(тип[5:и])
                остаток = тип[и + 1:].strip()
                результат = остаток[2:].strip() if остаток.startswith("->") else "пусто"
                return параметры, результат
    raise ValueError(тип)


def тип_функции(параметры, результат):
    тип = "функ(" + ", ".join(параметры) + ")"
    return тип if результат == "пусто" else тип + " -> " + результат


def это_необяз(тип):
    """Необязательное значение «тип?»: значение этого типа или ничего."""
    return тип.endswith("?") and not это_функция(тип)


def это_результат(тип):
    """Результат «тип!»: значение этого типа или ошибка (основа - то же «основа»)."""
    return тип.endswith("!") and not это_функция(тип)


def это_особое(тип):
    """Значение, которое нельзя использовать без проверки: «Т?» или «Т!»."""
    return это_необяз(тип) or это_результат(тип)


def основа(тип):
    """Тип значения внутри необязательного: для «стр?» это «стр»."""
    return тип[:-1]


def расширяемый_список(откуда, куда):
    """Список чисел расширяется так же, как число: [цел] -> [рац] -> [дроб],
    [[цел]] -> [[рац]]. Списки - значения, поэтому функция получает
    преобразованную копию и ничьих данных не меняет."""
    if not (это_список(откуда) and это_список(куда)):
        return False
    а, б = элемент(откуда), элемент(куда)
    if а in ЧИСЛА and б in ЧИСЛА:
        return ЧИСЛА.index(а) < ЧИСЛА.index(б)
    return расширяемый_список(а, б)


def совместим(откуда, куда):
    """Можно ли значение типа «откуда» использовать там, где ждут «куда»."""
    if НЕИЗВ in (откуда, куда):
        return True
    if откуда == ПУСТОЙ_СПИСОК:
        return это_список(куда) or (это_необяз(куда) and это_список(основа(куда)))
    if откуда == ПУСТОЙ_СЛОВАРЬ:
        return это_словарь(куда) or (это_необяз(куда) and это_словарь(основа(куда)))
    if это_результат(куда) and откуда != куда:
        return откуда == ОШИБКА or совместим(откуда, основа(куда))
    if это_необяз(куда) and откуда != куда:
        return откуда == НИЧЕГО or совместим(откуда, основа(куда))
    if откуда in ЧИСЛА and куда in ЧИСЛА:
        return ЧИСЛА.index(откуда) <= ЧИСЛА.index(куда)
    if расширяемый_список(откуда, куда):
        return True
    if куда == МН:
        return откуда in В_МНОГОЧЛЕН
    return откуда == куда


class Проверка:
    def __init__(self):
        self.ошибки = []
        self.функции = {}
        self.области = []          # стек словарей имя -> Переменная
        self.текущая_функция = None
        self.глубина_циклов = 0
        self.типы = {}             # собственные типы: имя -> [(поле, тип, значение по умолчанию)]
        self.лямбды = []           # стек (номер первой области безымянной функции, её узел)
        self.перечисления = {}     # тип -> [(вариант, [(поле, тип)])]
        self.вариант_тип = {}      # вариант -> тип перечисления
        self.написания = {}        # тип или (тип, поле) -> имя так, как оно написано в программе

    # ---------- общие средства ----------

    def ошибка(self, узел, текст):
        self.ошибки.append(Сообщение(узел.строка, узел.столбец, текст))

    def _найти(self, имя, захват=True):
        for номер in range(len(self.области) - 1, -1, -1):
            if имя in self.области[номер]:
                перем = self.области[номер][имя]
                if self.лямбды and номер < self.лямбды[-1][0]:
                    # переменная снаружи безымянной функции: функция получает её копию
                    if захват:
                        for граница, узел in self.лямбды:
                            if номер < граница:
                                узел.захваты.setdefault(имя, перем.тип)
                    return Переменная(перем.тип, False, "захват")
                return перем
        return None

    def _объявить(self, узел, имя, тип, изменяемая, вид="переменная"):
        if имя in self.функции or имя in ВСТРОЕННЫЕ or имя in self.типы or имя in self.вариант_тип \
                or имя in self.перечисления:
            self.ошибка(узел, f"имя «{имя}» уже занято функцией или названием типа")
        elif self._найти(имя, захват=False) is not None:
            self.ошибка(узел, f"переменная «{имя}» уже объявлена; "
                              f"повторно объявлять переменную с тем же именем нельзя")
        self.области[-1][имя] = Переменная(тип, изменяемая, вид)

    def _видимые_переменные(self):
        имена = []
        for область in self.области:
            имена.extend(область)
        return имена

    def _видимые_функции(self):
        return (list(self.функции) + list(ВСТРОЕННЫЕ) + list(matematika.ФУНКЦИИ)
                + list(dannye.ФУНКЦИИ))

    def _подсказка(self, имя, кандидаты):
        похожее = похожее_имя(имя, кандидаты)
        return f"; возможно, имелось в виду «{похожее}»" if похожее else ""

    def _тип_по_имени(self, узел, имя):
        if имя in ТИПЫ or имя in self.типы or имя in self.перечисления:
            return имя
        if это_функция(имя):
            параметры, результат = разобрать_тип_функции(имя)
            типы = [self._тип_по_имени(узел, п) for п in параметры]
            результат = результат if результат in (ПУСТО, ПУСТО + "!") else self._тип_по_имени(узел, результат)
            return НЕИЗВ if НЕИЗВ in типы + [результат] else тип_функции(типы, результат)
        if это_результат(имя):
            if основа(имя) == ПУСТО:
                return имя
            внутренний = self._тип_по_имени(узел, основа(имя))
            return НЕИЗВ if внутренний == НЕИЗВ else внутренний + "!"
        if это_необяз(имя):
            внутренний = self._тип_по_имени(узел, основа(имя))
            return НЕИЗВ if внутренний == НЕИЗВ else внутренний + "?"
        if имя.startswith("[") and имя.endswith("]"):
            внутренний = self._тип_по_имени(узел, элемент(имя))
            return НЕИЗВ if внутренний == НЕИЗВ else "[" + внутренний + "]"
        if это_словарь(имя):
            ключ = self._тип_по_имени(узел, ключ_словаря(имя))
            значение = self._тип_по_имени(узел, значение_словаря(имя))
            if ключ not in КЛЮЧИ_СЛОВАРЯ + (НЕИЗВ,):
                self.ошибка(узел, f"ключами словаря могут быть значения типов {', '.join(КЛЮЧИ_СЛОВАРЯ)}, "
                                  f"а не {ключ}")
                return НЕИЗВ
            return НЕИЗВ if НЕИЗВ in (ключ, значение) else словарь(ключ, значение)
        похожее = похожее_имя(имя, list(ТИПЫ) + list(self.типы))
        if похожее:
            self.ошибка(узел, f"неизвестный тип «{имя}»; возможно, имелось в виду «{похожее}»")
        else:
            собственные = f", собственные типы ({', '.join(self.типы)})" if self.типы else ""
            self.ошибка(узел, f"неизвестный тип «{имя}»; доступны типы: {', '.join(ТИПЫ)}{собственные}, "
                              f"списки, например [цел], и необязательные значения, например стр?")
        return НЕИЗВ

    def это_структура(self, тип):
        return тип in self.типы

    def _можно_вывести(self, тип):
        if тип in ТИПЫ or тип == НЕИЗВ or тип in self.типы or тип in self.перечисления:
            return True
        if это_словарь(тип):
            return self._можно_вывести(значение_словаря(тип))
        if это_необяз(тип):
            return self._можно_вывести(основа(тип))
        return это_список(тип) and self._можно_вывести(элемент(тип))

    def _сравнимый(self, тип, в_работе=None):
        """Можно ли сравнивать значения типа на равенство (==, «содержит», «найти»)."""
        в_работе = в_работе if в_работе is not None else set()
        if тип in СРАВНИМЫЕ:
            return True
        if это_необяз(тип):
            return self._сравнимый(основа(тип), в_работе)
        if это_список(тип):
            return self._сравнимый(элемент(тип), в_работе)
        if это_словарь(тип):
            return self._сравнимый(значение_словаря(тип), в_работе)
        if тип in self.типы:
            if тип in в_работе:          # рекурсивный тип: решает остальная часть полей
                return True
            в_работе.add(тип)
            return all(self._сравнимый(т, в_работе) for _, т, _ in self.типы[тип])
        if тип in self.перечисления:
            if тип in в_работе:
                return True
            в_работе.add(тип)
            return all(self._сравнимый(т, в_работе) for _, поля in self.перечисления[тип] for _, т in поля)
        return False

    def _место(self, узел):
        """Можно ли изменять значение по этому месту.

        Возвращает None, если можно, иначе пару (что, почему): «что» - кого
        нельзя изменять, в винительном падеже («параметр «с»»), «почему» -
        объяснение с подсказкой. Изменять можно переменную «перем», поле
        изменяемого значения и элемент изменяемого списка: значения в Дане не
        бывают общими, поэтому изменение всегда касается только одной переменной."""
        if isinstance(узел, у.Имя):
            перем = self._найти(узел.имя)
            if перем is None or перем.изменяемая:
                return None
            имя = узел.написание or узел.имя
            if перем.вид == "параметр":
                return (f"параметр «{имя}»", "функция получает копию значения и не может изменить "
                        "переменную вызывающей стороны; изменённое значение функция может вернуть")
            if перем.вид == "цикл":
                return (f"переменную цикла «{имя}»", "она сама получает новое значение на каждом шаге цикла")
            if перем.вид == "захват":
                return (f"переменную «{имя}»", "безымянная функция получила её копию в момент создания; "
                        "изменить переменную снаружи из функции нельзя - верните новое значение как результат")
            if перем.вид == "значение":
                return (f"значение «{имя}»", f"оно получено в «если пусть»; чтобы изменять его, "
                        f"скопируйте его в переменную: «перем копия = {имя}»")
            return (f"переменную «{имя}»", f"она объявлена через «пусть»; если её нужно менять, "
                    f"объявите её через «перем {имя} = ...»")
        if isinstance(узел, у.Поле) and узел.объект.тип_выр in self.типы:
            return self._место(узел.объект)
        if isinstance(узел, у.Индекс) and (это_список(узел.объект.тип_выр) or это_словарь(узел.объект.тип_выр)) \
                and not getattr(узел, "срез", False):
            return self._место(узел.объект)
        return (None, "изменить можно только значение в переменной «перем», его поле или элемент списка, "
                      "а здесь временное значение")

    @staticmethod
    def _запрет(действие, запрет):
        """Текст ошибки: «действие» (что пытаются сделать) невозможно по причине «запрет»."""
        что, почему = запрет
        if что is None:
            return f"{действие}: {почему}"
        return f"{действие}, так как {что} изменять нельзя: {почему}"

    def _ошибка_необяз(self, узел, тип, что):
        """Сообщение о попытке использовать необязательное значение без проверки."""
        if это_результат(тип):
            self.ошибка(узел, f"{что}: значение типа {тип} может оказаться ошибкой; передайте ошибку дальше "
                              f"знаком «!» («ф()!»), задайте запасное значение («... иначе запасное») "
                              f"или проверьте: «если пусть знач = ... {{ }} иначе ошибка о {{ }}»")
            return
        self.ошибка(узел, f"{что}: значение типа {тип} может отсутствовать (быть «ничего»); "
                          f"сначала проверьте его: «если пусть знач = ... {{ }}» "
                          f"или задайте запасное значение: «... иначе запасное»")

    def _согласовать(self, узел, тип, ожидаемый):
        """Подходит ли значение туда, где ждут тип «ожидаемый».

        Литерал списка подстраивается под ожидаемый тип: «[]» получает тип
        элементов, а «[1, 2]» годится и для [дроб]. Найденный тип
        записывается в узел, он нужен генератору кода.
        """
        if isinstance(узел, у.Лямбда) and тип == ОТЛОЖЕННАЯ:
            if not это_функция(ожидаемый):
                return False
            параметры, результат = разобрать_тип_функции(ожидаемый)
            if len(параметры) != len(узел.параметры):
                return False
            тип = self.в_Лямбда(узел, параметры, результат)
            узел.тип_выр = тип
            return тип == ожидаемый
        if getattr(узел, "в_необяз", None):
            узел.в_необяз = None
        if getattr(узел, "в_результат", None):
            узел.в_результат = None
        if это_результат(ожидаемый) and тип not in (НЕИЗВ, ожидаемый):
            if тип == ОШИБКА or (основа(ожидаемый) != ПУСТО and self._согласовать(узел, тип, основа(ожидаемый))):
                узел.в_результат = ожидаемый   # генератор «завернёт» значение или ошибку
                return True
            return False
        if это_необяз(ожидаемый) and тип not in (НЕИЗВ, ожидаемый):
            if тип == НИЧЕГО or self._согласовать(узел, тип, основа(ожидаемый)):
                узел.в_необяз = ожидаемый      # генератор «завернёт» значение
                return True
            return False
        if isinstance(узел, у.Словарь) and это_словарь(ожидаемый) and тип != НЕИЗВ:
            т_к, т_з = ключ_словаря(ожидаемый), значение_словаря(ожидаемый)
            if all(self._согласовать(к, к.тип_выр, т_к) for к in узел.ключи) and \
                    all(self._согласовать(з, з.тип_выр, т_з) for з in узел.значения):
                узел.тип_выр = ожидаемый
                return True
            return False
        if isinstance(узел, у.Список) and это_список(ожидаемый) and тип != НЕИЗВ:
            тип_эл = элемент(ожидаемый)
            if all(self._согласовать(э, э.тип_выр, тип_эл) for э in узел.элементы):
                узел.тип_выр = ожидаемый
                return True
            return False
        подходит = совместим(тип, ожидаемый)
        self._привести(узел, тип, ожидаемый if подходит else тип)
        return подходит

    @staticmethod
    def _привести(узел, тип, к_типу):
        """Отмечает, что числовое значение узла надо привести к типу «к_типу»."""
        if (тип in ЧИСЛА + (МН,) and к_типу in ЧИСЛА + (МН,) and тип != к_типу) \
                or расширяемый_список(тип, к_типу):
            узел.привести_к = к_типу
        elif getattr(узел, "привести_к", None):
            узел.привести_к = None

    # ---------- программа ----------

    def программа(self, программа):
        # Первый проход: собираем собственные типы и все функции, чтобы их
        # можно было использовать до места объявления.
        for о in программа.инструкции:      # названия перечислений нужны раньше полей типов
            if isinstance(о, у.ОбъявлениеВариантов) and о.имя not in self.перечисления:
                self.перечисления[о.имя] = None
        self._собрать_типы(программа)
        for имя in [и for и, з in self.перечисления.items() if з is None]:
            del self.перечисления[имя]
        self._собрать_перечисления(программа)
        for инстр in программа.инструкции:
            if isinstance(инстр, у.Функция):
                if инстр.имя in self.типы:
                    self.ошибка(инстр, f"имя «{инстр.имя}» уже занято типом")
                    continue
                if инстр.имя in ВСТРОЕННЫЕ:
                    self.ошибка(инстр, f"«{инстр.имя}» - встроенная функция, объявить её заново нельзя")
                    continue
                if инстр.имя in self.функции:
                    self.ошибка(инстр, f"функция «{инстр.имя}» уже объявлена")
                    continue
                параметры = [self._тип_по_имени(п, п.тип) for п in инстр.параметры]
                результат = (self._тип_по_имени(инстр, инстр.тип_результата)
                             if инстр.тип_результата else ПУСТО)
                self.функции[инстр.имя] = Сигнатура(параметры, результат,
                                                   [п.имя for п in инстр.параметры])

        # Второй проход: тела функций и инструкции верхнего уровня.
        self.области.append({})
        for инстр in программа.инструкции:
            if isinstance(инстр, у.Функция):
                self.функция(инстр)
            elif isinstance(инстр, у.ОбъявлениеТипа):
                self._значения_по_умолчанию(инстр)
            elif isinstance(инстр, у.ОбъявлениеВариантов):
                pass
            else:
                self.инструкция(инстр)
        self.области.pop()
        программа.типы = self.типы
        программа.перечисления = self.перечисления
        программа.вариант_тип = self.вариант_тип
        программа.написания = self.написания

        self.ошибки.sort(key=lambda о: (о.строка, о.столбец))
        if self.ошибки:
            raise ОшибкаПроверки(self.ошибки)

    def _собрать_перечисления(self, программа):
        объявления = [и for и in программа.инструкции if isinstance(и, у.ОбъявлениеВариантов)]
        for о in объявления:
            if о.имя in ТИПЫ or о.имя in ВСТРОЕННЫЕ or о.имя in self.перечисления:
                self.ошибка(о, f"название «{о.имя}» уже занято")
                continue
            self.перечисления[о.имя] = []
            self.написания[о.имя] = о.написание or о.имя
            for в in о.варианты:
                if в.имя in self.вариант_тип or в.имя in ТИПЫ or в.имя in ВСТРОЕННЫЕ:
                    self.ошибка(в, f"вариант «{в.имя}» уже есть в другом типе или это занятое название")
                    continue
                self.вариант_тип[в.имя] = о.имя
                self.написания[(о.имя, в.имя)] = в.написание or в.имя
                for п in в.поля:
                    self.написания[(о.имя, в.имя, п.имя)] = п.написание or п.имя
        for о in объявления:
            if о.имя not in self.перечисления or self.перечисления[о.имя]:
                continue
            for в in о.варианты:
                if self.вариант_тип.get(в.имя) == о.имя:
                    self.перечисления[о.имя].append(
                        (в.имя, [(п.имя, self._тип_по_имени(п, п.тип)) for п in в.поля]))

    def _собрать_типы(self, программа):
        объявления = [и for и in программа.инструкции if isinstance(и, у.ОбъявлениеТипа)]
        for о in объявления:
            if о.имя in self.перечисления or о.имя in self.вариант_тип:
                self.ошибка(о, f"название «{о.имя}» уже занято перечислением или его вариантом")
        for о in объявления:
            if о.имя in ТИПЫ or о.имя in ВСТРОЕННЫЕ:
                self.ошибка(о, f"«{о.имя}» - встроенный тип или функция, такое название занято")
            elif о.имя in self.типы:
                self.ошибка(о, f"тип «{о.имя}» уже объявлен")
            else:
                self.типы[о.имя] = []
        принятые = [о for о in объявления if self.типы.get(о.имя) == [] and
                    not any(д is not о and д.имя == о.имя for д in объявления[:объявления.index(о)])]
        for о in принятые:
            self.типы[о.имя] = [(п.имя, self._тип_по_имени(п, п.тип), п.по_умолчанию) for п in о.поля]
            self.написания[о.имя] = о.написание or о.имя
            for п in о.поля:
                self.написания[(о.имя, п.имя)] = п.написание or п.имя
        # Значение не может содержать само себя целиком (иначе оно бесконечно).
        for о in принятые:
            путь = self._цикл_типа(о.имя, о.имя, [])
            if путь:
                self.ошибка(о, f"тип «{о.имя}» содержит сам себя (через {' -> '.join(путь)}); "
                               f"такое значение было бы бесконечным. Сделайте поле необязательным "
                               f"(«след: {о.имя}?») или храните вложенные значения в списке "
                               f"(«дети: [{о.имя}]»)")

    def _цикл_типа(self, искомый, тип, путь, посещённые=None):
        посещённые = посещённые if посещённые is not None else set()
        if тип in посещённые:
            return None
        посещённые.add(тип)
        for поле, т, _ in self.типы.get(тип, []):
            # Необязательное поле может быть пустым, поэтому значение конечно:
            # «след: Узел?» допустимо (такое поле хранится по ссылке).
            if это_необяз(т):
                continue
            if т == искомый:
                return путь + [f"поле «{поле}»"]
            if т in self.типы:
                найдено = self._цикл_типа(искомый, т, путь + [f"поле «{поле}»"], посещённые)
                if найдено:
                    return найдено
        return None

    def _значения_по_умолчанию(self, о):
        """Значения полей по умолчанию вычисляются без доступа к переменным программы."""
        внешние_области, self.области = self.области, [{}]
        for п in о.поля:
            if п.по_умолчанию is None:
                continue
            тип_поля = self._тип_по_имени(п, п.тип) if self.типы.get(о.имя) else НЕИЗВ
            тип = self.выражение(п.по_умолчанию)
            if not self._согласовать(п.по_умолчанию, тип, тип_поля):
                self.ошибка(п.по_умолчанию, f"поле «{п.имя}» имеет тип {тип_поля}, "
                                           f"а значение по умолчанию имеет тип {тип}")
        self.области = внешние_области

    def и_ОбъявлениеВариантов(self, и):
        self.ошибка(и, "типы объявляются только на верхнем уровне программы")

    def и_Выбор(self, и):
        тип = self.выражение(и.значение)
        и.тип_значения = тип
        if тип in self.перечисления:
            варианты = dict(self.перечисления[тип])
            покрытые = set()
            for ветвь in и.ветви:
                привязки = {}
                for образец in ветвь.образцы:
                    if not isinstance(образец, у.ОбразецВарианта):
                        self.ошибка(образец, f"значение типа {тип} разбирается по вариантам: "
                                             f"{', '.join(варианты)}")
                        continue
                    if образец.имя not in варианты and "." in тип:
                        # вариант типа из модуля можно называть коротко: Круг вместо фигуры.Круг
                        полное = тип.rsplit(".", 1)[0] + "." + образец.имя.rsplit(".", 1)[-1]
                        if полное in варианты:
                            образец.имя = полное
                    if образец.имя not in варианты:
                        self.ошибка(образец, f"у типа {тип} нет варианта «{образец.имя}»"
                                             f"{self._подсказка(образец.имя, варианты)}")
                        continue
                    if образец.имя in покрытые:
                        self.ошибка(образец, f"вариант «{образец.имя}» уже разобран выше")
                    покрытые.add(образец.имя)
                    поля = варианты[образец.имя]
                    if образец.привязки:
                        if len(ветвь.образцы) > 1:
                            self.ошибка(образец, "если в ветви несколько вариантов, получить их поля нельзя")
                        elif len(образец.привязки) != len(поля):
                            self.ошибка(образец, f"у варианта «{образец.имя}» {склонение_полей(len(поля))} "
                                                 f"({', '.join(п for п, _ in поля) or 'нет полей'}), "
                                                 f"а указано {len(образец.привязки)}")
                        else:
                            for имя, (_, т) in zip(образец.привязки, поля):
                                if имя != "_":
                                    привязки[имя] = т
                self.области.append({})
                for имя, т in привязки.items():
                    self._объявить(ветвь, имя, т, False, "значение")
                self.блок(ветвь.тело, новая_область=False)
                self.области.pop()
            пропущенные = [в for в in варианты if в not in покрытые]
            if пропущенные and и.иначе is None:
                self.ошибка(и, f"в «выбор» не разобраны варианты типа {тип}: "
                               f"{', '.join('«' + в + '»' for в in пропущенные)}; добавьте для них ветви "
                               f"или ветвь «иначе»")
            и.полный = not пропущенные
        elif тип in (ЦЕЛ, СТР, ЛОГ, РАЦ, ДРОБ, НЕИЗВ):
            значения = set()
            for ветвь in и.ветви:
                for образец in ветвь.образцы:
                    if isinstance(образец, у.ОбразецВарианта):
                        if тип != НЕИЗВ:
                            self.ошибка(образец, f"для значения типа {тип} в ветви пишутся значения "
                                                 f"(числа, строки, диапазоны), а не имена; для сравнения с "
                                                 f"переменной используйте «если»")
                        continue
                    if not self._постоянное(образец):
                        self.ошибка(образец, "в ветви «выбор» допускаются только записанные значения: "
                                             "числа, строки, истина, ложь и диапазоны «1..5»")
                        continue
                    if isinstance(образец, у.Диапазон):
                        for граница in (образец.начало, образец.конец):
                            т = self.выражение(граница)
                            if т not in (ЦЕЛ, НЕИЗВ):
                                self.ошибка(граница, "границы диапазона должны быть целыми числами")
                        образец.тип_выр = ДИАПАЗОН
                        if тип not in (ЦЕЛ, НЕИЗВ):
                            self.ошибка(образец, f"диапазон применим только к целым числам, а здесь {тип}")
                        continue
                    т = self.выражение(образец)
                    if тип != НЕИЗВ and not self._согласовать(образец, т, тип):
                        self.ошибка(образец, f"значение имеет тип {т}, а в «выбор» - значение типа {тип}")
                    ключ = repr(self._значение_образца(образец))
                    if ключ in значения:
                        self.ошибка(образец, "это значение уже разобрано выше")
                    значения.add(ключ)
                self.блок(ветвь.тело)
            и.полный = тип == ЛОГ and {repr(True), repr(False)} <= значения
        else:
            self.ошибка(и.значение, f"«выбор» работает с перечислениями, числами, строками и логическими "
                                    f"значениями, а здесь {тип}")
            for ветвь in и.ветви:
                self.блок(ветвь.тело)
            и.полный = False
        if и.иначе is not None:
            self.блок(и.иначе)

    @staticmethod
    def _постоянное(узел):
        if isinstance(узел, (у.ЦелоеЧисло, у.ДробноеЧисло, у.Строка, у.Логическое)):
            return True
        if isinstance(узел, у.Унарная) and узел.оператор == "-":
            return isinstance(узел.операнд, (у.ЦелоеЧисло, у.ДробноеЧисло))
        if isinstance(узел, у.Диапазон):
            return Проверка._постоянное(узел.начало) and Проверка._постоянное(узел.конец)
        return False

    @staticmethod
    def _значение_образца(узел):
        if isinstance(узел, у.Унарная):
            return -узел.операнд.значение
        return узел.значение

    def и_ОбъявлениеТипа(self, и):
        self.ошибка(и, "типы объявляются только на верхнем уровне программы, "
                       "а не внутри функций или блоков")

    def функция(self, ф):
        сигнатура = self.функции.get(ф.имя)
        if сигнатура is None:      # ошибка уже сообщена в первом проходе
            return
        # Функции видят только свои параметры и свои переменные.
        внешние_области = self.области
        self.области = [{}]
        for параметр, тип in zip(ф.параметры, сигнатура.параметры):
            if параметр.имя in self.функции or параметр.имя in ВСТРОЕННЫЕ or параметр.имя in self.типы:
                self.ошибка(параметр, f"имя «{параметр.имя}» уже занято функцией")
            self.области[-1][параметр.имя] = Переменная(тип, False, "параметр")
        self.текущая_функция = (ф.имя, сигнатура.результат)
        self.блок(ф.тело, новая_область=False)
        if сигнатура.результат not in (ПУСТО, НЕИЗВ, ПУСТО + "!") and not всегда_возвращает(ф.тело):
            self.ошибка(ф, f"функция «{ф.имя}» может завершиться, не вернув значение; "
                           f"в конце каждой ветви нужна инструкция «вернуть»")
        self.текущая_функция = None
        self.области = внешние_области

    # ---------- инструкции ----------

    def блок(self, блок, новая_область=True):
        if новая_область:
            self.области.append({})
        for инстр in блок.инструкции:
            self.инструкция(инстр)
        if новая_область:
            self.области.pop()

    def инструкция(self, и):
        метод = getattr(self, "и_" + type(и).__name__, None)
        if метод is None:
            raise NotImplementedError(type(и).__name__)
        метод(и)

    def и_Функция(self, и):
        self.ошибка(и, "функции объявляются только на верхнем уровне программы, "
                       "а не внутри других функций или блоков")

    def и_ОбъявлениеПеременной(self, и):
        тип_знач = self.выражение(и.значение)
        if тип_знач == ПУСТО:
            self.ошибка(и.значение, "выражение не имеет значения, его нельзя сохранить в переменную")
            тип_знач = НЕИЗВ
        if тип_знач == ДИАПАЗОН:
            self.ошибка(и.значение, "диапазон можно использовать только в цикле «для»")
            тип_знач = НЕИЗВ
        if тип_знач == ОТЛОЖЕННАЯ and и.тип is None:
            self.ошибка(и.значение, "у параметров безымянной функции не указаны типы: укажите их "
                                    "(функ(х: цел) = ...) или тип переменной (пусть ф: функ(цел) -> цел = ...)")
            тип_знач = НЕИЗВ
        if тип_знач == ОШИБКА and и.тип is None:
            self.ошибка(и.значение, "ошибку можно вернуть из функции («вернуть ошибка(...)») или сохранить "
                                    "в переменной типа «Т!»")
            тип_знач = НЕИЗВ
        if тип_знач == НИЧЕГО and и.тип is None:
            self.ошибка(и.значение, f"у «ничего» неизвестен тип значения; укажите его: "
                                    f"«{'перем' if и.изменяемая else 'пусть'} {и.имя}: стр? = ничего»")
            тип_знач = НЕИЗВ
        if и.тип is not None:
            тип = self._тип_по_имени(и, и.тип)
            if not self._согласовать(и.значение, тип_знач, тип):
                self.ошибка(и.значение, f"переменная «{и.имя}» имеет тип {тип}, "
                                        f"а значение имеет тип {тип_знач}")
        elif тип_знач == ПУСТОЙ_СЛОВАРЬ:
            self.ошибка(и.значение, f"у пустого словаря неизвестны типы ключей и значений; укажите их: "
                                    f"«{'перем' if и.изменяемая else 'пусть'} {и.имя}: {{стр: цел}} = {{}}»")
            тип = НЕИЗВ
        elif тип_знач == ПУСТОЙ_СПИСОК:
            слово = 'перем' if и.изменяемая else 'пусть'
            self.ошибка(и.значение, f"у пустого списка неизвестен тип элементов; укажите его, например "
                                    f"«{слово} {и.имя}: [стр] = []» для списка строк или "
                                    f"«{слово} {и.имя}: [цел] = []» для списка целых чисел")
            тип = НЕИЗВ
        else:
            тип = тип_знач
        и.тип_итог = тип
        self._объявить(и, и.имя, тип, и.изменяемая)

    def и_Присваивание(self, и):
        тип_знач = self.выражение(и.значение)
        перем = self._найти(и.имя)
        if перем is None:
            if и.имя in self.функции or и.имя in ВСТРОЕННЫЕ:
                self.ошибка(и, f"«{и.имя}» - функция, ей нельзя присвоить значение")
            else:
                подсказка = self._подсказка(и.имя, self._видимые_переменные())
                if подсказка:
                    self.ошибка(и, f"переменная «{и.имя}» не объявлена{подсказка}")
                else:
                    self.ошибка(и, f"переменная «{и.имя}» не объявлена; "
                                   f"объявите её через «перем {и.имя} = ...»")
            return
        и.тип_цели = перем.тип
        if not перем.изменяемая:
            что, почему = self._место(у.Имя(и.имя, написание=и.написание))
            self.ошибка(и, f"{что} нельзя изменить: {почему}")
        if и.оператор == "=":
            if not self._согласовать(и.значение, тип_знач, перем.тип):
                self.ошибка(и.значение, f"переменная «{и.имя}» имеет тип {перем.тип}, "
                                        f"а значение имеет тип {тип_знач}")
            return
        оп = и.оператор[0]
        результат = self._арифметика(и, оп, перем.тип, тип_знач, None, и.значение)
        и.тип_результата = результат
        if not совместим(результат, перем.тип):
            self.ошибка(и, f"результат «{и.имя} {оп} ...» имеет тип {результат}, "
                           f"а переменная «{и.имя}» имеет тип {перем.тип}")

    def и_ПрисваиваниеЭлемента(self, и):
        тип_списка = self.выражение(и.объект)
        тип_индекса = self.выражение(и.индекс)
        тип_знач = self.выражение(и.значение)
        и.тип_элемента = НЕИЗВ
        if тип_списка in (СТР, БАЙТЫ):
            self.ошибка(и, f"значение типа {тип_списка} нельзя изменять по частям; соберите новое")
            return
        if это_словарь(тип_списка):
            self._присвоить_в_словарь(и, тип_списка, тип_индекса, тип_знач)
            return
        if not это_список(тип_списка):
            if тип_списка != НЕИЗВ:
                self.ошибка(и.объект, f"квадратные скобки применимы только к спискам, а здесь {тип_списка}")
            return
        if тип_индекса not in (ЦЕЛ, НЕИЗВ):
            self.ошибка(и.индекс, f"индекс должен быть целым числом, а здесь {тип_индекса}")
        тип_эл = элемент(тип_списка)
        и.тип_элемента = тип_эл
        запрет = self._место(и.объект)
        if запрет:
            self.ошибка(и, self._запрет("элемент списка нельзя изменить", запрет))
        if и.оператор == "=":
            if not self._согласовать(и.значение, тип_знач, тип_эл):
                self.ошибка(и.значение, f"элементы списка имеют тип {тип_эл}, "
                                        f"а значение имеет тип {тип_знач}")
            return
        оп = и.оператор[0]
        результат = self._арифметика(и, оп, тип_эл, тип_знач, None, и.значение)
        и.тип_результата = результат
        if not совместим(результат, тип_эл):
            self.ошибка(и, f"результат операции имеет тип {результат}, "
                           f"а элементы списка имеют тип {тип_эл}")

    def _присвоить_в_словарь(self, и, тип, тип_ключа, тип_знач):
        т_к, т_з = ключ_словаря(тип), значение_словаря(тип)
        и.тип_элемента = т_з
        и.словарь = True
        if not self._согласовать(и.индекс, тип_ключа, т_к):
            self.ошибка(и.индекс, f"ключи словаря имеют тип {т_к}, а здесь {тип_ключа}")
        запрет = self._место(и.объект)
        if запрет:
            self.ошибка(и, f"словарь нельзя изменить: {запрет}")
        if и.оператор == "=":
            if not self._согласовать(и.значение, тип_знач, т_з):
                self.ошибка(и.значение, f"значения словаря имеют тип {т_з}, а значение имеет тип {тип_знач}")
            return
        оп = и.оператор[0]
        результат = self._арифметика(и, оп, т_з, тип_знач, None, и.значение)
        и.тип_результата = результат
        if not совместим(результат, т_з):
            self.ошибка(и, f"результат операции имеет тип {результат}, а значения словаря имеют тип {т_з}")

    def и_ПрисваиваниеПоля(self, и):
        тип_объекта = self.выражение(и.объект)
        тип_знач = self.выражение(и.значение)
        и.тип_поля = НЕИЗВ
        if тип_объекта == НЕИЗВ:
            return
        if это_особое(тип_объекта):
            self._ошибка_необяз(и.объект, тип_объекта, f"поле «{и.имя}» нельзя изменить")
            return
        if тип_объекта not in self.типы:
            if и.имя == "длина" or и.имя in СВОЙСТВА.get(тип_объекта, {}):
                self.ошибка(и, f"свойство «{и.имя}» вычисляется само, изменить его нельзя")
            else:
                self.ошибка(и, f"у значения типа {тип_объекта} нет полей")
            return
        поля = {п: т for п, т, _ in self.типы[тип_объекта]}
        if и.имя not in поля:
            self.ошибка(и, f"у типа {тип_объекта} нет поля «{и.имя}»{self._подсказка(и.имя, поля)}")
            return
        тип_поля = поля[и.имя]
        и.тип_поля = тип_поля
        запрет = self._место(и.объект)
        if запрет:
            self.ошибка(и, self._запрет(f"поле «{и.имя}» нельзя изменить", запрет))
        if и.оператор == "=":
            if not self._согласовать(и.значение, тип_знач, тип_поля):
                self.ошибка(и.значение, f"поле «{и.имя}» имеет тип {тип_поля}, а значение имеет тип {тип_знач}")
            return
        оп = и.оператор[0]
        результат = self._арифметика(и, оп, тип_поля, тип_знач, None, и.значение)
        и.тип_результата = результат
        if not совместим(результат, тип_поля):
            self.ошибка(и, f"результат операции имеет тип {результат}, а поле «{и.имя}» имеет тип {тип_поля}")

    @staticmethod
    def _есть_вызов(узел):
        """Есть ли в выражении вызов функции (только вызов может что-то изменить или вывести)."""
        if isinstance(узел, у.Вызов):
            return True
        if isinstance(узел, у.Лямбда):
            return False
        if isinstance(узел, list):
            return any(Проверка._есть_вызов(ч) for ч in узел)
        if isinstance(узел, у.Узел):
            return any(Проверка._есть_вызов(з) for з in vars(узел).values() if isinstance(з, (у.Узел, list)))
        return False

    def _бесполезное_выражение(self, выр):
        """Сообщение о выражении отдельной инструкцией, которое ничего не делает."""
        if isinstance(выр, у.Бинарная) and выр.оператор == "==":
            подсказка = "; для присваивания используйте «=», а не «==»"
        elif isinstance(выр, у.Имя) and (выр.имя in self.функции or найти_в_библиотеке(выр.имя)[1] is not None):
            подсказка = f"; чтобы вызвать функцию, допишите скобки: «{выр.написание or выр.имя}(...)»"
        else:
            подсказка = "; чтобы показать его на экране, используйте «вывод(...)»"
        self.ошибка(выр, "значение этого выражения нигде не используется, и оно ничего не меняет" + подсказка)

    def и_Выражение(self, и):
        if not self._есть_вызов(и.выражение):
            было = len(self.ошибки)
            if not (isinstance(и.выражение, у.Имя) and (и.выражение.имя in self.функции
                                                         or найти_в_библиотеке(и.выражение.имя)[1] is not None)):
                self.выражение(и.выражение)
            if len(self.ошибки) == было:      # о других ошибках в выражении уже сообщено
                self._бесполезное_выражение(и.выражение)
            return
        тип = self.выражение(и.выражение)
        if тип == ДИАПАЗОН:
            self.ошибка(и.выражение, "диапазон можно использовать только в цикле «для»")
        if это_результат(тип):
            self.ошибка(и.выражение, "результат может оказаться ошибкой, и её нельзя молча проигнорировать: "
                                     "допишите «!», чтобы передать ошибку дальше, или обработайте её: "
                                     "«если ошибка о = ... { }»")

    def и_Если(self, и):
        self._условие(и.условие, "если")
        self.блок(и.тогда)
        self._иначе_ветвь(и)

    def _иначе_ветвь(self, и):
        if isinstance(и.иначе, (у.Если, у.ЕслиЕсть, у.ЕслиОшибка)):
            self.инструкция(и.иначе)
        elif и.иначе is not None:
            self.блок(и.иначе)

    def и_ЕслиЕсть(self, и):
        тип = self.выражение(и.значение)
        тип_перем = НЕИЗВ
        if это_результат(тип) and основа(тип) == ПУСТО:
            self.ошибка(и.значение, "у результата без значения нет значения для «если пусть»; "
                                    "используйте «если ошибка о = ... { }»")
        elif это_особое(тип):
            тип_перем = основа(тип)
        elif тип == НИЧЕГО:
            self.ошибка(и.значение, "здесь всегда «ничего», проверять нечего")
        elif тип != НЕИЗВ:
            self.ошибка(и.значение, f"после «если пусть {и.имя} =» ожидается необязательное значение "
                                    f"(тип со знаком «?»), а здесь {тип}; обычное условие "
                                    f"записывается без «пусть»: «если условие {{ }}»")
        и.тип_значения = тип
        self.области.append({})
        self._объявить(и, и.имя, тип_перем, False, "значение")
        self.блок(и.тогда, новая_область=False)
        self.области.pop()
        if и.имя_ошибки:
            if not это_результат(тип) and тип != НЕИЗВ:
                self.ошибка(и, f"«иначе ошибка {и.имя_ошибки}» возможно только для результата, который может "
                               f"быть ошибкой (тип со знаком «!»), а здесь {тип}")
            self.области.append({})
            self._объявить(и, и.имя_ошибки, СТР, False, "значение")
            self.блок(и.иначе, новая_область=False)
            self.области.pop()
            return
        self._иначе_ветвь(и)

    def и_ЕслиОшибка(self, и):
        тип = self.выражение(и.значение)
        if not это_результат(тип) and тип != НЕИЗВ:
            self.ошибка(и.значение, f"после «если ошибка {и.имя} =» ожидается результат, который может быть "
                                    f"ошибкой (тип со знаком «!»), а здесь {тип}")
        self.области.append({})
        self._объявить(и, и.имя, СТР, False, "значение")
        self.блок(и.тогда, новая_область=False)
        self.области.pop()
        self._иначе_ветвь(и)

    def и_Пока(self, и):
        self._условие(и.условие, "пока")
        self.глубина_циклов += 1
        self.блок(и.тело)
        self.глубина_циклов -= 1

    def и_Для(self, и):
        тип = self.выражение(и.источник)
        и.по_строке = тип == СТР
        if тип == ДИАПАЗОН:
            тип_перем = ЦЕЛ
        elif тип == СТР:
            тип_перем = СТР
        elif это_список(тип):
            тип_перем = элемент(тип)
        elif это_словарь(тип):
            тип_перем = ключ_словаря(тип)      # перебираются ключи в порядке добавления
            и.по_словарю = True
        else:
            if тип == ПУСТОЙ_СПИСОК:
                self.ошибка(и.источник, "перебирать пустой список «[]» бессмысленно")
            elif тип != НЕИЗВ:
                self.ошибка(и.источник, "после «в» ожидается диапазон, например «1..10», список, словарь или строка")
            тип_перем = НЕИЗВ
        и.тип_элемента = тип_перем if (это_список(тип) or это_словарь(тип) or тип == СТР) else None
        self.области.append({})
        self._объявить(и, и.переменная, тип_перем, False, "цикл")
        self.глубина_циклов += 1
        self.блок(и.тело)
        self.глубина_циклов -= 1
        self.области.pop()

    def и_Вернуть(self, и):
        if self.текущая_функция is None:
            self.ошибка(и, "«вернуть» можно использовать только внутри функции")
            if и.значение is not None:
                self.выражение(и.значение)
            return
        имя, ожидаемый = self.текущая_функция
        if и.значение is None:
            if ожидаемый not in (ПУСТО, НЕИЗВ, ПУСТО + "!"):
                self.ошибка(и, f"функция «{имя}» должна вернуть значение типа {ожидаемый}")
            return
        тип = self.выражение(и.значение)
        if isinstance(и.значение, у.Имя):
            перем = self._найти(и.значение.имя)
            # Возвращается собственная переменная функции: значение переходит к
            # вызывающей стороне без копирования.
            и.перемещение = перем is not None and перем.вид == "переменная"
        if ожидаемый == ПУСТО:
            self.ошибка(и, f"функция «{имя}» не возвращает значений; если она должна "
                           f"возвращать результат, укажите его тип после «->»")
        elif not self._согласовать(и.значение, тип, ожидаемый):
            self.ошибка(и.значение, f"функция «{имя}» должна вернуть {ожидаемый}, а возвращается {тип}")

    def и_Прервать(self, и):
        if self.глубина_циклов == 0:
            self.ошибка(и, "«прервать» можно использовать только внутри цикла")

    def и_Продолжить(self, и):
        if self.глубина_циклов == 0:
            self.ошибка(и, "«продолжить» можно использовать только внутри цикла")

    def _условие(self, выр, слово):
        тип = self.выражение(выр)
        if это_особое(тип):
            self._ошибка_необяз(выр, тип, f"условие после «{слово}» должно иметь тип лог")
        elif not совместим(тип, ЛОГ):
            self.ошибка(выр, f"условие после «{слово}» должно иметь тип лог "
                             f"(истина или ложь), а имеет тип {тип}")

    # ---------- выражения ----------

    def выражение(self, в):
        метод = getattr(self, "в_" + type(в).__name__)
        тип = метод(в)
        в.тип_выр = тип
        return тип

    def в_ЦелоеЧисло(self, в):
        if в.значение > 2**63 - 1:
            self.ошибка(в, "число слишком велико для типа цел")
        return ЦЕЛ

    def в_ДробноеЧисло(self, в):
        return ДРОБ

    def в_Строка(self, в):
        return СТР

    def в_Логическое(self, в):
        return ЛОГ

    def в_Ничего(self, в):
        return НИЧЕГО

    def в_Передать(self, в):
        тип = self.выражение(в.значение)
        if тип == НЕИЗВ:
            return НЕИЗВ
        if not это_результат(тип):
            self.ошибка(в, f"знак «!» передаёт дальше ошибку, а значение типа {тип} ошибкой быть не может")
            return тип
        if self.текущая_функция is not None and not это_результат(self.текущая_функция[1]):
            имя = self.текущая_функция[0]
            self.ошибка(в, f"передать ошибку можно только из функции, которая сама может завершиться ошибкой: "
                           f"отметьте тип результата функции «{имя}» знаком «!» (например, «-> цел!» или «-> !»), "
                           f"или обработайте ошибку здесь")
        в.функция_результат = self.текущая_функция[1] if self.текущая_функция else None
        return ПУСТО if основа(тип) == ПУСТО else основа(тип)

    def в_Иначе(self, в):
        тип = self.выражение(в.значение)
        запасной = self.выражение(в.запасное)
        if тип == НЕИЗВ:
            return НЕИЗВ
        if тип == НИЧЕГО:
            self.ошибка(в, "слева от «иначе» стоит «ничего», поэтому всегда будет выбрано запасное значение")
            return запасной
        if это_результат(тип) and основа(тип) == ПУСТО:
            self.ошибка(в, "у результата без значения («-> !») нет значения, которое можно заменить запасным; "
                           "обработайте ошибку: «если ошибка о = ... { }»")
            return НЕИЗВ
        if not это_особое(тип):
            self.ошибка(в, f"слева от «иначе» должно стоять необязательное значение (тип со знаком «?») "
                           f"или результат, который может быть ошибкой («!»), а здесь {тип}; такое значение есть всегда")
            return тип
        if запасной == НЕИЗВ:
            return основа(тип)
        if self._согласовать(в.запасное, запасной, основа(тип)):
            return основа(тип)
        if self._согласовать(в.запасное, запасной, тип):
            return тип
        self.ошибка(в.запасное, f"запасное значение должно иметь тип {основа(тип)}, а имеет тип {запасной}")
        return основа(тип)

    def в_Имя(self, в):
        перем = self._найти(в.имя)
        if перем is not None:
            return перем.тип
        if в.имя in matematika.КОНСТАНТЫ:
            в.константа = в.имя
            return matematika.КОНСТАНТЫ[в.имя][0]
        if в.имя in self.вариант_тип:
            тип = self.вариант_тип[в.имя]
            поля = dict(self.перечисления[тип]).get(в.имя, [])
            if поля:
                self.ошибка(в, f"у варианта «{в.имя}» есть поля ({', '.join(п for п, _ in поля)}); "
                               f"задайте их: {в.имя}(...)")
                return НЕИЗВ
            в.вариант = (тип, в.имя)
            return тип
        if в.имя in self.типы:
            self.ошибка(в, f"«{в.имя}» - название типа; чтобы создать значение, допишите скобки "
                           f"с полями: {в.имя}(...)")
        elif в.имя in self.функции:
            # функция программы как значение: её можно передать или сохранить
            сигн = self.функции[в.имя]
            в.функция_значение = в.имя
            return тип_функции(сигн.параметры, сигн.результат)
        elif в.имя in ВСТРОЕННЫЕ or найти_в_библиотеке(в.имя)[0]:
            что = "название типа" if в.имя in ТИПЫ else "функция"
            self.ошибка(в, f"«{в.имя}» - {что}; чтобы вызвать функцию, допишите скобки: {в.имя}(...)")
        else:
            подсказка = self._подсказка(в.имя, self._видимые_переменные()
                                        + list(matematika.КОНСТАНТЫ))
            self.ошибка(в, f"переменная «{в.имя}» не объявлена{подсказка}")
        return НЕИЗВ

    def в_Унарная(self, в):
        тип = self.выражение(в.операнд)
        if это_особое(тип):
            self._ошибка_необяз(в, тип, f"«{в.оператор}» нельзя применить")
            return НЕИЗВ
        if в.оператор == "-":
            if тип in ЧИСЛА or тип in (НЕИЗВ, МН):
                return тип
            self.ошибка(в, f"знак «-» применим только к числам, а не к типу {тип}")
            return НЕИЗВ
        # не
        if not совместим(тип, ЛОГ):
            self.ошибка(в, f"«не» применимо только к типу лог, а не к типу {тип}")
        return ЛОГ

    def в_Бинарная(self, в):
        л = self.выражение(в.левый)
        п = self.выражение(в.правый)
        оп = в.оператор
        if оп in АРИФМЕТИКА or оп == "%":
            return self._арифметика(в, оп, л, п, в.левый, в.правый)
        if оп == "^":
            return self._степень(в, л, п)
        if оп in ("и", "или"):
            for сторона, тип in ((в.левый, л), (в.правый, п)):
                if not совместим(тип, ЛОГ):
                    self.ошибка(сторона, f"«{оп}» соединяет значения типа лог, а здесь тип {тип}")
            return ЛОГ
        # сравнения
        if НЕИЗВ in (л, п):
            return ЛОГ
        if это_результат(л) or это_результат(п):
            self._ошибка_необяз(в, л if это_результат(л) else п, "сравнение невозможно")
            return ЛОГ
        if НИЧЕГО in (л, п):
            другой = п if л == НИЧЕГО else л
            if оп not in ("==", "!="):
                self.ошибка(в, "с «ничего» можно сравнивать только на равенство (== и !=)")
            elif другой == НИЧЕГО:
                self.ошибка(в, "«ничего» всегда равно «ничего»")
            elif not это_необяз(другой):
                self.ошибка(в, f"значение типа {другой} есть всегда, оно не может быть равно «ничего»")
            в.сравнение_с_ничего = в.правый if л == НИЧЕГО else в.левый
            return ЛОГ
        if это_необяз(л) or это_необяз(п):
            self.ошибка(в, "необязательное значение можно сравнить только с «ничего»; чтобы сравнить "
                           "само значение, извлеките его: «если пусть знач = ... { }»")
            return ЛОГ
        if л in self.типы or п in self.типы or л in self.перечисления or п in self.перечисления:
            if л != п:
                self.ошибка(в, f"нельзя сравнивать {л} и {п}")
            elif оп not in ("==", "!="):
                self.ошибка(в, f"значения типа {л} можно сравнивать только на равенство (== и !=)")
            elif not self._сравнимый(л):
                self.ошибка(в, f"значения типа {л} нельзя сравнивать: у него есть поля-списки")
            в.тип_операндов = л
            return ЛОГ
        if л in ЧИСЛА and п in ЧИСЛА:
            общий = общий_числовой(л, п)
            self._привести(в.левый, л, общий)
            self._привести(в.правый, п, общий)
            в.тип_операндов = общий
            return ЛОГ
        if МН in (л, п) and л in В_МНОГОЧЛЕН and п in В_МНОГОЧЛЕН:
            if оп not in ("==", "!="):
                self.ошибка(в, "многочлены можно сравнивать только на равенство (== и !=)")
            self._привести(в.левый, л, МН)
            self._привести(в.правый, п, МН)
            в.тип_операндов = МН
            return ЛОГ
        if оп in ("==", "!=") and л == п and л in (СТР, ЛОГ, БАЙТЫ):
            return ЛОГ
        if оп in СРАВНЕНИЯ_ПОРЯДКА and л == п == СТР:
            return ЛОГ
        if это_словарь(л) or это_словарь(п) or ПУСТОЙ_СЛОВАРЬ in (л, п):
            if оп not in ("==", "!="):
                self.ошибка(в, "словари можно сравнивать только на равенство (== и !=)")
                return ЛОГ
            тип = п if л == ПУСТОЙ_СЛОВАРЬ else л
            if тип == ПУСТОЙ_СЛОВАРЬ:
                self.ошибка(в, "пустые словари всегда равны")
                return ЛОГ
            for узел in (в.левый, в.правый):
                if not self._согласовать(узел, узел.тип_выр, тип):
                    self.ошибка(в, f"нельзя сравнивать {л} и {п}")
                    return ЛОГ
            if not self._сравнимый(тип):
                self.ошибка(в, f"словари типа {тип} нельзя сравнивать")
            в.тип_операндов = тип
            return ЛОГ
        if это_список(л) or это_список(п) or ПУСТОЙ_СПИСОК in (л, п):
            if оп not in ("==", "!="):
                self.ошибка(в, "списки можно сравнивать только на равенство (== и !=)")
                return ЛОГ
            if л == ПУСТОЙ_СПИСОК == п:
                self.ошибка(в, "пустые списки всегда равны")
                return ЛОГ
            тип = п if л == ПУСТОЙ_СПИСОК else л
            for узел in (в.левый, в.правый):
                if not self._согласовать(узел, узел.тип_выр, тип):
                    self.ошибка(в, f"нельзя сравнивать {л} и {п}")
                    return ЛОГ
            if not self._сравнимый(тип):
                self.ошибка(в, f"списки типа {тип} нельзя сравнивать: их элементы не сравниваются")
            в.тип_операндов = тип
            return ЛОГ
        if оп in СРАВНЕНИЯ_ПОРЯДКА and л == п and л in (СТР, ЛОГ):
            self.ошибка(в, f"значения типа {л} можно сравнивать только на равенство (== и !=)")
        else:
            self.ошибка(в, f"нельзя сравнивать {л} и {п}")
        return ЛОГ

    def _арифметика(self, узел, оп, л, п, узел_л=None, узел_п=None):
        """Тип результата «л оп п»; операнды отмечаются для приведения к нему."""
        if НЕИЗВ in (л, п):
            return НЕИЗВ
        if это_особое(л) or это_особое(п):
            self._ошибка_необяз(узел, л if это_особое(л) else п, f"операцию «{оп}» нельзя выполнить")
            return НЕИЗВ
        if МН in (л, п):
            if л in В_МНОГОЧЛЕН and п in В_МНОГОЧЛЕН:
                for узел_о, тип_о in ((узел_л, л), (узел_п, п)):
                    if узел_о is not None:
                        self._привести(узел_о, тип_о, МН)
                return МН
            self.ошибка(узел, f"многочлен можно соединять с целыми числами, обыкновенными дробями "
                              f"и другими многочленами, а здесь {л} и {п}; десятичную дробь запишите "
                              f"как рац(...)")
            return НЕИЗВ
        if оп == "%":
            if л == ЦЕЛ and п == ЦЕЛ:
                return ЦЕЛ
            self.ошибка(узел, f"остаток от деления «%» вычисляется только для целых чисел "
                              f"и многочленов, а здесь {л} и {п}")
            return НЕИЗВ
        if л in ЧИСЛА and п in ЧИСЛА:
            результат = общий_числовой(л, п)
            if узел_л is not None:
                self._привести(узел_л, л, результат)
            if узел_п is not None:
                self._привести(узел_п, п, результат)
            return результат
        if оп == "+" and л == п and л in (СТР, БАЙТЫ):
            return л
        if оп == "+" and СТР in (л, п):
            self.ошибка(узел, f"нельзя сложить {л} и {п}; строку можно соединять только со строкой")
        else:
            self.ошибка(узел, f"операция «{оп}» не применима к типам {л} и {п}")
        return НЕИЗВ

    def _степень(self, в, л, п):
        """Возведение в степень «а ^ н»."""
        if НЕИЗВ in (л, п):
            return НЕИЗВ
        if л == МН:
            if п != ЦЕЛ:
                self.ошибка(в.правый, f"многочлен можно возводить только в целую степень, а здесь {п}")
                return НЕИЗВ
            return МН
        if л not in ЧИСЛА or п not in ЧИСЛА:
            self.ошибка(в, f"возводить в степень можно только числа, а здесь {л} и {п}")
            return НЕИЗВ
        if п == ЦЕЛ and л in (ЦЕЛ, РАЦ):
            return л               # 2^10 = 1024, рац(2,3)^2 = 4/9
        # дробное основание или нецелый показатель: вычисление в дробных числах
        self._привести(в.левый, л, ДРОБ)
        self._привести(в.правый, п, ДРОБ)
        return ДРОБ

    def в_Диапазон(self, в):
        for сторона in (в.начало, в.конец):
            тип = self.выражение(сторона)
            if тип not in (ЦЕЛ, НЕИЗВ):
                self.ошибка(сторона, f"границы диапазона должны быть целыми числами, а здесь {тип}")
        return ДИАПАЗОН

    def в_Вызов(self, в):
        if isinstance(в.функция, у.Поле):
            return self._метод(в)
        типы_арг = [self.выражение(а) for а in в.аргументы]
        if not isinstance(в.функция, у.Имя) or (self._найти(в.функция.имя) is not None
                                                and это_функция(self._найти(в.функция.имя).тип)):
            return self._вызов_значения(в, типы_арг)
        имя = в.функция.имя
        в.функция.тип_выр = "функция"

        if имя in self.типы and self._найти(имя) is None:
            return self._конструктор(в, имя, типы_арг)
        if имя in self.вариант_тип and self._найти(имя) is None:
            return self._конструктор_варианта(в, имя, типы_арг)
        if в.имена and (имя not in self.функции or self._найти(имя) is not None):
            self.ошибка(в, "именованные аргументы («имя = значение») можно передавать функциям "
                           "программы и при создании значений собственных типов")
            в.имена = None

        if имя == "вывод":
            if len(типы_арг) != 1:
                self.ошибка(в, f"функция «вывод» принимает одно значение, а передано {len(типы_арг)}")
            elif типы_арг[0] == ПУСТОЙ_СПИСОК:
                в.аргументы[0].тип_выр = "[цел]"   # пустой список выводится как []
            elif это_особое(типы_арг[0]) and not self._можно_вывести(типы_арг[0]):
                self._ошибка_необяз(в.аргументы[0], типы_арг[0], "вывести нельзя")
            elif not self._можно_вывести(типы_арг[0]):
                self.ошибка(в.аргументы[0], "это выражение не имеет значения, которое можно вывести")
            return ПУСТО

        if имя == "ошибка":
            if len(типы_арг) != 1 or not совместим(типы_арг[0], СТР):
                self.ошибка(в, "«ошибка» принимает одно значение - текст ошибки: ошибка(\"файл не найден\")")
            return ОШИБКА

        if имя == "ввод":
            if len(типы_арг) > 1:
                self.ошибка(в, "функция «ввод» принимает не более одного значения: текст подсказки")
            elif типы_арг and not совместим(типы_арг[0], СТР):
                self.ошибка(в.аргументы[0], f"подсказка для «ввод» должна быть строкой, а здесь {типы_арг[0]}")
            return СТР

        if имя in ТИПЫ:
            if имя not in ПРЕОБРАЗОВАНИЯ:
                self.ошибка(в, f"преобразование в тип {имя} не поддерживается; "
                               f"используйте сравнение, например «х != 0»")
                return НЕИЗВ
            if имя == РАЦ and len(типы_арг) == 2:
                # рац(числитель, знаменатель)
                for арг, т in zip(в.аргументы, типы_арг):
                    if т not in (ЦЕЛ, НЕИЗВ):
                        self.ошибка(арг, f"числитель и знаменатель должны быть целыми числами, а здесь {т}")
                return РАЦ
            if len(типы_арг) != 1:
                self.ошибка(в, f"преобразование «{имя}(...)» принимает одно значение, а передано {len(типы_арг)}")
                return имя
            if имя == БАЙТЫ and (типы_арг[0] == ПУСТОЙ_СПИСОК
                                 or self._согласовать(в.аргументы[0], типы_арг[0], "[цел]")):
                if типы_арг[0] == ПУСТОЙ_СПИСОК:
                    в.аргументы[0].тип_выр = "[цел]"
                в.из_списка = True
                return БАЙТЫ
            if имя == СТР and (это_необяз(типы_арг[0]) or типы_арг[0] in self.типы or типы_арг[0] in self.перечисления or это_словарь(типы_арг[0])):
                return СТР
            if имя == СТР and (это_список(типы_арг[0]) or типы_арг[0] == ПУСТОЙ_СПИСОК):
                if типы_арг[0] == ПУСТОЙ_СПИСОК:
                    в.аргументы[0].тип_выр = "[цел]"
                return СТР
            if типы_арг[0] not in ПРЕОБРАЗОВАНИЯ[имя] + (НЕИЗВ,):
                self.ошибка(в.аргументы[0], f"значение типа {типы_арг[0]} нельзя преобразовать в {имя}")
            return имя

        сигнатура = self.функции.get(имя)
        if сигнатура is None:
            if self._найти(имя) is not None:
                self.ошибка(в, f"«{имя}» - переменная, а не функция")
                return НЕИЗВ
            каноническое, описание = найти_в_библиотеке(имя)
            if описание is not None:
                return self._библиотека(в, каноническое, описание, типы_арг)
            подсказка = self._подсказка(имя, self._видимые_функции())
            self.ошибка(в, f"функция «{имя}» не объявлена{подсказка}")
            return НЕИЗВ
        if в.имена:
            порядок = self._сопоставить(в, сигнатура.имена, [False] * len(сигнатура.имена),
                                        f"функции «{имя}»", "параметра")
            if порядок is None:
                return сигнатура.результат
            в.аргументы = [в.аргументы[и] for и in порядок]
            типы_арг = [типы_арг[и] for и in порядок]
            в.имена = None
        if len(типы_арг) != len(сигнатура.параметры):
            self.ошибка(в, f"функция «{имя}» принимает {склонение_значений(len(сигнатура.параметры))}, "
                           f"а передано {len(типы_арг)}")
        else:
            for номер, (арг, тип, нужен) in enumerate(
                    zip(в.аргументы, типы_арг, сигнатура.параметры), start=1):
                if not self._согласовать(арг, тип, нужен):
                    self.ошибка(арг, f"аргумент {номер} функции «{имя}» должен иметь тип {нужен}, "
                                     f"а имеет тип {тип}")
        return сигнатура.результат

    def _вызов_значения(self, в, типы_арг):
        """Вызов функции, которая хранится в переменной, элементе списка, поле и т.п."""
        тип = self.выражение(в.функция)
        if тип == НЕИЗВ:
            return НЕИЗВ
        if not это_функция(тип):
            self.ошибка(в, f"вызвать можно только функцию, а здесь значение типа {тип}")
            return НЕИЗВ
        if в.имена:
            self.ошибка(в, "функции-значению аргументы передаются по порядку, без имён")
        параметры, результат = разобрать_тип_функции(тип)
        if len(типы_арг) != len(параметры):
            self.ошибка(в, f"функция принимает {склонение_значений(len(параметры))}, а передано {len(типы_арг)}")
        else:
            for номер, (арг, т, нужен) in enumerate(zip(в.аргументы, типы_арг, параметры), start=1):
                if not self._согласовать(арг, т, нужен):
                    self.ошибка(арг, f"аргумент {номер} должен иметь тип {нужен}, а имеет тип {т}")
        в.вызов_значения = тип
        return результат

    def в_Лямбда(self, в, ожидаемые=None, ожидаемый_результат=None):
        """Безымянная функция. Если типы параметров не указаны, они берутся из
        места использования (ожидаемые); до этого проверка откладывается."""
        типы = []
        for номер, п in enumerate(в.параметры):
            if п.тип is not None:
                типы.append(self._тип_по_имени(п, п.тип))
            elif ожидаемые is not None:
                типы.append(ожидаемые[номер])
            else:
                return ОТЛОЖЕННАЯ
        if ожидаемые is not None:
            for п, т, нужен in zip(в.параметры, типы, ожидаемые):
                if п.тип is not None and т != нужен:
                    self.ошибка(п, f"параметр «{п.имя}» должен иметь тип {нужен}, а указан {т}")
        результат = self._тип_по_имени(в, в.тип_результата) if в.тип_результата not in (None, ПУСТО + "!") \
            else в.тип_результата
        if результат is None and ожидаемый_результат is not None and в.выражение is None:
            результат = ожидаемый_результат
        в.захваты = {}
        self.лямбды.append((len(self.области), в))
        self.области.append({})
        for п, т in zip(в.параметры, типы):
            self.области[-1][п.имя] = Переменная(т, False, "параметр")
        прежняя, прежние_циклы = self.текущая_функция, self.глубина_циклов
        self.глубина_циклов = 0
        if в.выражение is not None:
            self.текущая_функция = ("безымянная функция", результат or НЕИЗВ)
            т = self.выражение(в.выражение)
            if т == ОТЛОЖЕННАЯ:
                self.ошибка(в.выражение, "укажите типы параметров вложенной безымянной функции")
                т = НЕИЗВ
            нужный = результат or (ожидаемый_результат if ожидаемый_результат not in (None, НЕИЗВ) else None)
            if нужный is not None and нужный != ПУСТО:
                if not self._согласовать(в.выражение, т, нужный):
                    self.ошибка(в.выражение, f"функция должна вернуть {нужный}, а выражение имеет тип {т}")
                результат = нужный
            else:
                результат = т if т not in (ДИАПАЗОН,) else НЕИЗВ
        else:
            результат = результат or ПУСТО
            self.текущая_функция = ("безымянная функция", результат)
            self.блок(в.тело, новая_область=False)
            if результат not in (ПУСТО, НЕИЗВ, ПУСТО + "!") and not всегда_возвращает(в.тело):
                self.ошибка(в, "безымянная функция может завершиться, не вернув значение")
        self.текущая_функция, self.глубина_циклов = прежняя, прежние_циклы
        self.области.pop()
        self.лямбды.pop()
        в.типы_параметров = типы
        в.тип_итог = результат
        return тип_функции(типы, результат)

    def _функциональный_метод(self, в, имя, т, типы_арг):
        образец = ФУНКЦИОНАЛЬНЫЕ_МЕТОДЫ[имя]
        нужно = 2 if имя == "свернуть" else 1
        if len(типы_арг) != нужно:
            self.ошибка(в, f"метод вызывается так: {образец}")
            return НЕИЗВ

        def функция(арг, тип_арг, параметры, результат=None):
            if isinstance(арг, у.Лямбда) and тип_арг == ОТЛОЖЕННАЯ:
                if len(арг.параметры) != len(параметры):
                    self.ошибка(арг, f"функция должна принимать {склонение_значений(len(параметры))}: {образец}")
                    return None
                тип = self.в_Лямбда(арг, параметры, результат)
                арг.тип_выр = тип
                return тип
            if тип_арг == НЕИЗВ:
                return None
            if not это_функция(тип_арг) or разобрать_тип_функции(тип_арг)[0] != параметры:
                self.ошибка(арг, f"ожидается функция с параметрами ({', '.join(параметры)}), а здесь {тип_арг}: {образец}")
                return None
            return тип_арг

        if имя == "свернуть":
            начальное = типы_арг[0]
            if начальное in (НЕИЗВ, ПУСТОЙ_СПИСОК, ПУСТОЙ_СЛОВАРЬ, НИЧЕГО):
                if начальное != НЕИЗВ:
                    self.ошибка(в.аргументы[0], "у начального значения должен быть известен тип")
                return НЕИЗВ
            ф = функция(в.аргументы[1], типы_арг[1], [начальное, т], начальное)
            if ф is None:
                return НЕИЗВ
            рез = разобрать_тип_функции(ф)[1]
            if рез != начальное:
                self.ошибка(в.аргументы[1], f"функция должна возвращать {начальное} (тип начального значения), а возвращает {рез}")
            в.метод_функции = (имя, ф, начальное)
            return начальное
        ожидаемый = ЛОГ if имя in ("отобрать", "любой", "все", "найти_первый") else None
        ф = функция(в.аргументы[0], типы_арг[0], [т], ожидаемый)
        if ф is None:
            return НЕИЗВ
        рез = разобрать_тип_функции(ф)[1]
        if ожидаемый == ЛОГ and рез != ЛОГ:
            self.ошибка(в.аргументы[0], f"условие должно иметь тип лог, а функция возвращает {рез}")
            return НЕИЗВ
        if имя == "преобразовать":
            if рез in (ПУСТО, НЕИЗВ) or это_результат(рез):
                if рез != НЕИЗВ:
                    self.ошибка(в.аргументы[0], f"функция должна возвращать значение, а возвращает {рез}")
                return НЕИЗВ
            в.метод_функции = (имя, ф, рез)
            return "[" + рез + "]"
        if имя == "упорядочить_по":
            if рез not in (ЦЕЛ, РАЦ, ДРОБ, СТР):
                self.ошибка(в.аргументы[0], f"ключ упорядочивания должен быть числом или строкой, а здесь {рез}")
                return НЕИЗВ
            в.метод_функции = (имя, ф, рез)
            return "[" + т + "]"
        в.метод_функции = (имя, ф, ЛОГ)
        if имя == "найти_первый":
            if это_функция(т):
                self.ошибка(в, "для списка функций «найти_первый» недоступен; используйте «отобрать»")
                return НЕИЗВ
            return т if это_необяз(т) else т + "?"
        if имя == "отобрать":
            return "[" + т + "]"
        return ЛОГ

    def _сопоставить(self, в, имена, есть_по_умолчанию, чего, вид):
        """Сопоставляет аргументы вызова (позиционные и «имя = значение») с
        параметрами или полями. Возвращает для каждого параметра номер
        аргумента или None (взять значение по умолчанию); при ошибке - None."""
        порядок = [None] * len(имена)
        имена_арг = в.имена or [None] * len(в.аргументы)
        ошибка = False
        for номер, имя_арг in enumerate(имена_арг):
            if имя_арг is None:
                if номер >= len(имена):
                    self.ошибка(в.аргументы[номер], f"лишний аргумент: у {чего} {склонение_значений(len(имена))}")
                    ошибка = True
                    continue
                порядок[номер] = номер
            elif имя_арг not in имена:
                self.ошибка(в.аргументы[номер], f"у {чего} нет {вид} «{имя_арг}»"
                                               f"{self._подсказка(имя_арг, имена)}")
                ошибка = True
            elif порядок[имена.index(имя_арг)] is not None:
                self.ошибка(в.аргументы[номер], f"значение «{имя_арг}» уже задано")
                ошибка = True
            else:
                порядок[имена.index(имя_арг)] = номер
        пропущенные = [и for и, (п, д) in enumerate(zip(порядок, есть_по_умолчанию)) if п is None and not д]
        if пропущенные:
            список = ", ".join(f"«{имена[и]}»" for и in пропущенные)
            self.ошибка(в, f"для {чего} не задано: {список}")
            ошибка = True
        return None if ошибка else порядок

    def _конструктор(self, в, имя, типы_арг):
        """Создание значения собственного типа: Сотрудник(имя = "Иванов", оклад = 65000)."""
        поля = self.типы[имя]
        порядок = self._сопоставить(в, [п for п, _, _ in поля], [д is not None for _, _, д in поля],
                                    f"типа {имя}", "поля")
        в.конструктор = имя
        if порядок is None:
            в.значения_полей = None
            return имя
        значения = []
        for (поле, тип_поля, по_умолчанию), номер in zip(поля, порядок):
            if номер is None:
                значения.append(по_умолчанию)
                continue
            арг, тип = в.аргументы[номер], типы_арг[номер]
            if not self._согласовать(арг, тип, тип_поля):
                self.ошибка(арг, f"поле «{поле}» имеет тип {тип_поля}, а значение имеет тип {тип}")
            значения.append(арг)
        в.значения_полей = значения
        return имя

    def _конструктор_варианта(self, в, имя, типы_арг):
        тип = self.вариант_тип[имя]
        поля = dict(self.перечисления[тип]).get(имя, [])
        порядок = self._сопоставить(в, [п for п, _ in поля], [False] * len(поля), f"варианта {имя}", "поля")
        в.вариант = (тип, имя)
        if порядок is None:
            в.значения_полей = None
            return тип
        значения = []
        for (поле, тип_поля), номер in zip(поля, порядок):
            арг, т = в.аргументы[номер], типы_арг[номер]
            if not self._согласовать(арг, т, тип_поля):
                self.ошибка(арг, f"поле «{поле}» имеет тип {тип_поля}, а значение имеет тип {т}")
            значения.append(арг)
        в.значения_полей = значения
        return тип

    def _библиотека(self, в, имя, описание, типы_арг):
        """Вызов функции математической библиотеки: выбирается подходящий вариант."""
        for номер, (параметры, результат) in enumerate(описание["варианты"]):
            if len(параметры) == len(типы_арг) and all(
                    self._согласовать(а, т, п) and т != НЕИЗВ
                    for а, т, п in zip(в.аргументы, типы_арг, параметры)):
                в.библиотека = (имя, номер)
                return результат
        if НЕИЗВ in типы_арг:
            return НЕИЗВ
        варианты = " или ".join(
            f"{имя}({', '.join(параметры)})" for параметры, _ in описание["варианты"])
        переданы = ", ".join(типы_арг) or "ничего"
        self.ошибка(в, f"функция «{имя}» вызывается так: {варианты}; а передано: {переданы}")
        return НЕИЗВ

    def _метод(self, в):
        """Вызов через точку: список.добавить(х), строка.заменить(а, б)."""
        поле = в.функция
        тип_объекта = self.выражение(поле.объект)
        типы_арг = [self.выражение(а) for а in в.аргументы]
        имя = поле.имя
        в.метод = имя
        if тип_объекта == НЕИЗВ:
            return НЕИЗВ
        if это_особое(тип_объекта):
            self._ошибка_необяз(поле, тип_объекта, f"метод «{имя}» нельзя вызвать")
            return НЕИЗВ
        if имя == "длина" and (это_список(тип_объекта) or это_словарь(тип_объекта) or тип_объекта in (СТР, БАЙТЫ)):
            self.ошибка(в, "«длина» - свойство, а не функция; пишите без скобок: «с.длина»")
            return НЕИЗВ
        if это_словарь(тип_объекта) and имя in МЕТОДЫ_СЛОВАРЯ:
            т_к, т_з = ключ_словаря(тип_объекта), значение_словаря(тип_объекта)
            if имя == "найти" and это_функция(т_з):
                self.ошибка(в, "для словаря функций «найти» недоступен: проверьте ключ через «содержит» "
                               "и получите функцию через «с[к]»")
                return НЕИЗВ
            параметры, результат, суффикс = МЕТОДЫ_СЛОВАРЯ[имя]
            подстановка = {"К": т_к, "З": т_з, "З?": т_з + "?" if not это_необяз(т_з) else т_з,
                           "[К]": "[" + т_к + "]", "[З]": "[" + т_з + "]", "С": тип_объекта}
            параметры = [подстановка.get(п, п) for п in параметры]
            результат = подстановка.get(результат, результат)
            if len(типы_арг) != len(параметры):
                self.ошибка(в, f"«{имя}» принимает {склонение_значений(len(параметры))}, а передано {len(типы_арг)}")
                return результат
            for номер, (арг, т, нужен) in enumerate(zip(в.аргументы, типы_арг, параметры), start=1):
                if not self._согласовать(арг, т, нужен):
                    self.ошибка(арг, f"аргумент {номер} метода «{имя}» должен иметь тип {нужен}, а имеет тип {т}")
            if имя == "удалить":
                запрет = self._место(поле.объект)
                if запрет:
                    self.ошибка(в, f"словарь нельзя изменить методом «{имя}»: {запрет}")
            в.метод_словаря = суффикс
            return результат
        if тип_объекта == СТР and имя in МЕТОДЫ_СТР:
            варианты = МЕТОДЫ_СТР[имя]
            for параметры, результат, функция, строка in варианты:
                if len(параметры) == len(типы_арг) and all(
                        self._согласовать(а, т, п) for а, т, п in zip(в.аргументы, типы_арг, параметры)):
                    в.метод_c = (функция, строка)
                    return результат
            ожидается = " или ".join(f"с.{имя}({', '.join(п)})" for п, *_ in варианты)
            self.ошибка(в, f"метод строки вызывается так: {ожидается}")
            return НЕИЗВ
        if это_список(тип_объекта) and имя in ФУНКЦИОНАЛЬНЫЕ_МЕТОДЫ:
            return self._функциональный_метод(в, имя, элемент(тип_объекта), типы_арг)
        if это_список(тип_объекта) and имя in МЕТОДЫ_СПИСКА:
            тип_эл = элемент(тип_объекта)
            параметры, результат, суффикс, строка = МЕТОДЫ_СПИСКА[имя]
            подстановка = {"Т": тип_эл, "[Т]": тип_объекта}
            параметры = [подстановка.get(п, п) for п in параметры]
            результат = подстановка.get(результат, результат)
            if имя in ("содержит", "найти") and not self._сравнимый(тип_эл):
                self.ошибка(в, f"элементы типа {тип_эл} нельзя сравнивать, поэтому «{имя}» для них недоступен")
                return НЕИЗВ
            if имя == "соединить" and тип_эл != СТР:
                self.ошибка(в, "«соединить» работает только со списком строк; используйте стр(...) для элементов")
                return НЕИЗВ
            if len(типы_арг) != len(параметры):
                self.ошибка(в, f"«{имя}» принимает {склонение_значений(len(параметры))}, а передано {len(типы_арг)}")
                return результат
            for номер, (арг, т, нужен) in enumerate(zip(в.аргументы, типы_арг, параметры), start=1):
                if not self._согласовать(арг, т, нужен):
                    self.ошибка(арг, f"аргумент {номер} метода «{имя}» должен иметь тип {нужен}, а имеет тип {т}")
            if имя in ИЗМЕНЯЮЩИЕ_МЕТОДЫ:
                запрет = self._место(поле.объект)
                if запрет:
                    что, почему = запрет
                    self.ошибка(в, f"метод «{имя}» изменяет список, а {что} изменять нельзя: {почему}" if что
                                   else f"метод «{имя}» изменяет список: {почему}")
            в.метод_списка = (суффикс, строка)
            return результат
        if тип_объекта in self.типы:
            поля = {п: т for п, т, _ in self.типы[тип_объекта]}
            if имя in поля and это_функция(поля[имя]):
                return self._вызов_значения(в, типы_арг)     # поле хранит функцию
        self.ошибка(поле, f"у значения типа {тип_объекта} нет метода «{имя}»")
        return НЕИЗВ

    def в_Поле(self, в):
        тип = self.выражение(в.объект)
        if тип == НЕИЗВ:
            return НЕИЗВ
        if это_особое(тип):
            self._ошибка_необяз(в, тип, f"поле «{в.имя}» нельзя получить")
            return НЕИЗВ
        if тип in self.перечисления:
            self.ошибка(в, f"поля значения типа {тип} зависят от варианта; получите их через «выбор»")
            return НЕИЗВ
        if тип in self.типы:
            поля = {п: т for п, т, _ in self.типы[тип]}
            if в.имя in поля:
                return поля[в.имя]
            self.ошибка(в, f"у типа {тип} нет поля «{в.имя}»{self._подсказка(в.имя, поля)}")
            return НЕИЗВ
        if в.имя == "длина" and (это_список(тип) or это_словарь(тип) or тип in (СТР, БАЙТЫ)
                                 or тип in (ПУСТОЙ_СПИСОК, ПУСТОЙ_СЛОВАРЬ)):
            return ЦЕЛ
        if в.имя in СВОЙСТВА.get(тип, {}):
            return СВОЙСТВА[тип][в.имя]
        if (это_список(тип) and в.имя in МЕТОДЫ_СПИСКА) or (тип == СТР and в.имя in МЕТОДЫ_СТР) \
                or (это_словарь(тип) and в.имя in МЕТОДЫ_СЛОВАРЯ):
            self.ошибка(в, f"«{в.имя}» - метод; допишите скобки: «с.{в.имя}(...)»")
            return НЕИЗВ
        self.ошибка(в, f"у значения типа {тип} нет свойства «{в.имя}»")
        return НЕИЗВ

    def в_Список(self, в):
        типы = [self.выражение(э) for э in в.элементы]
        if not типы:
            return ПУСТОЙ_СПИСОК
        известные = [т for т in типы if т not in (НЕИЗВ, ПУСТОЙ_СПИСОК, НИЧЕГО)]
        if not известные:
            if НЕИЗВ in типы:
                return НЕИЗВ
            что = "«ничего»" if НИЧЕГО in типы else "пустых списков"
            self.ошибка(в, f"не удаётся определить тип элементов списка из одних {что}; "
                           f"укажите тип, например «пусть с: [стр?] = [ничего]»")
            return НЕИЗВ
        тип_эл = известные[0]
        if all(т in ЧИСЛА for т in известные):
            тип_эл = общий_числовой(*известные)
        if НИЧЕГО in типы and not это_необяз(тип_эл):
            тип_эл += "?"
        for э, т in zip(в.элементы, типы):
            if т in (ПУСТО, ДИАПАЗОН):
                self.ошибка(э, "это выражение нельзя сделать элементом списка")
                return НЕИЗВ
            if not self._согласовать(э, т, тип_эл):
                self.ошибка(э, f"все элементы списка должны иметь один тип: "
                               f"первый имеет тип {тип_эл}, а этот {т}")
                return НЕИЗВ
        return "[" + тип_эл + "]"

    def в_Словарь(self, в):
        типы_к = [self.выражение(к) for к in в.ключи]
        типы_з = [self.выражение(з) for з in в.значения]
        if not в.ключи:
            return ПУСТОЙ_СЛОВАРЬ
        т_к = self._общий_тип(в, в.ключи, типы_к, "ключи")
        т_з = self._общий_тип(в, в.значения, типы_з, "значения")
        if НЕИЗВ in (т_к, т_з):
            return НЕИЗВ
        if т_к not in КЛЮЧИ_СЛОВАРЯ:
            self.ошибка(в.ключи[0], f"ключами словаря могут быть значения типов {', '.join(КЛЮЧИ_СЛОВАРЯ)}, а не {т_к}")
            return НЕИЗВ
        return словарь(т_к, т_з)

    def _общий_тип(self, в, узлы, типы, что):
        """Общий тип элементов записи списка или словаря (числа приводятся к общему)."""
        известные = [т for т in типы if т not in (НЕИЗВ, ПУСТОЙ_СПИСОК, ПУСТОЙ_СЛОВАРЬ, НИЧЕГО)]
        if not известные:
            if НЕИЗВ not in типы:
                self.ошибка(в, f"не удаётся определить тип, у которого все {что} пустые или «ничего»; "
                               f"укажите тип переменной, например «пусть с: {{стр: [цел]}} = ...»")
            return НЕИЗВ
        тип = известные[0]
        if all(т in ЧИСЛА for т in известные):
            тип = общий_числовой(*известные)
        if НИЧЕГО in типы and not это_необяз(тип):
            тип += "?"
        for узел, т in zip(узлы, типы):
            if т in (ПУСТО, ДИАПАЗОН):
                self.ошибка(узел, "это выражение нельзя поместить в словарь")
                return НЕИЗВ
            if not self._согласовать(узел, т, тип):
                self.ошибка(узел, f"все {что} должны иметь один тип: первый имеет тип {тип}, а этот {т}")
                return НЕИЗВ
        return тип

    def в_Индекс(self, в):
        тип = self.выражение(в.объект)
        if isinstance(в.индекс, у.Диапазон):
            # срез: с[а..б] - элементы (символы, байты) с номерами от а до б включительно
            for граница in (в.индекс.начало, в.индекс.конец):
                т = self.выражение(граница)
                if т not in (ЦЕЛ, НЕИЗВ):
                    self.ошибка(граница, f"границы среза должны быть целыми числами, а здесь {т}")
            в.индекс.тип_выр = ДИАПАЗОН
            if тип == НЕИЗВ:
                return НЕИЗВ
            if тип in (СТР, БАЙТЫ) or это_список(тип):
                в.срез = True
                return тип
            self.ошибка(в.объект, f"срез применим к строкам, спискам и байтам, а здесь {тип}")
            return НЕИЗВ
        тип_индекса = self.выражение(в.индекс)
        if тип == НЕИЗВ:
            return НЕИЗВ
        if это_особое(тип):
            self._ошибка_необяз(в, тип, "элемент по номеру нельзя получить")
            return НЕИЗВ
        if тип in (СТР, БАЙТЫ):
            if тип_индекса not in (ЦЕЛ, НЕИЗВ):
                self.ошибка(в.индекс, f"индекс должен быть целым числом, а здесь {тип_индекса}")
            return СТР if тип == СТР else ЦЕЛ
        if это_словарь(тип):
            т_к = ключ_словаря(тип)
            if тип_индекса != НЕИЗВ and not self._согласовать(в.индекс, тип_индекса, т_к):
                self.ошибка(в.индекс, f"ключи словаря имеют тип {т_к}, а здесь {тип_индекса}")
            return значение_словаря(тип)
        if not это_список(тип):
            self.ошибка(в.объект, f"квадратные скобки применимы к спискам, словарям, строкам и байтам, а здесь {тип}")
            return НЕИЗВ
        if тип_индекса not in (ЦЕЛ, НЕИЗВ):
            self.ошибка(в.индекс, f"индекс должен быть целым числом, а здесь {тип_индекса}")
        return элемент(тип)


def склонение_полей(н):
    if н % 10 == 1 and н % 100 != 11:
        return f"{н} поле"
    if н % 10 in (2, 3, 4) and н % 100 not in (12, 13, 14):
        return f"{н} поля"
    return f"{н} полей"


def склонение_значений(н):
    if н % 10 == 1 and н % 100 != 11:
        слово = "значение"
    elif н % 10 in (2, 3, 4) and н % 100 not in (12, 13, 14):
        слово = "значения"
    else:
        слово = "значений"
    return f"{н} {слово}"


def всегда_возвращает(узел):
    """Возвращает ли блок значение при любом пути выполнения."""
    if isinstance(узел, у.Вернуть):
        return True
    if isinstance(узел, у.Блок):
        return any(всегда_возвращает(и) for и in узел.инструкции)
    if isinstance(узел, у.Выбор):
        return ((узел.иначе is not None and всегда_возвращает(узел.иначе)) or getattr(узел, "полный", False)) \
            and all(всегда_возвращает(в.тело) for в in узел.ветви)
    if isinstance(узел, (у.Если, у.ЕслиЕсть, у.ЕслиОшибка)):
        return (узел.иначе is not None
                and всегда_возвращает(узел.тогда)
                and всегда_возвращает(узел.иначе))
    return False


def проверить(программа):
    """Проверяет дерево программы. При ошибках выбрасывает ОшибкаПроверки."""
    Проверка().программа(программа)
    return программа
