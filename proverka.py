def похожее_имя(имя, кандидаты):
    """Ближайшее по написанию имя из кандидатов (для подсказки при опечатке)."""
    варианты = difflib.get_close_matches(имя, sorted(set(кандидаты)), n=1, cutoff=0.7)
    return варианты[0] if варианты else None


def найти_в_библиотеке(имя):
    """Функция стандартной библиотеки (математика или данные): (имя, описание)."""
    каноническое, описание = matematika.найти(имя)
    if описание is None:
        каноническое, описание = dannye.найти(имя)
    return каноническое, описание
