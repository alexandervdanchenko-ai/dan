def общий_числовой(*типы):
    """Тип результата арифметики: самый «широкий» из числовых типов."""
    return max(типы, key=ЧИСЛА.index)


def это_список(тип):
    return тип.startswith("[") and тип.endswith("]") and тип != ПУСТОЙ_СПИСОК


def элемент(тип):
    return тип[1:-1]


def это_словарь(тип):
    return тип.startswith("{") and тип.endswith("}") and тип != ПУСТОЙ_СЛОВАРЬ


def ключ_словаря(тип):
    """Тип ключей: для «{стр: [цел]}» это «стр» (ключи - простые типы без двоеточий)."""
    return тип[1:тип.index(": ")]


def значение_словаря(тип):
    return тип[тип.index(": ") + 2:-1]


def словарь(ключ, значение):
    return "{" + ключ + ": " + значение + "}"


def это_функция(тип):
    """Тип функции: «функ(цел, стр) -> лог»."""
    return тип.startswith("функ(")


def _части_верхнего_уровня(текст):
    """Делит текст по запятым, не входящим в скобки."""
    части, глубина, начало = [], 0, 0
    for и, с in enumerate(текст):
        if с in "([{":
            глубина += 1
        elif с in ")]}":
            глубина -= 1
        elif с == "," and глубина == 0:
            части.append(текст[начало:и].strip())
            начало = и + 1
    if текст.strip():
        части.append(текст[начало:].strip())
    return части


def разобрать_тип_функции(тип):
    """(типы параметров, тип результата) для «функ(цел, стр) -> лог»; без «->» результат «пусто»."""
    глубина = 0
    for и, с in enumerate(тип):
        if с == "(":
            глубина += 1
        elif с == ")":
            глубина -= 1
            if глубина == 0:
                параметры = _части_верхнего_уровня(тип[5:и])
                остаток = тип[и + 1:].strip()
                результат = остаток[2:].strip() if остаток.startswith("->") else "пусто"
                return параметры, результат
    raise ValueError(тип)


def тип_функции(параметры, результат):
    тип = "функ(" + ", ".join(параметры) + ")"
    return тип if результат == "пусто" else тип + " -> " + результат


def это_необяз(тип):
    """Необязательное значение «тип?»: значение этого типа или ничего."""
    return тип.endswith("?") and not это_функция(тип)


def это_результат(тип):
    """Результат «тип!»: значение этого типа или ошибка (основа - то же «основа»)."""
    return тип.endswith("!") and not это_функция(тип)


def это_особое(тип):
    """Значение, которое нельзя использовать без проверки: «Т?» или «Т!»."""
    return это_необяз(тип) or это_результат(тип)


def основа(тип):
    """Тип значения внутри необязательного: для «стр?» это «стр»."""
    return тип[:-1]


def расширяемый_список(откуда, куда):
    """Список чисел расширяется так же, как число: [цел] -> [рац] -> [дроб],
    [[цел]] -> [[рац]]. Списки - значения, поэтому функция получает
    преобразованную копию и ничьих данных не меняет."""
    if not (это_список(откуда) and это_список(куда)):
        return False
    а, б = элемент(откуда), элемент(куда)
    if а in ЧИСЛА and б in ЧИСЛА:
        return ЧИСЛА.index(а) < ЧИСЛА.index(б)
    return расширяемый_список(а, б)


def совместим(откуда, куда):
    """Можно ли значение типа «откуда» использовать там, где ждут «куда»."""
    if НЕИЗВ in (откуда, куда):
        return True
    if откуда.endswith("<>") and куда.startswith(откуда[:-1]) and куда.endswith(">"):
        return True      # «Нет» обобщённого перечисления подходит к Ответ<цел>
    if откуда == ПУСТОЙ_СПИСОК:
        return это_список(куда) or (это_необяз(куда) and это_список(основа(куда)))
    if откуда == ПУСТОЙ_СЛОВАРЬ:
        return это_словарь(куда) or (это_необяз(куда) and это_словарь(основа(куда)))
    if это_результат(куда) and откуда != куда:
        return откуда == ОШИБКА or совместим(откуда, основа(куда))
    if это_необяз(куда) and откуда != куда:
        return откуда == НИЧЕГО or совместим(откуда, основа(куда))
    if откуда in ЧИСЛА and куда in ЧИСЛА:
        return ЧИСЛА.index(откуда) <= ЧИСЛА.index(куда)
    if куда == ДЛИН:
        return откуда in (ЦЕЛ, ДЛИН)
    if куда == КОМПЛ:
        return откуда in ЧИСЛА + (КОМПЛ,)
    if расширяемый_список(откуда, куда):
        return True
    if куда == МН:
        return откуда in В_МНОГОЧЛЕН
    return откуда == куда


