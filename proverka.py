    ВНЕШНИЕ_ТИПЫ = {"цел": ЦЕЛ, "цел32": ЦЕЛ, "дроб": ДРОБ, "дроб32": ДРОБ, "лог": ЛОГ, "стр": СТР}

    def _собрать_внешние(self, блок):
        for ф in блок.функции:
            if ф.имя in self.функции or ф.имя in ВСТРОЕННЫЕ or self._занято_как_тип(ф.имя):
                self.ошибка(ф, f"имя «{ф.имя}» уже занято")
                continue
            типы = []
            for п in ф.параметры:
                if п.тип not in self.ВНЕШНИЕ_ТИПЫ:
                    self.ошибка(п, f"параметр внешней функции может иметь тип {', '.join(self.ВНЕШНИЕ_ТИПЫ)}, "
                                   f"а здесь {п.тип}")
                    типы.append(НЕИЗВ)
                else:
                    типы.append(self.ВНЕШНИЕ_ТИПЫ[п.тип])
            результат = ПУСТО
            if ф.тип_результата is not None:
                if ф.тип_результата == "стр?":
                    результат = "стр?"
                elif ф.тип_результата in self.ВНЕШНИЕ_ТИПЫ:
                    результат = self.ВНЕШНИЕ_ТИПЫ[ф.тип_результата]
                else:
                    self.ошибка(ф, f"внешняя функция может возвращать {', '.join(self.ВНЕШНИЕ_ТИПЫ)} или стр?, "
                                   f"а здесь {ф.тип_результата}")
                    результат = НЕИЗВ
            if not ф.имя_c or not ф.имя_c.replace("_", "a").isascii() or not ф.имя_c.replace("_", "a").isalnum():
                self.ошибка(ф, f"имя функции в библиотеке C пишется латинскими буквами, цифрами и «_», "
                               f"а здесь «{ф.имя_c}»")
            self.функции[ф.имя] = Сигнатура(типы, результат, [п.имя for п in ф.параметры])
            self.внешние[ф.имя] = ф

