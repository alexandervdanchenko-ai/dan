"""Проверка смысла программы на языке Дан (версия 0.1).

Получает дерево программы от парсера и проверяет то, что нельзя увидеть
по одной только записи: объявлены ли переменные, совпадают ли типы,
правильно ли вызываются функции, не изменяется ли неизменяемое.

Проверка не останавливается на первой ошибке, а собирает все ошибки
программы. Если тип выражения из-за ошибки установить нельзя, ему
присваивается «неизвестный» тип, который не порождает новых сообщений,
чтобы одна ошибка не вызывала лавину следствий.

Каждому выражению проставляется найденный тип (атрибут «тип_выр»),
им воспользуется генератор кода.
"""

from dataclasses import dataclass

import uzly as у

ЦЕЛ, ДРОБ, СТР, ЛОГ = "цел", "дроб", "стр", "лог"
ПУСТО = "пусто"            # результат функции, которая ничего не возвращает
ДИАПАЗОН = "диапазон"      # служебный тип выражения «а..б»
НЕИЗВ = "?"                # тип выражения, в котором уже найдена ошибка

ТИПЫ = (ЦЕЛ, ДРОБ, СТР, ЛОГ)
ЧИСЛА = (ЦЕЛ, ДРОБ)
АРИФМЕТИКА = ("+", "-", "*", "/")
СРАВНЕНИЯ_ПОРЯДКА = ("<", "<=", ">", ">=")


class ОшибкаПроверки(Exception):
    def __init__(self, ошибки):
        self.ошибки = ошибки
        super().__init__("\n".join(str(о) for о in ошибки))


@dataclass(frozen=True)
class Сообщение:
    строка: int
    столбец: int
    текст: str

    def __str__(self):
        return f"Строка {self.строка}, позиция {self.столбец}: {self.текст}"


@dataclass
class Переменная:
    тип: str
    изменяемая: bool
    вид: str = "переменная"   # "переменная", "параметр" или "цикл"


@dataclass
class Сигнатура:
    параметры: list        # список типов
    результат: str


ВСТРОЕННЫЕ = {"вывод"}


def совместим(откуда, куда):
    """Можно ли значение типа «откуда» использовать там, где ждут «куда»."""
    if НЕИЗВ in (откуда, куда):
        return True
    return откуда == куда or (откуда == ЦЕЛ and куда == ДРОБ)


class Проверка:
    def __init__(self):
        self.ошибки = []
        self.функции = {}
        self.области = []          # стек словарей имя -> Переменная
        self.текущая_функция = None
        self.глубина_циклов = 0

    # ---------- общие средства ----------

    def ошибка(self, узел, текст):
        self.ошибки.append(Сообщение(узел.строка, узел.столбец, текст))

    def _найти(self, имя):
        for область in reversed(self.области):
            if имя in область:
                return область[имя]
        return None

    def _объявить(self, узел, имя, тип, изменяемая, вид="переменная"):
        if имя in self.функции or имя in ВСТРОЕННЫЕ:
            self.ошибка(узел, f"имя «{имя}» уже занято функцией")
        elif self._найти(имя) is not None:
            self.ошибка(узел, f"переменная «{имя}» уже объявлена; "
                              f"повторно объявлять переменную с тем же именем нельзя")
        self.области[-1][имя] = Переменная(тип, изменяемая, вид)

    def _тип_по_имени(self, узел, имя):
        if имя in ТИПЫ:
            return имя
        self.ошибка(узел, f"неизвестный тип «{имя}»; доступны типы: {', '.join(ТИПЫ)}")
        return НЕИЗВ

    # ---------- программа ----------

    def программа(self, программа):
        # Первый проход: собираем все функции, чтобы их можно было
        # вызывать до места объявления.
        for инстр in программа.инструкции:
            if isinstance(инстр, у.Функция):
                if инстр.имя in ВСТРОЕННЫЕ:
                    self.ошибка(инстр, f"«{инстр.имя}» - встроенная функция, объявить её заново нельзя")
                    continue
                if инстр.имя in self.функции:
                    self.ошибка(инстр, f"функция «{инстр.имя}» уже объявлена")
                    continue
                параметры = [self._тип_по_имени(п, п.тип) for п in инстр.параметры]
                результат = (self._тип_по_имени(инстр, инстр.тип_результата)
                             if инстр.тип_результата else ПУСТО)
                self.функции[инстр.имя] = Сигнатура(параметры, результат)

        # Второй проход: тела функций и инструкции верхнего уровня.
        self.области.append({})
        for инстр in программа.инструкции:
            if isinstance(инстр, у.Функция):
                self.функция(инстр)
            else:
                self.инструкция(инстр)
        self.области.pop()

        self.ошибки.sort(key=lambda о: (о.строка, о.столбец))
        if self.ошибки:
            raise ОшибкаПроверки(self.ошибки)

    def функция(self, ф):
        сигнатура = self.функции.get(ф.имя)
        if сигнатура is None:      # ошибка уже сообщена в первом проходе
            return
        # Функции видят только свои параметры и свои переменные.
        внешние_области = self.области
        self.области = [{}]
        for параметр, тип in zip(ф.параметры, сигнатура.параметры):
            if параметр.имя in self.функции or параметр.имя in ВСТРОЕННЫЕ:
                self.ошибка(параметр, f"имя «{параметр.имя}» уже занято функцией")
            self.области[-1][параметр.имя] = Переменная(тип, False, "параметр")
        self.текущая_функция = (ф.имя, сигнатура.результат)
        self.блок(ф.тело, новая_область=False)
        if сигнатура.результат not in (ПУСТО, НЕИЗВ) and not всегда_возвращает(ф.тело):
            self.ошибка(ф, f"функция «{ф.имя}» может завершиться, не вернув значение; "
                           f"в конце каждой ветви нужна инструкция «вернуть»")
        self.текущая_функция = None
        self.области = внешние_области

    # ---------- инструкции ----------

    def блок(self, блок, новая_область=True):
        if новая_область:
            self.области.append({})
        for инстр in блок.инструкции:
            self.инструкция(инстр)
        if новая_область:
            self.области.pop()

    def инструкция(self, и):
        метод = getattr(self, "и_" + type(и).__name__, None)
        if метод is None:
            raise NotImplementedError(type(и).__name__)
        метод(и)

    def и_Функция(self, и):
        self.ошибка(и, "функции объявляются только на верхнем уровне программы, "
                       "а не внутри других функций или блоков")

    def и_ОбъявлениеПеременной(self, и):
        тип_знач = self.выражение(и.значение)
        if тип_знач == ПУСТО:
            self.ошибка(и.значение, "выражение не имеет значения, его нельзя сохранить в переменную")
            тип_знач = НЕИЗВ
        if тип_знач == ДИАПАЗОН:
            self.ошибка(и.значение, "диапазон можно использовать только в цикле «для»")
            тип_знач = НЕИЗВ
        if и.тип is not None:
            тип = self._тип_по_имени(и, и.тип)
            if not совместим(тип_знач, тип):
                self.ошибка(и.значение, f"переменная «{и.имя}» имеет тип {тип}, "
                                        f"а значение имеет тип {тип_знач}")
        else:
            тип = тип_знач
        self._объявить(и, и.имя, тип, и.изменяемая)

    def и_Присваивание(self, и):
        тип_знач = self.выражение(и.значение)
        перем = self._найти(и.имя)
        if перем is None:
            if и.имя in self.функции or и.имя in ВСТРОЕННЫЕ:
                self.ошибка(и, f"«{и.имя}» - функция, ей нельзя присвоить значение")
            else:
                self.ошибка(и, f"переменная «{и.имя}» не объявлена; "
                               f"объявите её через «перем {и.имя} = ...»")
            return
        и.тип_цели = перем.тип
        if not перем.изменяемая:
            причина = {
                "параметр": "это параметр функции",
                "цикл": "это переменная цикла «для»",
            }.get(перем.вид, f"она объявлена через «пусть»; если её нужно менять, "
                             f"объявите через «перем {и.имя} = ...»")
            self.ошибка(и, f"«{и.имя}» нельзя изменить: {причина}")
        if и.оператор == "=":
            if not совместим(тип_знач, перем.тип):
                self.ошибка(и.значение, f"переменная «{и.имя}» имеет тип {перем.тип}, "
                                        f"а значение имеет тип {тип_знач}")
            return
        оп = и.оператор[0]
        результат = self._арифметика(и, оп, перем.тип, тип_знач)
        if not совместим(результат, перем.тип):
            self.ошибка(и, f"результат «{и.имя} {оп} ...» имеет тип {результат}, "
                           f"а переменная «{и.имя}» имеет тип {перем.тип}")

    def и_Выражение(self, и):
        тип = self.выражение(и.выражение)
        if тип == ДИАПАЗОН:
            self.ошибка(и.выражение, "диапазон можно использовать только в цикле «для»")

    def и_Если(self, и):
        self._условие(и.условие, "если")
        self.блок(и.тогда)
        if isinstance(и.иначе, у.Если):
            self.и_Если(и.иначе)
        elif и.иначе is not None:
            self.блок(и.иначе)

    def и_Пока(self, и):
        self._условие(и.условие, "пока")
        self.глубина_циклов += 1
        self.блок(и.тело)
        self.глубина_циклов -= 1

    def и_Для(self, и):
        тип = self.выражение(и.источник)
        if тип not in (ДИАПАЗОН, НЕИЗВ):
            self.ошибка(и.источник, "после «в» ожидается диапазон, например «1..10»")
        self.области.append({})
        self._объявить(и, и.переменная, ЦЕЛ, False, "цикл")
        self.глубина_циклов += 1
        self.блок(и.тело)
        self.глубина_циклов -= 1
        self.области.pop()

    def и_Вернуть(self, и):
        if self.текущая_функция is None:
            self.ошибка(и, "«вернуть» можно использовать только внутри функции")
            if и.значение is not None:
                self.выражение(и.значение)
            return
        имя, ожидаемый = self.текущая_функция
        if и.значение is None:
            if ожидаемый not in (ПУСТО, НЕИЗВ):
                self.ошибка(и, f"функция «{имя}» должна вернуть значение типа {ожидаемый}")
            return
        тип = self.выражение(и.значение)
        if ожидаемый == ПУСТО:
            self.ошибка(и, f"функция «{имя}» не возвращает значений; если она должна "
                           f"возвращать результат, укажите его тип после «->»")
        elif not совместим(тип, ожидаемый):
            self.ошибка(и.значение, f"функция «{имя}» должна вернуть {ожидаемый}, а возвращается {тип}")

    def и_Прервать(self, и):
        if self.глубина_циклов == 0:
            self.ошибка(и, "«прервать» можно использовать только внутри цикла")

    def и_Продолжить(self, и):
        if self.глубина_циклов == 0:
            self.ошибка(и, "«продолжить» можно использовать только внутри цикла")

    def _условие(self, выр, слово):
        тип = self.выражение(выр)
        if not совместим(тип, ЛОГ):
            self.ошибка(выр, f"условие после «{слово}» должно иметь тип лог "
                             f"(истина или ложь), а имеет тип {тип}")

    # ---------- выражения ----------

    def выражение(self, в):
        метод = getattr(self, "в_" + type(в).__name__)
        тип = метод(в)
        в.тип_выр = тип
        return тип

    def в_ЦелоеЧисло(self, в):
        if в.значение > 2**63 - 1:
            self.ошибка(в, "число слишком велико для типа цел")
        return ЦЕЛ

    def в_ДробноеЧисло(self, в):
        return ДРОБ

    def в_Строка(self, в):
        return СТР

    def в_Логическое(self, в):
        return ЛОГ

    def в_Имя(self, в):
        перем = self._найти(в.имя)
        if перем is not None:
            return перем.тип
        if в.имя in self.функции or в.имя in ВСТРОЕННЫЕ:
            self.ошибка(в, f"«{в.имя}» - функция; чтобы её вызвать, допишите скобки: {в.имя}(...)")
        else:
            self.ошибка(в, f"переменная «{в.имя}» не объявлена")
        return НЕИЗВ

    def в_Унарная(self, в):
        тип = self.выражение(в.операнд)
        if в.оператор == "-":
            if тип in ЧИСЛА or тип == НЕИЗВ:
                return тип
            self.ошибка(в, f"знак «-» применим только к числам, а не к типу {тип}")
            return НЕИЗВ
        # не
        if not совместим(тип, ЛОГ):
            self.ошибка(в, f"«не» применимо только к типу лог, а не к типу {тип}")
        return ЛОГ

    def в_Бинарная(self, в):
        л = self.выражение(в.левый)
        п = self.выражение(в.правый)
        оп = в.оператор
        if оп in АРИФМЕТИКА or оп == "%":
            return self._арифметика(в, оп, л, п)
        if оп in ("и", "или"):
            for сторона, тип in ((в.левый, л), (в.правый, п)):
                if not совместим(тип, ЛОГ):
                    self.ошибка(сторона, f"«{оп}» соединяет значения типа лог, а здесь тип {тип}")
            return ЛОГ
        # сравнения
        if НЕИЗВ in (л, п):
            return ЛОГ
        if л in ЧИСЛА and п in ЧИСЛА:
            return ЛОГ
        if оп in ("==", "!=") and л == п and л in (СТР, ЛОГ):
            return ЛОГ
        if оп in СРАВНЕНИЯ_ПОРЯДКА and л == п and л in (СТР, ЛОГ):
            self.ошибка(в, f"значения типа {л} можно сравнивать только на равенство (== и !=)")
        else:
            self.ошибка(в, f"нельзя сравнивать {л} и {п}")
        return ЛОГ

    def _арифметика(self, узел, оп, л, п):
        if НЕИЗВ in (л, п):
            return НЕИЗВ
        if оп == "%":
            if л == ЦЕЛ and п == ЦЕЛ:
                return ЦЕЛ
            self.ошибка(узел, f"остаток от деления «%» вычисляется только для целых чисел, "
                              f"а здесь {л} и {п}")
            return НЕИЗВ
        if л in ЧИСЛА and п in ЧИСЛА:
            return ЦЕЛ if л == п == ЦЕЛ else ДРОБ
        if оп == "+" and л == п == СТР:
            return СТР
        if оп == "+" and СТР in (л, п):
            self.ошибка(узел, f"нельзя сложить {л} и {п}; строку можно соединять только со строкой")
        else:
            self.ошибка(узел, f"операция «{оп}» не применима к типам {л} и {п}")
        return НЕИЗВ

    def в_Диапазон(self, в):
        for сторона in (в.начало, в.конец):
            тип = self.выражение(сторона)
            if not совместим(тип, ЦЕЛ) or тип == ДРОБ:
                self.ошибка(сторона, f"границы диапазона должны быть целыми числами, а здесь {тип}")
        return ДИАПАЗОН

    def в_Вызов(self, в):
        типы_арг = [self.выражение(а) for а in в.аргументы]
        if not isinstance(в.функция, у.Имя):
            self.ошибка(в, "вызывать можно только функцию по её имени")
            return НЕИЗВ
        имя = в.функция.имя
        в.функция.тип_выр = "функция"

        if имя == "вывод":
            if len(типы_арг) != 1:
                self.ошибка(в, f"функция «вывод» принимает одно значение, а передано {len(типы_арг)}")
            elif типы_арг[0] not in ТИПЫ + (НЕИЗВ,):
                self.ошибка(в.аргументы[0], "это выражение не имеет значения, которое можно вывести")
            return ПУСТО

        сигнатура = self.функции.get(имя)
        if сигнатура is None:
            if self._найти(имя) is not None:
                self.ошибка(в, f"«{имя}» - переменная, а не функция")
            else:
                self.ошибка(в, f"функция «{имя}» не объявлена")
            return НЕИЗВ
        if len(типы_арг) != len(сигнатура.параметры):
            self.ошибка(в, f"функция «{имя}» принимает {склонение_значений(len(сигнатура.параметры))}, "
                           f"а передано {len(типы_арг)}")
        else:
            for номер, (арг, тип, нужен) in enumerate(
                    zip(в.аргументы, типы_арг, сигнатура.параметры), start=1):
                if not совместим(тип, нужен):
                    self.ошибка(арг, f"аргумент {номер} функции «{имя}» должен иметь тип {нужен}, "
                                     f"а имеет тип {тип}")
        return сигнатура.результат

    def в_Поле(self, в):
        self.выражение(в.объект)
        self.ошибка(в, "обращение через точку появится в следующих версиях языка")
        return НЕИЗВ


def склонение_значений(н):
    if н % 10 == 1 and н % 100 != 11:
        слово = "значение"
    elif н % 10 in (2, 3, 4) and н % 100 not in (12, 13, 14):
        слово = "значения"
    else:
        слово = "значений"
    return f"{н} {слово}"


def всегда_возвращает(узел):
    """Возвращает ли блок значение при любом пути выполнения."""
    if isinstance(узел, у.Вернуть):
        return True
    if isinstance(узел, у.Блок):
        return any(всегда_возвращает(и) for и in узел.инструкции)
    if isinstance(узел, у.Если):
        return (узел.иначе is not None
                and всегда_возвращает(узел.тогда)
                and всегда_возвращает(узел.иначе))
    return False


def проверить(программа):
    """Проверяет дерево программы. При ошибках выбрасывает ОшибкаПроверки."""
    Проверка().программа(программа)
    return программа
