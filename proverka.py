    def _запуск(self, в):
        """Проверяет вызов после «запустить» и возвращает тип его результата."""
        вызов = в.вызов
        тип = self.выражение(вызов)
        вызов.тип_выр = тип
        if getattr(вызов, "метод", None) in ИЗМЕНЯЮЩИЕ_МЕТОДЫ or getattr(вызов, "метод_словаря", None) == "remove":
            self.ошибка(в, "задача не может изменить значение из запустившего её блока: она получает копии "
                           "значений; верните результат («з.дождаться()») или передайте его через канал")
            return НЕИЗВ
        if тип == ДИАПАЗОН:
            self.ошибка(в, "диапазон нельзя получить как результат задачи")
            return НЕИЗВ
        в.тип_результата = тип
        в.тип_выр = f"задача<{тип}>" if тип != НЕИЗВ else НЕИЗВ
        return тип

    def в_Запуск(self, в):
        self.ошибка(в, "«запустить» пишется так: «пусть з = запустить ф(...)», затем «з.дождаться()»; "
                       "или отдельной строкой внутри блока «параллельно { ... }»")
        self._запуск(в)
        return НЕИЗВ

    def _объявление_задачи(self, и):
        if и.изменяемая:
            self.ошибка(и, f"задача объявляется через «пусть»: «пусть {и.имя} = запустить ...»")
        тип = self._запуск(и.значение)
        тип_задачи = НЕИЗВ if тип == НЕИЗВ else f"задача<{тип}>"
        if и.тип is not None:
            self.задача_разрешена = True
            явный = self._тип_по_имени(и, и.тип)
            self.задача_разрешена = False
            if НЕИЗВ not in (явный, тип_задачи) and явный != тип_задачи:
                self.ошибка(и, f"переменная «{и.имя}» имеет тип {явный}, а запущена задача типа {тип_задачи}")
        и.значение.тип_выр = тип_задачи
        и.тип_итог = тип_задачи
        self._объявить(и, и.имя, тип_задачи, False)

    def и_Параллельно(self, и):
        self.параллельно += 1
        self.блок(и.тело)
        self.параллельно -= 1

    def _метод_задачи(self, в, тип, имя, типы_арг):
        if имя != "дождаться" or типы_арг:
            self.ошибка(в, "у задачи есть метод «дождаться()» (результат задачи) и свойство «готова»")
            return НЕИЗВ
        в.метод_задачи = имя
        return тип[len("задача<"):-1]

    def _метод_канала(self, в, тип, имя, типы_арг):
        т = элемент_канала(тип)
        вид = {"отправить": 1, "получить": 0, "закрыть": 0}
        if имя not in вид:
            self.ошибка(в, f"у канала есть методы «отправить(значение)», «получить()» и «закрыть()»"
                           f"{self._подсказка(имя, вид)}")
            return НЕИЗВ
        if len(типы_арг) != вид[имя]:
            self.ошибка(в, f"«{имя}» принимает {склонение_значений(вид[имя])}, а передано {len(типы_арг)}")
            return НЕИЗВ
        в.метод_канала = имя
        if имя == "отправить":
            if not self._согласовать(в.аргументы[0], типы_арг[0], т):
                self.ошибка(в.аргументы[0], f"по каналу передаются значения типа {т}, а здесь {типы_арг[0]}")
            return ПУСТО
        if имя == "получить":
            return т + "?"
        return ПУСТО

