"""Шестнадцатеричные и двоичные числа (0x1F, 0b1010) и побитовые действия над цел (bity.py).

Запись чисел и функции есть только в компиляторе на Дане (сам/лексер.dan, bity.py через
сам/встроенные.dan и сам/среда.dan): компилятор на Python заморожен. Тесты переводят программы
компилятором на Дане.
"""

import os
import subprocess
import tempfile
import unittest

import dan
import kody
import sam_kompilyator
from test_kodogen import КОМПИЛЯТОР_ЕСТЬ


def ошибка_перевода(текст):
    """Текст ошибки компилятора на Дане или пустая строка, если программа верна."""
    try:
        sam_kompilyator.перевести(текст)
    except Exception as о:
        return str(о)
    return ""


def выполнить(текст):
    код_c = sam_kompilyator.перевести(текст)
    with tempfile.TemporaryDirectory() as папка:
        исполняемый = dan.собрать_код(код_c, os.path.join(папка, "программа"), папка, выпуск=True)
        р = subprocess.run([исполняемый], capture_output=True, text=True, encoding="utf-8", timeout=60)
        return р.returncode, р.stdout, р.stderr


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыЗаписиЧисел(unittest.TestCase):

    def test_значения(self):
        код, вывод_, ошибки = выполнить(
            "вывод(0xFF)\nвывод(0х1f)\nвывод(0X10)\nвывод(0b1010)\nвывод(0д1111_0000)\nвывод(0xFFFF_FFFF)\n"
            "вывод(0x7FFF_FFFF_FFFF_FFFF)\nвывод(0x0)\nвывод(-0x10 + 1)\nвывод(0x1e5)\n"
            "для к в 0x1..0b11 { вывод(к) }\n")
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.split(), ["255", "31", "16", "10", "240", "4294967295", "9223372036854775807", "0",
                                          "-15", "485", "1", "2", "3"])

    def test_ошибки_записи(self):
        for запись, часть in [
                ("0x", "после «0x» нужны шестнадцатеричные цифры"),
                ("0b", "после «0b» нужны двоичные цифры"),
                ("0x_1", "после «0x» нужны шестнадцатеричные цифры"),
                ("0b102", "«2» - не двоичная цифра"),
                ("0xFG", "«G» - не шестнадцатеричная цифра"),
                ("0x1С", "в шестнадцатеричном числе русская буква «С»"),
                ("0o17", "в Дане нет восьмеричной записи «0o»"),
                ("0x8000_0000_0000_0000", "шестнадцатеричное число не помещается в цел"),
                ("0b" + "1" * 64, "двоичное число не помещается в цел")]:
            with self.subTest(запись=запись):
                self.assertIn(часть, ошибка_перевода(f"вывод({запись})\n"))

    def test_коды_ошибок(self):
        for текст in ["после «0x» нужны шестнадцатеричные цифры: 0-9", "«2» - не двоичная цифра: в",
                      "в шестнадцатеричном числе русская буква «С»: цифры", "в Дане нет восьмеричной записи «0o»: х",
                      "двоичное число не помещается в цел: наибольшее"]:
            with self.subTest(текст=текст):
                self.assertNotEqual(kody.код(текст), "Д0000")

    def test_форматирование_сохраняет_запись(self):
        with tempfile.TemporaryDirectory() as папка:
            путь = os.path.join(папка, "ч.dan")
            with open(путь, "w", encoding="utf-8") as ф:
                ф.write("пусть  м=биты_и(0xFF,0b1010)\nвывод( м )\n")
            р = subprocess.run([sam_kompilyator.исполняемый(), "формат", путь], capture_output=True,
                               env=sam_kompilyator.среда(), timeout=120)
            self.assertEqual(р.returncode, 0, р.stdout.decode("utf-8", "replace"))
            with open(путь, encoding="utf-8") as ф:
                self.assertEqual(ф.read(), "пусть м = биты_и(0xFF, 0b1010)\nвывод(м)\n")


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыПобитовыхДействий(unittest.TestCase):

    def test_действия(self):
        код, вывод_, ошибки = выполнить(
            "вывод(биты_и(0b1100, 0b1010))\nвывод(биты_или(0b1100, 0b1010))\nвывод(биты_искл(0b1100, 0b1010))\n"
            "вывод(биты_не(0))\nвывод(биты_не(5))\nвывод(биты_и(-1, 0xFF))\n"
            "вывод(сдвиг_влево(1, 10))\nвывод(сдвиг_влево(1, 63))\nвывод(сдвиг_влево(3, 63))\nвывод(сдвиг_влево(5, 0))\n"
            "вывод(сдвиг_вправо(-8, 1))\nвывод(сдвиг_вправо(-7, 1))\nвывод(сдвиг_вправо(-1, 63))\nвывод(сдвиг_вправо(1024, 3))\n"
            "вывод(сдвиг_вправо_логический(-1, 60))\nвывод(сдвиг_вправо_логический(-1, 0))\n"
            "вывод(сдвиг_вправо_логический(-9223372036854775807 - 1, 63))\n")
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.split(), ["8", "14", "6", "-1", "-6", "255", "1024", "-9223372036854775808",
                                          "-9223372036854775808", "5", "-4", "-4", "-1", "128", "15", "-1", "1"])

    def test_сдвиг_вправо_как_частное(self):
        код, вывод_, ошибки = выполнить(
            "перем плохих = 0\nдля а в -300..300 {\n    для н в 0..9 {\n"
            "        если сдвиг_вправо(а, н) != частное(а, 2 ^ н) { плохих += 1 }\n"
            "        если сдвиг_влево(а, н) != а * 2 ^ н { плохих += 1 }\n"
            "        если биты_искл(биты_искл(а, н), н) != а { плохих += 1 }\n    }\n}\nвывод(плохих)\n")
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.strip(), "0")

    def test_сдвиг_вне_пределов(self):
        for н in ["64", "-1", "1000"]:
            for функция in ["сдвиг_влево", "сдвиг_вправо", "сдвиг_вправо_логический"]:
                with self.subTest(функция=функция, н=н):
                    код, _, ошибки = выполнить(f"перем н = {н}\nвывод({функция}(1, н))\n")
                    self.assertEqual(код, 1)
                    self.assertIn(f"Ошибка выполнения в строке 2: сдвиг на число битов {н}: допустимо от 0 до 63",
                                  ошибки)

    def test_своя_функция_с_тем_же_именем(self):
        код, вывод_, ошибки = выполнить("функ биты_и(а: цел, б: цел) -> цел { вернуть а + б }\nвывод(биты_и(1, 2))\n")
        self.assertEqual(код, 0, ошибки)
        self.assertEqual(вывод_.strip(), "3")

    def test_привычки_других_языков(self):
        for запись, часть in [
                ("1 & 2", "«&» - не знак Дана: побитовое «и» - функция биты_и(а, б)"),
                ("1 | 2", "«|» - не знак Дана: побитовое «или» - функция биты_или(а, б)"),
                ("~1", "«~» - не знак Дана: побитовое «не» - функция биты_не(а)"),
                ("1 << 2", "«<<» - не знак Дана: сдвиг влево - функция сдвиг_влево(а, н)"),
                ("8 >> 2", "«>>» - не знак Дана: сдвиг вправо - функция сдвиг_вправо(а, н)"),
                ("1 && 2", "«&&» - не знак Дана: напишите «и»")]:
            with self.subTest(запись=запись):
                self.assertIn(часть, ошибка_перевода(f"вывод({запись})\n"))

    def test_конец_вложенного_типа_не_привычка(self):
        # «>>» в конце типа - не сдвиг: подсказка о сдвиге не появляется
        текст = ошибка_перевода("тип Ящик<Т> {\n    х: Т\n}\nпусть я: Ящик<Ящик<цел>> = 5\n")
        self.assertNotIn("сдвиг", текст)


if __name__ == "__main__":
    unittest.main()
