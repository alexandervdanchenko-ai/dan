"""Объяснение строки программы: dan объяснить программа.dan:строка."""

import glob
import os
import subprocess
import sys
import tempfile
import unittest

import objasnenie
from parser import разобрать

ПАПКА = os.path.dirname(os.path.abspath(__file__))

ПРОГРАММА = '''подключить "json"

/// Площадь круга радиуса р.
функ площадь(р: дроб) -> дроб {
    вернуть 3.14 * р * р
}

тип Точка { х: дроб, у: дроб }

перем с = [1, 2, 3]
с.добавить(4)
пусть доля = 3 / 4
для к в 1..10 { вывод(к) }
если с.длина > 2 и доля < 1 {
    вывод("много")
} иначе {
    вывод(площадь(2.0))
}
пусть ч = разобрать_цел("42") иначе 0
пусть т = Точка(1.0, 2.0)
// комментарий
перем словарь_ = {"а": 1}
словарь_["б"] = 2
с[0] += 5
пусть кор = корень(16.0)

тест "площадь" { утвердить(площадь(1.0) > 3.0) }
'''


class ТестыОбъяснения(unittest.TestCase):

    def объяснение(self, номер, текст=ПРОГРАММА):
        return objasnenie.объяснить(текст, "п.dan", номер)

    def test_объявления(self):
        self.assertEqual(self.объяснение(1), 'Строка 1: подключить "json"\n\n'
                         "Подключается модуль «json»: его общие функции и типы доступны через точку (модуль.имя).")
        self.assertIn("Объявляется функция «площадь» с параметром «р» типа дроб; она возвращает дробное число "
                      "(тип дроб).", self.объяснение(4))
        self.assertIn("Объявляется собственный тип «Точка» с полями «х» типа дроб, «у» типа дроб.", self.объяснение(8))
        self.assertIn("Объявляется переменная «с» (её значение можно менять); тип - список (тип [цел]), он выведен "
                      "из значения. Значение - список из 3 элементов.", self.объяснение(10))
        self.assertIn("Тест «площадь»", self.объяснение(27))

    def test_вычисления(self):
        self.assertIn("Функция завершается и возвращает произведение «3.14 * р» и «р».", self.объяснение(5))
        self.assertIn("тип - обыкновенная дробь (тип рац)", self.объяснение(12))
        self.assertIn("деление целых чисел «/» точное и даёт обыкновенную дробь", self.объяснение(12))
        self.assertIn("Значение - новое значение типа «Точка», поля: «1.0», «2.0».", self.объяснение(20))
        self.assertIn("а если его нет (или вместо него ошибка) - «0»", self.объяснение(19))
        self.assertIn("функции «корень» с аргументом «16.0» (функция квадратный корень", self.объяснение(25))

    def test_инструкции(self):
        self.assertIn("Вызывается метод «добавить» значения «с» с аргументом «4»: он добавляет элемент в конец "
                      "списка.", self.объяснение(11))
        для = self.объяснение(13)
        self.assertIn("Цикл «для»: переменная «к» по очереди принимает числа от «1» до «10» включительно", для)
        self.assertIn("Вызывается функция «вывод» с аргументом «к»: она выводит значение на экран", для)
        self.assertIn("Проверяется условие: выполнено и «с.длина > 2», и «доля < 1». Если оно истинно, выполняется "
                      "блок в фигурных скобках. Иначе выполняется ветвь после «иначе».", self.объяснение(14))
        self.assertIn("Значение словаря «словарь_» по ключу «\"б\"» получает новое значение: число 2.",
                      self.объяснение(23))
        self.assertIn("Элемент «с» с номером «0» увеличивается на «5».", self.объяснение(24))

    def test_особые_строки(self):
        self.assertEqual(self.объяснение(2), "Строка 2 пустая")
        self.assertIn("комментарий", self.объяснение(21))
        self.assertIn("закрывает блок", self.объяснение(16))
        self.assertIn("строки 99 в ней нет", self.объяснение(99))

    def test_ошибки_проверки_не_мешают(self):
        текст = "пусть х: стр = 5\nвывод(х)\n"
        объяснение = self.объяснение(2, текст)
        self.assertIn("Вызывается функция «вывод»", объяснение)
        self.assertIn("В программе есть ошибки", объяснение)

    def test_запись_выражений(self):
        for запись in ("а + б + ц - г", "а - (б - ц)", "(а + б) * ц", "а ^ б ^ ц", "(а ^ б) ^ ц",
                       "не (а и б) или ц", "-(а + б)", "(а или б) и ц", "х иначе 0 + 1", "(-а) ^ 2",
                       "ф(1, имя = \"а\")[0].поле", "{\"а\": [1, 2]}"):
            значение = разобрать("пусть з = " + запись).инструкции[0].значение
            self.assertEqual(objasnenie.код(значение), запись)

    def test_все_строки_примеров(self):
        for путь in sorted(glob.glob(os.path.join(ПАПКА, "примеры", "*.dan")))[:12]:
            with open(путь, encoding="utf-8") as ф:
                текст = ф.read()
            for номер in range(1, текст.count("\n") + 2):
                with self.subTest(файл=os.path.basename(путь), строка=номер):
                    self.assertTrue(objasnenie.объяснить(текст, путь, номер))

    def test_команда(self):
        with tempfile.TemporaryDirectory() as папка:
            путь = os.path.join(папка, "п.dan")
            with open(путь, "w", encoding="utf-8") as ф:
                ф.write("пусть х = 2 + 3\n")
            р = subprocess.run([sys.executable, os.path.join(ПАПКА, "dan.py"), "объяснить", путь + ":1"],
                               capture_output=True, text=True, encoding="utf-8", timeout=120)
            self.assertEqual(р.returncode, 0, р.stdout + р.stderr)
            self.assertIn("Значение - сумма «2» и «3».", р.stdout)
            р = subprocess.run([sys.executable, os.path.join(ПАПКА, "dan.py"), "объяснить", путь],
                               capture_output=True, text=True, encoding="utf-8", timeout=120)
            self.assertEqual(р.returncode, 2)


if __name__ == "__main__":
    unittest.main()
