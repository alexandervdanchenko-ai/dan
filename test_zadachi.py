def под_tsan(текст, путь=None):
    """(код завершения, вывод, ошибки) программы, собранной с ThreadSanitizer (сообщения - со строками .dan)."""
    with tempfile.TemporaryDirectory() as п:
        с = os.path.join(п, "программа.c")
        with open(с, "w", encoding="utf-8") as ф:
            ф.write(dan.перевести(текст, путь, строки_дан=True))
        исп = os.path.join(п, "программа")
        subprocess.run([КОМПИЛЯТОР, "-std=c11", "-fwrapv", "-ffp-contract=off", "-w", "-g", "-O1", "-fsanitize=thread",
                        с, "-o", исп, "-lm", "-pthread"], check=True)
        р = subprocess.run([исп], capture_output=True, text=True, encoding="utf-8", timeout=300, cwd=п,
                           env=dict(os.environ, TSAN_OPTIONS="halt_on_error=1"))
    return р.returncode, р.stdout, р.stderr


@unittest.skipUnless(санитайзер("thread"), "компилятор без ThreadSanitizer")
class ТестыГонок(unittest.TestCase):
    """ThreadSanitizer ищет гонки данных: одновременную работу задач с одной памятью."""

    def test_конвейер_без_гонок(self):
        код, вывод_, ошибки = под_tsan(КОНВЕЙЕР)
        self.assertEqual(код, 0, ошибки[-3000:])
        self.assertEqual(вывод_.strip(), "180300")
        self.assertNotIn("ThreadSanitizer", ошибки)

    def test_значения_между_задачами_без_гонок(self):
        for попытка in range(3):         # гонка проявляется не при каждом запуске
            код, вывод_, ошибки = под_tsan(ЗНАЧЕНИЯ_МЕЖДУ_ЗАДАЧАМИ)
            self.assertEqual(код, 0, ошибки[-3000:])
            self.assertEqual(вывод_.split("\n")[:2], ["60", "135"])
            self.assertNotIn("ThreadSanitizer", ошибки)

    def test_каталог_и_примеры_без_гонок(self):
        папка = os.path.dirname(os.path.abspath(__file__))
        программы = [os.path.join(папка, "каталог", "программы", имя) for имя in
                     ("44_параллельные_задачи.dan", "45_каналы.dan")] + [os.path.join(папка, "примеры", "задачи.dan")]
        for путь in программы:
            with self.subTest(программа=os.path.basename(путь)):
                with open(путь, encoding="utf-8") as ф:
                    текст = ф.read()
                код, вывод_, ошибки = под_tsan(текст, путь)
                self.assertEqual(код, 0, ошибки[-3000:])
                self.assertNotIn("ThreadSanitizer", ошибки)
                образец = путь[:-4] + ".вывод"
                if os.path.exists(образец):
                    with open(образец, encoding="utf-8") as ф:
                        self.assertEqual(вывод_, ф.read())


