def санитайзер(вид):
    if not КОМПИЛЯТОР or sys.platform != "linux":
        return False
    with tempfile.TemporaryDirectory() as п:
        с = os.path.join(п, "п.c")
        with open(с, "w") as ф:
            ф.write("int main(void) { return 0; }\n")
        if subprocess.run([КОМПИЛЯТОР, f"-fsanitize={вид}", с, "-o", os.path.join(п, "п")],
                          capture_output=True).returncode != 0:
            return False
        return subprocess.run([os.path.join(п, "п")], capture_output=True).returncode == 0


