class ТестыПроверки(unittest.TestCase):

    def test_где_можно_запускать(self):
        основа = "функ ф() -> цел { вернуть 1 }\n"
        self.assertIn("внутри блока «параллельно", ошибки(основа + "запустить ф()"))
        self.assertIn("через «пусть»", ошибки(основа + "перем з = запустить ф()"))
        self.assertIn("«запустить» пишется так", ошибки(основа + "вывод(запустить ф())"))
        self.assertEqual(ошибки(основа + "параллельно { запустить ф() }"), "")

    def test_задачу_можно_только_дождаться(self):
        основа = "функ ф() -> цел { вернуть 1 }\nпусть з = запустить ф()\n"
        self.assertIn("задачу можно только дождаться", ошибки(основа + "вывод(з)"))
        self.assertIn("задачу можно только дождаться", ошибки(основа + "пусть у = з"))
        self.assertIn("не может пользоваться задачей", ошибки(основа + "пусть г = функ() = з.дождаться()"))
        self.assertIn("нельзя хранить", ошибки("функ г(з: задача<цел>) {}"))
        self.assertEqual(ошибки(основа + "вывод(з.дождаться() + 1)\nвывод(з.готова)"), "")

    def test_задача_не_меняет_чужое(self):
        self.assertIn("получает копии значений", ошибки("перем с = [1]\nпусть з = запустить с.добавить(2)"))

    def test_ошибку_задачи_нельзя_забыть(self):
        self.assertIn("нельзя молча проигнорировать",
                      ошибки("функ ф() -> цел! { вернуть 1 }\nпараллельно { запустить ф() }"))

    def test_каналы(self):
        self.assertIn("укажите, значения какого типа", ошибки("пусть к = канал()"))
        self.assertIn("означает, что канал закрыт", ошибки("пусть к: канал<цел?> = канал()"))
        self.assertIn("по каналу передаются значения типа цел",
                      ошибки("пусть к: канал<цел> = канал()\nк.отправить(\"а\")"))
        self.assertIn("отправить(значение)", ошибки("пусть к: канал<цел> = канал()\nк.послать(1)"))
        self.assertEqual(ошибки("функ ф(к: канал<стр>) { к.отправить(\"а\") }\nф(канал(3))"), "")


