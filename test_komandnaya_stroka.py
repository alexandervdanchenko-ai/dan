"""Тесты модуля командная_строка (библиотека/командная_строка.dan): разбор ключей и значений, справка."""

import os
import subprocess
import tempfile
import unittest

import dan
from test_kodogen import КОМПИЛЯТОР_ЕСТЬ, выполнить

ОПИСАНИЕ = """
подключить "командная_строка"

функ описание() -> командная_строка.Описание {
    перем о = командная_строка.описание("сводка", "Сводка по файлам отчётов")
    о = о.флаг("подробно", "п", "печатать каждую строку")
    о = о.флаг("коротко", "к", "только итог")
    о = о.параметр("вывод", "в", "файл для итога", "итог.txt")
    о = о.обязательный("год", "", "год отчёта")
    о = о.позиционный("папка", "папка с отчётами")
    о = о.необязательный("маска", "какие файлы брать", "*.csv")
    о = о.остальные("файлы", "ещё файлы")
    вернуть о
}

функ показать(з: [стр]) {
    если пусть а = описание().разобрать(з) {
        если а.нужна_справка {
            вывод("справка")
            вернуть
        }
        вывод(стр(а.флаг("подробно")) + " " + стр(а.флаг("коротко")) + " " + а.значение("вывод") + " "
            + а.значение("год") + " " + а.значение("папка") + " " + а.значение("маска") + " "
            + а.остальные.соединить(",") + " " + стр(а.задан("вывод")) + " " + стр(а.цел("год") иначе -1))
    } иначе ошибка е {
        вывод(е)
    }
}
"""


@unittest.skipUnless(КОМПИЛЯТОР_ЕСТЬ, "нет компилятора C")
class ТестыКоманднойСтроки(unittest.TestCase):

    def вывод(self, текст):
        код, вывод_, ошибки = выполнить(текст)
        self.assertEqual(код, 0, ошибки)
        return вывод_.splitlines()

    def test_разбор(self):
        строки = self.вывод(ОПИСАНИЕ + """
показать(["--год=2026", "отчёты"])
показать(["-пк", "-витог2.txt", "--год", "2025", "отчёты", "*.txt", "а", "-", "--", "-б"])
показать(["отчёты", "--вывод", "x", "--год=две", "-в", "=y"])
показать(["--год=", "п"])
""")
        self.assertEqual(строки, [
            "ложь ложь итог.txt 2026 отчёты *.csv  ложь 2026",
            "истина истина итог2.txt 2025 отчёты *.txt а,-,-б истина 2025",
            "ложь ложь =y две отчёты *.csv  истина -1",
            "ложь ложь итог.txt  п *.csv  ложь -1",
        ])

    def test_ошибки_и_справка(self):
        строки = self.вывод(ОПИСАНИЕ + """
показать(["--неизвестный"])
показать(["-з"])
показать(["отчёты", "--год"])
показать(["отчёты"])
показать(["--год=1"])
показать(["--подробно=да", "--год=1", "п"])
показать(["-h"])
показать(["--год=1", "п", "--справка"])
перем д = командная_строка.описание("д", "")
д = д.флаг("а", "", "")
если ошибка е = д.разобрать(["лишнее"]) { вывод(е) }
если пусть а = описание().разобрать(["--год=x", "п"]) {
    если ошибка е = а.цел("год") { вывод(е) }
    если ошибка е = а.дроб("год") { вывод(е) }
}
если пусть а = описание().разобрать(["--год=2,5", "п"]) { вывод(а.дроб("год")!) }
вывод(описание().справка())
""")
        конец = "(справка: сводка --справка)"
        self.assertEqual(строки[:12], [
            "сводка: неизвестный ключ --неизвестный " + конец,
            "сводка: неизвестный ключ -з " + конец,
            "сводка: после --год нужно значение " + конец,
            "сводка: нужен ключ --год " + конец,
            "сводка: нужно значение «папка» " + конец,
            "сводка: ключ --подробно не принимает значения " + конец,
            "справка", "справка",
            "д: лишнее значение «лишнее» (справка: д --справка)",
            "год: нужно целое число, а не «x»",
            "год: нужно число, а не «x»",
            "2.5",
        ])
        self.assertEqual(строки[12:], [
            "Запуск: сводка [ключи] папка [маска] [файлы ...]",
            "",
            "Сводка по файлам отчётов",
            "",
            "Значения:",
            "  папка                 папка с отчётами",
            "  маска                 какие файлы брать (по умолчанию: *.csv)",
            "  файлы ...             ещё файлы",
            "",
            "Ключи:",
            "  -п, --подробно        печатать каждую строку",
            "  -к, --коротко         только итог",
            "  -в, --вывод ЗНАЧЕНИЕ  файл для итога (по умолчанию: итог.txt)",
            "      --год ЗНАЧЕНИЕ    год отчёта (обязательно)",
            "  -h, --справка         показать эту справку",
        ])

    def test_ошибки_описания(self):
        for строка, ожидается in [
                ('о = о.флаг("а", "а", "")\nо = о.флаг("б", "а", "")', "описан дважды"),
                ('о = о.флаг("справка", "", "")', "заняты"),
                ('о = о.флаг("-а", "", "")', "имя ключа"),
                ('о = о.флаг("а", "аб", "")', "одна буква"),
                ('о = о.необязательный("а", "", "")\nо = о.позиционный("б", "")', "после необязательного"),
                ('о = о.остальные("в", "")\nо = о.позиционный("б", "")', "после остальных")]:
            код, вывод_, ошибки = выполнить('подключить "командная_строка"\n'
                                            'перем о = командная_строка.описание("п", "")\n' + строка + "\n")
            self.assertNotEqual(код, 0, строка)
            self.assertIn(ожидается, ошибки, строка)

    def test_значения_запуска(self):
        with tempfile.TemporaryDirectory() as папка:
            путь = os.path.join(папка, "сводка.dan")
            текст = ОПИСАНИЕ + "показать(аргументы())\n"
            with open(путь, "w", encoding="utf-8") as ф:
                ф.write(текст)
            исполняемый = dan.собрать(путь, текст)
            р = subprocess.run([исполняемый, "-п", "--год", "2026", "Отчёты 2026", "--", "-1"], capture_output=True,
                               timeout=60)
            self.assertEqual(р.returncode, 0, р.stderr)
            self.assertEqual(р.stdout.decode("utf-8").strip(), "истина ложь итог.txt 2026 Отчёты 2026 -1  ложь 2026")


if __name__ == "__main__":
    unittest.main()
